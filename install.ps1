$менеджер = ''
if (Есть-Команда 'uv') {
    Отметить-Пропуск 'uv уже установлен — не переустанавливаю'
    $менеджер = 'uv'
} else {
    Write-Host '      uv не найден, ставлю официальным установщиком Astral.'
    $взлетело = $false
    try {
        $установщик = Invoke-RestMethod -Uri 'https://astral.sh/uv/install.ps1' -UseBasicParsing -ErrorAction Stop
        Invoke-Expression $установщик
        # $LASTEXITCODE здесь не спрашивается, и это не пропущенная проверка:
        # установщик uv — код PowerShell, а не внешняя программа, и кода
        # возврата у него нет вовсе; в переменной осталось бы значение от
        # какого-то прежнего вызова. Судим по факту: появилась ли команда
        # (`Есть-Команда 'uv'` ниже). Факт сильнее рапорта.
        $взлетело = $true
    } catch {
        Write-Host ('      установщик uv не отработал: ' + $_.Exception.Message) -ForegroundColor Red
    }
    Обновить-PATH
    if ($взлетело -and (Есть-Команда 'uv')) {
        Отметить-Сделано 'uv установлен'
        $менеджер = 'uv'
    } elseif (Есть-Команда 'pipx') {
        # УСПЕШНЫЙ ОТКАТ — НЕ ОТКАЗ, и код возврата остаётся нулевым.
        # Запасной путь для того и держат, чтобы им пользоваться: пакет
        # будет поставлен, `garant setup` отработает, человек получит
        # рабочую установку. Ненулевой код сказал бы, что что-то не удалось,
        # — это была бы неправда, а неправдивый код перестают читать, и
        # следом пропускают настоящий отказ.
        #
        # Но и молчать нельзя: каким менеджером поставлено, человеку нужно
        # знать — от этого зависит обновление. Поэтому «пропущено», а не
        # «сделано», и формулировка называет и причину, и запасной путь.
        Отметить-Пропуск 'uv недоступен — иду запасным путём, через pipx'
        Совет 'Это не отказ: пакет будет поставлен, установка продолжается.'
        Совет 'Разница, о которой стоит знать: pipx требует уже установленного'
        Совет 'Python 3.12 или новее, а uv поставил бы Python сам.'
        $менеджер = 'pipx'
    } else {
        Отметить-Отказ 'uv установить не удалось, pipx тоже нет'
        Совет 'Поставьте руками что-нибудь одно и запустите этот файл снова:'
        Совет '  uv   — инструкция на https://docs.astral.sh/uv/getting-started/installation/'
        Совет '  pipx — python -m pip install --user pipx   (нужен Python 3.12 или новее)'
        Совет 'Предпочтительнее uv: он поставит Python сам.'
        $менеджер = ''
    }
}

# ------------------------------------------------------- 2/4  пакет
Шаг '2/4  пакет garant-mcp'
$адрес = $Источник
if ([string]::IsNullOrWhiteSpace($адрес)) { $адрес = $ИСТОЧНИК_ПО_УМОЛЧАНИЮ }
$разбор = Разобрать-Источник $адрес
$адрес = [string]$разбор[0]
$бедаИсточника = [string]$разбор[1]
if ($менеджер -eq '') {
    Отметить-Пропуск 'пропущено: ставить нечем — нет ни uv, ни pipx'
} elseif ($бедаИсточника -ne '') {
    Отметить-Отказ ('источник указан неверно: ' + $бедаИсточника)
    Совет ('указано: ' + $адрес)
    Совет 'Из локального каталога ставится КОРЕНЬ репозитория — тот, где лежит'
    Совет 'pyproject.toml. Пример (каталог свой, этот файл его не знает):'
    Совет '  .\install.ps1 -Источник <каталог клона>'
    $менеджер = ''
} elseif ((Адрес-Требует-Git $адрес) -and -not (Есть-Команда 'git')) {
    # Проверяем ДО установки, а не после: без этой проверки отказ случается
    # внутри пакетного менеджера, и человек видит его сообщение, а не наше,
    # — «команда просто не сработала».
    Отметить-Отказ 'git не установлен, а пакет ставится из git-репозитория'
    Сказать-Про-Git
    # Ставить нечего и звать потом некого: шаг 3 честно отметится пропуском.
    $менеджер = ''
} else {
    Write-Host ('      источник: ' + $адрес)
    if ($менеджер -eq 'uv') {
        & uv tool install $адрес
    } else {
        & pipx install $адрес
    }
    $код = $LASTEXITCODE
    if ($код -eq 0) {
        # Повторный запуск доходит сюда и заканчивается тем же нулём: оба
        # менеджера сами видят, что пакет уже стоит. Обновление — отдельное
        # действие и делается ключом --force у того же менеджера.
        $поставленоЧерез = $менеджер
        Отметить-Сделано ('пакет установлен менеджером ' + $менеджер)
    } else {
        Отметить-Отказ ('установка пакета вернула код ' + $код)
        # Выключенные длинные пути называем ПЕРВОЙ причиной, потому что
        # 09.09.2026 отказ этого шага был именно ими: сборочный каталог uv
        # упирается в предел 248 символов и валится «[WinError 206] Имя файла
        # или его расширение имеет слишком большую длину». Прежний список из
        # трёх причин не содержал тогда ни одной верной и уводил человека
        # искать беду с сетью — при том, что $длинныеПути уже вычислены выше
        # и предупреждение о них напечатано первым экраном.
        #
        # Судим по ключу реестра, а не по тексту вывода uv: чтобы прочитать
        # его stderr, пришлось бы перенаправить 2>&1, а PowerShell 5.1
        # заворачивает тогда каждую строку в ErrorRecord и объявляет вызов
        # неудачным даже при нулевом коде; вдобавок вывод перестал бы идти
        # человеку живьём, пока установка ещё работает.
        if (-not $длинныеПути) {
            Совет 'Первая причина здесь — ВЫКЛЮЧЕННЫЕ ДЛИННЫЕ ПУТИ WINDOWS:'
            Совет 'сборочный каталог упирается в предел 248 символов, и отказ'
            Совет 'выглядит так — «[WinError 206] Имя файла или его расширение'
            Совет 'имеет слишком большую длину».'
            Сказать-Про-Длинные-Пути
            Совет ''
            Совет 'Если дело не в них — три обычные причины, в порядке частоты:'
        } else {
            Совет 'Три обычные причины, в порядке частоты:'
        }
        Совет '  1) нет сети или адрес недоступен;'
        # Про «нет git» здесь больше не сказано: он проверен выше, до вызова.
        # Подсказка, называющая уже исключённую причину, уводит в сторону.
        Совет '  2) репозиторий закрыт и требует настроенного доступа git;'
        Совет '  3) адрес указан неверно. Проверить можно так:'
        Совет ('     git ls-remote ' + ($адрес -replace '^git\+', ''))
        # Дальше идти незачем: звать нечего. Обнуляем менеджер, и шаг 3
        # честно отметится пропущенным, а не «не удалось» второй раз.
        $менеджер = ''
    }
}

# ------------------------------------------------- 3/4  garant setup
Шаг '3/4  garant setup — chromium, регистрация у клиентов, вход, диагностика'
if ($менеджер -eq '') {
    Отметить-Пропуск 'пропущено: пакет не установлен, звать нечего'
} else {
    $гарант = Найти-Гарант $менеджер
    if ($null -eq $гарант) {
        Отметить-Отказ 'исполняемый файл garant не найден после установки пакета'
        Совет 'Откройте новое окно консоли и наберите: garant doctor'
        Совет 'Если и там команда не находится — пакет установился не туда, куда'
        Совет 'смотрит PATH; нужный каталог покажет команда: uv tool dir --bin'
    } elseif ($БезРегистрации) {
        # `garant setup` не зовём ВОВСЕ, и это не лень. Регистрация — его
        # третий шаг, отдельного ключа «пропустить регистрацию» у него нет,
        # а неизвестный ключ setup принимает молча: передав такой ключ, мы
        # получили бы ключ, который ничего не запрещает и об этом не говорит.
        # Из двух зол честнее не звать: тогда сводка называет ровно то, что
        # не сделано, и одну команду, которой это добирается.
        & $гарант --version
        $код = $LASTEXITCODE
        if ($код -eq 0) {
            Отметить-Пропуск 'garant setup не вызван по ключу -БезРегистрации: пакет поставлен, настройка после установки не делалась'
            Совет 'Не сделано ничего из этого: chromium не поставлен, записи'
            Совет 'у MCP-клиентов не появилось, вход не выполнялся, диагностика'
            Совет 'не запускалась. Ключ для того и нужен: настройки клиентов'
            Совет 'этой машины остались нетронутыми.'
            Совет 'Добрать всё разом, когда это будет уместно:  garant setup'
        } else {
            Отметить-Отказ ('пакет установлен, но команда garant не запускается (код ' + $код + ')')
            Совет 'Проверить руками:  garant --version'
        }
        if ($БезАвтозапуска) {
            # Молча пропущенная проверка хуже отсутствующей — то же правило,
            # что и ниже в ветке со снимками. Здесь снимок не берётся вовсе:
            # setup не звали, а сверять «до и после» вокруг несостоявшегося
            # вызова нечего. Сказать об этом обязаны: иначе человек, давший
            # оба ключа сразу, прочтёт сводку как «автозапуск проверен».
            Отметить-Пропуск 'ключ -БезАвтозапуска не проверялся: сверки до и после не было, garant setup не вызывался (-БезРегистрации) — менять автозапуск было нечему'
            Совет 'Состояние автозапуска этой машины установщик не смотрел вовсе.'
            Совет 'Посмотреть руками:  garant autostart status'
        }
    } else {
        # Снимок ДО и ПОСЛЕ — единственный способ сделать ключ проверяемым.
        # Обещание «мы автозапуск не трогаем» ключом не является: setup
        # исполняется отдельной программой, и запретить ей что-либо этот
        # файл не может. Заметить — может, и тогда об этом будет сказано.
        $автоДо = ''
        if ($БезАвтозапуска) { $автоДо = Снимок-Автозапуска $гарант }

        $аргументы = @('setup')
        if ($БезВхода) { $аргументы += '--без-входа' }
        # PYTHONUTF8=1 здесь НЕ ставится, хотя в install.sh перед этим же
        # вызовом он стоит, и это не забывчивость. Там он защищает
        # кириллический ключ от локали: python декодирует argv кодировкой
        # локали, и при LANG=C ключ приехал бы искажённым и был бы молча
        # проигнорирован. На Windows такого пути нет — аргументы python
        # берёт из GetCommandLineW уже широкими символами, локаль их не
        # портит. А включить UTF-8-режим «на всякий случай» здесь дороже,
        # чем не включать: он переключил бы и вывод дочернего процесса,
        # тогда как консоль тут чаще всего cp866, — русские строки setup
        # стали бы нечитаемы ровно там, где человек читает диагностику.
        & $гарант @аргументы
        $код = $LASTEXITCODE

        if ($БезАвтозапуска) {
            $автоПосле = Снимок-Автозапуска $гарант
            if ($автоДо -eq '' -or $автоПосле -eq '') {
                # Молча пропущенная проверка хуже отсутствующей: говорим вслух,
                # что ключ остался непроверенным, а не делаем вид, что всё сошлось.
                Отметить-Пропуск 'состояние автозапуска спросить не удалось — ключ -БезАвтозапуска НЕ проверен'
                Совет 'Посмотреть руками:  garant autostart status'
            } elseif ($автоДо -ne $автоПосле) {
                Отметить-Отказ 'автозапуск изменился, хотя запрошен ключ -БезАвтозапуска'
                Совет ('было:  ' + $автоДо)
                Совет ('стало: ' + $автоПосле)
                Совет 'Снять:  garant autostart off'
            } else {
                # Имя ключа обещает больше, чем ключ делает, и сводка обязана
                # назвать факт. Установщик автозапуска не заводит НИ ПРИ КАКИХ
                # ключах: `garant setup` его не касается, а запретить чужой
                # программе установщик и не может. Работа ключа — сверка, что
                # состояние не изменилось. Без этой оговорки читатель сводки
                # вправе решить, что ключ что-то предотвратил.
                Отметить-Пропуск ('автозапуск не появился — сверено «garant autostart status» до и после setup: ' + $автоДо + '. Предотвращать было нечего: установщик автозапуска не заводит ни при каких ключах')
            }
        }

        if ($код -eq 0) {
            Отметить-Сделано 'garant setup прошёл целиком'
        } else {
            # Формулировка называет ГРАНИЦУ: пакет стоит и команда работает,
            # не доделана настройка после установки. Прежнее «сделано не всё»
            # оставляло человека гадать, что именно не так, — а список уже
            # напечатан строкой выше самим setup, последним шагом которого
            # идёт диагностика.
            Отметить-Отказ ('пакет установлен, но настройка после установки доделана не до конца (garant setup, код ' + $код + ')')
            Совет 'ЧТО именно не доделано — красные пункты в разделе ДИАГНОСТИКА'
            Совет 'выше, у каждого названа своя команда починки. Показать их снова:'
            Совет '  garant doctor'
            if (-not $длинныеПути) {
                Совет ''
                Сказать-Про-Длинные-Пути
            }
        }
    }
}

} catch {
    # Сюда попадает только неожиданное: обрывающая ошибка, которой мы
    # не предусмотрели. Она становится обычной строкой [X] — сводка ниже
    # печатается, код возврата ненулевой, и человек видит, что именно
    # успело сделаться до обрыва.
    Отметить-Отказ ('непредвиденная ошибка установщика: ' + $_.Exception.Message)
    Совет 'Это не отказ шага, а обрыв: строки выше показывают, докуда дошло.'
}

# ------------------------------------------------------- 4/4  сводка
Шаг '4/4  сводка'
Write-Host ''
Write-Host ('  сделано:    ' + $Сделано.Count)
foreach ($т in $Сделано)   { Write-Host ('      [+] ' + $т) -ForegroundColor Green }
Write-Host ('  пропущено:  ' + $Пропущено.Count)
foreach ($т in $Пропущено) { Write-Host ('      [=] ' + $т) -ForegroundColor DarkGray }
Write-Host ('  не удалось: ' + $НеУдалось.Count)
foreach ($т in $НеУдалось) { Write-Host ('      [X] ' + $т) -ForegroundColor Red }
Write-Host ''

if ($НеУдалось.Count -gt 0) {
    # Сводка обязана читаться однозначно, поэтому положений два, и они
    # разные по смыслу. «Пакет не установлен» — команды garant нет вовсе.
    # «Пакет установлен, настройка не доделана» — команда есть и работает,
    # но часть возможностей не поднялась. Один общий текст на оба случая
    # тревожил и не говорил, что делать.
    Write-Host 'Установка завершена НЕ полностью. Код возврата 1.' -ForegroundColor Red
    if ([string]::IsNullOrWhiteSpace($поставленоЧерез)) {
        Write-Host 'Пакет НЕ установлен: команды garant на этой машине нет.'
        Write-Host 'Что делать — сказано выше, под строкой [X]. Устраните причину'
        Write-Host 'и запустите этот файл снова.'
    } else {
        Write-Host ('Пакет установлен (менеджер ' + $поставленоЧерез + '), команда garant работает.')
        Write-Host 'Не доделана настройка после установки. Красным помечено ровно то,'
        Write-Host 'что не сделано, — список выше, у каждого пункта своя команда починки.'
        Write-Host 'Пока красное не снято, работает не всё: например, если красным'
        Write-Host 'помечена регистрация у клиента, инструменты «Гаранта» в нём'
        Write-Host 'не появятся, сколько его ни перезапускай.'
        Write-Host 'Показать список снова:'
        Write-Host '  garant doctor'
    }
    exit 1
}
Write-Host 'Установка завершена. Код возврата 0.' -ForegroundColor Green
if ($поставленоЧерез -eq 'pipx') {
    # Названо отдельной строкой, потому что это не мелочь: обновление
    # делается тем же менеджером, которым поставлено, и человек должен
    # понимать, почему у него pipx, а не uv.
    Write-Host 'Внимание: uv поставить не удалось, пакет установлен через pipx.' -ForegroundColor Yellow
    Write-Host 'Обновлять надо тем же, чем поставлено.'
}
Write-Host 'Дальше: перезапустите MCP-клиент, чтобы он увидел сервер.'
Write-Host 'Проверить состояние в любой момент:  garant status'
exit 0
