function Обновить-PATH {
    # Свежепоставленный uv правит PATH в реестре, но текущий процесс об этом
    # не узнает: переменные среды копируются процессу при старте. Без этого
    # `garant` не находится сразу после установки, и человек решает, что
    # установка не сработала. Дописываем недостающее, а не переприсваиваем:
    # то, что добавили в PATH этой консоли до нас, ломать нельзя.
    foreach ($область in @('Machine', 'User')) {
        $значение = [Environment]::GetEnvironmentVariable('Path', $область)
        if ([string]::IsNullOrWhiteSpace($значение)) { continue }
        foreach ($кусок in $значение.Split(';')) {
            if ([string]::IsNullOrWhiteSpace($кусок)) { continue }
            $есть = $false
            foreach ($имеющийся in $env:Path.Split(';')) {
                if ($имеющийся.TrimEnd('\') -eq $кусок.TrimEnd('\')) { $есть = $true }
            }
            if (-not $есть) { $env:Path = $env:Path + ';' + $кусок }
        }
    }
}

function Есть-Команда([string]$имя) {
