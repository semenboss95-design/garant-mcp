function Найти-Гарант([string]$менеджер) {
    # Каталог с исполняемыми файлами спрашиваем у того, кто их туда положил.
    # Вычислять его самостоятельно нельзя: это второй источник истины, и он
    # однажды найдёт чужой файл.
    Обновить-PATH
    $найдено = Get-Command 'garant' -ErrorAction SilentlyContinue
    if ($null -ne $найдено) { return $найдено.Source }

    $бин = ''
    if ($менеджер -eq 'uv') {
        $вывод = & uv tool dir --bin
        if ($LASTEXITCODE -eq 0 -and $вывод) { $бин = ([string]($вывод | Select-Object -Last 1)).Trim() }
    } elseif ($менеджер -eq 'pipx') {
        $вывод = & pipx environment --value PIPX_BIN_DIR
        if ($LASTEXITCODE -eq 0 -and $вывод) { $бин = ([string]($вывод | Select-Object -Last 1)).Trim() }
    }
    if (-not [string]::IsNullOrWhiteSpace($бин)) {
        $путь = Join-Path $бин 'garant.exe'
        if (Test-Path -LiteralPath $путь) {
            # Досюда доходят ТОЛЬКО когда Get-Command не нашёл garant уже
            # ПОСЛЕ Обновить-PATH, а тот слил в $env:Path обе постоянные
            # ветки — Machine и User. Значит, каталога нет и в постоянном
            # PATH, и новое окно консоли его тоже не получит: прежний совет
            # «откройте новое окно, PATH там уже правильный» был неисполним
            # ровно в том случае, ради которого печатался. Постоянный PATH
            # правит сам менеджер — его команду и называем, а окно консоли
            # вторым шагом, уже после неё.
            #
            # Команда выбирается по менеджеру: `uv tool update-shell` для
            # pipx не существует, а неверный совет — та же беда, которая
            # здесь чинится.
            $починка = 'uv tool update-shell'
            if ($менеджер -eq 'pipx') { $починка = 'pipx ensurepath' }
            Совет ('Каталог с командами пока не в PATH этой консоли: ' + $бин)
            Совет 'Сейчас зову garant по полному пути. В постоянном PATH (ни в ветке'
            Совет 'Machine, ни в User) этого каталога тоже нет, поэтому одним новым'
            Совет 'окном консоли дело не поправить. Чтобы команда работала просто'
            Совет 'как «garant», нужны два шага:'
            Совет ('  1) ' + $починка + '  — менеджер пропишет свой каталог команд в PATH навсегда;')
            Совет '  2) после этого откройте новое окно консоли — PATH попадёт в него при старте.'
            return $путь
        }
    }
    return $null
}

function Снимок-Автозапуска([string]$гарант) {
    # Состояние автозапуска СЛОВАМИ, как его видит сам пакет. Свой опрос
    # планировщика писать нельзя: это второй источник истины, и он разойдётся
    # с первым молча. `autostart status` ничего не меняет — только опрашивает.
    #
    # Пустая строка означает «спросить не удалось», и это не то же самое,
    # что «автозапуска нет»: разница названа в месте вызова вслух.
    $вывод = & $гарант autostart status
    if ($LASTEXITCODE -ne 0) { return '' }
    if ($null -eq $вывод) { return '' }
    return ([string]($вывод | Select-Object -Last 1)).Trim()
}

