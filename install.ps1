#requires -Version 5.1
# =====================================================================
#  install.ps1 — установка garant-mcp на Windows одной командой.
#
#  Делает РОВНО ЧЕТЫРЕ ШАГА и ни одним больше: uv, пакет, `garant setup`,
#  сводка. Всё остальное — управление контуром — живёт в команде `garant`
#  и здесь не дублируется (решение 18): второе место, где написано то же
#  самое, приходится чинить дважды.
#
#  КОД ВОЗВРАТА У КАЖДОГО ШАГА ПРОВЕРЯЕТСЯ ЯВНО. $ErrorActionPreference
#  на нативные программы НЕ ДЕЙСТВУЕТ, и прежний установщик именно поэтому
#  печатал «успешно» после двух ERROR подряд — с этого начался этап 02.
#  Здесь после каждого внешнего вызова стоит $LASTEXITCODE, а итоговый код —
#  ноль только тогда, когда в графе «не удалось» пусто.
#
#  СВОДКА ПЕЧАТАЕТСЯ ВСЕГДА — и после неожиданного обрыва тоже. Установщик,
#  оборвавшийся молча, оставляет человека без ответа на единственный важный
#  вопрос: что теперь стоит на машине.
#
#  ТРИ КЛЮЧА ИЗОЛЯЦИИ (-БезВхода, -БезРегистрации, -БезАвтозапуска) нужны затем,
#  чтобы установку мог пройти целиком и посторонний проверяющий: не входя
#  в чужую подписку и не прикасаясь к конфигурациям MCP-клиентов этой
#  машины. Пока их не было, проверить установщика мог ровно один человек —
#  тот, у кого есть и подписка, и не жалко настроек, то есть его автор.
#
#  ИДЕМПОТЕНТНОСТЬ. Повторный запуск ничего не дублирует: uv не ставится
#  поверх найденного, пакет ставит менеджер, который сам знает, что уже
#  установлено, а каталога состояния этот файл не трогает вовсе — им ведает
#  `garant`. Профиль браузера с живым входом в подписку не удаляется ни при
#  каких обстоятельствах: повторная установка не имеет права стоить человеку
#  повторного входа.
#
#  Это Windows PowerShell 5.1, а не 7: без «&&», «||», тернарного оператора
#  и «??». Файл в UTF-8 С BOM — без BOM 5.1 читает его как ANSI и ломается
#  на кириллице, а её здесь весь текст. Концы строк годятся любые: в рабочем
#  дереве CRLF (их подставляет .gitattributes), в скачанном с публичного
#  адреса экземпляре LF — git хранит LF, а PowerShell разбирает и то, и
#  другое. Обязателен ровно BOM.
#
#  «irm <адрес> | iex» С ЭТИМ ФАЙЛОМ НЕ РАБОТАЕТ — проверено 09.09.2026.
#  irm отдаёт текст ВМЕСТЕ с меткой порядка байтов (U+FEFF), а для парсера
#  она не пробел: первым оператором перестаёт быть [CmdletBinding()], разбор
#  падает до исполнения, и установлено оказывается ничего. Убрать BOM из
#  файла нельзя — см. абзац выше. Поэтому работают две другие формы: скачать
#  файлом и запустить с -File, либо срезать метку на лету —
#  & ([scriptblock]::Create((irm <адрес>/install.ps1).TrimStart([char]0xFEFF)))
#  Сказано здесь для того, кто соберётся править однострочник в README.
#
#  Прав администратора файл не просит: и uv, и pipx ставят в пользовательский
#  каталог. Единственное, что требует администратора, — включение длинных
#  путей Windows, и его установщик не делает, а называет командой.
# =====================================================================

