function Адрес-Требует-Git([string]$адрес) {
    # Проверено 06.09.2026 на uv 0.11.8: uv РАЗРЕШАЕТ git-адрес своими силами
    # (`uv pip install --dry-run` доходит до коммита без git.exe в PATH), но
    # на скачивании и сборке падает «Git executable not found». То есть для
    # git-адреса требование абсолютное, и отказ здесь честен.
    #
    # А вот для любого другого источника git не нужен вовсе: имя пакета
    # с PyPI, .whl или каталог ставятся без него. Поэтому проверка привязана
    # к виду адреса, а не стоит безусловно: ложный отказ на первом шаге
    # дороже лишнего сообщения — человек, которому велели поставить git там,
    # где он не нужен, до конца установки не дойдёт.
    return ($адрес -match '^git\+' -or $адрес -match '\.git($|@)')
}

function Разобрать-Источник([string]$адрес) {
    # Возвращает пару: годный адрес и текст беды (пустой, если беды нет).
    # Локальный каталог приводим к полному пути НАРОЧНО: относительный
    # путь пакетный менеджер разрешает от своего текущего каталога, и это
    # тот же класс ошибки, из-за которого в этом репозитории все пути
    # считаются от расположения, а не от того, откуда запустили.
    if (Адрес-Требует-Git $адрес) { return @($адрес, '') }
    if ($адрес -match '^[A-Za-z][A-Za-z0-9+.-]*://') { return @($адрес, '') }
    if (-not (Test-Path -LiteralPath $адрес -PathType Container)) {
        # Не каталог — значит имя пакета, .whl или что-то ещё, о чём судить
        # не нам: пусть отвечает пакетный менеджер.
        return @($адрес, '')
    }
    $полный = (Resolve-Path -LiteralPath $адрес).ProviderPath
    if (-not (Test-Path -LiteralPath (Join-Path $полный 'pyproject.toml'))) {
        # Диагноз ставим сами: сообщение пакетного менеджера про
        # отсутствующий pyproject.toml человек читает как поломку
        # установщика, а не как «указан не тот каталог».
        return @($полный, 'в этом каталоге нет pyproject.toml — это не каталог пакета')
    }
    return @($полный, '')
}

