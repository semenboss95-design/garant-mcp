function Длинные-Пути-Включены {
    # Известный отказ, проверенный 06.09.2026: без включённых длинных путей
    # установка chromium в глубокий каталог падает OSError внутри playwright.
    # Человек видит трассу питона и не понимает ничего — поэтому причину
    # называем словами ЗАРАНЕЕ, а не после падения.
    try {
        $ключ = Get-ItemProperty -Path 'HKLM:\SYSTEM\CurrentControlSet\Control\FileSystem' -Name 'LongPathsEnabled' -ErrorAction Stop
        return ([int]$ключ.LongPathsEnabled -eq 1)
    } catch {
        # Значения нет — значит, длинные пути выключены: это умолчание Windows.
        return $false
    }
}

