#!/bin/sh
# =====================================================================
#  install.sh — установка garant-mcp на macOS и Linux одной командой.
#
#  Делает РОВНО ЧЕТЫРЕ ШАГА и ни одним больше: uv, пакет, `garant setup`,
#  сводка. Управление контуром живёт в команде `garant` и здесь не
#  дублируется (решение 18).
#
#  КОД ВОЗВРАТА У КАЖДОГО ШАГА ПРОВЕРЯЕТСЯ ЯВНО, и итоговый код — ноль
#  только тогда, когда в графе «не удалось» пусто. Прежний установщик
#  (на другом языке, но с той же болезнью) не смотрел ни на один код
#  и печатал «успешно» после двух ошибок подряд.
#
#  СВОДКА ПЕЧАТАЕТСЯ ВСЕГДА — и после неожиданного обрыва тоже. Установщик,
#  оборвавшийся молча, оставляет человека без ответа на единственный важный
#  вопрос: что теперь стоит на машине.
#
#  ТРИ КЛЮЧА ИЗОЛЯЦИИ (--no-login, --no-register, --no-autostart) нужны затем,
#  чтобы установку мог пройти целиком и посторонний проверяющий: не входя
#  в чужую подписку и не прикасаясь к конфигурациям MCP-клиентов этой
#  машины. Пока их не было, проверить установщика мог ровно один человек —
#  тот, у кого есть и подписка, и не жалко настроек, то есть его автор.
#
#  ИДЕМПОТЕНТНОСТЬ. Повторный запуск ничего не дублирует: uv не ставится
#  поверх найденного, пакет ставит менеджер, который сам знает, что уже
#  установлено, а каталога состояния этот файл не трогает вовсе. Профиль
#  браузера с живым входом в подписку не удаляется ни при каких
#  обстоятельствах: повторная установка не имеет права стоить человеку
#  повторного входа.
#
#  ЭТО /bin/sh, а не bash: файл исполняется тем sh, который найдётся
#  у постороннего. Отсюда — имена переменных и функций ЛАТИНИЦЕЙ (не всякий
#  sh принимает кириллицу в имени), никаких массивов и никаких [[ ]].
#  Концы строк LF, BOM нет: CRLF в шебанге даёт «bad interpreter».
#
#  Прав root файл не просит: и uv, и pipx ставят в пользовательский каталог.
#  sudo здесь не нужен ни на одном шаге.
# =====================================================================

set -u

# ------------------------------------------------------------------ адрес
# ОДНА СТРОКА, и при выходе на PyPI менять надо только её: там, где сейчас
# git-адрес, останется имя пакета — 'garant-mcp'. Больше про адрес в файле
# не сказано нигде.
SOURCE_DEFAULT='git+https://github.com/semenboss95-design/garant-mcp'

SOURCE=''
NO_LOGIN=0
NO_REGISTER=0
NO_AUTOSTART=0
# Три ключа изоляции нужны затем, чтобы установку можно было пройти целиком,
# не входя в чужую подписку и не трогая настройки MCP-клиентов этой машины.
# Без них проверить установщика способен только тот, у кого есть и подписка,
# и не жалко конфигураций, — то есть один человек, и он же его написал.
while [ $# -gt 0 ]; do
    case "$1" in
        # Обе формы, «--source X» и «--source=X»: вторую набирают по привычке,
        # а неизвестный ключ здесь — выход с кодом 2, то есть проверка,
        # сорвавшаяся на опечатке в собственной команде.
        --source)
            shift
            SOURCE="${1:-}"
            if [ -z "$SOURCE" ]; then
                echo "--source требует адреса" >&2
                exit 2
            fi
            ;;
        --source=*) SOURCE="${1#--source=}" ;;
        --no-login) NO_LOGIN=1 ;;
        --no-register) NO_REGISTER=1 ;;
        --no-autostart) NO_AUTOSTART=1 ;;
        -h|--help)
            # Синопсис называет и сам ключ справки: ключ, о котором можно
            # узнать, только уже набрав его правильно, для пришедшего
            # со стороны не существует.
            echo "install.sh [--source АДРЕС] [--no-login] [--no-register] [--no-autostart] [--help]"
            echo "  --source       откуда ставить пакет. По умолчанию — адрес"
            echo "                 репозитория. Годится и git-адрес, и имя пакета,"
            echo "                 и файл .whl, и КАТАЛОГ клона: последнее нужно"
            echo "                 тому, кто ставит из своей копии до публикации."
            echo "  --no-login     не открывать окно входа; вход потом: garant login"
            echo "  --no-register  не прикасаться к конфигурациям MCP-клиентов."
            echo "                 Тогда garant setup не вызывается вовсе — почему"
            echo "                 именно так, сказано в шаге 3/4."
            echo "  --no-autostart установщик автозапуска не заводит ни при каких ключах;"
            echo "                 этот ключ сверяет «garant autostart status» до и после"
            echo "                 setup, и изменение делает отказом установки."
            echo "  -h, --help     показать эти ключи и выйти, код 0"
            exit 0
            ;;
        *)
            echo "неизвестный ключ: $1" >&2
            exit 2
            ;;
    esac
    shift
done

INSTALLED_BY=''
DONE_LIST=''
SKIP_LIST=''
FAIL_LIST=''
FAIL_N=0
DONE_N=0
SKIP_N=0

mark_done() { DONE_LIST="$DONE_LIST      [+] $1
"; DONE_N=$((DONE_N + 1)); echo "  [+] $1"; }
mark_skip() { SKIP_LIST="$SKIP_LIST      [=] $1
"; SKIP_N=$((SKIP_N + 1)); echo "  [=] $1"; }
mark_fail() { FAIL_LIST="$FAIL_LIST      [X] $1
"; FAIL_N=$((FAIL_N + 1)); echo "  [X] $1" >&2; }
hint()      { echo "      $1"; }
step()      { echo ""; echo "$1"; }

have() { command -v "$1" >/dev/null 2>&1; }

# Нужен ли git для этого источника. Проверено 06.09.2026 на uv 0.11.8:
# uv РАЗРЕШАЕТ git-адрес своими силами (dry-run доходит до коммита без git
# в PATH), но на скачивании и сборке падает «Git executable not found».
# Для git-адреса требование абсолютное, и отказ честен. Для любого другого
# источника — имя пакета, .whl, каталог — git не нужен вовсе, поэтому
# проверка привязана к виду адреса: ложный отказ на первом шаге дороже
# лишнего сообщения, человек до конца установки просто не дойдёт.
addr_needs_git() {
    case "$1" in
        git+*|*.git|*.git@*) return 0 ;;
        *) return 1 ;;
    esac
}

# Разбор источника. Значения кладём в глобальные ADDR и ADDR_PROBLEM, а не
# печатаем: подстановка команд исполняется в подоболочке, и присвоение внутри
# неё до вызывающего не доходит — беда была бы обнаружена и потеряна разом.
ADDR=''
ADDR_PROBLEM=''
resolve_source() {
    ADDR="$1"
    ADDR_PROBLEM=''
    case "$1" in
        git+*|*.git|*.git@*|*://*) return 0 ;;
    esac
    # Не каталог — значит имя пакета, .whl или что-то ещё, о чём судить
    # не нам: пусть отвечает пакетный менеджер.
    [ -d "$1" ] || return 0
    # Локальный каталог приводим к полному пути НАРОЧНО: относительный путь
    # пакетный менеджер разрешает от своего текущего каталога, и это тот же
    # класс ошибки, из-за которого здесь все пути считаются от расположения,
    # а не от того, откуда запустили.
    _abs="$(cd "$1" 2>/dev/null && pwd)"
    [ -n "$_abs" ] || return 0
    ADDR="$_abs"
    if [ ! -f "$_abs/pyproject.toml" ]; then
        # Диагноз ставим сами: сообщение пакетного менеджера про
        # отсутствующий pyproject.toml человек читает как поломку
        # установщика, а не как «указан не тот каталог».
        ADDR_PROBLEM='в этом каталоге нет pyproject.toml — это не каталог пакета'
    fi
}

# Состояние автозапуска СЛОВАМИ, как его видит сам пакет. Свой опрос
# планировщика писать нельзя: это второй источник истины, и он разойдётся
# с первым молча. `autostart status` ничего не меняет — только опрашивает.
# Пустой ответ означает «спросить не удалось», и это не то же самое, что
# «автозапуска нет»: разница названа в месте вызова вслух.
autostart_snapshot() {
    # Код возврата снимается с САМОЙ программы, а не с конвейера: в конвейере
    # он принадлежит последней команде, и `... | tail` бодро вернул бы ноль
    # после провала. Поэтому сначала подстановка, потом отдельно tail.
    _out="$("$1" autostart status 2>/dev/null)"
    _rc=$?
    if [ "$_rc" -ne 0 ]; then
        printf ''
        return 0
    fi
    printf '%s' "$_out" | tail -n 1
}

say_about_git() {
    hint "Пакет берётся из git-репозитория, а скачать его без git невозможно:"
    hint "uv умеет разобрать git-адрес сам, но клонирует всё равно через git"
    hint "и без него падает с «Git executable not found»."
    hint "Поставьте git тем, чем ставите пакеты в своей системе:"
    hint "  macOS:         brew install git   (либо xcode-select --install)"
    hint "  Debian/Ubuntu: sudo apt install git"
    hint "  Fedora/RHEL:   sudo dnf install git"
    hint "  прочее:        https://git-scm.com/downloads"
    hint "ПОСЛЕ УСТАНОВКИ ОТКРОЙТЕ НОВУЮ ОБОЛОЧКУ и запустите этот файл снова:"
    hint "PATH достаётся процессу при старте, и в текущей оболочке git может"
    hint "не найтись, даже когда он уже установлен."
    hint "Если ставите не из git-адреса (свой --source: имя пакета, .whl,"
    hint "каталог), git не нужен — на такой источник проверка не срабатывает."
}

# Сводка — отдельной функцией и под ловушкой на выход. Она обязана печататься
# ВСЕГДА, в том числе когда оболочка обрывает исполнение сама: нераскрытая
# переменная при `set -u`, сигнал, ошибка в неучтённом месте. Установщик,
# оборвавшийся без сводки, оставляет человека без ответа на единственный
# важный вопрос — что теперь стоит на машине.
SUMMARY_SHOWN=0
summary() {
    SUMMARY_SHOWN=1
    step "4/4  сводка"
    echo ""
    echo "  сделано:    $DONE_N"
    printf '%s' "$DONE_LIST"
    echo "  пропущено:  $SKIP_N"
    printf '%s' "$SKIP_LIST"
    echo "  не удалось: $FAIL_N"
    printf '%s' "$FAIL_LIST"
    echo ""
}

on_exit() {
    _rc=$?
    if [ "$SUMMARY_SHOWN" -eq 0 ]; then
        echo "" >&2
        echo "Установщик оборвался, не дойдя до сводки (код $_rc)." >&2
        echo "Печатаю то, что успело сделаться:" >&2
        summary
    fi
}
trap on_exit EXIT

# ===================================================================== ход
echo ""
echo "=== установка garant-mcp ==="
echo "MCP-сервер над правовой базой «Гарант». Доступ даёт ваша собственная"
echo "подписка: ничего не проксируется, учётные данные никуда не уходят."

# ------------------------------------------------------------ 1/4  uv
step "1/4  uv — менеджер пакетов"
echo "      uv ставит и Python тоже, поэтому отдельно ставить Python не нужно."
MANAGER=''
if have uv; then
    mark_skip "uv уже установлен — не переустанавливаю"
    MANAGER='uv'
else
    echo "      uv не найден, ставлю официальным установщиком Astral."
    # Скачиваем во временный файл и запускаем отдельной командой, а не через
    # «curl | sh»: в конвейере код возврата принадлежит последней команде,
    # и сорвавшаяся закачка выглядела бы как успешная установка. Ровно эта
    # ошибка и стоила этапа 02.
    TMP_INSTALLER="$(mktemp 2>/dev/null || echo "${TMPDIR:-/tmp}/uv-install.$$")"
    RC=0
    if have curl; then
        curl -LsSf https://astral.sh/uv/install.sh -o "$TMP_INSTALLER"
        RC=$?
    elif have wget; then
        wget -qO "$TMP_INSTALLER" https://astral.sh/uv/install.sh
        RC=$?
    else
        RC=127
        echo "      нет ни curl, ни wget — скачать установщик нечем." >&2
    fi
    if [ "$RC" -eq 0 ]; then
        sh "$TMP_INSTALLER"
        RC=$?
    fi
    rm -f "$TMP_INSTALLER"
    # Установщик кладёт uv в пользовательский каталог и правит профиль
    # оболочки, но текущий процесс об этом не узнает: PATH копируется
    # процессу при старте.
    PATH="$HOME/.local/bin:$PATH"
    export PATH
    if [ "$RC" -eq 0 ] && ! have uv; then
        # Установщик доложил об успехе, а команды нет: чаще всего оболочка
        # кладёт uv в каталог, которого нет в PATH. Успехом это считать
        # нельзя — дальше ставить пакет всё равно нечем.
        echo "      установщик отработал, но команда uv не находится." >&2
        RC=1
    fi
    if [ "$RC" -eq 0 ]; then
        mark_done "uv установлен"
        MANAGER='uv'
    elif have pipx; then
        # УСПЕШНЫЙ ОТКАТ — НЕ ОТКАЗ, и код возврата остаётся нулевым.
        # Запасной путь для того и держат, чтобы им пользоваться: пакет
        # будет поставлен, `garant setup` отработает, человек получит
        # рабочую установку. Ненулевой код сказал бы, что что-то не удалось,
        # — это была бы неправда, а неправдивый код перестают читать, и
        # следом пропускают настоящий отказ.
        #
        # Но и молчать нельзя: каким менеджером поставлено, человеку нужно
        # знать — от этого зависит обновление. Поэтому «пропущено», а не
        # «сделано», и формулировка называет и причину, и запасной путь.
        mark_skip "uv недоступен (код $RC) — иду запасным путём, через pipx"
        hint "Это не отказ: пакет будет поставлен, установка продолжается."
        hint "Разница, о которой стоит знать: pipx требует уже установленного"
        hint "Python 3.12 или новее, а uv поставил бы Python сам."
        MANAGER='pipx'
    else
        mark_fail "uv установить не удалось (код $RC), pipx тоже нет"
        hint "Поставьте руками что-нибудь одно и запустите этот файл снова:"
        hint "  uv   — инструкция на https://docs.astral.sh/uv/getting-started/installation/"
        hint "  pipx — python3 -m pip install --user pipx  (нужен Python 3.12 или новее)"
        hint "Предпочтительнее uv: он поставит Python сам."
        MANAGER=''
    fi
fi

# ------------------------------------------------------- 2/4  пакет
step "2/4  пакет garant-mcp"
if [ -n "$SOURCE" ]; then
    resolve_source "$SOURCE"
else
    resolve_source "$SOURCE_DEFAULT"
fi
if [ -z "$MANAGER" ]; then
    mark_skip "пропущено: ставить нечем — нет ни uv, ни pipx"
elif [ -n "$ADDR_PROBLEM" ]; then
    mark_fail "источник указан неверно: $ADDR_PROBLEM"
    hint "указано: $ADDR"
    hint "Из локального каталога ставится КОРЕНЬ репозитория — тот, где лежит"
    hint "pyproject.toml. Пример (каталог свой, этот файл его не знает):"
    hint "  ./install.sh --source <каталог клона>"
    MANAGER=''
elif addr_needs_git "$ADDR" && ! have git; then
    # Проверяем ДО установки, а не после: без этой проверки отказ случается
    # внутри пакетного менеджера, и человек видит его сообщение, а не наше,
    # — «команда просто не сработала».
    mark_fail "git не установлен, а пакет ставится из git-репозитория"
    say_about_git
    # Ставить нечего и звать потом некого: шаг 3 честно отметится пропуском.
    MANAGER=''
else
    echo "      источник: $ADDR"
    if [ "$MANAGER" = 'uv' ]; then
        uv tool install "$ADDR"
    else
        pipx install "$ADDR"
    fi
    RC=$?
    if [ "$RC" -eq 0 ]; then
        # Повторный запуск доходит сюда и заканчивается тем же нулём: оба
        # менеджера сами видят, что пакет уже стоит. Обновление — отдельное
        # действие и делается ключом --force у того же менеджера.
        INSTALLED_BY="$MANAGER"
        mark_done "пакет установлен менеджером $MANAGER"
    else
        mark_fail "установка пакета вернула код $RC"
        hint "Три обычные причины, в порядке частоты:"
        hint "  1) нет сети или адрес недоступен;"
        # Про «нет git» здесь больше не сказано: он проверен выше, до вызова.
        # Подсказка, называющая уже исключённую причину, уводит в сторону.
        hint "  2) репозиторий закрыт и требует настроенного доступа git;"
        hint "  3) адрес указан неверно. Проверить можно так:"
        hint "     git ls-remote $(printf '%s' "$ADDR" | sed 's/^git+//')"
        # Дальше идти незачем: звать нечего. Обнуляем менеджер, и шаг 3
        # честно отметится пропущенным, а не «не удалось» второй раз.
        MANAGER=''
    fi
fi

# ------------------------------------------------- 3/4  garant setup
step "3/4  garant setup — chromium, регистрация у клиентов, вход, диагностика"
if [ -z "$MANAGER" ]; then
    mark_skip "пропущено: пакет не установлен, звать нечего"
else
    # Каталог с исполняемыми файлами спрашиваем у того, кто их туда положил.
    # Вычислять его самостоятельно нельзя: это второй источник истины, и он
    # однажды найдёт чужой файл.
    GARANT=''
    if have garant; then
        GARANT='garant'
    else
        # Код возврата менеджера здесь отдельно не проверяется намеренно:
        # его ответ проверяется по существу — каталог обязан существовать
        # и содержать исполняемый файл. Провалившийся вызов даёт пустую
        # строку и не проходит эту проверку.
        BIN=''
        if [ "$MANAGER" = 'uv' ]; then
            BIN="$(uv tool dir --bin 2>/dev/null)"
        else
            BIN="$(pipx environment --value PIPX_BIN_DIR 2>/dev/null)"
        fi
        # Только последняя строка: диагностическая болтовня менеджера в путь
        # не годится, а «путь» из двух строк молча не найдётся.
        BIN="$(printf '%s' "$BIN" | tail -n 1)"
        if [ -n "$BIN" ] && [ -x "$BIN/garant" ]; then
            GARANT="$BIN/garant"
            # Совет «откройте новую оболочку» сам по себе неисполним: новая
            # оболочка берёт PATH из профиля, а этого каталога в профиле
            # может не быть вовсе — так бывает у uv из пакетного менеджера
            # и при своём UV_TOOL_BIN_DIR. Прописать каталог в профиль умеет
            # сам менеджер, поэтому его команда идёт первым шагом, а новая
            # оболочка — вторым: без первого шага второй ничего не меняет.
            #
            # Команда выбирается по менеджеру: `uv tool update-shell` для
            # pipx не существует, а неверный совет — та же беда, которая
            # здесь чинится.
            FIX='pipx ensurepath'
            if [ "$MANAGER" = 'uv' ]; then
                FIX='uv tool update-shell'
            fi
            hint "Каталог с командами пока не в PATH этой оболочки: $BIN"
            hint "Сейчас зову garant по полному пути. Чтобы команда работала просто"
            hint "как «garant», нужны два шага:"
            hint "  1) $FIX  — менеджер пропишет свой каталог команд в профиль;"
            hint "  2) после этого откройте новую оболочку."
        fi
    fi
    if [ -z "$GARANT" ]; then
        mark_fail "исполняемый файл garant не найден после установки пакета"
        hint "Откройте новую оболочку и наберите: garant doctor"
        hint "Если и там команда не находится — пакет установился не туда, куда"
        hint "смотрит PATH; нужный каталог покажет команда: uv tool dir --bin"
    elif [ "$NO_REGISTER" -eq 1 ]; then
        # `garant setup` не зовём ВОВСЕ, и это не лень. Регистрация — его
        # третий шаг, отдельного ключа «пропустить регистрацию» у него нет,
        # а неизвестный ключ setup принимает молча: передав такой ключ, мы
        # получили бы ключ, который ничего не запрещает и об этом не говорит.
        # Из двух зол честнее не звать: тогда сводка называет ровно то, что
        # не сделано, и одну команду, которой это добирается.
        "$GARANT" --version
        RC=$?
        if [ "$RC" -eq 0 ]; then
            mark_skip "garant setup не вызван по ключу --no-register: пакет поставлен, настройка после установки не делалась"
            hint "Не сделано ничего из этого: chromium не поставлен, записи"
            hint "у MCP-клиентов не появилось, вход не выполнялся, диагностика"
            hint "не запускалась. Ключ для того и нужен: настройки клиентов"
            hint "этой машины остались нетронутыми."
            hint "Добрать всё разом, когда это будет уместно:  garant setup"
        else
            mark_fail "пакет установлен, но команда garant не запускается (код $RC)"
            hint "Проверить руками:  garant --version"
        fi
        if [ "$NO_AUTOSTART" -eq 1 ]; then
            # Молча пропущенная проверка хуже отсутствующей — то же правило,
            # что и ниже в ветке со снимками. Здесь snapshot не берётся вовсе:
            # setup не звали, а сверять «до и после» вокруг несостоявшегося
            # вызова нечего. Сказать об этом обязаны: иначе человек, давший
            # оба ключа сразу, прочтёт сводку как «автозапуск проверен».
            mark_skip "ключ --no-autostart не проверялся: сверки до и после не было, garant setup не вызывался (--no-register) — менять автозапуск было нечему"
            hint "Состояние автозапуска этой машины установщик не смотрел вовсе."
            hint "Посмотреть руками:  garant autostart status"
        fi
    else
        # Снимок ДО и ПОСЛЕ — единственный способ сделать ключ проверяемым.
        # Обещание «мы автозапуск не трогаем» ключом не является: setup
        # исполняется отдельной программой, и запретить ей что-либо этот
        # файл не может. Заметить — может, и тогда об этом будет сказано.
        AUTO_BEFORE=''
        if [ "$NO_AUTOSTART" -eq 1 ]; then
            AUTO_BEFORE="$(autostart_snapshot "$GARANT")"
        fi

        if [ "$NO_LOGIN" -eq 1 ]; then
            # PYTHONUTF8=1 не украшение: ключ кириллический, а Python
            # декодирует argv кодировкой локали. При LANG=C аргумент
            # приехал бы искажённым, пульт бы его не узнал и молча открыл
            # окно входа — то есть ключ бы не сработал, не сказав об этом.
            PYTHONUTF8=1 "$GARANT" setup --без-входа
        else
            "$GARANT" setup
        fi
        RC=$?

        if [ "$NO_AUTOSTART" -eq 1 ]; then
            AUTO_AFTER="$(autostart_snapshot "$GARANT")"
            if [ -z "$AUTO_BEFORE" ] || [ -z "$AUTO_AFTER" ]; then
                # Молча пропущенная проверка хуже отсутствующей: говорим
                # вслух, что ключ остался непроверенным, а не делаем вид,
                # что всё сошлось.
                mark_skip "состояние автозапуска спросить не удалось — ключ --no-autostart НЕ проверен"
                hint "Посмотреть руками:  garant autostart status"
            elif [ "$AUTO_BEFORE" != "$AUTO_AFTER" ]; then
                mark_fail "автозапуск изменился, хотя запрошен ключ --no-autostart"
                hint "было:  $AUTO_BEFORE"
                hint "стало: $AUTO_AFTER"
                hint "Снять:  garant autostart off"
            else
                # Имя ключа обещает больше, чем ключ делает, и сводка обязана
                # назвать факт. Установщик автозапуска не заводит НИ ПРИ КАКИХ
                # ключах: `garant setup` его не касается, а запретить чужой
                # программе установщик и не может. Работа ключа — сверка, что
                # состояние не изменилось. Без этой оговорки читатель сводки
                # вправе решить, что ключ что-то предотвратил.
                mark_skip "автозапуск не появился — сверено «garant autostart status» до и после setup: $AUTO_BEFORE. Предотвращать было нечего: установщик автозапуска не заводит ни при каких ключах"
            fi
        fi

        if [ "$RC" -eq 0 ]; then
            mark_done "garant setup прошёл целиком"
        else
            # Формулировка называет ГРАНИЦУ: пакет стоит и команда работает,
            # не доделана настройка после установки. Прежнее «сделано не всё»
            # оставляло человека гадать, что именно не так, — а список уже
            # напечатан выше самим setup, последним шагом которого идёт
            # диагностика.
            mark_fail "пакет установлен, но настройка после установки доделана не до конца (garant setup, код $RC)"
            hint "ЧТО именно не доделано — красные пункты в разделе ДИАГНОСТИКА"
            hint "выше, у каждого названа своя команда починки. Показать снова:"
            hint "  garant doctor"
        fi
    fi
fi

