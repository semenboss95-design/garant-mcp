# -*- coding: utf-8 -*-
"""Автозапуск демона при входе в систему. Необязательная опция.

По умолчанию выключено, и это не забывчивость: демона поднимает сам сервер
при первом обращении инструмента. Автозапуск нужен ровно за одним — чтобы
keepalive шёл и тогда, когда MCP-клиент за день ни разу не открывали,
и сессия подписки не отваливалась к вечеру.

Во всех трёх ОС запись ссылается на `garant-daemon` ПО ИМЕНИ, из PATH.
Абсолютный путь здесь и был тем дефектом, с которого начался этап 02:
обновление пакета переставляло код, а задача планировщика продолжала
указывать в исчезнувший каталог — и молча не запускалась.

ПОЧЕМУ ОДНОГО ИМЕНИ МАЛО. Окружение автозапуска — не окружение оболочки.
launchd даёт агенту PATH из четырёх системных каталогов, `systemd --user`
даёт свой, столь же короткий; каталога, куда `uv tool` или `pipx` кладут
`garant-daemon`, там нет ни у кого. На Windows задача берёт PATH из
реестра, и установка, поправившая PATH только в текущем сеансе оболочки,
даёт тот же исход. То есть запись «запусти garant-daemon» в нормальном
случае молча не срабатывает.

Поэтому `on` разрешает имя через PATH СВОЕЙ оболочки и кладёт найденный
КАТАЛОГ в окружение запуска записи. Какой именно каталог — сказать надо точно,
потому что `resolve()` ИДЁТ ПО СИМВОЛЬНОЙ ССЫЛКЕ: под `uv tool` и `pipx`
на POSIX `~/.local/bin/garant-daemon` — ссылка в venv самого инструмента,
и в запись ляжет `bin` этого venv, а не каталог, где оказалось имя в PATH.
Возврата к дефекту от этого нет: имя такого каталога у обоих установщиков
задаётся именем пакета и обновление его не переставляет — переставляется
содержимое, а не путь. Абсолютного пути к КОДУ (модулям пакета) в записи
по-прежнему нет. Ломает запись только смена способа установки, и тогда
`состояние()` об этом скажет — см. ниже.

ТРИ СОСТОЯНИЯ, А НЕ ДВА. «Запись есть» и «запись сработает» — разные вещи,
и называть первое вторым нельзя: именно так doctor показывал зелёным задачу
прежнего установщика, ведущую в каталог, которого больше нет. Различаются
НЕТ, НАША и ЧУЖАЯ (запись с нашим именем, ведущая не туда либо в никуда);
когда проверить нечем — НЕИЗВЕСТНО, и это не «стоит».

`off` обязана убирать ровно то, что поставила `on`, и говорить, что убрала:
«готово» без называния убранного не проверяется никем, включая автора.

НИ ОДНОГО mkdir И НИ ОДНОГО ЗАПУСКА ПРОЦЕССА НА ИМПОРТЕ.
"""

from __future__ import annotations

import os
import shutil
import subprocess
import sys
from pathlib import Path
from xml.sax.saxutils import escape as _xml

from . import paths

# Имя записи одно на все три ОС: по нему её и находят, и снимают.
ИМЯ = "GarantDaemon"
СЛУЖБА = "garant-daemon"

# Почему на POSIX запись идёт через `/usr/bin/env`: launchd и systemd
# программу в PATH сами не ищут, а имя из PATH — ровно то, что переживает
# обновление пакета. `/usr/bin/env` — путь системный, он есть на всякой
# POSIX-машине и ничьей машины не называет.

# То, что launchd выдаёт агенту по умолчанию. Пишется в запись рядом
# с найденным каталогом, а не вместо него: убрать системные каталоги значит
# отнять у демона `env`, `python` и всё, чем он пользуется дальше.
_БАЗОВЫЙ_PATH = "/usr/bin:/bin:/usr/sbin:/sbin"

# Коды состояния записи. Строки, а не флаги: они уходят и в doctor, и в тесты.
НЕТ = "нет"
НАША = "наша"
ЧУЖАЯ = "чужая"
НЕИЗВЕСТНО = "неизвестно"

СОВЕТ_УСТАНОВКИ = (
    "uv tool install --force garant-mcp   (или pipx install --force garant-mcp)")


class НетПоддержки(RuntimeError):
    """ОС, для которой автозапуска не написано. Молчать об этом нельзя."""


def _ос() -> str:
    if os.name == "nt":
        return "windows"
    if sys.platform == "darwin":
        return "macos"
    if sys.platform.startswith("linux"):
        return "linux"
    raise НетПоддержки(
        "Автозапуск для {} не написан. Демон при этом работает: его поднимает "
        "сервер при первом обращении инструмента — автозапуск нужен только "
        "затем, чтобы сессия жила в дни, когда MCP-клиент не открывали."
        .format(sys.platform))


def _каталог_запуска() -> str | None:
    """Каталог исполняемого файла `garant-daemon`, найденного PATH этой оболочки.

    Именно исполняемого файла, а не места, где имя нашлось: `resolve()`
    разыменовывает символьную ссылку, и под `uv tool`/`pipx` это `bin`
    служебного venv (см. докстроку модуля — там же, почему это не дефект 02).

    None означает «имя не разрешается», и это отказ, а не предупреждение:
    записывать автозапуск на программу, которой мы сами найти не смогли,
    значит обещать пользователю то, чего не будет.
    """
    найдено = shutil.which(СЛУЖБА)
    return str(Path(найдено).resolve().parent) if найдено else None


def _выполнить(аргументы: list[str]) -> tuple[int, str]:
    """Запустить внешнюю команду и вернуть код с выводом.

    Код возврата возвращается вызывающему, а не проверяется здесь: «сделано»
    без проверки кода — это в точности та ошибка прежнего установщика,
    который печатал «ок» после провала.

    Кодировка на Windows — `oem`, а не utf-8: `schtasks` пишет в кодировке
    консоли, и её вывод (в том числе путь с кириллицей в имени пользователя)
    под utf-8 превращается в замену символов. Сравнивать такое с найденным
    каталогом нельзя — запись собственной установки читалась бы как чужая.
    """
    кодировка = "oem" if os.name == "nt" else "utf-8"
    try:
        p = subprocess.run(аргументы, capture_output=True, text=True,
                           encoding=кодировка, errors="replace", timeout=60)
    except (OSError, subprocess.SubprocessError) as e:
        return 127, "{}: {}".format(type(e).__name__, e)
    return p.returncode, (p.stdout or "") + (p.stderr or "")


# --- Windows: планировщик задач --------------------------------------------
def _windows_действие(каталог: str) -> str:
    """Строка `/TR`: PATH дополняется найденным каталогом, программа — по имени.

    Обёртка `cmd /c` нужна затем, что у задачи планировщика нет поля
    окружения: XML планировщика его не описывает вовсе. Кавычки вокруг
    присваивания — форма `set "PATH=..."`, единственная, которая переживает
    каталог с пробелом или амперсандом в имени.
    """
    return 'cmd /c set "PATH={};%PATH%" & {}'.format(каталог, СЛУЖБА)


def _windows_вкл(каталог: str) -> tuple[bool, str]:
    # /SC ONLOGON — при входе ЭТОГО пользователя: демон держит его личную
    # сессию подписки, и запускать его от имени системы нечего.
    # /F — перезапись: запись с нашим именем, оставшаяся от прежней
    # установки, обязана уйти, а не пережить включение (см. включить()).
    код, вывод = _выполнить([
        "schtasks", "/Create", "/TN", ИМЯ, "/TR", _windows_действие(каталог),
        "/SC", "ONLOGON", "/F"])
    if код != 0:
        return False, "планировщик отказал (код {}): {}".format(код, вывод.strip())
    return True, ("задача планировщика {} создана: запускает {} при входе, "
                  "каталог запуска {}".format(ИМЯ, СЛУЖБА, каталог))


def _windows_выкл() -> tuple[bool, str]:
    опрошено, запись = _windows_запись()
    if опрошено and not запись:
        return True, "задачи {} нет — снимать нечего".format(ИМЯ)
    код, вывод = _выполнить(["schtasks", "/Delete", "/TN", ИМЯ, "/F"])
    if код != 0:
        return False, "планировщик отказал (код {}): {}".format(код, вывод.strip())
    return True, "задача планировщика {} удалена".format(ИМЯ)


def _windows_запись() -> tuple[bool, str]:
    """(опрошено, что записано). Пустая строка при успешном опросе — записи нет.

    Спрашивается `/XML`, а не `/FO LIST`: имена полей списочного вывода
    переведены на язык системы, и разбор по ним ломается на первой же машине
    с другой локалью. В XML имена узлов постоянны.
    """
    код, вывод = _выполнить(["schtasks", "/Query", "/TN", ИМЯ, "/XML", "ONE"])
    if код == 127:
        # Самого schtasks нет или он не запустился — это «не выяснили»,
        # а не «записи нет»: второе утверждать не на чем.
        return False, ""
    if код != 0:
        # Ненулевой код при работающем schtasks означает «такой задачи нет».
        # Разбирать текст ошибки нельзя по той же причине, что и /FO LIST.
        return True, ""
    return True, вывод


# --- macOS: launchd --------------------------------------------------------
def _plist_путь() -> Path:
    return Path.home() / "Library" / "LaunchAgents" / "com.garant-mcp.daemon.plist"


_PLIST = """<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN"
  "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key><string>com.garant-mcp.daemon</string>
  <key>ProgramArguments</key>
  <array><string>/usr/bin/env</string><string>{служба}</string></array>
  <key>EnvironmentVariables</key>
  <dict><key>PATH</key><string>{каталог}:{база}</string></dict>
  <key>RunAtLoad</key><true/>
</dict>
</plist>
"""


def _macos_вкл(каталог: str) -> tuple[bool, str]:
    путь = _plist_путь()
    путь.parent.mkdir(parents=True, exist_ok=True)
    # Выгрузка перед перезаписью: launchd держит в памяти загруженную
    # версию агента, и запись файла поверх неё ничего не меняет до
    # перелогина — то есть «заменили» было бы неправдой.
    _выполнить(["launchctl", "unload", "-w", str(путь)])
    путь.write_text(_PLIST.format(служба=СЛУЖБА, каталог=_xml(каталог),
                                  база=_БАЗОВЫЙ_PATH), encoding="utf-8")
    код, вывод = _выполнить(["launchctl", "load", "-w", str(путь)])
    if код != 0:
        return False, "launchctl отказал (код {}): {}\nАгент записан: {}".format(
            код, вывод.strip(), путь.name)
    return True, "агент launchd {} записан и загружен, каталог запуска {}".format(
        путь.name, каталог)


def _macos_выкл() -> tuple[bool, str]:
    путь = _plist_путь()
    if not путь.exists():
        return True, "агента launchd нет — снимать нечего"
    _выполнить(["launchctl", "unload", "-w", str(путь)])
    путь.unlink()
    return True, "агент launchd {} выгружен и удалён".format(путь.name)


def _macos_запись() -> tuple[bool, str]:
    return _прочитать_файл(_plist_путь())


# --- Linux: systemd --user -------------------------------------------------
def _unit_путь() -> Path:
    return Path.home() / ".config" / "systemd" / "user" / "garant-daemon.service"


_UNIT = """[Unit]
Description=garant-daemon — владелец браузерного профиля «Гаранта»

[Service]
Environment="PATH={каталог}:{база}"
ExecStart=/usr/bin/env {служба}
Restart=on-failure

[Install]
WantedBy=default.target
"""


def _linux_вкл(каталог: str) -> tuple[bool, str]:
    путь = _unit_путь()
    путь.parent.mkdir(parents=True, exist_ok=True)
    путь.write_text(_UNIT.format(служба=СЛУЖБА, каталог=каталог,
                                 база=_БАЗОВЫЙ_PATH), encoding="utf-8")
    _выполнить(["systemctl", "--user", "daemon-reload"])
    код, вывод = _выполнить(["systemctl", "--user", "enable", путь.name])
    if код != 0:
        return False, "systemctl отказал (код {}): {}\nЮнит записан: {}".format(
            код, вывод.strip(), путь.name)
    return True, "юнит systemd {} записан и включён, каталог запуска {}".format(
        путь.name, каталог)


def _linux_выкл() -> tuple[bool, str]:
    путь = _unit_путь()
    if not путь.exists():
        return True, "юнита systemd нет — снимать нечего"
    _выполнить(["systemctl", "--user", "disable", "--now", путь.name])
    путь.unlink()
    _выполнить(["systemctl", "--user", "daemon-reload"])
    return True, "юнит systemd {} выключен и удалён".format(путь.name)


def _linux_запись() -> tuple[bool, str]:
    return _прочитать_файл(_unit_путь())


def _прочитать_файл(путь: Path) -> tuple[bool, str]:
    """(опрошено, содержимое). Нечитаемый существующий файл — «не выяснили»."""
    try:
        if not путь.exists():
            return True, ""
        return True, путь.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return False, ""


# --- общий интерфейс -------------------------------------------------------
_ТАБЛИЦА = {
    "windows": (_windows_вкл, _windows_выкл, _windows_запись,
                "задача планировщика " + ИМЯ),
    "macos": (_macos_вкл, _macos_выкл, _macos_запись, "агент launchd"),
    "linux": (_linux_вкл, _linux_выкл, _linux_запись, "юнит systemd --user"),
}


def _разобрать(опрошено: bool, содержимое: str, каталог: str | None,
               что: str) -> tuple[str, str]:
    """Код состояния записи и строка о нём.

    Признак «наша» — вхождение имени службы И найденного каталога, а не
    посимвольное равенство эталону. Причина в том, что хранилище записи наше
    только на POSIX: планировщик Windows отдаёт `/TR` уже разобранным на
    команду и аргументы и волен нормализовать кавычки. Равенство эталону
    объявляло бы чужой запись, только что созданную нами, — то есть врало бы
    в другую сторону. Оба случая, ради которых состояние и различается,
    вхождением ловятся: запись прежнего установщика имени службы не содержит
    вовсе, а запись, пережившая смену способа установки, содержит имя,
    но другой каталог.
    """
    if not опрошено:
        return НЕИЗВЕСТНО, "{}: спросить не удалось — состояние неизвестно".format(что)
    if not содержимое:
        return НЕТ, "{}: не стоит".format(что)
    if каталог is None:
        return НЕИЗВЕСТНО, (
            "{}: запись есть, но {} сейчас в PATH не находится — куда она "
            "ведёт, проверить нечем".format(что, СЛУЖБА))
    низ = содержимое.lower()
    # Каталог ищется и сырым, и XML-экранированным. Хранилище записи —
    # XML в обоих случаях, где символ вообще может встретиться: plist на
    # macOS пишется через escape(), а `schtasks /Query /XML` отдаёт `/TR`
    # уже экранированным. Сравнение только с сырым объявляло бы чужой
    # собственную рабочую запись, стоило каталогу содержать «&», «<» или
    # «>» — при том что `_windows_действие` этот случай отдельно переживает.
    варианты = (каталог.lower(), _xml(каталог).lower())
    if СЛУЖБА in низ and any(в in низ for в in варианты):
        return НАША, "{}: стоит, запускает {} из {}".format(что, СЛУЖБА, каталог)
    return ЧУЖАЯ, (
        "{}: запись с этим именем есть, но ведёт не на {} из {} — сработать "
        "она не может".format(что, СЛУЖБА, каталог))


def проверить() -> tuple[str, str]:
    """Код состояния (НЕТ/НАША/ЧУЖАЯ/НЕИЗВЕСТНО) и строка о нём.

    Ничего не меняет: только опрос. `НетПоддержки` не гасится — решать,
    считать ли неподдержанную ОС отказом, вызывающему.
    """
    _вкл, _выкл, читать, что = _ТАБЛИЦА[_ос()]
    опрошено, содержимое = читать()
    return _разобрать(опрошено, содержимое, _каталог_запуска(), что)


def включить() -> tuple[bool, str]:
    вкл, _выкл, читать, что = _ТАБЛИЦА[_ос()]
    каталог = _каталог_запуска()
    if каталог is None:
        # Отказ, а не запись «на авось»: запись, которая не сможет запустить
        # программу, неотличима снаружи от работающей — это ровно тот
        # молчаливый провал, ради которого затевался шаг.
        return False, (
            "{} не найден в PATH — автозапуск не создаю: запись, которая "
            "его не запустит, выглядит как работающая и молчит. Поставьте "
            "пакет так, чтобы имя оказалось в PATH:\n  {}\nи повторите "
            "{}".format(СЛУЖБА, СОВЕТ_УСТАНОВКИ,
                        paths.команда("autostart", "on")))
    код, _текст = _разобрать(*читать(), каталог, что)
    if код == НАША:
        return True, "{} уже стоит и ведёт куда надо — ничего не меняю".format(что)
    ок, сообщение = вкл(каталог)
    if код == ЧУЖАЯ and ок:
        # Перезаписываем молча-но-вслух, а не требуем согласия отдельным
        # ключом: имя записи наше, `on` — уже явная команда, а оставленная
        # чужая запись это автозапуск, который падает при каждом входе.
        # Требование «подтвердите» оставило бы поломку стоять ровно у того,
        # кто обновляется, — то есть у всех.
        return True, "прежняя запись с именем {} заменена; {}".format(ИМЯ, сообщение)
    return ок, сообщение


def выключить() -> tuple[bool, str]:
    _вкл, выкл, _читать, _что = _ТАБЛИЦА[_ос()]
    return выкл()


def состояние() -> str:
    """Строка о том, стоит ли автозапуск. Ничего не меняет — можно звать из doctor.

    «Стоит» отсюда выходит только про запись, про которую это проверено:
    прежняя семантика называла так сам факт наличия записи с нашим именем.
    """
    try:
        return проверить()[1]
    except НетПоддержки as e:
        return str(e).splitlines()[0]
