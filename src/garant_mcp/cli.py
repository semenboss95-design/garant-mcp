СОВЕТ_ОБНОВИТЬ = ("uv tool upgrade garant-mcp   (либо pipx upgrade garant-mcp "
                  "— тем, чем ставили)")
СОВЕТ_СНЯТЬ = ("uv tool uninstall garant-mcp   (либо pipx uninstall garant-mcp "
               "— тем, чем ставили)")


def _чем_поставлено() -> tuple[str | None, str]:
    """Каким инструментом установлен пакет: «uv», «pipx» либо None.

    Спрашивается у того места, где лежит наш собственный код: `uv tool`
    и `pipx` держат окружения каждый в своём каталоге, и путь до пакета —
    это факт про эту установку, а не память о том, что человек когда-то
    набрал. Спрашивать `uv tool list` мало: обе программы могут стоять
    на машине одновременно, и обе ответят про свои установки, а обновить
    надо ту, которой исполняется этот процесс.

    Не выяснилось — None. Выполнить неверную команду обновления хуже, чем
    не выполнить никакой: `pipx upgrade` при установке через uv молча
    поставит ВТОРУЮ копию, и дальше человек будет чинить не то.
    """
    части = {ч.lower() for ч in paths.HOME.parts}
    if "pipx" in части:
        return "pipx", "код лежит в окружении pipx: {}".format(paths.HOME)
    if "uv" in части and "tools" in части:
        return "uv", "код лежит в окружении uv tool: {}".format(paths.HOME)
    return None, "код лежит в {} — это не окружение uv tool и не окружение " \
                 "pipx".format(paths.HOME)


def update() -> int:
    """Обновить пакет, перезапустить демона, показать диагностику.

    Перезапускается ПРОЦЕСС демона, а не браузерный контекст: старый процесс
    импортировал старый код на старте и продолжит его исполнять, сколько бы
    раз ни пересоздал контекст, — то есть «обновились» было бы неправдой
    ровно у того, кто обновление и делает.

    Профиль подписки обновление не трогает и тронуть не может: он живёт
    в каталоге состояния, а переустанавливается каталог кода (решение 14).
    Повторный вход после обновления не требуется, и это здесь говорится
    вслух — иначе человек, увидев перезапуск демона, начнёт входить сам.
    """
    from . import daemon_client as dc

    print("{0}{0}{0} ОБНОВЛЕНИЕ garant-mcp {0}{0}{0}\n".format(РАМКА))
    print("1/3 чем поставлен пакет")
    чем, почему = _чем_поставлено()
    if чем is None:
        return _отказ(
            "не понял, чем поставлен пакет: {}. Ничего не обновляю: неверная "
            "команда обновления поставит вторую копию рядом с работающей. "
            "Обновите тем, чем ставили:\n  {}".format(почему, СОВЕТ_ОБНОВИТЬ))
    if not shutil.which(чем):
        return _отказ(
            "{} — но самого «{}» в PATH нет, обновлять нечем. Ничего "
            "не тронуто.".format(почему, чем))
    _печать(ОК, почему)

    print("\n2/3 обновление пакета")
    аргументы = ([чем, "tool", "upgrade", "garant-mcp"] if чем == "uv"
                 else [чем, "upgrade", "garant-mcp"])
    print("  выполняю: " + " ".join(аргументы))
    код = subprocess.call(аргументы)
    if код != 0:
        # Демона при этом не трогаем намеренно: он работает на прежнем коде,
        # то есть на том, который у человека до сих пор работал. Перезапуск
        # после неудачного обновления только отнял бы у него рабочий контур.
        return _отказ("«{}» вернул код {}. Демона не трогаю: он работает "
                      "на прежнем коде.".format(" ".join(аргументы), код))
    _печать(ОК, "пакет обновлён")
    print("  вход в подписку не потребуется: профиль живёт в {} и "
          "обновлением пакета не затрагивается".format(paths.STATE))

    print("\n3/3 перезапуск демона")
    if dc.адрес()["alive"]:
        код = restart()
        if код != КОД_ОК:
            return _отказ("демон не перезапущен — он остался на прежнем коде. "
                          "Повторите: " + paths.команда("restart"))
    else:
        _печать(ОК, "демон не работает — старый код держать некому")

    print("\nдиагностика\n")
    return doctor()


def _подтверждено(вопрос: str, слово: str) -> tuple[bool, str]:
    """Согласие человека на необратимое: (да/нет, почему нет).

    Нет терминала — «нет», а не «да». Пульт зовут из установщика, из задачи
    планировщика и из тестов, и там `input()` получает EOF мгновенно; счесть
    это согласием значит удалить профиль с живым входом в подписку у того,
    кто ни о чём не просил.
    """
    try:
        интерактивно = bool(sys.stdin) and sys.stdin.isatty()
    except Exception:
        интерактивно = False
    if not интерактивно:
        return False, "ввод не терминал — спросить некого"
    try:
        ответ = input(вопрос).strip().lower()
    except (EOFError, KeyboardInterrupt):
        return False, "ответа нет"
    if ответ != слово:
        return False, "введено не «{}»".format(слово)
    return True, ""


def _что_осталось(чем: str | None) -> None:
    """Назвать поимённо всё, что после uninstall осталось на машине.

    Это половина смысла команды. «Удалено» без «осталось» — обещание,
    которое человек не может проверить, а проверять он будет именно то,
    что мы не удалили: каталог с профилем подписки и кэш браузеров.
    """
    print("\nОСТАЛОСЬ НА МАШИНЕ:")
    print("  · каталог состояния: {}".format(paths.STATE))
    print("      токен, порт, логи, кэш, отпечаток{}. Это ваш каталог — "
          "удалите его сами, если он не нужен."
          .format(", профиль подписки" if paths.profile_dir.exists() else ""))
    каталог, беда = _место_браузеров()
    print("  · кэш браузеров playwright: {}".format(каталог or "не выяснен ({})"
                                                    .format(беда)))
    # Playwright называет место установки и тогда, когда ни разу туда ничего
    # не ставил, — а по этому пункту человек идёт смотреть глазами. Обещать
    # оставленное там, где ничего нет, значит соврать ровно в том списке,
    # ради которого команда и печатает «осталось». Невыясненное место
    # (каталог is None) содержимым не описываем: неизвестность не факт.
    if каталог is not None and not os.path.exists(каталог):
        print("      каталога нет — playwright сюда ничего не ставил, "
              "удалять нечего.")
    elif каталог is not None and not any(Path(каталог).glob("*")):
        print("      каталог пуст — playwright сюда ничего не ставил, "
              "удалять нечего.")
    else:
        print("      не трогаю: он общий для всех окружений этой машины, и его "
              "используют другие программы на playwright.")
    print("  · сам пакет garant-mcp. Снять:\n      {}".format(
        "{} tool uninstall garant-mcp".format(чем) if чем == "uv"
        else "pipx uninstall garant-mcp" if чем == "pipx" else СОВЕТ_СНЯТЬ))


def uninstall(purge: bool = False, без_вопросов: bool = False) -> int:
    """Снять поставленное и сказать, что осталось.

    `--purge` и подтверждение — два разных условия, и оба обязательны для
    профиля. Флаг говорит «я имею в виду профиль», подтверждение — «я имею
    в виду сейчас». Ключ `--yes` второе условие НЕ снимает: он существует
    для установщика и для скрипта, а цена ошибки у профиля ровно одна —
    повторный ручной вход в подписку, и платит её человек, а не скрипт.
    """
    from . import autostart
    from . import register

    print("{0}{0}{0} СНЯТИЕ garant-mcp {0}{0}{0}\n".format(РАМКА))
    # Список считается ДО вопроса: человек соглашается на то, что ему назвали.
    # Codex попадает в него, только если наша запись у него есть, — снимать
    # её надо (это наша запись), а называть клиента, которого нет, незачем.
    цели_записей = [register.цель_desktop(), register.цель_code()]
    if register.статус(register.цель_codex()) == "зарегистрирован":
        цели_записей.append(register.цель_codex())
    print("Будет снято: регистрация у {}, автозапуск; демон остановлен."
          .format(", ".join(ц.имя for ц in цели_записей)))
    print("Профиль подписки ({}): {}".format(
        paths.profile_dir,
        "БУДЕТ УДАЛЁН — вход придётся выполнить заново" if purge
        else "останется, вход сохранится"))
    if not без_вопросов:
        ок, почему = _подтверждено("Продолжить? введите «y»: ", "y")
        if not ок:
            return _отказ("ничего не тронуто ({}). Подтвердить заранее: {}"
                          .format(почему, paths.команда("uninstall", "--yes")))
    неудач = 0

    print("\n1/4 демон")
    неудач += 1 if stop() != КОД_ОК else 0

    print("\n2/4 регистрация у MCP-клиентов")
    for цель in цели_записей:
        ок, текст = register.снять(цель)
        _печать(ОК if ок else ПЛОХО, текст)
        неудач += 0 if ок else 1
    print("  регистрации в отдельных проектах (.mcp.json) отсюда не видны — "
          "снимаются: " + paths.команда("unregister", "--project", "ПУТЬ"))

    print("\n3/4 автозапуск")
    try:
        ок, текст = autostart.выключить()
    except autostart.НетПоддержки as e:
        _печать(ВНИМАНИЕ, str(e).splitlines()[0])
    else:
        _печать(ОК if ок else ПЛОХО, текст)
        неудач += 0 if ок else 1

    print("\n4/4 профиль подписки")
    if not paths.profile_dir.exists():
        _печать(ОК, "каталога профиля нет — удалять нечего")
    elif not purge:
        _печать(ОК, "оставлен: {}".format(paths.profile_dir))
        print("  в нём живой вход в подписку. Удалить вместе с ним: "
              + paths.команда("uninstall", "--purge"))
    else:
        ок, почему = _подтверждено(
            "Удалить профиль с живым входом? введите «удалить»: ", "удалить")
        if not ок:
            неудач += 1
            _печать(ВНИМАНИЕ, "профиль НЕ удалён ({}): {}".format(
                почему, paths.profile_dir))
        else:
            try:
                shutil.rmtree(paths.profile_dir)
            except OSError as e:
                неудач += 1
                _печать(ПЛОХО, "профиль удалить не удалось ({}: {}). Обычно "
                        "это живой chromium — остановите его и повторите: {}"
                        .format(type(e).__name__, e,
                                paths.команда("uninstall", "--purge")))
            else:
                _печать(ОК, "профиль удалён: {}".format(paths.profile_dir))

    чем, _почему = _чем_поставлено()
    _что_осталось(чем)
    if неудач:
        return _отказ("снято не всё: {} пункт(ов) выше не сделаны. Повторный "
                      "запуск безопасен.".format(неудач))
    print("\n{} снято всё перечисленное. Повторный запуск безопасен.".format(ОК))
    return КОД_ОК


# Признаки каталога профиля Chromium. Ими же он опознаётся у чужой раскладки:
# имя каталога у старой установки могло быть любым, а эти два файла кладёт
# сам браузер.
def _похоже_на_профиль(путь) -> bool:
    return путь.is_dir() and ((путь / "Default").is_dir()
                              or (путь / "Local State").exists())


def _где_профиль(корень):
    """Найти профиль в том, на что указал человек. None — не нашли.

    По указанному пути лежит что угодно: каталог состояния старой установки,
    клон репозитория с профилем внутри, сам каталог профиля. Поэтому список
    мест, а не одно, — и он же печатается при неудаче, чтобы человек указал
    точнее, а не гадал.
    """
    имя = paths.ПРОФИЛЬ
    for относительно in ("", имя, "garant-mcp/" + имя, "src/garant_mcp/" + имя):
        кандидат = корень / относительно if относительно else корень
        if _похоже_на_профиль(кандидат):
            return кандидат
    return None


def _профиль_занят() -> bool:
    """Держит ли кто-то замок профиля прямо сейчас.

    Проверяется в дополнение к `/health`: демон, застрявший на подъёме
    chromium, на `/health` ещё не отвечает, но профилем уже владеет —
    и именно в это окно перенос попал бы файлами по живому.
    """
    if not paths.profile_lock_file.exists():
        return False
    try:
        файл = open(paths.profile_lock_file, "a+b")
    except OSError:
        return True
    try:
        if os.name == "nt":
            import msvcrt

            файл.seek(0)
            msvcrt.locking(файл.fileno(), msvcrt.LK_NBLCK, 1)
            файл.seek(0)
            msvcrt.locking(файл.fileno(), msvcrt.LK_UNLCK, 1)
        else:
            import fcntl

            fcntl.flock(файл.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
            fcntl.flock(файл.fileno(), fcntl.LOCK_UN)
    except OSError:
        return True
    finally:
        файл.close()
    return False


def migrate(источник: str) -> int:
    """Перенести профиль из старой установки. Копия; оригинал не трогается.

    Копия, а не перемещение, — потому что цена неудачной операции здесь
    ровно один повторный ручной вход в подписку, и человеку должно остаться
    то, с чего он начал. Ничего в исходном каталоге эта функция не пишет
    и не удаляет.
    """
    from . import daemon_client as dc
    from . import fingerprint

    корень = Path(os.path.abspath(os.path.expanduser(
        источник.strip().strip('"'))))
    print("{0}{0}{0} ПЕРЕНОС ПРОФИЛЯ {0}{0}{0}\n".format(РАМКА))
    if not корень.exists():
        return _отказ("нет такого пути: {}".format(корень))

    # Порядок проверок не случаен: сначала «кто держит профиль», потом всё
    # остальное. Копирование профиля Chromium на ходу даёт профиль, который
    # выглядит целым и не работает, а лечится он тем самым повторным входом,
    # ради отмены которого перенос и делается.
    if dc.адрес()["alive"] or _профиль_занят():
        return _отказ(
            "демон работает и владеет профилем. Перенос на ходу ломает "
            "профиль Chromium. Остановите и повторите:\n  {}\n  {}"
            .format(paths.команда("stop"), paths.команда("migrate", источник)))

    откуда = _где_профиль(корень)
    if откуда is None:
        return _отказ(
            "профиля не нашёл. Искал каталог с «Default» или «Local State» "
            "здесь: сам путь, «{0}», «garant-mcp/{0}», «src/garant_mcp/{0}» "
            "внутри {1}. Укажите путь прямо к каталогу профиля."
            .format(paths.ПРОФИЛЬ, корень))
    куда = paths.profile_dir
    if куда.exists() and any(куда.iterdir()):
        return _отказ(
            "в целевом каталоге уже есть профиль: {}. Молча затирать его "
            "нельзя — в нём может быть живой вход. Уберите его сами либо "
            "снимите вместе с установкой ({}) и повторите перенос."
            .format(куда, paths.команда("uninstall", "--purge")))

    paths.ensure_state()
    # Копируем во временное имя и переименовываем: оборванная на середине
    # копия под настоящим именем выглядит как готовый профиль, и следующий
    # запуск открыл бы её — то есть тихо сломанную сессию вместо честного
    # «переноса не было».
    врем = куда.with_name(куда.name + ".копируется")
    if врем.exists():
        shutil.rmtree(врем, ignore_errors=True)
    print("копирую {}\n     в {}".format(откуда, куда))
    try:
        # Singleton* — служебные ссылки работающего chromium: на POSIX это
        # симлинки в никуда, copytree на них падает, а на новой машине они
        # всё равно недействительны.
        shutil.copytree(откуда, врем,
                        ignore=shutil.ignore_patterns("Singleton*"),
                        symlinks=True, ignore_dangling_symlinks=True)
    except (OSError, shutil.Error) as e:
        shutil.rmtree(врем, ignore_errors=True)
        return _отказ("копирование не удалось ({}: {}). Целевой каталог "
                      "оставлен пустым, оригинал не тронут."
                      .format(type(e).__name__, e))
    файлов = байтов = 0
    for каталог, _, имена in os.walk(врем):
        for имя in имена:
            файлов += 1
            try:
                байтов += os.path.getsize(os.path.join(каталог, имя))
            except OSError:
                pass
    if куда.exists():
        куда.rmdir()
    os.replace(врем, куда)
    _печать(ОК, "профиль скопирован: {} файлов, {:.1f} МБ".format(
        файлов, байтов / 1048576))
    _печать(ОК, "оригинал не тронут: {}".format(откуда))

    # Отпечаток. Сессия в перенесённом профиле выдана окну с отпечатком СТАРОЙ
    # установки (ограничение 3), а у новой отпечаток свой, снятый с этой
    # машины. Разойдясь, они дают Unauthorized, который читается как
    # «сессия истекла», — поэтому отпечаток переносится вместе с профилем,
    # а когда переносить нечего, об этом говорится вслух.
    старый = откуда.parent / paths.fingerprint_file.name
    print()
    if старый.exists():
        # .bak делается только когда есть что откладывать. Строка о нём
        # печаталась безусловно и обещала файл, которого на чистой установке
        # не было вовсе.
        свой = paths.fingerprint_file.with_name(
            paths.fingerprint_file.name + ".bak")
        отложен = paths.fingerprint_file.exists()
        if отложен:
            shutil.copy2(paths.fingerprint_file, свой)
        shutil.copy2(старый, paths.fingerprint_file)
        # Галочка ставится по ПРОЧИТАННОМУ отпечатку, а не по тому, что
        # copy2 не бросил исключения: скопировать можно и файл без
        # user_agent, и тогда «✓ перенесён» стояло в одном выводе со
        # следующей же строкой «отпечаток: не снят».
        #
        # Годность спрашивается у fingerprint.прочитать(), а не проверяется
        # здесь по ключам: правило годности одно, и второе его написание
        # разошлось бы с первым молча.
        if fingerprint.прочитать() is not None:
            _печать(ОК, "отпечаток перенесён вместе с профилем: " + старый.name)
            if отложен:
                print("  сессия привязана к отпечатку окна входа — свой, снятый "
                      "с этой машины, отложен в .bak")
        else:
            # Негодным файлом свой отпечаток уже затёрт — возвращаем, что было.
            # Иначе неудачный перенос молча ухудшал бы установку: до него
            # отпечаток был, после него нет.
            if отложен:
                shutil.copy2(свой, paths.fingerprint_file)
            else:
                paths.fingerprint_file.unlink(missing_ok=True)
            _печать(ВНИМАНИЕ, "файл отпечатка старой установки не читается "
                              "как отпечаток — перенести нечего: " + старый.name)
            print("  {} Сессия «Гаранта» привязана к отпечатку браузера, а у "
                  "этой установки он свой.".format(ВНИМАНИЕ))
            print("  Если «Гарант» ответит Unauthorized — это оно, а не "
                  "истёкшая подписка. Лечится входом: " + paths.команда("login"))
    else:
        _печать(ВНИМАНИЕ, "отпечатка у старой установки нет — перенести нечего")
        print("  {} Сессия «Гаранта» привязана к отпечатку браузера, а у этой "
              "установки он свой.".format(ВНИМАНИЕ))
        print("  Если «Гарант» ответит Unauthorized — это оно, а не истёкшая "
              "подписка. Лечится входом: " + paths.команда("login"))
    print("  сейчас: " + fingerprint.описание())

    print("\nДальше: {}\n        {}".format(
        paths.команда("start"), paths.команда("doctor", "--живой")))
    return КОД_ОК


def main() -> int:
    _настроить_вывод()
    аргументы = sys.argv[1:]
    if not аргументы or аргументы[0] in ("-h", "--help", "help"):
        print(СПРАВКА)
        return КОД_ОК if аргументы else КОД_УПОТРЕБЛЕНИЕ
    команда, хвост = аргументы[0], аргументы[1:]

    if команда in ("--version", "-V", "version"):
        print(__version__)
        return КОД_ОК
    if команда == "setup":
        return setup(без_входа="--без-входа" in хвост)
    if команда == "login":
        return login(готово=("--готово" in хвост))
    if команда == "status":
        return status()
    if команда == "doctor":
        return doctor(живой=("--живой" in хвост))
    if команда == "start":
        return start()
    if команда == "stop":
        return stop()
    if команда == "restart":
        return restart()
    if команда == "logs":
        try:
            строк = int(хвост[0]) if хвост else 40
        except ValueError:
            print("{} logs принимает число строк".format(ПЛОХО), file=sys.stderr)
            return КОД_УПОТРЕБЛЕНИЕ
        return logs(строк)
    if команда == "register":
        return register_cmd(хвост)
    if команда == "unregister":
        return register_cmd(хвост, снять=True)
    if команда == "autostart":
        if not хвост or хвост[0] not in ("on", "off", "status"):
            print("{} autostart on | off | status".format(ПЛОХО), file=sys.stderr)
            return КОД_УПОТРЕБЛЕНИЕ
        return autostart_cmd(хвост[0])
    if команда == "call":
        return call(хвост)
    if команда == "update":
        return update()
    if команда == "uninstall":
        return uninstall(purge=("--purge" in хвост), без_вопросов=("--yes" in хвост))
    if команда == "migrate":
        if not хвост or хвост[0].startswith("-"):
            print("{} migrate ПУТЬ — путь к старой установке или прямо "
                  "к каталогу профиля".format(ПЛОХО), file=sys.stderr)
            return КОД_УПОТРЕБЛЕНИЕ
        return migrate(хвост[0])

    print("{} нет такой команды: {}\n".format(ПЛОХО, команда), file=sys.stderr)
    print(СПРАВКА, file=sys.stderr)
    return КОД_УПОТРЕБЛЕНИЕ


if __name__ == "__main__":
    sys.exit(main())
