def _спросить_ps(pid: int, поле: str) -> tuple[int, str, str]:
    """`ps -p N -o stat=,<поле>=` одним вызовом: (код, состояние, поле).

    Состояние спрашивается тем же вызовом, что и поле, а не отдельным: между
    двумя вызовами процесс успевает его сменить, и ответ склеился бы из разных
    мгновений. Исключение наружу не ловится: «процесса нет» это или «спросить
    не удалось», решает вызывающий, и решают они по-разному.
    """
    p = subprocess.run(["ps", "-p", str(pid), "-o", "stat=,{}=".format(поле)],
                       capture_output=True, text=True, timeout=20,
                       encoding="utf-8", errors="replace")
    состояние, _, значение = (p.stdout or "").strip().partition(" ")
    return p.returncode, состояние, значение.strip()


def _имя_процесса(pid: int) -> str | None:
    """Имя исполняемого файла процесса. None — процесса нет или не спросить."""
    if os.name == "nt":
        try:
            p = subprocess.run(["tasklist", "/FI", "PID eq {}".format(pid),
                                "/FO", "CSV", "/NH"],
                               capture_output=True, text=True, timeout=20,
                               encoding="utf-8", errors="replace")
        except (OSError, subprocess.SubprocessError):
            return None
        # Совпадений нет — tasklist печатает фразу без кавычек, а не пустоту.
        if p.returncode != 0 or '"' not in (p.stdout or ""):
            return None
        return p.stdout.split('"')[1]
    try:
        _код, состояние, имя = _спросить_ps(pid, "comm")
    except (OSError, subprocess.SubprocessError):
        return None
    # Зомби для пульта — ушедший процесс: файлы он закрыл, замок профиля снял,
    # за ним осталась одна запись в таблице с кодом выхода для родителя, и
    # держать он ничего не может (ограничение 2). Имя своё зомби при этом
    # печатает по-прежнему, поэтому без проверки состояния ожидание после
    # сигнала не увидело бы ухода никогда: демона, порождённого ещё живым
    # родителем, пульт на POSIX считал бы живым до самого потолка.
    if состояние.startswith("Z"):
        return None
    return имя or None


def _выполнить_tk(pid: int) -> tuple[int, str]:
    """taskkill по дереву процессов. Отдельно — чтобы stop читался целиком."""
    try:
        p = subprocess.run(["taskkill", "/PID", str(pid), "/T", "/F"],
                           capture_output=True, text=True, timeout=30,
                           encoding="utf-8", errors="replace")
    except (OSError, subprocess.SubprocessError) as e:
        return 127, "{}: {}".format(type(e).__name__, e)
    return p.returncode, (p.stdout or "") + (p.stderr or "")


def _pid_из_порта() -> int | None:
    """PID из daemon_port. None — файла нет, он битый или PID в нём не число.

    `daemon_client.адрес()` этот PID намеренно не отдаёт, пока демон не
    опознан по /health: пульт по PID убивает, и предлагать ему чужую
    программу нельзя. Здесь файл читается не вместо опознания, а ради
    сверки stop(), которая и решает, наш ли это процесс: на отвечающем
    пути — имени процесса, на молчащем — его командной строки.
    Расположение спрашивается у paths, второго вычислителя STATE нет.
    """
    try:
        pid = json.loads(paths.port_file.read_text(encoding="utf-8")).get("pid")
    except (OSError, ValueError, AttributeError):
        return None
    return pid if isinstance(pid, int) else None


def _наш_на_вид(имя: str | None) -> bool:
    """Похоже ли имя процесса на наше.

    Два семейства имён, и оба законны: `python`/`pythonw` — запуск через
    `-m`, `garant-daemon` — консольный скрипт установленного пакета.
    Второе даже надёжнее первого: чужой программы с таким именем не бывает.
    """
    н = (имя or "").lower()
    return "python" in н or "garant" in н


# Маркеры из `daemon_client._команда_демона()` — единственного места, откуда
# демона запускают: консольный скрипт `garant-daemon` установленного пакета
# и модульный запуск `-m garant_mcp.daemon`. Хвост после `daemon` отсечён
# намеренно: `garant_mcp.daemon_client` — разовый клиент К демону, и убивать
# его деревом нельзя.
_МАРКЕР_ДЕМОНА = re.compile(r"garant-daemon|garant_mcp\.daemon(?![\w.])",
                            re.IGNORECASE)


def _демон_в_строке(строка: str) -> bool:
    """Называет ли командная строка НАШ демон — тем же, чем его зовёт start()."""
    return bool(_МАРКЕР_ДЕМОНА.search(строка))


def _командная_строка(pid: int) -> tuple[str, str]:
    """Чем запущен процесс: («есть», строка) | («нет», "") | («неизвестно», причина).

    Имя образа на вопрос «наш ли это процесс» не отвечает: «python.exe»
    носит любая чужая программа, а протухший `daemon_port` называет как раз
    её — ядро выдаёт номера PID по кругу, и номер умершего демона достаётся
    постороннему. Демона называет только командная строка.

    «нет» отделено от «неизвестно» намеренно: первое разрешает снять запись
    `daemon_port`, второе не разрешает ничего. Молчание сломанного
    инструмента — это отсутствие знания, а не знание об отсутствии процесса.
    """
    if os.name == "nt":
        # PowerShell и CIM, а не wmic: wmic на Windows 10 ещё есть, но
        # объявлен устаревшим и из свежих сборок Windows уже изымается —
        # опираться на него значит завести поломку с датой срабатывания.
        # Метка латиницей: powershell отдаёт вывод в кодовой странице
        # консоли, и кириллическую метку мы получили бы искажённой.
        запрос = ("$p = Get-CimInstance Win32_Process -Filter "
                  "'ProcessId={}' -ErrorAction Stop; "
                  "if ($null -eq $p) {{ 'NO_SUCH_PROCESS' }} "
                  "else {{ $p.CommandLine }}".format(pid))
        try:
            p = subprocess.run(["powershell", "-NoProfile", "-NonInteractive",
                                "-Command", запрос],
                               capture_output=True, text=True, timeout=20,
                               encoding="utf-8", errors="replace")
        except (OSError, subprocess.SubprocessError) as e:
            return "неизвестно", "{}: {}".format(type(e).__name__, e)
        if p.returncode != 0:
            return "неизвестно", "powershell вышел с кодом {} ({})".format(
                p.returncode, (p.stderr or "").strip() or "без объяснения")
        вывод = (p.stdout or "").strip()
        if вывод == "NO_SUCH_PROCESS":
            return "нет", ""
        if not вывод:
            # Процесс есть, а строки нет: так CIM отвечает про процессы,
            # читать которые нам не дают прав. Знания это не даёт.
            return "неизвестно", "командная строка процесса недоступна"
        return "есть", вывод
    try:
        код, состояние, строка = _спросить_ps(pid, "args")
    except (OSError, subprocess.SubprocessError) as e:
        return "неизвестно", "{}: {}".format(type(e).__name__, e)
    # Код 1 у `ps -p` означает именно «такого процесса нет» — этим он и
    # отличает отсутствие процесса от неудачи вопроса.
    if код == 1:
        return "нет", ""
    if код != 0:
        return "неизвестно", "ps вышел с кодом {}".format(код)
    # Зомби и здесь «процесса нет», и отличить его можно только состоянием:
    # своей командной строки он уже лишён, ps печатает «[имя] <defunct>», и
    # маркера демона там нет. Иначе молчащий путь объявил бы, что PID достался
    # чужой программе, и снял бы daemon_port, — тогда как PID не доставался
    # никому, а профиль зомби не держит.
    if состояние.startswith("Z"):
        return "нет", ""
    if not строка:
        return "неизвестно", "ps ничего не сказал о процессе"
    return "есть", строка


def stop() -> int:
    """Остановить демона по PID со сверкой, а не «всех на порту».

    Порт после смерти демона мог занять чужая программа, а `daemon_port` —
    остаться от прежнего запуска: убийство «всех на порту N» в этом случае
    убивает постороннего, и человек узнаёт об этом по потерянной работе
    в другом окне.

    Путей два, и сверка у них РАЗНАЯ.

    ОТВЕЧАЮЩИЙ — три условия: на порту опознан НАШ демон (GET /health, без
    токена); PID взят из daemon_port, который пишет сам демон; имя процесса
    с этим PID похоже на наше.

    МОЛЧАЩИЙ — опознавать по HTTP нечем, и остаётся PID из daemon_port.
    Здесь решает КОМАНДНАЯ СТРОКА процесса: тот же маркер демона, каким его
    запускает start(). Имени образа тут мало, и это измерено воротами
    09.09.2026: посторонний `python -c "time.sleep(90)"`, чей PID лежал
    в протухшем daemon_port, был убит деревом и объявлен остановленным
    демоном. Исходов пять: процесса нет — запись снимается, останавливать
    нечего; строка называет демон — сигнал, как на отвечающем пути (профиль
    держит процесс, а не слушатель порта, ограничение 2); строка называет
    не нас — не убито ничего, а запись снята, PID достался чужой программе;
    строку прочесть не удалось — не убито ничего и запись оставлена;
    строка назвала демон, а имени процесса не добиться — так же ничего
    не убито и запись оставлена.
    """
    from . import daemon_client as dc

    адрес = dc.адрес()
    молчит = not адрес["alive"]
    if молчит:
        # Молчание HTTP — не «демона нет», и один этот признак решения не
        # стоит. Приёмка 7б 09.09.2026: после серии вызовов `stop` ответил
        # «останавливать нечего», хотя `start` перед ней прошёл; причина
        # молчания к этому часу не установлена. Путь, который о процессе
        # даже не спрашивает, неверен при ЛЮБОЙ её причине: профиль держит
        # живой процесс, а не открытый порт (ограничение 2), и уйти он
        # обязан по нашему сигналу, а не по нашему предположению.
        pid = _pid_из_порта()
        if not pid:
            _печать(ОК, "демон не отвечает на 127.0.0.1:{} — останавливать "
                    "нечего".format(адрес["port"]))
            return КОД_ОК
        исход, строка = _командная_строка(pid)
        if исход == "нет":
            # Запись описывает процесс, которого нет: оставить её значит
            # отправить следующего клиента на порт, где демона нет.
            _убрать_протухший_порт(pid)
            _печать(ОК, "демон не отвечает на 127.0.0.1:{}, процесса {} нет — "
                    "останавливать нечего, запись daemon_port снята"
                    .format(адрес["port"], pid))
            return КОД_ОК
        if исход == "неизвестно":
            return _отказ(
                "Удостовериться, что процесс {} — демон, не удалось: {}. "
                "Ничего не убил; запись daemon_port оставлена — она "
                "единственный след того, кто мог занять профиль. Остановите "
                "демона тем способом, которым запускали.".format(pid, строка))
        if not _демон_в_строке(строка):
            # PID достался чужой программе, а daemon_port остался от прежнего
            # запуска. Убивать нечего, но запись врёт — её снимаем.
            # Строку показываем урезанной: у чужой программы она бывает
            # в тысячу символов, а узнать её человеку хватит начала.
            чем = строка if len(строка) <= 120 else строка[:120] + "..."
            _печать(ОК, "процесс {} — не наш демон, а «{}»: ничего не "
                    "остановлено, запись daemon_port о нём снята — PID "
                    "достался чужой программе".format(pid, чем))
            _убрать_протухший_порт(pid)
            return КОД_ОК
        имя = _имя_процесса(pid)
        if имя is None:
            # Командная строка демона прочитана, а имени нет — значит,
            # tasklist/ps не отвечает. Убивать вслепую нельзя: уход процесса
            # пульт видит ТЕМ ЖЕ вызовом, и молчание сломанного инструмента
            # он принял бы за «процесс ушёл», объявив успех по незнанию.
            return _отказ(
                "Процесс {} по командной строке — наш демон, но имени его "
                "не добиться: tasklist/ps не ответил. Ничего не убил; запись "
                "daemon_port оставлена. Остановите демона тем способом, "
                "которым запускали.".format(pid))
        _печать(ВНИМАНИЕ, "демон молчит на 127.0.0.1:{}, но процесс {} ({}) "
                "жив — профиль держит он, и останавливается он так же, как "
                "отвечающий".format(адрес["port"], pid, имя))
    else:
        pid = адрес["pid"]
        if not pid:
            return _отказ(
                "Демон на 127.0.0.1:{} отвечает, но PID неизвестен: "
                "в daemon_port его нет. Убивать «всех на порту» нельзя — порт "
                "мог занять чужой процесс. Остановите демона тем способом, "
                "которым запустили.".format(адрес["port"]))
        имя = _имя_процесса(pid)
        if not _наш_на_вид(имя):
            return _отказ(
                "PID {} из daemon_port принадлежит процессу «{}» — на наш "
                "демон не похоже. Ничего не убил: файл, скорее всего, остался "
                "от прежнего запуска, а PID успел достаться чужой программе."
                .format(pid, имя or "неизвестно"))

    if os.name == "nt":
        # Деревом, а не одним процессом. Мягкого сигнала в Windows нет:
        # SIGTERM там — это TerminateProcess, и finally демона не исполняется,
        # то есть браузер он закрыть не успевает. Осиротевший chromium
        # переживает своего хозяина и продолжает держать профиль — следующий
        # демон не поднимет контекст, а выглядит это как «Гарант сломался».
        код, вывод = _выполнить_tk(pid)
        if код != 0:
            return _отказ("taskkill не смог остановить процесс {} (код {}): {}"
                          .format(pid, код, вывод.strip()))
    else:
        try:
            # На POSIX сигнал мягкий: демон доходит до своего finally, сам
            # закрывает браузер и снимает daemon_port.
            os.kill(pid, signal.SIGTERM)
        except OSError as e:
            return _отказ("Не удалось послать сигнал процессу {} ({}: {})".format(
                pid, type(e).__name__, e))
    _печать(ОК, "процессу {} ({}) послан сигнал остановки".format(pid, имя))

    # Ждём не молчания HTTP, а смерти процесса. Молчание наступает раньше:
    # демон снимает слушателя и только потом прибирается, а замок профиля
    # снимается лишь смертью процесса (ограничение 2). `restart()` берёт
    # КОД_ОК отсюда как разрешение немедленно поднимать нового демона —
    # отдав успех по молчанию, мы отправляли бы его в занятый профиль.
    #
    # `_имя_процесса` возвращает None и когда процесса нет, и когда о нём
    # не удалось спросить. Здесь второе исключено самим ходом stop(): выше
    # тот же вызов вернул имя, иначе `_наш_на_вид(None)` отказал бы до сигнала.
    предел = time.time() + protocol.ПОТОЛОК_ОСТАНОВКИ_СЕК
    начало = time.time()
    # Демон, молчавший ещё до сигнала, ждать своего молчания не заставляет:
    # опрашивать порт, который уже не отвечает, значит тратить потолок на
    # выяснение известного.
    замолчал = молчит
    while time.time() < предел:
        time.sleep(0.5)
        if not замолчал:
            # Пока демон отвечает, процесс заведомо жив — незачем спрашивать
            # о нём ОС: опрос идёт подпроцессом (tasklist/ps).
            замолчал = not dc.адрес()["alive"]
            if not замолчал:
                continue
        if _имя_процесса(pid) is None:
            # Пульт видит два факта: демон замолчал и процесс ушёл. Закрылся
            # ли браузер, он не видит — уборку демон делает уже после того,
            # как замолчал, и о её провале говорит только его лог. Называть
            # это «демон остановлен» значит выдать за факт неизмеренный запас
            # в пять секунд, отделяющий потолок уборки от потолка ожидания.
            вступление = ("демон {} молчал на 127.0.0.1:{} ещё до сигнала"
                          if молчит else
                          "демон {} перестал отвечать на 127.0.0.1:{}")
            _печать(ОК, (вступление + ", процесс ушёл за {:.1f} с. Закрылся ли "
                         "браузер, пульт не видит: если профиль окажется "
                         "занят, ответ будет в `garant logs`.")
                    .format(pid, адрес["port"], time.time() - начало))
            _убрать_протухший_порт(pid)
            return КОД_ОК
    if замолчал:
        # daemon_port не трогаем: он всё ещё описывает живой процесс, и снять
        # его значило бы спрятать от следующей команды единственный след того,
        # кто держит профиль.
        return _отказ(
            "Демон {} не отвечает по HTTP, но сам процесс спустя {} с ещё жив: он "
            "прибирается дольше отведённого либо завис. Нового демона "
            "поднимать рано — профиль занят этим. Что делал процесс, скажет "
            "{}; если он так и не уйдёт, повторите {}."
            .format(pid, protocol.ПОТОЛОК_ОСТАНОВКИ_СЕК,
                    paths.команда("logs"), paths.команда("stop")))
    return _отказ(
        "Демон {} за {} с не остановился и продолжает отвечать. Возможно, он "
        "занят входом в подписку — окно входа держит поток до {} мин."
        .format(pid, protocol.ПОТОЛОК_ОСТАНОВКИ_СЕК,
                protocol.ПОТОЛОК_ВХОДА_СЕК // 60))


def _убрать_протухший_порт(pid: int) -> None:
    """Снять daemon_port, если он всё ещё описывает убитый процесс.

    На Windows завершение по сигналу не даёт демону доработать свой finally,
    и файл остаётся. Оставить его значит отправить следующего клиента на
    порт, где демона нет, — а там его встретит либо тишина, либо чужая
    программа, которой клиент не покажет токен, но и не объяснит причину
    коротко.
    """
    try:
        данные = json.loads(paths.port_file.read_text(encoding="utf-8"))
        if данные.get("pid") == pid:
            paths.port_file.unlink()
    except (OSError, ValueError):
        pass


def restart() -> int:
    """Перезапуск ПРОЦЕССА, а не браузерного контекста.

    Именно процесса: на `garant restart` ведёт совет при расхождении версий
    («демон работает на старом коде»), а перезапуск контекста внутри старого
    процесса кода не меняет и совет сделал бы ложным.
    """
    код = stop()
    if код != КОД_ОК:
        return код
    return start()


def logs(строк: int = 40) -> int:
    from . import daemon_client as dc

    try:
        строки = dc.logs()["лог"]
    except dc.DaemonError:
        # Журнал спрашивают у демона, но нужен он чаще всего тогда, когда
        # демона уже нет: после `garant stop` ответ на вопрос «закрылся ли
        # браузер» лежит ровно здесь, и отказ «демон не отвечает» отправил бы
        # человека за ответом к тому, кого он только что остановил. Файл тот
        # же самый, который отдаёт эндпоинт /logs.
        файл = paths.log_dir / "daemon.log"
        if not файл.exists():
            return _отказ(
                "Демон не отвечает, и журнала на диске нет — похоже, демон "
                "в этой установке ни разу не запускался. Поднять: "
                + paths.команда("start"))
        строки = файл.read_text(encoding="utf-8",
                                errors="replace").splitlines()
        # Пометка идёт в stderr: вывод `garant logs` читают глазами и
        # программами как сам журнал, и подмешивать в него строку о том,
        # откуда он взят, значит подделывать журнал.
        _печать(ВНИМАНИЕ, "демон не отвечает — журнал прочитан с диска: это "
                "записи последнего запуска, дописывать их сейчас некому.",
                поток=sys.stderr)
    for строка in строки[-строк:]:
        print(строка)
    return КОД_ОК


