def _значки() -> tuple[str, str, str, str, str]:
    """Значки, которые эта консоль умеет напечатать.

    Не украшательство. Консоль Windows работает в кодовой странице ОС —
    cp866 или cp1251, — и «✓» в неё не кодируется: печать падает
    UnicodeEncodeError, то есть пульт разваливается на собственном выводе
    ровно тогда, когда его позвали выяснить, что сломано. Кириллица в обе
    страницы кодируется, а рамки и галочки — нет.
    """
    кодировка = getattr(sys.stdout, "encoding", "") or "ascii"
    try:
        "✓✗⚠═·".encode(кодировка)
    except (UnicodeError, LookupError):
        return "[ok]", "[X]", "[!]", "=", "[-]"
    return "✓", "✗", "⚠", "═", "·"


ОК, ПЛОХО, ВНИМАНИЕ, РАМКА, НЕЙТРАЛЬНО = _значки()


def _настроить_вывод() -> None:
    """Ни одна строка вывода не имеет права уронить пульт.

    Значки мы подобрали по кодировке, но текст приходит и извне — путь
    с необычным символом, имя процесса, ответ демона. Замена вместо
    исключения: испорченный символ читается, оборванная диагностика — нет.
    """
    for поток in (sys.stdout, sys.stderr):
        try:
            поток.reconfigure(errors="replace")
        except Exception:
            pass


def _печать(значок: str, текст: str, поток=None) -> None:
    # Поток берётся в момент вызова, а не значением по умолчанию: умолчание
    # вычислилось бы один раз на импорте и промахнулось бы мимо sys.stdout,
    # подменённого вызывающим. Второй поток нужен там, где пометка о самом
    # выводе не имеет права попасть в вывод (`logs`).
    print("{} {}".format(значок, текст), file=поток or sys.stdout)


def _отказ(текст: str) -> int:
    """Печатает причину в stderr и отдаёт ненулевой код.

    В stderr, а не в stdout: `garant status` вызывают из скриптов, и там
    разбирают вывод; смешать причину отказа с данными значит заставить
    скрипт угадывать, что он читает.
    """
    # Сначала выталкиваем накопленное в stdout: иначе причина отказа
    # обгоняет по буферу строки, которые её объясняют, и в перенаправленном
    # выводе читается раньше их.
    try:
        sys.stdout.flush()
    except Exception:
        pass
    print("{} {}".format(ПЛОХО, текст), file=sys.stderr)
    return КОД_НЕ_СДЕЛАНО


# --- диагностика по частям -------------------------------------------------
def _пункт(значок: str, заголовок: str, текст: str, починка: str = "") -> bool:
    """Печатает пункт диагностики. Возвращает True, если пункт красный.

    Красный пункт БЕЗ команды починки не печатается вовсе — на такой пункт
    человеку нечего ответить, и он хуже отсутствия пункта. Поэтому починка
    обязательна: она проверяется здесь, а не обещанием в докстроке.
    """
    print("{} {:<22} {}".format(значок, заголовок + ":", текст))
    if значок != ПЛОХО:
        return False
    if not починка:
        # Не assert: под -O он исчезает, и правило «на каждый красный пункт —
        # команда починки» перестало бы проверяться ровно там, где пульт
        # работает у пользователя.
        raise RuntimeError(
            "дефект пульта: красный пункт «{}» без команды починки".format(
                заголовок))
    print("  {:<22} {}".format("починить:", починка))
    return True


def _питон() -> tuple[str, str, str]:
    в = sys.version_info
    строка = "{}.{}.{}".format(в.major, в.minor, в.micro)
    if в >= (3, 12):
        return ОК, строка, ""
    return (ПЛОХО, строка + " — пакету нужен 3.12 или новее",
            "переустановите пакет на Python 3.12+: "
            "uv tool install --python 3.12 garant-mcp")


def _команды_на_диске() -> bool:
    """Доказано ли, что консольные файлы пакета на машине уже есть.

    Признак спрашивается у самого исполняющегося процесса, а не у имени
    каталога: «uv» или «tools» в пути — догадка о чужой раскладке, она
    разъезжается с первым же UV_TOOL_BIN_DIR и объявила бы установку там,
    где её нет. Честных фактов два, и каждого хватает.

      · doctor запущен САМИМ файлом команды (`sys.argv[0]` называется
        «garant» и лежит на диске) — команда работает прямо сейчас, её
        просто нельзя позвать по имени;
      · в каталоге скриптов ЭТОГО интерпретатора лежит «garant» — туда
        консольные файлы кладёт установщик пакета, и каталог мы спрашиваем
        у sysconfig, а не выводим из раскладки окружения.
    """
    argv0 = Path(sys.argv[0] or "")
    # «.exe» проверяется отдельным путём, а не одним is_file(): windows-лаунчер
    # отдаёт argv[0] БЕЗ расширения («…\Scripts\garant»), и одной проверки
    # хватило бы ровно на то, чтобы объявить ненайденным файл, которым пульт
    # прямо сейчас исполняется. Замерено на установке через uv tool.
    if argv0.stem.lower() == "garant" and (
            argv0.is_file() or argv0.with_suffix(".exe").is_file()):
        return True
    скрипты = Path(sysconfig.get_path("scripts"))
    return (скрипты / "garant").is_file() or (скрипты / "garant.exe").is_file()


def _исполняемые() -> tuple[str, str, str]:
    """Три консольных файла пакета — в PATH или нет.

    Именно наличие в PATH, а не путь: путь у каждого свой и меняется
    с обновлением, а регистрация у клиентов ссылается на имя.

    Отсутствие в PATH — два разных состояния, и починка у них разная.
    Пакета нет вовсе — ставить; пакет стоит и работает, а в PATH не внесён
    каталог его команд — переустановка не меняет ничего, и совет «поставьте
    заново» наблюдался живьём как красный пункт у работающей установки.
    """
    нет = [и for и in ("garant", "garant-mcp", "garant-daemon")
           if not shutil.which(и)]
    if not нет:
        return ОК, "garant, garant-mcp, garant-daemon — все в PATH", ""
    if _команды_на_диске():
        # Каталог в тексте не называется намеренно: человеку нужна команда,
        # а путь у него свой и меняется с обновлением. PATH правит тот же
        # инструмент, которым ставили, — и новая запись видна только новой
        # консоли, поэтому это сказано здесь, а не остаётся сюрпризом.
        return (ПЛОХО,
                "пакет установлен, но каталог его команд не в PATH: "
                + ", ".join(нет),
                "uv tool update-shell   (либо pipx ensurepath — тем, чем "
                "ставили), затем новое окно консоли")
    return (ПЛОХО, "нет в PATH: " + ", ".join(нет),
            # Единственный совет не в форме `garant …`, и иначе быть
            # не может: если самого `garant` в PATH нет, советовать его
            # бессмысленно. Абсолютного пути здесь всё равно нет.
            "uv tool install --force garant-mcp   (или pipx install --force garant-mcp)")


def _место_браузеров() -> tuple[str | None, str]:
    """Куда playwright ставит браузеры: (каталог, причина неудачи).

    Спрашивается у самого playwright. Ни одной догадки о раскладке кэша
    браузеров: она у трёх ОС разная и меняется от версии к версии.

    Отдельным процессом, а не через `sync_playwright()` в этом же: подъём
    и остановка драйвера ради одного пути оставляли в выводе диагностики
    «Task was destroyed but it is pending» и TargetClosedError из недр
    playwright — то есть пульт, позванный выяснить, что сломано, сам
    выглядел сломанным.
    """
    try:
        p = subprocess.run(
            [sys.executable, "-m", "playwright", "install", "--dry-run",
             "chromium"],
            capture_output=True, text=True, encoding="utf-8",
            errors="replace", timeout=120)
    except (OSError, subprocess.SubprocessError) as e:
        return None, "playwright не отвечает ({}: {})".format(
            type(e).__name__, e)
    if p.returncode != 0:
        return None, "playwright вернул код {}: {}".format(
            p.returncode, (p.stderr or p.stdout or "").strip()[:200])
    for строка in (p.stdout or "").splitlines():
        if "Install location:" in строка:
            каталог = строка.split("Install location:", 1)[1].strip()
            if каталог:
                return каталог, ""
    return None, "не удалось выяснить, куда playwright ставит chromium"


def _chromium() -> tuple[str, str, str]:
    """Есть ли браузер, которым работает демон. Браузер при этом НЕ запускается.

    Неизвестность считается красным, а не зелёным: «не выяснили» и «есть» —
    разные вещи, и второе без первого утверждать нельзя.
    """
    каталог, беда = _место_браузеров()
    if каталог is None:
        return ПЛОХО, беда, paths.команда("setup")
    if os.path.exists(каталог):
        return ОК, "установлен", ""
    return ПЛОХО, "не установлен", paths.команда("setup")


def _состояние_каталога() -> tuple[str, str, str]:
    """Каталог состояния и ПОЧЕМУ он выбран.

    Причина печатается не для красоты: две установки с разным `GARANT_HOME`
    выглядят одинаково, пока не спросить, откуда взялся каталог, — и именно
    так рождалось «правки не доходят».
    """
    описание = "{} ({})".format(paths.STATE, paths.ПРИЧИНА_STATE)
    if not paths.STATE.exists():
        return (ВНИМАНИЕ, описание + " — каталога ещё нет, создастся при "
                "первом запуске демона", "")
    if not os.access(paths.STATE, os.W_OK):
        return ПЛОХО, описание + " — нет прав на запись", paths.команда("setup")
    return ОК, описание, ""


def _пункт_keepalive(состояние: dict) -> tuple[str, str]:
    """Значок и текст строки keepalive. Зелёное — ровно один факт.

    Факт этот такой: последнее продление вернуло HTTP 200 И было не позже
    двух тактов назад. О живости сессии пункт по-прежнему не говорит
    ничего — её доказывает живой запрос.

    Оба края ошибались, и каждый живьём. Жёсткое зелёное по исходу прятало
    неудачное продление (решение 29). Жёсткое ВНИМАНИЕ, пришедшее ему на
    смену, встретилось владельцу на приёмке 09.09.2026: предупреждающий
    значок у «HTTP 200» отправляет искать поломку там, где всё сделано.
    Времени не хватало и там, и там: удачный исход суточной давности —
    это демон, который давно не продлевает, а по одному исходу он
    неотличим от только что сходившего.

    Два такта, а не один: продление идёт по таймеру демона, и одного
    такта могло просто ещё не наступить. Такт берётся из `config` ЭТОЙ
    копии — второго написания периода в пульте быть не должно; демон,
    поднятый с другим GARANT_KEEPALIVE_SEC, сделает оценку давности
    приблизительной, но не молча неверной.
    """
    from . import config

    когда = состояние.get("последний_keepalive")
    исход = состояние.get("последний_keepalive_исход")
    текст = "{} ({})".format(когда or "ещё не было",
                             исход or "исход неизвестен")
    предел = 2 * config.KEEPALIVE_SEC
    try:
        # Момент пишет демон этой же машины (datetime.now без зоны),
        # поэтому и сравнивается с местным временем.
        прошло = (datetime.now()
                  - datetime.fromisoformat(str(когда))).total_seconds()
    except (TypeError, ValueError):
        прошло = None
    # Ровно «HTTP 200», а не любое 2xx или 3xx: других исходов подписка
    # на этом эндпоинте здесь не показывала, и красить зелёным неизвестное
    # значит вернуть ту же подмену с другой стороны.
    if исход == "HTTP 200" and прошло is not None and 0 <= прошло <= предел:
        return ОК, текст
    if исход == "HTTP 200" and прошло is not None:
        текст += " — старше двух тактов продления ({} с)".format(предел)
    return ВНИМАНИЕ, текст


def doctor(живой: bool = False) -> int:
    """Полная диагностика: почему не работает — вместо владельца.

    Печатается только доказанное. `сессия: жива` не появляется от того, что
    демон отвечает: живость сессии знает демон, и он теперь честен —
    «не проверена» означает ровно «никто не ходил в Гарант».
    """
    from . import autostart
    from . import daemon_client as dc
    from . import fingerprint
    from . import register

    красных = 0
    print("{0}{0}{0} ДИАГНОСТИКА garant-mcp {0}{0}{0}\n".format(РАМКА))

    for проверка, заголовок in ((_питон, "python"),
                                (_исполняемые, "пакет в PATH"),
                                (_chromium, "chromium"),
                                (_состояние_каталога, "каталог состояния")):
        значок, текст, починка = проверка()
        красных += _пункт(значок, заголовок, текст, починка)

    # Нейтральный, а не зелёный: пункт ничего не проверяет, он сообщает.
    # Зелёным в этой выдаче называется только доказанное — иначе значок
    # перестаёт что-либо значить и там, где он заработан.
    _пункт(НЕЙТРАЛЬНО, "версия пакета", __version__)

    # --- демон ---
    адрес = dc.адрес()

    # Опознание по /health доказывает «на порту garant-daemon», но НЕ «демон
    # этой установки»: признак у всех копий один, а каталог состояния у каждой
    # свой. Принадлежность доказывает только /state под нашим токеном: токен
    # демон читает из СВОЕГО каталога, поэтому принятый токен плюс названный
    # им каталог, совпавший с paths.STATE, и означают «этот демон живёт нашим
    # состоянием». Спрашиваем ДО печати пункта, а не после: зелёное «демон
    # работает» без этого утверждает больше доказанного — ровно так ворота
    # этапа приняли за свой чужой демон, оставшийся на том же порту.
    состояние_демона: dict = {}
    беда_состояния = ""
    if адрес["alive"]:
        try:
            состояние_демона = dc.состояние()
        except dc.DaemonError as e:
            беда_состояния = str(e)

    if адрес["alive"]:
        порт_демона = "127.0.0.1:{}".format(адрес["port"])
        назвал = (состояние_демона.get("каталоги") or {}).get("состояние")
        if назвал and (os.path.normcase(os.path.abspath(назвал))
                       == os.path.normcase(str(paths.STATE))):
            _пункт(ОК, "демон", "работает на {}, pid {}".format(
                порт_демона,
                адрес["pid"] if адрес["pid"] is not None else "неизвестен"))
        elif назвал:
            _пункт(ВНИМАНИЕ, "демон",
                   "на {} отвечает garant-daemon ДРУГОЙ установки: состоянием "
                   "он живёт в {}, а эта копия — в {}".format(
                       порт_демона, назвал, paths.STATE))
        else:
            почему = ("состояние он не отдал: " + беда_состояния.splitlines()[0]
                      if беда_состояния else "свой каталог он не назвал")
            _пункт(ВНИМАНИЕ, "демон",
                   "на {} отвечает garant-daemon, но принадлежность ЭТОЙ "
                   "установке не доказана — {}".format(порт_демона, почему))
    elif dc.TOKEN_FILE.exists():
        красных += _пункт(ПЛОХО, "демон",
                          "не отвечает на 127.0.0.1:{}".format(адрес["port"]),
                          paths.команда("start"))
    else:
        # «Отказал» и «не поднимался» — разные события, и различаются они
        # дёшево: токен кладёт сам демон при первом же запуске. Токена нет —
        # значит демона в этой установке не запускали, а не он упал; сам он
        # поднимется при первом обращении инструмента (обеспечить_демона).
        # Красным это красить нельзя: тогда `setup --без-входа` — режим,
        # существующий ровно ради установки без входа, — штатно кончался бы
        # отказом, и коды возврата обесценились бы тем же способом, каким
        # обесценился «успех после двух ERROR».
        _пункт(ВНИМАНИЕ, "демон",
               "не запускался ни разу (порт 127.0.0.1:{}) — поднимется сам "
               "при первом обращении, либо сразу: {}".format(
                   адрес["port"], paths.команда("start")))

    if адрес["alive"]:
        try:
            dc.сверить_версию()
        except dc.DaemonError as e:
            красных += _пункт(ПЛОХО, "версия демона",
                              str(e).splitlines()[0], paths.команда("restart"))
        if беда_состояния:
            красных += _пункт(ПЛОХО, "состояние демона",
                              беда_состояния.splitlines()[0],
                              paths.команда("restart"))

    # --- живой запрос ---
    # Раньше он шёл последним, ПОСЛЕ строки «сессия», и та печаталась
    # снимком, снятым до единственной проверки, которая о сессии что-либо
    # доказывает. На живой приёмке 09.09.2026 это читалось прямо: «сессия:
    # не проверена» стояла над успешным живым запросом, а «жива» появлялась
    # лишь у следующего doctor. Спрашиваем раньше и перечитываем состояние:
    # сессию судит демон, и утверждать о ней надо по самому свежему из его
    # ответов, а не по первому.
    if живой:
        if not адрес["alive"]:
            красных += _пункт(ПЛОХО, "живой запрос", "некому исполнить",
                              paths.команда("start"))
        else:
            print("\nДелаю живой запрос к «Гаранту»…")
            try:
                r = dc.probe()
            except dc.DaemonError as e:
                красных += _пункт(ПЛОХО, "живой запрос",
                                  str(e).splitlines()[0], paths.команда("login"))
            else:
                if r.get("подписка_ответила"):
                    _пункт(ОК, "живой запрос",
                           "подписка отвечает, видов информации: {}".format(
                               r.get("видов")))
                else:
                    красных += _пункт(
                        ПЛОХО, "живой запрос",
                        str(r.get("пояснение") or r), paths.команда("login"))
            try:
                состояние_демона = dc.состояние()
            except dc.DaemonError:
                # Молча: неудачу того же вызова уже назвал пункт «состояние
                # демона» выше, и второй раз она ничего не добавит. Строки
                # ниже останутся на прежнем снимке — это хуже свежего, но
                # честно: они говорят то, что демон сказал последним.
                pass
            print()

    # --- сессия ---
    if not адрес["alive"]:
        _пункт(ВНИМАНИЕ, "сессия", "неизвестна: спросить некого, демон молчит")
    else:
        сессия = состояние_демона.get("сессия") or "неизвестна"
        if сессия == "жива":
            _пункт(ОК, "сессия", "жива с {}".format(
                состояние_демона.get("сессия_жива_с") or "неизвестного момента"))
        elif сессия == "недействительна":
            красных += _пункт(ПЛОХО, "сессия", "недействительна",
                              paths.команда("login"))
        else:
            # «Не проверена» — не отказ: демон не ходил в «Гарант» и честно
            # об этом говорит. Красным это делать нельзя, иначе doctor
            # объявит поломкой нормальное состояние свежего демона.
            _пункт(ВНИМАНИЕ, "сессия",
                   "{} — проверяется живым запросом: {}".format(
                       сессия, paths.команда("doctor", "--живой")))
        # Красным этот пункт не бывает: на красный нужна команда починки,
        # а чинить тут нечего — сессию доказывает живой запрос, а не эта
        # строка. Зелёное и внимание разводит _пункт_keepalive.
        значок_ka, текст_ka = _пункт_keepalive(состояние_демона)
        _пункт(значок_ka, "keepalive", текст_ka)

    # --- регистрация у клиентов ---
    for цель in (register.цель_desktop(), register.цель_code()):
        текст = register.статус(цель)
        if текст == "зарегистрирован":
            _пункт(ОК, цель.имя, текст)
        elif текст == "клиент не установлен":
            _пункт(ВНИМАНИЕ, цель.имя, текст)
        elif текст == register.БИТЫЙ:
            красных += _пункт(ПЛОХО, цель.имя,
                              "{}: {}".format(текст, цель.путь),
                              "исправьте файл и повторите "
                              + paths.команда("register"))
        else:
            красных += _пункт(ПЛОХО, цель.имя, текст, paths.команда("register"))

    # Codex необязателен: подписка ChatGPT есть не у всех, и «записи нет» —
    # не поломка, а несостоявшийся выбор. Красным её называть нельзя, иначе
    # значок перестанет значить «сломано» и там, где он заработан. Битый
    # файл и запись, ведущая в никуда, — исключения: это уже поломки,
    # и чинить их человеку.
    цель_codex = register.цель_codex()
    текст = register.статус_codex(цель_codex)
    if текст == "зарегистрирован":
        _пункт(ОК, цель_codex.имя, текст)
    elif текст == register.ЗАПИСЬ_БЕЗ_ФАЙЛА:
        # Выбор Codex здесь уже сделан — запись есть, — и сервер по ней
        # не поднимется: это поломка, а не пропущенная необязательность.
        # Путь не печатаем: он ничего не чинит, чинит команда ниже.
        красных += _пункт(ПЛОХО, цель_codex.имя,
                          текст + " — пакет переустановлен в другой каталог?",
                          paths.команда("register", "--codex"))
    elif текст == register.БИТЫЙ_TOML:
        красных += _пункт(ПЛОХО, цель_codex.имя,
                          "{}: {}".format(текст, цель_codex.путь),
                          "исправьте файл и повторите "
                          + paths.команда("register", "--codex"))
    else:
        _пункт(НЕЙТРАЛЬНО, цель_codex.имя, "{} — необязательно: {}".format(
            текст, paths.команда("register", "--codex")))

    # Зелёным называется только доказанное. «Запись есть» зелёным не
    # называется вовсе: именно так doctor показывал исправной задачу
    # прежнего установщика, которая вела в исчезнувший каталог и падала
    # при каждом входе.
    try:
        код_ас, текст_ас = autostart.проверить()
    except autostart.НетПоддержки as e:
        _пункт(ВНИМАНИЕ, "автозапуск", str(e).splitlines()[0])
    else:
        if код_ас == autostart.ЧУЖАЯ:
            красных += _пункт(ПЛОХО, "автозапуск", текст_ас,
                              paths.команда("autostart", "on")
                              + "   (заменит прежнюю запись) либо "
                              + paths.команда("autostart", "off"))
        elif код_ас == autostart.НЕИЗВЕСТНО:
            _пункт(ВНИМАНИЕ, "автозапуск", текст_ас)
        else:
            _пункт(ОК, "автозапуск", текст_ас)

    # --- отпечаток ---
    # Три состояния, а не два. У отсутствующего файла расхождение() пусто —
    # неотличимо от «сошлось», и doctor ставил зелёную галочку строке
    # «не снят». Зелёным называется только доказанное; «не снят» —
    # нейтрально, потому что отпечаток законно появляется лишь при первом
    # входе, и чинить тут нечего.
    снят = fingerprint.прочитать() is not None
    разница = fingerprint.расхождение()
    _пункт(ОК if снят and not разница else (ВНИМАНИЕ if снят else НЕЙТРАЛЬНО),
           "отпечаток", fingerprint.описание())
    if разница:
        # Решение 16: расхождение — предупреждение, а не ошибка. Отпечаток
        # менять нельзя: сессия привязана к записанному, и «починка» здесь
        # означала бы повторный ручной вход на ровном месте.
        print("  {:<22} {}".format("это не ошибка:",
                                   "сессия привязана к записанному отпечатку; "
                                   "менять его нельзя"))

    print()
    if красных:
        print("{} красных пунктов: {}. У каждого выше названа команда починки."
              .format(ПЛОХО, красных))
        return КОД_НЕ_СДЕЛАНО
    print("{} красных пунктов нет.".format(ОК))
    if not живой:
        print("  Живость подписки этим НЕ доказана: {}".format(
            paths.команда("doctor", "--живой")))
    return КОД_ОК


