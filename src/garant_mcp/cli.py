def call(аргументы: list[str]) -> int:
    from . import daemon_client as dc

    if not аргументы:
        print("{} укажите метод. Пример: garant call article doc_id=12125178 "
              "article=97".format(ПЛОХО), file=sys.stderr)
        return КОД_УПОТРЕБЛЕНИЕ
    метод, пары = аргументы[0], аргументы[1:]
    параметры: dict = {}
    for кв in пары:
        if "=" not in кв:
            print("{} аргумент «{}» без знака равенства".format(ПЛОХО, кв),
                  file=sys.stderr)
            return КОД_УПОТРЕБЛЕНИЕ
        к, з = кв.split("=", 1)
        параметры[к] = int(з) if з.isdigit() else з
    try:
        dc.готов_к_работе()
        print(json.dumps(dc.call(метод, **параметры), ensure_ascii=False,
                         indent=2))
    except dc.DaemonError as e:
        return _отказ(str(e))
    return КОД_ОК


# --- установка -------------------------------------------------------------
def setup(без_входа: bool = False) -> int:
    """Всё, что делается после установки пакета. Повторный запуск безвреден.

    Идемпотентность здесь не удобство, а требование: `setup` зовут второй раз
    именно тогда, когда первый раз что-то не доделал, — и переписать при этом
    рабочее состояние значило бы выбить человека из подписки за его же
    попытку починиться.
    """
    from . import daemon_client as dc
    from . import register

    print("{0}{0}{0} УСТАНОВКА garant-mcp {0}{0}{0}\n".format(РАМКА))

    print("1/5 каталог состояния")
    paths.ensure_state()
    _печать(ОК, "{} ({})".format(paths.STATE, paths.ПРИЧИНА_STATE))

    print("\n2/5 chromium")
    значок, текст, _ = _chromium()
    if значок == ОК:
        _печать(ОК, "уже установлен — не переустанавливаю")
    else:
        _печать(ВНИМАНИЕ, текст + " — ставлю")
        код = subprocess.call([sys.executable, "-m", "playwright",
                               "install", "chromium"])
        if код != 0:
            return _отказ(
                "playwright install chromium вернул код {}. Дальше идти "
                "нельзя: без браузера демон не поднимет профиль.".format(код))
        _печать(ОК, "chromium установлен")

    print("\n3/5 регистрация у MCP-клиентов")
    код = register_cmd([])
    # Код register_cmd итогом здесь быть не может: он ненулевой и тогда, когда
    # клиент просто не установлен, — а это не отказ установки. Спрашиваем то же,
    # что спросит doctor на шаге 5, чтобы вес сказанного здесь совпал с весом
    # итога: иначе человек читает «продолжаю», через десять строк «завершена
    # не полностью» и не понимает, одно это событие или разные.
    без_записи = [ц.имя for ц in (register.цель_desktop(), register.цель_code())
                  if register.статус(ц) not in ("зарегистрирован",
                                                "клиент не установлен")]
    if без_записи:
        _печать(ПЛОХО,
                "записи нет у: {}. Инструменты «Гаранта» в этом клиенте "
                "не появятся, сколько его ни перезапускай — он о сервере "
                "не знает. Остальные шаги доделаю, но итог установки будет "
                "ненулевым, пока не выполнено: {}".format(
                    ", ".join(без_записи), paths.команда("register")))
    elif код != КОД_ОК:
        # Тот же перекос, только в другую сторону: register_cmd отказал
        # из-за клиента, которого на машине нет. Промолчать нельзя —
        # ✗ выше уже напечатан, и без объяснения он выглядит поломкой.
        _печать(ВНИМАНИЕ, "отказ выше — про клиента, которого на машине нет; "
                          "каталог настроек ему не создаём. На итог установки "
                          "это не влияет: поставите клиента — выполните {}"
                .format(paths.команда("register")))

    print("\n4/5 вход в подписку")
    if без_входа:
        _печать(ВНИМАНИЕ, "пропущен по ключу --без-входа; выполнить: "
                + paths.команда("login"))
    else:
        сессия = ""
        try:
            dc.обеспечить_демона()
            сессия = dc.состояние().get("сессия") or ""
        except dc.DaemonError as e:
            _печать(ВНИМАНИЕ, str(e).splitlines()[0])
        if сессия == "жива":
            _печать(ОК, "сессия уже жива — окно входа не открываю")
        else:
            код = login()
            if код != КОД_ОК:
                _печать(ВНИМАНИЕ, "вход не завершён; повторить: "
                        + paths.команда("login"))

    print("\n5/5 диагностика\n")
    код = doctor()

    if без_входа:
        # Ноль — только если сделано всё, но «всё» это то, за что взялись.
        # Осознанно пропущенный вход — выбор человека, и кода он не портит:
        # иначе успешная установка без входа штатно рапортует «не полностью»,
        # и на коды перестают смотреть. Но молчаливый ноль тут опаснее лишней
        # единицы, поэтому недостающее называется вслух и одной командой.
        print("\n{} Вход НЕ выполнен — пропущен по ключу --без-входа. "
              "До входа инструменты «Гаранта» не работают: подписку "
              "открывает только он.".format(ВНИМАНИЕ))
        print("  Добрать: " + paths.команда("login"))
    return код


