def _dig(obj: Any, path: str) -> Any:
    if not path:
        return None
    cur = obj
    for part in path.split("."):
        if cur is None:
            return None
        if isinstance(cur, list):
            try:
                cur = cur[int(part)]
            except (ValueError, IndexError):
                return None
        elif isinstance(cur, dict):
            cur = cur.get(part)
        else:
            return None
    return cur


def _fill(tpl: Any, params: dict) -> Any:
    if isinstance(tpl, str):
        whole = re.fullmatch(r"\{(\w+)\}", tpl)
        if whole:
            return params.get(whole.group(1), "")
        return re.sub(r"\{(\w+)\}", lambda m: str(params.get(m.group(1), "")), tpl)
    if isinstance(tpl, dict):
        return {k: _fill(v, params) for k, v in tpl.items()}
    if isinstance(tpl, list):
        return [_fill(v, params) for v in tpl]
    return tpl


def new_hash() -> str:
    """Гарант ждёт клиентский идентификатор сессии поиска (11 симв., base36)."""
    a = string.ascii_lowercase + string.digits
    return "".join(random.choice(a) for _ in range(11))


