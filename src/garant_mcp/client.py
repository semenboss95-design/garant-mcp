_TAG_BR = re.compile(r"</(p|div|tr|li|h\d)>|<br\s*/?>", re.I)
_TAG_CELL = re.compile(r"</(td|th)>", re.I)
_TAG_SUP = re.compile(r"<sup[^>]*>(.*?)</sup>", re.I | re.S)
_TAG_SUB = re.compile(r"<sub[^>]*>(.*?)</sub>", re.I | re.S)
_TAG_ANY = re.compile(r"<[^>]+>")


def strip_html(s: str) -> str:
    """Гарант отдаёт куски документа как HTML — приводим к чистому тексту.

    Всё, что тут делается, делается ради одного: снятие разметки не имеет
    права ИЗМЕНИТЬ цитату. Молчаливое искажение здесь опаснее потери:
    hash_текста заверяет то, что вышло отсюда, и подмена уезжает к читателю
    с отпечатком, подтверждающим её подлинность.
    """
    if not s:
        return ""
    # Надстрочный индекс обязан пережить снятие тегов: «ст. 5<sup>1</sup>»
    # превращалось в «ст. 51» — другую норму под видом процитированной.
    # Каретка, а не «¹»: индексом бывает не только цифра (буква, звёздочка),
    # и надстрочных букв в юникоде на всю кириллицу нет; каретка же читается
    # и человеком, и любым последующим разбором, и ищется в любом редакторе.
    # Пустой <sup></sup> каретку НЕ даёт: знак, поставленный нами там, где
    # индекса не было, — то же искажение, только в другую сторону.
    s = _TAG_SUP.sub(lambda m: "^" + m.group(1) if m.group(1).strip() else "", s)
    # Подстрочный индекс — та же беда, что надстрочный, и разбирается так же:
    # в формуле налоговой нормы «К_д» и «Кд» — разные переменные, и склейка
    # уходит к читателю заверенной отпечатком. Подчёркивание, а не «д»
    # в юникоде: подстрочных букв кириллицы в нём нет вовсе, а «_» — общая
    # для всей отрасли запись индекса, читается человеком и ищется в любом
    # редакторе. Пустой <sub></sub> знака НЕ даёт — по той же причине, что
    # и пустой <sup>.
    s = _TAG_SUB.sub(lambda m: "_" + m.group(1) if m.group(1).strip() else "", s)
    s = _TAG_BR.sub("\n", s)
    # Ячейки таблицы разделяются видимым знаком: «<td>А</td><td>Б</td>»
    # склеивалось в «АБ» — слово, которого в документе нет.
    s = _TAG_CELL.sub(" | ", s)
    s = _TAG_ANY.sub("", s)
    s = html_mod.unescape(s)
    # &nbsp; доживал до цитаты как \xa0. Он неотличим от пробела на глаз,
    # и поиск по цитате — в том числе сверка с окном подписки — на нём
    # молча не находит ничего.
    s = s.replace("\xa0", " ")
    s = re.sub(r"[ \t]+", " ", s)
    # Разделитель ячеек в конце строки — наш след, а не текст документа.
    # Повторяется, потому что пустых ячеек в хвосте строки бывает несколько:
    # один проход снимал последнюю и оставлял «А |» — знак, который читатель
    # прочтёт как продолжение, которого нет.
    s = re.sub(r"(?: ?\|)+[ \t]*(?=\n|$)", "", s)
    s = re.sub(r"\n{3,}", "\n\n", s)
    return s.strip()


def _form(d: dict) -> str:
    return "&".join(f"{k}={quote(str(v), safe='')}" for k, v in d.items())


def _cache_key(name: str, params: dict) -> Path:
    raw = name + json.dumps(params, sort_keys=True, ensure_ascii=False, default=str)
    return CACHE_DIR / (hashlib.sha256(raw.encode()).hexdigest()[:32] + ".json")


def parse_ru_date(s: str) -> date | None:
    try:
        return datetime.strptime(s.strip(), "%d.%m.%Y").date()
    except Exception:
        return None


def _граница_текстом(значение: Any) -> str:
    """Граница периода текстом: «есть ли что читать», без предположения о типе.

    `_dig` отдаёт то, что лежит в чужом JSON, а не строку. До 08.09.2026 три
    места читали границу как `(значение or "").strip()` и на числе, списке
    или объекте падали `AttributeError`: терялся весь ответ — и `revisions`,
    и `revision_on_date`, и провенанс документа, — тогда как честный ответ
    здесь «граница есть, прочесть её нечем».

    Пустое по-питоновски — `None`, пустая строка, `0`, `False`, пустой список
    или объект — это ОТСУТСТВИЕ границы, ровно как читал его прежний
    `(значение or "").strip()`: пустым «по» «Гарант» пишет бессрочность,
    и подменять её незнанием нельзя. Иначе элемент `{с: 0, по: 0}` — шум
    карты без обеих границ — стал бы значащим периодом, а рендер того же
    значения рядом сказал бы «бессрочно»: расчёт и текст разошлись бы
    на одном и том же значении.

    Непустое нестроковое печатается JSON, а не `repr`: та же строка едет
    читателю в перечень периодов, и `['01.01.2015']` в нём — питоновский
    диалект, которого «Гарант» не присылал. `default=str` — потому что
    несериализуемое здесь обязано дать текст, а не исключение: ради этого
    функция и заведена.
    """
    if isinstance(значение, str):
        return значение.strip()
    if not значение:
        return ""
    return json.dumps(значение, ensure_ascii=False, default=str)


_MONTHS = {"января": 1, "февраля": 2, "марта": 3, "апреля": 4, "мая": 5, "июня": 6,
           "июля": 7, "августа": 8, "сентября": 9, "октября": 10, "ноября": 11,
           "декабря": 12}


def extract_doc_date(title: str) -> date | None:
    """Дата акта из заголовка: «от 12 марта 2025 г.» → date(2025, 3, 12)."""
    m = re.search(r"от\s+(\d{1,2})\s+([а-яё]+)\s+(\d{4})", title, re.I)
    if not m:
        return None
    mon = _MONTHS.get(m.group(2).lower())
    if not mon:
        return None
    try:
        return date(int(m.group(3)), mon, int(m.group(1)))
    except ValueError:
        return None


# Версия правила нормализации HTML. Отпечаток текста — функция «текст ×
# версия правила»: правка strip_html меняет ВСЕ ранее выданные отпечатки,
# и без маркера они обесцениваются молча — тот, кто пересчитает sha256
# сегодняшним кодом, получит «не совпало» и не поймёт, из-за чего.
# Меняя strip_html, поднимите версию.
# /2 — 07.09.2026: <br> и ячейки таблицы перестали склеивать текст, &nbsp;
# приведён к пробелу, надстрочный индекс отделён кареткой, подстрочный —
# подчёркиванием. Отпечатки, выданные под /1, сегодняшним кодом
# не пересчитываются — и это видно.
# Подстрочный индекс добавлен ТЕМ ЖЕ /2, а не /3: сама /2 ещё не выпущена
# ни одним релизом, ни одного отпечатка под ней наружу не ушло. Версия,
# растущая внутри невыпущенного шага, перестаёт означать «цитата у кого-то
# на руках посчитана иначе» — то есть обесценивает сама себя.
ПРАВИЛО_ОТПЕЧАТКА = "strip_html/2"


def _знаки_нормализации() -> str:
    """Что нормализация делает со знаками. Общая часть для текста и заголовков.

    Отдельно от `_оговорка_о_нормализации` потому, что заголовку перечня
    находок не подходит остальная её половина: врезок и отпечатка там нет,
    а знаки ровно те же. Второе написание перечня знаков разошлось бы
    с первым молча — и разошлось бы там, где читатель переносит реквизиты
    акта в подаваемый документ.

    Перечень не объявляется числом намеренно: «два знака — наши» было
    неправдой уже в момент, когда писалось, — неразрывный пробел и хвостовой
    «|» меняются здесь же и в счёт не попали.
    """
    return ("ОТЛИЧИТЬ НАШ ЗНАК ОТ ЗНАКА САМОГО АКТА ПО РЕЗУЛЬТАТУ НЕЛЬЗЯ: "
            "стоял ли такой же знак в документе «Гаранта», нормализация "
            "не знает. Ставим мы: «^» отделяет надстрочный индекс "
            "от основания («ст. 5^1» читается «ст. 5¹», а не «ст. 51»), "
            "«_» — подстрочный («К_д», а не «Кд»), « | » разделяет ячейки "
            "таблицы. Изменяем мы: неразрывный пробел заменён обычным "
            "(иначе поиск по цитате молча не находит ничего), «|» в конце "
            "строки УДАЛЁН — в том числе если он стоял в акте, "
            "подряд идущие пробелы и табуляции схлопнуты в один, три "
            "и более перевода строки — в два: разбивка акта на строки "
            "и его отступы здесь НЕ воспроизводятся.")


