# -*- coding: utf-8 -*-
"""Единственный слой настроек: env → endpoints.local.json → endpoints.json → умолчание.

Порядок именно такой, и он не произволен. `endpoints.json` лежит в репозитории
и приезжает всем одинаковым; переменная окружения принадлежит конкретной
машине. Настройка машины обязана побеждать файл из репозитория — иначе
пользователь, у которого порт занят чужой программой, не сможет ничего
сделать, не правя файл, который затрёт следующее обновление. Между ними лежит
endpoints.local.json из каталога состояния: он принадлежит машине и обновлением
не затирается, поэтому побеждает пакетный файл и проигрывает переменной.

До этого модуля настроек не было вовсе: порт был константой в двух Python-файлах
и трижды в PowerShell, keepalive — умолчанием параметра, headless — прямым
чтением os.environ по месту. Значения расходились молча.

НИ ОДНОГО mkdir И НИ ОДНОГО СЕТЕВОГО ВЫЗОВА НА ИМПОРТЕ — как и в paths.py.
Модуль только читает и приводит типы.

Порт здесь — ЖЕЛАЕМЫЙ, а не фактический. Демон может обнаружить его занятым
и сесть на соседний; фактический он пишет в STATE/daemon_port. Клиенту,
который хочет знать, куда стучаться на самом деле, одного config.PORT мало.
"""

from __future__ import annotations

import json
import os

# Умолчания. Здесь, а не в местах использования: разъехавшиеся умолчания
# ровно так и появляются.
УМОЛЧАНИЯ = {
    "port": 8787,
    "keepalive_sec": 120,
    "headless": True,
    "bridge": False,
    "call_timeout_sec": 180,
    "cache_ttl_hours": 24.0,
    "record": False,
}

_КЭШ_КАРТЫ: dict | None = None


def _прочитать(файл) -> dict:
    """JSON из файла; любая неудача — пустой словарь, а не исключение.

    Отсутствие файла тут норма (локального может не быть вовсе), а битый
    JSON не повод не запуститься: работающий контур на умолчаниях полезнее
    исключения в момент импорта.
    """
    try:
        разобранное = json.loads(файл.read_text(encoding="utf-8"))
        return разобранное if isinstance(разобранное, dict) else {}
    except (OSError, ValueError, AttributeError):
        return {}


def _слить(база: dict, поверх: dict) -> dict:
    """Локальная карта поверх пакетной — по секциям, а не подменой файла.

    Подмена целиком означала бы, что человек, переопределивший один ключ,
    молча теряет всю остальную карту эндпоинтов и получает нерабочий клиент.
    Глубина ровно одна: секции карты — плоские словари, а рекурсивное слияние
    сделало бы невозможным убрать ключ, не убрав секцию.
    """
    итог = dict(база)
    for ключ, значение in поверх.items():
        текущее = итог.get(ключ)
        if isinstance(текущее, dict) and isinstance(значение, dict):
            итог[ключ] = {**текущее, **значение}
        else:
            итог[ключ] = значение
    return итог


def карта() -> dict:
    """Карта эндпоинтов: пакетный endpoints.json + endpoints.local.json поверх.

    Локальный слой существует затем, что пакетный файл затирается обновлением:
    без него «обновить» означало бы «потерять свою настройку молча».

    paths импортируется здесь, а не наверху, намеренно: paths спрашивает у нас
    имя каталога профиля, и импорт на уровне модуля замкнул бы круг — какой из
    двух модулей окажется первым, зависит от того, кого позвал вызывающий.

    Кэш здесь — от ПОВТОРНОГО чтения файлов, а не отсрочка первого: первое
    обращение случается на импорте этого же модуля (СЕКЦИЯ ниже), потому что
    PORT, KEEPALIVE_SEC и остальные значения — модульные константы. Обещать
    ленивость было бы неправдой: два файла читаются в момент импорта, и
    правило «импорт без побочных эффектов» это допускает ровно потому, что
    чтение — не запись и на read-only установке проходит.
    """
    global _КЭШ_КАРТЫ
    if _КЭШ_КАРТЫ is None:
        from . import paths

        _КЭШ_КАРТЫ = _слить(_прочитать(paths.HOME / "endpoints.json"),
                            _прочитать(paths.local_endpoints_file))
    return _КЭШ_КАРТЫ


def _секция_daemon() -> dict:
    """Секция `daemon` из карты эндпоинтов (с учётом локального слоя)."""
    секция = карта().get("daemon")
    return секция if isinstance(секция, dict) else {}


СЕКЦИЯ = _секция_daemon()


def _флаг(значение: str) -> bool:
    """Строка окружения — в булево.

    «0», «false», «no», «off» и пустая строка — ложь, остальное — истина.
    Терпимость здесь уместна: переменную задаёт человек в ярлыке или в
    планировщике, и GARANT_BRIDGE=false не должна означать «включено».
    """
    return значение.strip().strip('"').lower() not in (
        "", "0", "false", "no", "off", "нет")


def _значение(ключ: str, env: str | None, json_ключ: str | None):
    """env → endpoints.json → умолчание, с приведением к типу умолчания.

    Тип берётся у умолчания, а не задаётся отдельно: тогда его нельзя
    забыть, а неверное значение («порт=восемь») падает здесь, при импорте,
    а не через час работы там, где им попытались воспользоваться.
    """
    умолчание = УМОЛЧАНИЯ[ключ]

    if env:
        сырое = os.environ.get(env)
        if сырое is not None and сырое.strip() != "":
            if isinstance(умолчание, bool):
                return _флаг(сырое)
            try:
                return type(умолчание)(сырое.strip().strip('"'))
            except ValueError:
                raise ValueError(
                    "{}={!r} — не {}. Исправьте переменную окружения или "
                    "снимите её.".format(env, сырое, type(умолчание).__name__))

    if json_ключ is not None and json_ключ in СЕКЦИЯ:
        сырое = СЕКЦИЯ[json_ключ]
        if isinstance(умолчание, bool):
            return _флаг(сырое) if isinstance(сырое, str) else bool(сырое)
        try:
            return type(умолчание)(сырое)
        except (TypeError, ValueError):
            raise ValueError(
                "endpoints.json, daemon.{}={!r} — не {}.".format(
                    json_ключ, сырое, type(умолчание).__name__))

    return умолчание


PORT = _значение("port", "GARANT_PORT", "port")

# Период keepalive настраиваемый, но НЕ произвольный. Cookie `_keepalive_`
# живёт единицы минут: период за этой границей означает, что подписка
# отваливается посреди работы, а выглядит это как «Гарант сломался» — до
# ручного повторного входа в браузере. Настройка, способная тихо сломать
# рабочую вещь, настройкой быть не должна, поэтому значение зажимается,
# а не принимается как есть.
#
# Нижняя граница — не про Гарант, а про приличия: пинг раз в секунду это
# просто лишний трафик к чужому серверу.
ПРЕДЕЛ_KEEPALIVE = (15, 240)

ЗАПРОШЕННЫЙ_KEEPALIVE = _значение(
    "keepalive_sec", "GARANT_KEEPALIVE_SEC", "keepalive_sec")
KEEPALIVE_SEC = min(max(ЗАПРОШЕННЫЙ_KEEPALIVE, ПРЕДЕЛ_KEEPALIVE[0]),
                    ПРЕДЕЛ_KEEPALIVE[1])

# Зажали молча — и человек весь день гадает, почему GARANT_KEEPALIVE_SEC=600
# ничего не изменила. Строку печатает не config (импорт обязан молчать:
# server.py говорит с клиентом по stdout), а тот, у кого есть лог, — см.
# keepalive_зажат() и её вызов в daemon.main().
def keepalive_зажат() -> str | None:
    """Сообщение, если запрошенный период не влез в предел. Иначе None."""
    if ЗАПРОШЕННЫЙ_KEEPALIVE == KEEPALIVE_SEC:
        return None
    return ("keepalive: запрошено {} с, применено {} с (предел {}…{} с — "
            "cookie _keepalive_ живёт единицы минут)".format(
                ЗАПРОШЕННЫЙ_KEEPALIVE, KEEPALIVE_SEC, *ПРЕДЕЛ_KEEPALIVE))


CALL_TIMEOUT = _значение("call_timeout_sec", "GARANT_CALL_TIMEOUT", "call_timeout_sec")

# Мост в endpoints.json есть, включается — шаг 4 этого же этапа. Здесь только
# читается: слой настроек обязан знать про ключ раньше, чем им пользуются,
# иначе ключ заводят по месту и он снова оказывается вне слоя.
BRIDGE = _значение("bridge", "GARANT_BRIDGE", "bridge")

# Срок годности записи кэша поиска. Кэшируются только перечни находок, не
# тексты норм, поэтому риск не «неверный текст», а неполная выдача: документ,
# появившийся в базе после записи, в этом поиске не появится никогда. Без
# срока годности это «никогда» буквально: запись жила до ручного удаления
# файлов. Часы, а не секунды, потому что величина человеческая, и дробные
# значения осмысленны (0 — не отдавать из кэша ничего).
CACHE_TTL_HOURS = _значение("cache_ttl_hours", "GARANT_CACHE_TTL_HOURS",
                            "cache_ttl_hours")

# Запись сырых тел ответов в <состояние>/recordings (решение 17). Ключа
# в endpoints.json нет намеренно, как и у headless: это переключатель на один
# сеанс живой приёмки, а не настройка установки. Читается через модуль, а не
# из os.environ по месту, — иначе флаг заводится по месту и снова оказывается
# вне слоя настроек.
RECORD = _значение("record", "GARANT_RECORD", None)

# У headless нет ключа в endpoints.json намеренно: это отладочный
# переключатель на один запуск («покажи мне окно»), а не настройка установки.
# Историческая семантика сохранена: GARANT_HEADLESS=0 — ВИДИМОЕ окно.
HEADLESS = _значение("headless", "GARANT_HEADLESS", None)


def описание() -> str:
    """Одна строка о действующих настройках. Для логов и диагностики."""
    return ("порт {} (желаемый), keepalive {} с, таймаут вызова {} с, "
            "headless {}, мост {}, кэш поиска {} ч, запись тел {}").format(
        PORT, KEEPALIVE_SEC, CALL_TIMEOUT,
        "да" if HEADLESS else "нет", "вкл" if BRIDGE else "выкл",
        CACHE_TTL_HOURS, "вкл" if RECORD else "выкл")
