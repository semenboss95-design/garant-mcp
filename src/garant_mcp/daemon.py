"""
garant-daemon — служба, владеющая браузерным профилем «Гаранта».

ЗАЧЕМ. Сессию Гаранта держит живой периодический вызов /server/keepalive:
cookie _keepalive_ живёт единицы минут. Пока браузер поднимал MCP-сервер,
сессия жила ровно столько, сколько открыт Claude Code, — закрыли окно,
и через несколько минут подписка отваливалась. Плюс профиль браузера может
держать только один процесс, поэтому фоновый пингер рядом было не поставить:
он занял бы профиль, и сервер не запустился бы.

РЕШЕНИЕ. Профилем владеет ОДИН постоянный процесс — этот. Он:
  · держит браузерный контекст открытым всегда;
  · пингует keepalive по таймеру, независимо от Claude Code;
  · выполняет запросы к Гаранту по HTTP на 127.0.0.1;
  · пишет структурный лог: каждый вызов, каждый keepalive, каждая смена
    состояния сессии;
  · умеет открыть видимое окно для входа в том же профиле.

MCP-сервер и утилиты становятся его клиентами. Конфликта «профиль занят»
больше не существует: владелец один — и вход в подписку он тоже выполняет
сам, видимым окном на своём же профиле (решение 15).

Запуск вручную:      garant-daemon
Состояние:           garant status
"""
