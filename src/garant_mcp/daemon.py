def _из_кэша(результат) -> bool:
    """Ответ пришёл из кэша, а не из «Гаранта».

    Отметку ставит сам клиент при чтении записи (`provenance.из_кэша`).
    Нужна ровно для одного решения: кэшированный ответ живость сессии
    не подтверждает — в «Гарант» он не ходил.
    """
    return bool(isinstance(результат, dict)
                and (результат.get("provenance") or {}).get("из_кэша"))


def _признак_состояния() -> str:
    """Значение признака демона: правда о РАБОЧЕМ ПОТОКЕ, а не литерал.

    «работает» было безусловной строкой: поток браузера мог быть мёртв,
    /health отвечал «работает», а каждый вызов после этого ждал полный
    таймаут. Ключ при этом остаётся тем же — на нём держится опознание
    до отправки токена (решение 9), и наш_демон_на_порту() ищет именно его.
    """
    if WORKER is None:
        return "рабочий поток не запущен"
    return "работает" if WORKER.is_alive() else "рабочий поток мёртв"


class Handler(BaseHTTPRequestHandler):
    def log_message(self, *a):
        pass  # свой лог, стандартный шум не нужен

    def _send(self, code: int, obj):
        body = json.dumps(obj, ensure_ascii=False).encode("utf-8")
        self.send_response(code)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def _отказ(self, ошибка):
        """Ответ на ошибку: код и текст решает ТИП, а не поиск подстрок.

        Прежний код выбирал между 503 и 500 по наличию «сесси», «401» или
        «403» в тексте — то есть запрос про статью 401.11 приходил
        пользователю как «сессия недействительна, войдите заново».
        """
        тело = {"ошибка": ошибка.сообщение, "тип": ошибка.тип,
                "сессия": WORKER.state["сессия"]}
        тело["что_делать"] = (
            "Сессия подписки недействительна. Выполните: " + paths.команда("login")
            if ошибка.тип == protocol.ТИП_СЕССИЯ
            else "Подробности: " + paths.команда("logs"))
        self._send(protocol.HTTP_ПО_ТИПУ.get(ошибка.тип, 500), тело)

    def _auth(self) -> bool:
        if self.headers.get("X-Token", "") == TOKEN:
            return True
        self._send(401, {"ошибка": "неверный токен"})
        return False

    def do_GET(self):
        if self.path.startswith("/health"):
            # БЕЗ ТОКЕНА, а значит — без путей и без последней ошибки.
            # Этот ответ читает любой, кто может сделать GET на петлю
            # (заголовок Host демон не проверяет), а «последняя_ошибка»
            # носила msg[:300] с абсолютными путями машины. Пути и
            # состояние сессии переехали под токен, в /state.
            #
            # Ключ — из той же константы, что ищут в ответе. Здесь он и был
            # третьим независимым литералом: сменить признак в protocol.py
            # и не тронуть эту строку означало демона, который сам себя не
            # опознаёт.
            self._send(200, {
                ПРИЗНАК_ДЕМОНА: _признак_состояния(),
                "запущен": WORKER.state["запущен"],
                "вызовов_всего": WORKER.state["вызовов_всего"],
                "вызовов_с_ошибкой": WORKER.state["вызовов_с_ошибкой"],
                "перезапусков_браузера": WORKER.state["перезапусков_браузера"],
                "очередь": WORKER.q.qsize(),
                "вход_идёт": WORKER.вход_идёт.is_set(),
            })
            return
        if self.path.startswith("/version"):
            # Версия и признак — и только. Нужна серверу, чтобы не работать
            # молча на старом коде демона после обновления пакета.
            self._send(200, {ПРИЗНАК_ДЕМОНА: _признак_состояния(),
                             "версия": __version__})
            return
        if self.path.startswith("/state"):
            if not self._auth():
                return
            st = dict(WORKER.state)
            st[ПРИЗНАК_ДЕМОНА] = _признак_состояния()
            st["версия"] = __version__
            st["очередь"] = WORKER.q.qsize()
            st["вход_идёт"] = WORKER.вход_идёт.is_set()
            # Абсолютные пути живут ЗДЕСЬ и только здесь: под токеном.
            st["каталоги"] = {"состояние": str(paths.STATE),
                              "профиль": str(paths.profile_dir),
                              "логи": str(LOG_DIR)}
            st["отпечаток"] = fingerprint.описание()
            self._send(200, st)
            return
        if self.path.startswith("/logs"):
            if not self._auth():
                return
            f = LOG_DIR / "daemon.log"
            tail = f.read_text(encoding="utf-8", errors="replace").splitlines()[-200:] \
                if f.exists() else []
            self._send(200, {"строк": len(tail), "лог": tail})
            return
        self._send(404, {"ошибка": "нет такого пути"})

    def do_POST(self):
        if not self._auth():
            return
        n = int(self.headers.get("Content-Length", 0) or 0)
        try:
            req = json.loads(self.rfile.read(n) or b"{}")
        except Exception:
            self._send(400, {"ошибка": "тело не JSON"})
            return

        if self.path.startswith("/login"):
            # «Я вошёл» приходит, ПОКА поток занят входом, поэтому команда
            # не идёт в очередь: она только ставит событие, которое ждёт
            # окно входа. Через очередь она дождалась бы конца ожидания,
            # то есть себя самой.
            if req.get("готово") is True or req.get("действие") == "готово":
                WORKER.вход_подтверждён.set()
                self._send(200, {"подтверждено": True,
                                 "вход_идёт": WORKER.вход_идёт.is_set()})
                return
            if WORKER.вход_идёт.is_set():
                self._send(409, {"ошибка": "вход уже идёт — окно открыто",
                                 "что_делать": "Войдите в открытом окне либо "
                                               "дождитесь конца ожидания."})
                return
            try:
                # Запас над потолком: ждать вход столько же, сколько
                # обычный вызов, — значит оборвать человека на середине.
                self._send(200, WORKER.submit(
                    "_login", {}, timeout=ПОТОЛОК_ВХОДА_СЕК + 60))
            except Exception as e:
                self._отказ(protocol.классифицировать(e))
            return

        if self.path.startswith("/probe"):
            try:
                # Тот же таймаут, что у обычного вызова: probe — такой же
                # поход в браузер. Со своим литералом он объявил бы подписку
                # мёртвой раньше срока, настроенного пользователем.
                self._send(200, WORKER.submit("_probe", {},
                                              timeout=config.CALL_TIMEOUT))
            except Exception as e:
                self._отказ(protocol.классифицировать(e))
            return

        if self.path.startswith("/restart"):
            # Свой таймаут намеренно: перезапуск — короткая операция
            # (закрыть контекст и отпустить профиль), и ждать её столько же,
            # сколько запрос к Гаранту, незачем.
            try:
                self._send(200, WORKER.submit("_restart", {}, timeout=60))
            except Exception as e:
                self._отказ(protocol.классифицировать(e))
            return

        if self.path.startswith("/call"):
            name = req.get("метод") or req.get("method")
            params = req.get("параметры") or req.get("params") or {}
            if name in ВНУТРЕННИЕ:
                self._send(400, {"ошибка": "«{}» — внутренняя операция демона, "
                                           "она выполняется POST /login".format(name)})
                return
            if name not in ALLOWED:
                self._send(400, {"ошибка": f"метод «{name}» не разрешён",
                                 "разрешены": sorted(ALLOWED - ВНУТРЕННИЕ)})
                return
            try:
                self._send(200, {"результат": WORKER.submit(name, params)})
            except Exception as e:
                self._отказ(protocol.классифицировать(e))
            return

        self._send(404, {"ошибка": "нет такого пути"})


class _Сервер(ThreadingHTTPServer):
    """HTTP-сервер, у которого занятый порт ЗАНЯТ.

    ThreadingHTTPServer по умолчанию ставит SO_REUSEADDR. На POSIX это
    безобидно — флаг лишь разрешает переиспользовать порт в TIME_WAIT.
    На Windows тот же флаг разрешает сесть ПОВЕРХ чужого живого слушателя:
    бинд «успешен», порт делят два процесса, и запросы достаются кому
    придётся. Занятость мы выясняем именно биндом — значит, на Windows
    флаг обязан быть снят, иначе выяснять нечего.

    SO_EXCLUSIVEADDRUSE — вторая половина того же: она запрещает уже нас
    самих подсадить на этот порт. Демон держит авторизованную сессию
    платной подписки, и делить с кем-то свой порт ему нечего.
    """

    allow_reuse_address = os.name != "nt"

    def server_bind(self):
        if os.name == "nt":
            self.socket.setsockopt(socket.SOL_SOCKET,
                                   socket.SO_EXCLUSIVEADDRUSE, 1)
        super().server_bind()


# Замок владения профилем держится открытым дескриптором на всё время жизни
# процесса. Ссылка глобальная не для удобства: закрытый файл снимает замок,
# и сборщик мусора сделал бы это молча, оставив профиль без защиты.
_ЗАМОК_ПРОФИЛЯ = None


def занять_профиль() -> None:
    """Монопольное владение профилем. Занято другим — выйти кодом 0.

    Раньше монопольность держал только порт, и этого не хватало. Между
    биндом порта и первым ответом на /health лежит подъём chromium —
    секунды; в этом окне наш_демон_на_порту() отвечает «нет», и второй
    экземпляр садится на СОСЕДНИЙ порт. Получаются два процесса на один
    профиль, то есть прямое нарушение ограничения 2. Тот же исход даёт
    протухший daemon_port: живой демон сидит не на желаемом порту, и новый
    спокойно занимает желаемый рядом с работающим. Раньше это окно открывал
    человек руками, теперь — любой вызов инструмента: демона поднимает сам
    сервер.

    Поэтому защищается то, что защищать и требуется: владение профилем.
    Порт — следствие, и оно остаётся как было.

    Блокировка файла, а не PID-файл: её снимает ОС в момент смерти процесса
    любым способом, включая kill -9 и отключение питания. Застрять
    в «занято» после падения демона такой замок не может, а PID-файл может
    и обязательно однажды застрянет.

    Чего замок НЕ покрывает, и это надо знать:
      · два каталога состояния (GARANT_HOME), указывающие на один физический
        профиль, — замки разные, профиль один;
      · чужую программу, открывшую chrome_profile напрямую: замок знают
        только наши;
      · сетевую файловую систему, где семантика flock ненадёжна;
      · внутренний однопроцессный локер самого chromium — он свой и о нашем
        замке не знает;
      · демона ПРЕЖНЕЙ версии. Замка в нём не было: процесс, поднятый до
        обновления пакета, не держит ничего, и новый демон займёт профиль
        рядом с ним. Окно короткое, но приходится ровно на обновление —
        закрыть его отсюда нечем, потому что вторая сторона о договорённости
        не знает. Лечится единственно `garant restart` после обновления.

    АСИММЕТРИЯ ОС, и она существенная. Замок привязан к inode, а не к имени.
    На POSIX `rm <состояние>/profile.lock` при живом владельце проходит —
    так делает чистка каталога состояния, восстановление из копии и всякий
    будущий `uninstall`/`migrate`, — и следующий экземпляр создаёт файл
    с НОВЫМ inode и спокойно берёт замок: два процесса на один профиль.
    На Windows дыры нет: занятый файл не удаляется вовсе.

    Поэтому на POSIX владелец переподтверждает замок — см. подтвердить_замок().
    Дыра от этого не исчезает, а превращается из вечной в окно. Окно НЕ равно
    периоду keepalive: цикл однопоточный и переподтверждение едет на его такте,
    поэтому окно — период keepalive ПЛЮС длительность самого долгого вызова,
    который такт в этот момент выполняет. Худший случай тут не поиск, а _login:
    он ждёт человека до ПОТОЛОК_ВХОДА_СЕК — и приходится ровно на вход, то есть
    на момент, когда профиль отпускается и берётся заново. Второго механизма
    монопольности при этом не заводится, замок остаётся тот же самый.
    Длительность окна вживую не мерялась: непроверено.
    """
    global _ЗАМОК_ПРОФИЛЯ
    файл = open(paths.profile_lock_file, "a+b")
    try:
        if os.name == "nt":
            import msvcrt

            файл.seek(0)
            msvcrt.locking(файл.fileno(), msvcrt.LK_NBLCK, 1)
        else:
            import fcntl

            fcntl.flock(файл.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
    except OSError:
        файл.close()
        # print, а не только log: второй экземпляр запускают руками, ярлыком
        # или сервером — и человек должен увидеть строку, а не искать её
        # в файле, который ведёт чужой процесс.
        print("garant-daemon уже владеет профилем в этом каталоге состояния. "
              "Второй не поднимаю.")
        log.info("профиль занят другим процессом — выхожу кодом 0")
        raise SystemExit(0)
    _ЗАМОК_ПРОФИЛЯ = файл


def подтвердить_замок() -> None:
    """POSIX: убедиться, что замок всё ещё лежит по своему имени, иначе взять заново.

    Только POSIX: на Windows удалить занятый файл нельзя, и проверять нечего.

    Сравниваются inode открытого дескриптора и файла по пути. Разошлись
    (или файла нет) — значит замок, который мы держим, больше никому
    не виден, и следующий экземпляр возьмёт свой на новом файле.

    Не занять_профиль(): та при неудаче уходит SystemExit(0), а здесь неудача
    означает, что второй демон УЖЕ поднялся в окне — уходить обязан не мы,
    законный владелец профиля. Поэтому громкая запись в лог и продолжение
    работы: два процесса на профиле хуже, чем один жалующийся.
    """
    global _ЗАМОК_ПРОФИЛЯ
    if os.name == "nt" or _ЗАМОК_ПРОФИЛЯ is None:
        return
    import fcntl

    try:
        свой = os.fstat(_ЗАМОК_ПРОФИЛЯ.fileno())
        на_месте = os.stat(paths.profile_lock_file)
        if (на_месте.st_dev, на_месте.st_ino) == (свой.st_dev, свой.st_ino):
            return
    except OSError:
        pass  # файла по пути нет — тот же случай, что и подмена inode

    try:
        новый = open(paths.profile_lock_file, "a+b")
    except OSError as e:
        log.error("файл замка профиля пропал и не создаётся заново (%s) — "
                  "монопольность профиля сейчас ничем не держится", e)
        return
    try:
        fcntl.flock(новый.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
    except OSError:
        новый.close()
        log.error("файл замка профиля был удалён, и новый уже занят другим "
                  "процессом: похоже, второй garant-daemon поднялся на этот "
                  "же профиль. Остановите лишний — ограничение «один профиль "
                  "= один процесс» сейчас нарушено")
        return
    прежний, _ЗАМОК_ПРОФИЛЯ = _ЗАМОК_ПРОФИЛЯ, новый
    прежний.close()
    log.warning("файл замка профиля был удалён при живом демоне — замок взят "
                "заново на новом файле")


def наш_демон_на_порту(порт: int, таймаут: float = 2.0) -> bool:
    """Отвечает ли на этом порту НАШ демон.

    GET /health токена не требует — и не должен: именно этим запросом
    выясняется, кому вообще можно показывать токен. Проверяется признак
    в теле, а не сам факт ответа: «ответили 200» умеет кто угодно, включая
    случайный локальный сервис, занявший порт после смерти демона.
    """
    try:
        with urllib.request.urlopen(
                "http://127.0.0.1:{}/health".format(порт), timeout=таймаут) as r:
            return ПРИЗНАК_ДЕМОНА in json.loads(r.read().decode("utf-8"))
    except Exception:
        return False


def записать_порт(порт: int) -> None:
    """Фактический порт и PID — атомарно.

    Временный файл рядом и os.replace, а не запись на месте: читатель,
    заставший запись на середине, получил бы обрезанный JSON. У файла два
    читателя — клиент и PowerShell-пульт, — и второй по нему УБИВАЕТ процесс.
    Половина числа в поле pid означает убийство постороннего.

    Рядом, а не во временном каталоге ОС: os.replace атомарен только в
    пределах одной файловой системы.
    """
    врем = PORT_FILE.with_name(PORT_FILE.name + ".tmp")
    врем.write_text(
        json.dumps({"порт": порт, "pid": os.getpid(),
                    "записан": datetime.now().isoformat(timespec="seconds")},
                   ensure_ascii=False),
        encoding="utf-8")
    os.replace(врем, PORT_FILE)


def занять_порт(желаемый: int) -> ThreadingHTTPServer:
    """Сесть на первый свободный порт диапазона. Бинд, а не проверка.

    Проверять занятость перед биндом — TOCTOU: между проверкой и биндом
    порт заберёт другой процесс, и демон изредка падал бы «уже занят» на
    порту, который секунду назад был свободен. Воспроизводится плохо,
    чинится долго.

    Особый случай — порт занят НАШИМ же демоном. Это не сбой, а достигнутое
    желаемое состояние, и второй экземпляр обязан уйти, а не сесть рядом:
    профиль браузера монопольный, один профиль = один процесс.
    """
    for порт in range(желаемый, желаемый + ПОРТОВ_В_ДИАПАЗОНЕ):
        try:
            return _Сервер(("127.0.0.1", порт), Handler)
        except OSError:
            if наш_демон_на_порту(порт):
                # Не log: второй экземпляр запускают руками или ярлыком,
                # и человек должен увидеть строку, а не искать её в файле.
                print("garant-daemon уже работает на порту {}. "
                      "Второй не поднимаю.".format(порт))
                log.info("порт %d занят нашим же демоном — выхожу кодом 0", порт)
                raise SystemExit(0)
            log.info("порт %d занят посторонним — пробую следующий", порт)
    raise SystemExit(
        "Все порты диапазона {}…{} заняты. Освободите один из них либо "
        "задайте другой начальный: GARANT_PORT=<порт> или ключ daemon.port "
        "в endpoints.json.".format(желаемый, желаемый + ПОРТОВ_В_ДИАПАЗОНЕ - 1))


def _убрать_свой_порт(порт: int) -> None:
    """Снять daemon_port, если он всё ещё описывает НАС.

    Сверка перед удалением обязательна: демона могли перезапустить, пока
    этот экземпляр останавливался, и файл уже описывает нового. Удалить его
    значит увести клиента в никуда — и, что хуже, лишить пульт PID, по
    которому он отличает наш процесс от постороннего.
    """
    try:
        данные = json.loads(PORT_FILE.read_text(encoding="utf-8"))
        if данные.get("pid") == os.getpid() and данные.get("порт") == порт:
            PORT_FILE.unlink()
    except (OSError, ValueError):
        pass


class _Остановка(BaseException):
    """Пришёл SIGTERM. Исключение, потому что выход из serve_forever нужен
    штатный: только он доводит main до finally, где закрывается браузер.

    Наследник BaseException, а НЕ Exception, и это не вкусовщина.
    socketserver._handle_request_noblock оборачивает process_request в
    `except Exception: handle_error(...)` — наследник Exception, поднятый
    обработчиком сигнала в это окно (у ThreadingMixIn это создание и старт
    потока, окно короткое, но оно на каждом запросе, а `garant stop` бьёт
    по работающему демону), был бы съеден: в лог лёг бы трейсбек,
    serve_forever продолжил бы цикл, до finally дело не дошло бы вовсе.
    Соседняя ветвь `except KeyboardInterrupt` надёжна именно этим свойством,
    а не своей формой.
    """

    def __init__(self, номер: int):
        super().__init__(номер)
        self.номер = номер


def _на_сигнал(номер, _кадр):
    raise _Остановка(номер)


def main():
    global WORKER, TOKEN
    # Единственное место, где создаются каталоги. До этой строки контур
    # не трогает файловую систему вовсе.
    #
    # Каталоги моста создаются только при включённом мосте: пустые
    # bridge/requests и bridge/responses у того, кто мостом не пользуется, —
    # это не «лишние папки», а приглашение положить туда файл.
    paths.ensure_state(bridge=МОСТ)
    log.info(paths.описание())
    log.info("настройки: " + config.описание())
    # Отпечаток не снимается здесь: снимает его первый, кому он понадобился
    # (вход или подъём контекста), и записывает в файл. Строка в логе —
    # только о том, что уже есть.
    log.info(fingerprint.описание())
    зажат = config.keepalive_зажат()
    if зажат:
        log.warning(зажат)
    желаемый = int(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_PORT

    # Профиль занимается ПЕРВЫМ, до порта: ограничение 2 говорит про профиль,
    # а порт лишь следствие. Проверка порта окно гонки не закрывает — она
    # сама в нём и живёт.
    занять_профиль()

    # Порт занимается ДО запуска рабочего потока: если демон уходит кодом 0,
    # потому что уже работает, второй браузерный поток поднимать незачем.
    srv = занять_порт(желаемый)
    port = srv.server_address[1]

    TOKEN = token()
    WORKER = BrowserWorker()
    WORKER.start()

    # Только после успешного бинда. Файл, написанный раньше, отправлял бы
    # клиента на порт, которого нет.
    записать_порт(port)
    log.info("HTTP: слушаю 127.0.0.1:%d (токен в daemon_token)", port)
    if port != желаемый:
        log.warning("желаемый порт %d был занят — сел на %d", желаемый, port)
    # Без обработчика CPython умирает на SIGTERM средствами ОС: finally ниже
    # не исполняется, браузер не закрывается — и осиротевший chromium
    # переживает демона, продолжая держать профиль. Это ровно тот исход,
    # которым ограничение 2 и вызвано, и `garant stop` на POSIX посылает
    # именно SIGTERM.
    #
    # Обработчик поднимает исключение, а не зовёт srv.shutdown(): shutdown
    # ждёт выхода из serve_forever, а тот крутится в ЭТОМ же потоке —
    # получилось бы взаимное ожидание. Исключение выходит прямо из цикла
    # и уходит в finally. SIGINT не трогаем: Ctrl+C и так даёт
    # KeyboardInterrupt, и своим обработчиком мы бы только отняли у него
    # ветвь ниже.
    #
    # Ставится ВНУТРИ try, а не перед ним: сигнал, пришедший между установкой
    # обработчика и входом в try, поднял бы _Остановку мимо finally — то есть
    # daemon_port пережил бы демона, и следующий клиент пошёл бы на порт,
    # которого нет. Окно в несколько байт-кодов, но закрывается даром.
    try:
        try:
            signal.signal(signal.SIGTERM, _на_сигнал)
        except (ValueError, OSError, AttributeError) as e:
            # Не главный поток или платформа без SIGTERM: демон работать
            # обязан, но обещание мягкой остановки здесь не выполняется —
            # молчать нельзя.
            log.warning("обработчик SIGTERM не поставлен (%s: %s): остановка "
                        "сигналом не даст закрыть браузер", type(e).__name__, e)
        srv.serve_forever()
    except KeyboardInterrupt:
        log.info("остановка по Ctrl+C")
    except _Остановка as e:
        log.info("остановка по сигналу %s", e.номер)
    except Exception:
        log.error("фатально: %s", traceback.format_exc())
    finally:
        WORKER._остановлен.set()
        # Ждём, а не закрываем сами: браузер закрывает поток-владелец,
        # см. BrowserWorker.run(). Ожидание ограничено — поток может
        # стоять в окне входа, а снять daemon_port и уйти мы обязаны
        # в любом случае.
        WORKER.join(ПОТОЛОК_УБОРКИ_СЕК)
        if WORKER.is_alive():
            log.error("поток браузера не завершился за %d с — chromium мог "
                      "пережить демона и продолжает держать профиль",
                      ПОТОЛОК_УБОРКИ_СЕК)
        # Свой и только свой файл: если демон уже перезапущен и переписал
        # daemon_port, удаление здесь увело бы клиента в никуда.
        _убрать_свой_порт(port)
        log.info("garant-daemon остановлен")


if __name__ == "__main__":
    main()
