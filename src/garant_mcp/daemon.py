# --- логирование -----------------------------------------------------------
def setup_log() -> logging.Logger:
    log = logging.getLogger("garant")
    log.setLevel(logging.INFO)
    fmt = logging.Formatter("%(asctime)s  %(levelname)-7s  %(message)s",
                            datefmt="%d.%m.%Y %H:%M:%S")
    # delay=True: файл открывается при первой записи, а не при создании
    # обработчика. Без этого setup_log() на уровне модуля открывал бы файл
    # в каталоге, которого ещё нет, — и импорт падал бы ровно там, откуда
    # мы только что убрали mkdir.
    fh = logging.handlers.RotatingFileHandler(
        LOG_DIR / "daemon.log", maxBytes=2_000_000, backupCount=5,
        encoding="utf-8", delay=True)
    fh.setFormatter(fmt)
    log.addHandler(fh)
    sh = logging.StreamHandler(sys.stdout)
    sh.setFormatter(fmt)
    log.addHandler(sh)
    return log


log = setup_log()


# --- поток-владелец браузера ----------------------------------------------
class BrowserWorker(threading.Thread):
    """Единственный поток, который трогает Playwright.

    Объекты Playwright привязаны к создавшему их потоку, поэтому все обращения
    к браузеру сериализуются через очередь задач.
    """

    def __init__(self, keepalive_sec: int | None = None):
        super().__init__(daemon=True, name="garant-browser")
        self.q: queue.Queue = queue.Queue()
        # None, а не число в сигнатуре: умолчание живёт в config.py,
        # и второе его написание здесь разошлось бы с первым молча.
        self.keepalive_sec = (config.KEEPALIVE_SEC if keepalive_sec is None
                              else keepalive_sec)
        self.client: gc.GarantClient | None = None
        self.state = {
            "запущен": datetime.now().isoformat(timespec="seconds"),
            "сессия": "не проверена",
            "последний_keepalive": None,
            # Исход, а не факт: «keepalive: ok» демон писал в том числе
            # тогда, когда браузера не было вовсе и продлевать было нечего.
            "последний_keepalive_исход": None,
            "последняя_ошибка": None,
            "вызовов_всего": 0,
            "вызовов_с_ошибкой": 0,
            "перезапусков_браузера": 0,
            "сессия_жива_с": None,
            "последний_вход": None,
        }
        # Имя намеренно не `_stop`: у threading.Thread это приватный МЕТОД,
        # и на python 3.12 (минимум пакета и версия CI) Thread.join() зовёт
        # его через _wait_for_tstate_lock — событие, перекрывшее метод, даёт
        # TypeError: 'Event' object is not callable. На 3.14 реализация иная
        # и дефект не виден, поэтому здесь и нужна оговорка, а не молчание.
        self._остановлен = threading.Event()
        # Момент последнего keepalive. В __init__, а не в run(): такт цикла
        # вынесен в отдельный метод, и он обязан быть вызываемым сам по себе.
        self._last_ka = 0.0
        # Ставится HTTP-обработчиком по команде «я вошёл» и читается изнутри
        # окна входа. Событие, а не очередь: команда приходит, ПОКА поток
        # занят входом, — через очередь она дождалась бы конца ожидания,
        # то есть себя самой.
        self.вход_подтверждён = threading.Event()
        self.вход_идёт = threading.Event()

    # -- публичный интерфейс (вызывается из HTTP-потоков) --
    def submit(self, fn_name: str, kwargs: dict, timeout: float | None = None):
        """Выполнить в потоке браузера. Ошибка переезжает границу С ТИПОМ.

        Раньше в box лежала строка, submit поднимал RuntimeError(строка),
        и HTTP-слой решал по подстрокам, что именно случилось. Тип пережить
        такую границу не мог: он в ней и терялся.
        """
        timeout = config.CALL_TIMEOUT if timeout is None else timeout
        box: dict = {}
        done = threading.Event()
        self.q.put((fn_name, kwargs, box, done))
        if not done.wait(timeout):
            raise protocol.GarantError(
                f"Демон не ответил за {timeout:.0f} с",
                # Не дождались — это НЕ повод судить о сессии подписки:
                # именно так живая сессия и объявлялась мёртвой.
                protocol.ТИП_ТАЙМАУТ)
        if "error" in box:
            raise protocol.из_словаря(box["error"])
        return box["result"]

    # -- внутреннее --
    def _ensure_client(self):
        if self.client is None:
            # GARANT_HEADLESS=0 — окно браузера видно, и в нём можно работать
            # руками в ТОЙ ЖЕ сессии подписки. Это единственный способ смотреть
            # ГАРАНТ вживую, не создавая вторую сессию: профиль монопольный
            # (один профиль = один процесс), а подписка допускает одно
            # одновременное подключение — второй вход выбивает первый.
            видимый = not config.HEADLESS
            клиент = gc.GarantClient(headless=config.HEADLESS)
            if видимый:
                log.info("браузер: ВИДИМЫЙ режим (GARANT_HEADLESS=0)")
            log.info("браузер: поднимаю контекст")
            клиент._ensure()
            # self.client — ТОЛЬКО после успешного подъёма контекста.
            # Пока присваивание стояло до _ensure(), провалившийся подъём
            # оставлял клиента без страницы, keepalive молча возвращался
            # и писал «ok»: демон отчитывался о продлении сессии, которого
            # не было и быть не могло.
            self.client = клиент
            self.state["перезапусков_браузера"] += 1
            log.info("браузер: контекст поднят")

    def _set_session(self, alive: bool, reason: str = ""):
        was = self.state["сессия"]
        now = "жива" if alive else "недействительна"
        self.state["сессия"] = now
        if alive and was != "жива":
            self.state["сессия_жива_с"] = datetime.now().isoformat(timespec="seconds")
            log.info("СЕССИЯ: жива")
        elif not alive and was == "жива":
            lived = ""
            if self.state["сессия_жива_с"]:
                d = datetime.now() - datetime.fromisoformat(self.state["сессия_жива_с"])
                lived = f" (прожила {str(timedelta(seconds=int(d.total_seconds())))})"
            log.warning("СЕССИЯ: недействительна%s — %s", lived, reason)
            self.state["сессия_жива_с"] = None

    def _keepalive(self):
        """Продлить сессию и записать ИСХОД. Состояния «сессия» не трогает.

        Никогда — и это не упущение. «Гарант» отвечает 403 на живой сессии
        при холодном старте: код признаёт эту гонку сам, повтором после
        принудительного продления в GarantClient._fetch. Честный keepalive,
        пишущий в «сессия», объявил бы живую подписку недействительной
        ровно по той гонке, которую контур уже умеет переживать.
        """
        try:
            self._ensure_client()
            исход = self.client._keepalive(force=True)
            self.state["последний_keepalive"] = datetime.now().isoformat(
                timespec="seconds")
        except Exception as e:
            исход = "исключение: {}: {}".format(type(e).__name__, e)
            self.state["последняя_ошибка"] = "keepalive: {}".format(e)
        self.state["последний_keepalive_исход"] = исход
        (log.info if исход.startswith("HTTP 2") else log.warning)(
            "keepalive: %s", исход)

    def _probe(self):
        """Живая проверка подписки. Отвечает ровно тем, что доказано.

        Пустой список видов подпиской НЕ подтверждается: «Гарант» ответил,
        но не тем, чем описан картой. Прежний код на этом печатал галочку
        «ПОДПИСКА ОТВЕЧАЕТ. Видов информации: 0».

        Неудача судит сессию только по типу session. Таймаут и сетевая
        ошибка состояния сессии не трогают: раньше любое исключение,
        включая «не дождались», объявляло подписку мёртвой.
        """
        try:
            self._ensure_client()
            kinds = self.client.kinds(0)
        except Exception as e:
            ошибка = protocol.классифицировать(e)
            if ошибка.тип == protocol.ТИП_СЕССИЯ:
                self._set_session(False, ошибка.сообщение[:160])
            self.state["последняя_ошибка"] = ошибка.сообщение[:300]
            raise ошибка
        if kinds:
            self._set_session(True)
            return {"видов": len(kinds), "сессия": self.state["сессия"],
                    "подписка_ответила": True}
        return {"видов": 0, "сессия": self.state["сессия"],
                "подписка_ответила": False,
                "пояснение": ("Гарант ответил, но дерево видов пусто — это не "
                              "подтверждение подписки. Проверьте вход: "
                              + paths.команда("login"))}

    def _login(self) -> dict:
        """Вход в подписку силами демона (решение 15).

        Порядок здесь и есть выполнение ограничения 2: сначала отпускаем
        профиль, и только потом открываем окно. Прежний вход печатал «демон
        будет остановлен», слал /restart — а тот перезапускает контекст, не
        процесс, — и запускал вторым процессом отдельную программу входа на
        тот же монопольный профиль. Кто успел первым, решал случай.

        Исполняется в потоке-владельце браузера, поэтому таймер keepalive
        на время входа не идёт: продлевать нечего, контекст занят человеком.
        Возобновляется он сам, следующим оборотом цикла, — а вернуться к
        циклу гарантирует потолок ожидания.
        """
        self.вход_идёт.set()
        self.вход_подтверждён.clear()
        try:
            # Профиль монопольный: пока headless-контекст жив, окно входа
            # открыть нельзя, а второго процесса быть не должно.
            self._restart_browser()
            итог = gc.окно_входа(self.вход_подтверждён, ПОТОЛОК_ВХОДА_СЕК,
                                 лог=log.info)
        finally:
            self.вход_идёт.clear()
            self.вход_подтверждён.clear()
        self.state["последний_вход"] = "{} — {}".format(
            datetime.now().isoformat(timespec="seconds"), итог["как"])
        log.info("вход: %s (ждали %s с)", итог["как"], итог["ждали_сек"])
        # Состояние «сессия» здесь не трогаем намеренно: вход в окне не
        # доказывает, что подписка отвечает рабочему контексту. Доказывает
        # это только поход в «Гарант» — /probe.
        итог["что_дальше"] = ("Проверить подписку живым запросом: "
                              + paths.команда("doctor"))
        return итог

    def _restart_browser(self):
        log.warning("браузер: перезапуск контекста")
        try:
            if self.client:
                self.client.close()
        except Exception:
            pass
        self.client = None

    def run(self):
        log.info("=" * 62)
        log.info("garant-daemon запущен, keepalive каждые %d с", self.keepalive_sec)
        log.info("файловый мост: %s", BRIDGE if МОСТ else "выключен")
        try:
            while not self._остановлен.is_set():
                try:
                    self._такт()
                except Exception:
                    # Такт не имеет права убить поток. HTTP-сервер живёт
                    # в других потоках и продолжает отвечать, а keepalive
                    # прекращается навсегда — снаружи это не «демон упал»,
                    # а «Гарант перестал отвечать», и лечится ручным входом.
                    # Перехват стоит здесь, вокруг всего такта, а не вокруг
                    # отдельных вызовов: строка, дописанная в такт завтра,
                    # защищена по умолчанию, а не тем, что автор вспомнил
                    # про try.
                    log.error("такт цикла упал, работа продолжается: %s",
                              traceback.format_exc())
                    # Без паузы такт, падающий мгновенно (например, на самом
                    # q.get), крутился бы на полном ядре.
                    time.sleep(1.0)
        finally:
            # Уйти отсюда можно и по тому, что except выше не ловит:
            # SystemExit, MemoryError, KeyboardInterrupt. Тогда keepalive
            # прекращается; /health скажет правду (там спрашивают
            # is_alive() на месте), но след обязан остаться и в логе.
            if not self._остановлен.is_set():
                log.error("рабочий поток завершается НЕ по команде остановки — "
                          "keepalive больше не идёт: %s", traceback.format_exc())
            # Контекст закрывает ТОТ поток, который его открывал: объекты
            # Playwright привязаны к своему потоку, и close() из главного —
            # не гарантия, а надежда. Раньше эта уборка жила в finally main
            # и исполнялась только по Ctrl+C; со штатной остановкой сигналом
            # она стала главным путём, и бросок оттуда уводил бы выполнение
            # мимо _убрать_свой_порт, оставляя браузер незакрытым.
            try:
                if self.client:
                    self.client.close()
            except Exception:
                log.error("браузер не закрылся штатно: %s",
                          traceback.format_exc())
            self.client = None

    def _такт(self):
        """Один оборот цикла. Вызывается только из run() и только под перехватом."""
        try:
            item = self.q.get(timeout=1.0)
        except queue.Empty:
            item = None

        if item:
            fn_name, kwargs, box, done = item
            t0 = time.time()
            try:
                if fn_name == "_login":
                    # Без _ensure_client: вход начинается с ОТПУСКАНИЯ
                    # профиля, а не с его захвата.
                    box["result"] = self._login()
                elif fn_name == "_probe":
                    box["result"] = self._probe()
                elif fn_name == "_restart":
                    self._restart_browser()
                    box["result"] = {"перезапущен": True}
                else:
                    self._ensure_client()
                    fn = getattr(self.client, fn_name)
                    результат = fn(**kwargs)
                    box["result"] = результат
                    # Живость сессии подтверждает поход в «Гарант», а не
                    # факт ответа: выдача из кэша в «Гарант» не ходила
                    # и доказывает лишь то, что файл на диске читается.
                    if _из_кэша(результат):
                        log.info("вызов %s — ответ из кэша, сессию "
                                 "не подтверждает", fn_name)
                    else:
                        self._set_session(True)
                self.state["вызовов_всего"] += 1
                log.info("вызов %s(%s) — ok за %.1f с", fn_name,
                         ", ".join(f"{k}={str(v)[:40]}" for k, v in kwargs.items()),
                         time.time() - t0)
            except Exception as e:
                # Тип ставится один раз и здесь же принимает решения.
                # Прежний код искал подстроки «401», «403», «сесси»
                # в тексте любого исключения без приведения регистра:
                # запрос про статью 401.11 объявлял сессию мёртвой,
                # а «Сессия…» с заглавной не ловился вовсе.
                ошибка = protocol.классифицировать(e)
                self.state["вызовов_всего"] += 1
                self.state["вызовов_с_ошибкой"] += 1
                box["error"] = ошибка.словарь()
                self.state["последняя_ошибка"] = ошибка.сообщение[:300]
                log.error("вызов %s — ОШИБКА [%s] за %.1f с: %s", fn_name,
                          ошибка.тип, time.time() - t0, ошибка.сообщение)
                if ошибка.тип == protocol.ТИП_СЕССИЯ:
                    self._set_session(False, ошибка.сообщение[:160])
                if ошибка.тип == protocol.ТИП_БРАУЗЕР and self.client:
                    self._restart_browser()
            finally:
                done.set()

        # Проверка флага здесь, а не внутри _bridge_scan: сканирование
        # идёт в каждом обороте цикла, то есть раз в секунду, и на
        # выключенном мосту это был бы glob по несуществующему каталогу
        # до конца работы демона.
        if МОСТ:
            self._bridge_scan()

        if time.time() - self._last_ka >= self.keepalive_sec:
            # Отметка ставится ДО работы: сорвись что-нибудь ниже, следующий
            # keepalive пойдёт по расписанию, а не через секунду. Иначе
            # неудачный такт превращался бы в поток запросов к «Гаранту».
            self._last_ka = time.time()
            try:
                # Переподтверждение замка едет на такте keepalive, а не своим
                # таймером: отдельный поток был бы вторым механизмом там, где
                # механизм обязан остаться один. Свой перехват, поверх общего
                # на весь такт, — из-за порядка: сорвавшийся замок не смеет
                # отменить продление сессии. Цена у двух отказов разная,
                # отвалившаяся подписка дороже.
                подтвердить_замок()
            except Exception:
                log.error("переподтверждение замка профиля сорвалось, "
                          "keepalive идёт дальше: %s", traceback.format_exc())
            self._keepalive()
            self._save_state()

    def _bridge_scan(self):
        """Разобрать запросы, положенные файлами. Формат: {"метод": ..., "параметры": {...}}."""
        try:
            files = sorted(BR_IN.glob("*.json"))
        except Exception:
            return
        for f in files:
            rid = f.stem
            out = BR_OUT / f"{rid}.json"
            try:
                req = json.loads(f.read_text(encoding="utf-8"))
            except Exception as e:
                out.write_text(json.dumps(
                    {"ошибка": f"запрос не разобран: {e}"}, ensure_ascii=False),
                    encoding="utf-8")
                f.unlink(missing_ok=True)
                continue

            name = req.get("метод") or req.get("method")
            params = req.get("параметры") or req.get("params") or {}
            log.info("мост: запрос %s → %s(%s)", rid, name,
                     ", ".join(f"{k}={str(v)[:30]}" for k, v in params.items()))

            if name in ВНУТРЕННИЕ:
                # Мост безтокенный: кто может писать в каталог состояния,
                # тот через него вызывает метод. Вход открывает окно на
                # монопольном профиле — такое делается только под токеном.
                res = {"ошибка": "«{}» через мост не выполняется — только "
                                 "POST /login под токеном".format(name)}
            elif name not in ALLOWED:
                res = {"ошибка": f"метод «{name}» не разрешён",
                       "разрешены": sorted(ALLOWED)}
            else:
                try:
                    self._ensure_client()
                    fn = getattr(self.client, name)
                    результат = fn(**params)
                    res = {"результат": результат}
                    if not _из_кэша(результат):
                        self._set_session(True)
                    self.state["вызовов_всего"] += 1
                except Exception as e:
                    ошибка = protocol.классифицировать(e)
                    res = {"ошибка": ошибка.сообщение, "тип": ошибка.тип,
                           "сессия": self.state["сессия"]}
                    self.state["вызовов_всего"] += 1
                    self.state["вызовов_с_ошибкой"] += 1
                    self.state["последняя_ошибка"] = ошибка.сообщение[:300]
                    log.error("мост: %s — ОШИБКА [%s]: %s", rid, ошибка.тип,
                              ошибка.сообщение)
                    if ошибка.тип == protocol.ТИП_СЕССИЯ:
                        self._set_session(False, ошибка.сообщение[:160])
                    if ошибка.тип == protocol.ТИП_БРАУЗЕР and self.client:
                        self._restart_browser()

            # ответ пишем во временный файл и переименовываем: читатель никогда
            # не увидит наполовину записанный JSON
            tmp = out.with_suffix(".part")
            tmp.write_text(json.dumps(res, ensure_ascii=False, indent=2), encoding="utf-8")
            tmp.replace(out)
            f.unlink(missing_ok=True)
            log.info("мост: ответ %s готов", rid)

        # подчистить ответы старше суток
        import time as _t
        for old in BR_OUT.glob("*.json"):
            try:
                if _t.time() - old.stat().st_mtime > 86400:
                    old.unlink()
            except Exception:
                pass

    def _save_state(self):
        try:
            STATE_FILE.write_text(json.dumps(self.state, ensure_ascii=False, indent=2),
                                  encoding="utf-8")
        except Exception:
            pass


