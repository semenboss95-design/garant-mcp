# -*- coding: utf-8 -*-
"""
daemon_client — тонкий клиент к garant-daemon.

Используется MCP-сервером и утилитами. Своего браузера не поднимает,
поэтому конфликта за профиль не создаёт.

Демона он умеет и поднять: `обеспечить_демона()` запускает `garant-daemon`
отсоединённым процессом, если на порту его нет. Гонку двух поднимающих
разрешает сам демон, и не портом, а замком владения профилем: второй
экземпляр, увидев профиль занятым, выходит кодом 0 (ограничение 2).

CLI:
    python -m garant_mcp.daemon_client health    жив ли демон, счётчики
    python -m garant_mcp.daemon_client state     состояние сессии и каталоги
    python -m garant_mcp.daemon_client probe     живая проверка подписки
    python -m garant_mcp.daemon_client login     вход в Гарант (откроется окно)
    python -m garant_mcp.daemon_client вошёл     сказать демону «я вошёл»
    python -m garant_mcp.daemon_client logs      последние строки лога
    python -m garant_mcp.daemon_client restart   перезапустить браузер демона
    python -m garant_mcp.daemon_client port      фактический порт, PID (JSON)

    python -m garant_mcp.daemon_client call <метод> ключ=значение ...
        прямой вызов ГАРАНТа из терминала, в обход MCP. Нужен, когда среда
        не поднимает MCP-серверы, а работать надо. Примеры:
            call article doc_id=12125178 article=97
            call revision_on_date doc_id=12125178 on=26.05.2026
            call search query="статья 401.11 УПК" limit=5
            call practice query="мера пресечения истечение срока" kind="Высшие суды"
"""
from __future__ import annotations

import json
import os
import shutil
import subprocess
import sys
import threading
import time
import urllib.error
import urllib.request

from . import __version__
from . import config
from . import paths
from . import protocol

# Токен — из paths, а не рядом с кодом: пишет его демон, и пишет он
# в paths.token_file. Пока состояние лежит рядом с кодом, разница не
# видна; как только STATE уезжает в каталог данных ОС, клиент ищет
# токен там, где его никто не создавал, и сообщает «демон ни разу не
# запускался» про работающий демон.
TOKEN_FILE = paths.token_file

# Порт — через тот же слой, что у демона. Своя константа здесь уже была
# и расходилась бы с настройкой машины: демон сел бы на GARANT_PORT,
# а клиент продолжил стучаться в умолчание.
#
# И это всё равно только ЖЕЛАЕМЫЙ порт: демон мог найти его занятым
# и сесть на соседний, о чём написал в daemon_port. Фактический адрес
# считает _порт(), а доверять ему можно лишь после _убедиться_что_наш().
PORT = config.PORT
PORT_FILE = paths.port_file

# Тот же признак, что демон кладёт в тело GET /health. «Тот же» — буквально
# один объект из protocol.py, а не одинаково написанная строка: совпадение,
# которое держится на внимательности, однажды не удержится.
ПРИЗНАК_ДЕМОНА = protocol.ПРИЗНАК_ДЕМОНА


class DaemonError(protocol.GarantError):
    """Ошибка обращения к демону — с тем же типом, что и ошибки контура.

    Наследование, а не свой класс: тип ставится на той стороне границы,
    где известна причина, и обязан доехать до MCP-клиента неизменным.
    Два независимых класса с одинаковым смыслом теряли бы его на границе.
    """


def _база(порт: int) -> str:
    return f"http://127.0.0.1:{порт}"


def _порт() -> int:
    """Фактический порт демона: GARANT_PORT → daemon_port → умолчание.

    Переменная окружения впереди файла намеренно: человек, задавший её
    руками, отлаживает конкретный демон и не должен переспорить сам себя
    содержимым файла.

    Значение из файла доверия не даёт: файл может быть протухшим — демон
    умер, порт занял кто-то другой. Поэтому за чтением обязана идти
    проверка _убедиться_что_наш().
    """
    if os.environ.get("GARANT_PORT", "").strip():
        return PORT
    try:
        данные = json.loads(PORT_FILE.read_text(encoding="utf-8"))
        return int(данные["порт"])
    except (OSError, ValueError, KeyError, TypeError):
        return PORT


# Сколько ждать демона после запуска. Chromium стартует долго, и первый
# подъём контекста упирается в диск, а не в нас; девяносто секунд — это
# «долго, но не бесконечно»: за ними стоит не медленная машина, а поломка,
# и молчать о ней ещё минуту незачем.
СЕКУНД_НА_ПОДЪЁМ = 90

# Подъём демона — один на процесс. У сервера четыре потока в пуле, и на
# холодном старте каждый из них зовёт готов_к_работе(): без этого замка
# четыре потока делают четыре Popen подряд. Лишние экземпляры отсечёт
# замок профиля в самом демоне, но платить за это четырьмя запусками
# chromium незачем, а в логе это выглядит как поломка.
_ЗАМОК_ПОДЪЁМА = threading.Lock()


def _сырой(порт: int, path: str, payload=None, timeout: float = 10.0,
           токен: str | None = None):
    """Один HTTP-запрос. Токен добавляется, ТОЛЬКО если передан явно.

    Явно, а не «возьми сам»: прежний _req добавлял X-Token всякому, кто
    ответит, и на протухшем daemon_port токен от живой подписки уходил
    случайному локальному слушателю. Решение показать токен принимается
    в одном месте — в _req, после опознания.
    """
    url = _база(порт) + path
    data = (json.dumps(payload, ensure_ascii=False).encode("utf-8")
            if payload is not None else None)
    r = urllib.request.Request(
        url, data=data, method="POST" if data is not None else "GET")
    r.add_header("Content-Type", "application/json; charset=utf-8")
    if токен is not None:
        r.add_header("X-Token", токен)
    with urllib.request.urlopen(r, timeout=timeout) as resp:
        return json.loads(resp.read().decode("utf-8"))


def _убедиться_что_наш(порт: int) -> None:
    """GET /health без токена — и только потом токен.

    Рекурсии здесь нет: проверка ходит через _сырой, минуя _req, и токена
    не несёт. Сам /health токена не требует — именно поэтому им и можно
    спросить «кто там» у неизвестного.

    Отсутствие признака — не «странный ответ», а подмена: на порту, куда
    послал daemon_port, сидит посторонний. Показывать ему токен нельзя,
    и деградировать тут не во что.
    """
    try:
        тело = _сырой(порт, "/health", timeout=5.0)
    except urllib.error.HTTPError as e:
        raise DaemonError(
            f"На порту {порт} кто-то есть, но на /health отвечает HTTP "
            f"{e.code}. Это не наш демон — токен ему не отправлен.")
    except urllib.error.URLError as e:
        raise DaemonError(
            f"Демон не отвечает на {_база(порт)} ({e.reason}).\n"
            "Поднять:\n  " + paths.команда("restart")
            + "\nЧтобы поднимался при входе в систему:\n  "
            + paths.команда("autostart", "on"))
    except ValueError:
        raise DaemonError(
            f"На порту {порт} отвечают не JSON. Это не наш демон — "
            "токен ему не отправлен.")
    if not isinstance(тело, dict) or ПРИЗНАК_ДЕМОНА not in тело:
        raise DaemonError(
            f"На порту {порт} отвечает посторонняя программа, а не "
            "garant-daemon. Токен ей НЕ отправлен.\n"
            "Так бывает, когда демон умер, а порт занял кто-то другой: "
            "файл daemon_port остался от прежнего запуска. Поднимите "
            "демона заново — он перепишет файл:\n  " + paths.команда("restart"))


def _команда_демона() -> list[str]:
    """Чем запускать демона: консольный скрипт из PATH, иначе -m.

    Скрипт впереди намеренно: он лежит в окружении установленного пакета,
    и это тот же код, которым работает сервер. Запасной вариант через -m
    нужен запуску из исходников, где консольных скриптов ещё нет.
    """
    путь = shutil.which("garant-daemon")
    return [путь] if путь else [sys.executable, "-m", "garant_mcp.daemon"]


def обеспечить_демона(ждать_сек: float = СЕКУНД_НА_ПОДЪЁМ) -> str:
    """Демон работает. Если нет — поднять и дождаться.

    Раньше демона поднимала только задача планировщика или человек руками,
    и без неё инструменты не работали, а причина не называлась нигде.

    Гонку РАЗНЫХ процессов разрешает не этот код: её закрывает замок
    владения профилем в самом демоне — второй экземпляр, увидев профиль
    занятым, выходит кодом 0 (ограничение 2). Бинда порта для этого мало:
    между биндом и первым ответом на /health есть окно, в котором демон
    уже занял профиль, а опознать себя ещё не может.

    Гонка ВНУТРИ процесса закрывается здесь, замком: у сервера четыре
    потока в пуле, и на холодном старте каждый зовёт эту функцию.

    Порт перечитывается на каждой попытке: свежий демон мог найти желаемый
    занятым и сесть на соседний, о чём написал в daemon_port.
    """
    try:
        _убедиться_что_наш(_порт())
        return "демон уже работал"
    except DaemonError:
        pass

    with _ЗАМОК_ПОДЪЁМА:
        # Проверка повторяется под замком, и это не перестраховка: пока
        # поток ждал замка, демона мог поднять сосед по пулу — и ждал он
        # ровно столько, сколько поднимается chromium.
        try:
            _убедиться_что_наш(_порт())
            return "демон уже работал"
        except DaemonError:
            pass
        return _поднять(ждать_сек)


def _поднять(ждать_сек: float) -> str:
    """Запустить демона и дождаться его ответа. Зовётся только под замком."""
    команда = _команда_демона()
    # Отсоединённым процессом: демон переживает и MCP-клиента, и терминал,
    # из которого его подняли, — сессия подписки живёт keepalive-таймером,
    # а не чьим-то открытым окном.
    параметры: dict = {"stdin": subprocess.DEVNULL,
                       "stdout": subprocess.DEVNULL,
                       "stderr": subprocess.DEVNULL}
    if os.name == "nt":
        # Без окна консоли: сервер запускает MCP-клиент, и мигающее чёрное
        # окно посреди работы выглядит как чужая программа.
        параметры["creationflags"] = (getattr(subprocess, "CREATE_NO_WINDOW", 0)
                                      | getattr(subprocess, "DETACHED_PROCESS", 0))
    else:
        параметры["start_new_session"] = True
    try:
        subprocess.Popen(команда, **параметры)
    except OSError as e:
        raise DaemonError(
            "Не удалось запустить демона ({}: {}).\nЗапустите вручную:\n  ".format(
                type(e).__name__, e) + paths.команда("start"),
            protocol.ТИП_БРАУЗЕР)

    предел = time.time() + ждать_сек
    последняя = None
    while time.time() < предел:
        time.sleep(1.0)
        try:
            _убедиться_что_наш(_порт())
            return "демон поднят"
        except DaemonError as e:
            последняя = e
    raise DaemonError(
        "Демон не поднялся за {:.0f} с.\n{}\nПосмотрите, что он написал:\n  "
        .format(ждать_сек, последняя or "") + paths.команда("logs"),
        protocol.ТИП_ТАЙМАУТ)


def _версия_кортежем(строка) -> tuple:
    try:
        return tuple(int(x) for x in str(строка).split(".")[:3])
    except (TypeError, ValueError):
        return ()


def сверить_версию() -> None:
    """Демон старше сервера — это ошибка, а не мелочь.

    Пакет обновляется целиком, но демон при этом продолжает работать
    процессом со СТАРЫМ кодом: он поднят до обновления и живёт часами.
    Молча работать через него значит получать поведение прошлой версии
    и не иметь ни одного признака, что дело в этом.

    /version токена не требует — сверка идёт до всякого обращения под
    токеном и опознание не заменяет.
    """
    try:
        тело = _сырой(_порт(), "/version", timeout=5.0)
    except Exception:
        # Демон старой сборки про /version не знает вовсе. Это тоже
        # расхождение версий, и говорим о нём тем же способом.
        тело = {}
    демон = _версия_кортежем(тело.get("версия"))
    сервер = _версия_кортежем(__version__)
    if демон and сервер and демон >= сервер:
        return
    raise DaemonError(
        "Демон работает на версии {}, а этот код — {}. Пока демон не "
        "перезапущен, вызовы уходят в старый код.\nВыполните:\n  ".format(
            тело.get("версия") or "неизвестной (старая сборка)", __version__)
        + paths.команда("restart"))


def готов_к_работе() -> None:
    """Демон поднят и не старше нас. Зовётся перед первым вызовом инструмента."""
    обеспечить_демона()
    сверить_версию()


def _token(демон_отвечает: bool = False, порт: int | None = None) -> str:
    """Токен из STATE. Сообщение об отсутствии обязано называть, ГДЕ искали.

    Прежний текст говорил «демон ни разу не запускался» — и это утверждение
    о факте, которое бывает прямо ложным. Ровно так и случилось 05.09.2026:
    демон работал, keepalive шёл каждые две минуты, а клиент из другой копии
    кода объявлял, что демона никогда не было.

    Причина не в токене, а в расположении: `paths.STATE` у двух копий кода
    разное. Демон, запущенный из старой установки, держит токен рядом с собой;
    новая копия без `GARANT_HOME` и без следов установки рядом ищет его
    в каталоге данных ОС — и не находит.

    Отличить эти два случая можно, и клиент их различает: `_req` зовёт
    `_убедиться_что_наш` ДО токена, то есть к моменту отказа уже известно,
    отвечает ли на порту опознанный демон. Отвечает — «ни разу не
    запускался» заведомо ложь, и текст должен вести к переезду, а не
    к запуску второго процесса на монопольный профиль.
    """
    if TOKEN_FILE.exists():
        return TOKEN_FILE.read_text(encoding="utf-8").strip()

    # Оба текста собраны f-строками, и это не вкусовщина. Прежде здесь была
    # смесь «+» и .format: конкатенация выполняется раньше вызова, .format
    # достаётся ЛИШЬ последнему куску, а плейсхолдеры соседних уезжают
    # пользователю сырыми «{}». Так и уехал главный блок — «Искал здесь»,
    # ровно то единственное, ради чего это сообщение писалось. Ошибка молчит:
    # ни исключения, ни предупреждения, видно только в готовом тексте.
    # У f-строки каждый кусок подставляет себя сам, и потерять подстановку
    # конкатенацией уже нельзя.
    где = (f"Искал здесь: {TOKEN_FILE}\n"
           f"Каталог состояния выбран так: {paths.описание()}")

    if демон_отвечает:
        raise DaemonError(
            f"Демон на порту {порт} отвечает и опознан, но его токена нет там, "
            f"где ищет ЭТА копия кода.\n\n{где}\n\n"
            f"Это не «демон не запускался» — он работает. Это две установки: "
            f"демон запущен из другой папки и держит состояние рядом с собой.\n\n"
            f"Что делать, по возрастанию цены:\n"
            f"  1) указать этой копии на состояние работающего демона —\n"
            f"     GARANT_HOME=<папка, где лежит daemon_token>. Вход в подписку\n"
            f"     сохраняется, ничего не переносится;\n"
            f"  2) остановить того демона и поднять своего:\n"
            f"     {paths.команда('restart')}\n"
            f"     Вход в подписку придётся выполнить заново.\n"
            f"Где искать чужое состояние: у работающего демона оно названо в его "
            f"собственном логе первой строкой запуска. Совет «искать рядом "
            f"с кодом» неисполним с решения 14: код ставится пакетом, "
            f"и состояния рядом с ним нет ни у одной установки.")

    raise DaemonError(
        f"Файла daemon_token нет, и на порту никто не отвечает — похоже, демон "
        f"в этой установке ни разу не запускался.\n\n{где}\n\n"
        f"Запустите:\n  {paths.команда('start')}\n"
        f"Чтобы поднимался при входе в систему:\n  "
        f"{paths.команда('autostart', 'on')}")


# Клиент ждёт дольше демона намеренно: если оба отмерят одно и то же,
# клиент оборвёт соединение одновременно с таймаутом демона, и вместо
# внятного «демон не ответил за N с» пользователь увидит обрыв связи.
ЗАПАС_КЛИЕНТА_СЕК = 20


def _req(path: str, payload: dict | None = None,
         timeout: float | None = None):
    timeout = (config.CALL_TIMEOUT + ЗАПАС_КЛИЕНТА_СЕК
               if timeout is None else timeout)
    порт = _порт()

    # Сначала выясняем, кто на порту, и только потом достаём токен.
    # Порядок здесь и есть защита: /health токена не требует, всё остальное
    # требует — и получает его лишь после опознания. Рекурсии нет: проверка
    # ходит через _сырой, минуя _req.
    # Опознание прошло — значит на порту наш демон. Это и есть тот факт,
    # который отличает «токена нет, потому что демон не запускался» от
    # «токена нет здесь, потому что демон запущен из другой установки».
    _убедиться_что_наш(порт)
    токен = None if path == "/health" else _token(демон_отвечает=True, порт=порт)

    try:
        return _сырой(порт, path, payload, timeout, токен)
    except urllib.error.HTTPError as e:
        try:
            body = json.loads(e.read().decode("utf-8"))
        except Exception:
            body = {"ошибка": f"HTTP {e.code}"}
        # Тип берётся из тела, а не угадывается по коду и не теряется:
        # его поставил тот, кто знал причину, — поток браузера демона.
        # Пользователю при этом уходит текст, а не сериализованный JSON,
        # как было раньше.
        текст = str(body.get("ошибка") or body)
        если_есть = body.get("что_делать")
        raise DaemonError(текст + ("\n" + если_есть if если_есть else ""),
                          str(body.get("тип") or protocol.ТИП_API), e.code)
    except urllib.error.URLError as e:
        # Отдельный текст от того, что в _убедиться_что_наш: там демон не
        # ответил вовсе, здесь — ответил на /health секунду назад и пропал
        # посреди запроса. Это разные поломки и разные действия.
        raise DaemonError(
            f"Демон перестал отвечать на {_база(порт)} ({e.reason}).\n"
            "На /health он отвечал только что — похоже, упал посреди "
            "запроса. Что он написал перед этим:\n  " + paths.команда("logs"))


# --- прикладной интерфейс, повторяет методы GarantClient -------------------
def call(method: str, **params):
    return _req("/call", {"метод": method, "параметры": params})["результат"]


def адрес() -> dict:
    """Фактический порт, PID и живость демона — одним JSON.

    Существует ради PowerShell-пульта. Пульт мог бы прочитать daemon_port
    сам, но для этого ему пришлось бы заново вычислять STATE — портативная
    установка, GARANT_HOME, каталог данных ОС, — то есть завести второй
    источник истины о расположении, ровно тот, от которого этап 01
    и избавляется.

    Живость проверяется тем же опознанием, что и перед отправкой токена:
    пульт УБИВАЕТ по этому PID, и «файл есть» для такого решения мало.

    Ключи ЛАТИНИЦЕЙ, в отличие от остального контура. PowerShell 5.1
    декодирует stdout нативной программы в кодировке консоли, а не в
    UTF-8, и кириллические ключи приезжали бы битыми на машине с любой
    другой кодовой страницей. Машинный интерфейс не должен зависеть
    от настроек консоли.
    """
    порт = _порт()
    pid = None
    try:
        pid = json.loads(PORT_FILE.read_text(encoding="utf-8")).get("pid")
    except (OSError, ValueError, AttributeError):
        pass
    try:
        _убедиться_что_наш(порт)
        живой = True
    except DaemonError:
        живой = False
        # PID из протухшего файла принадлежит уже не нам. Отдать его пульту
        # значит предложить убить постороннюю программу.
        pid = None
    return {"port": порт, "pid": pid, "alive": живой}


def health() -> dict:
    """Безтокенный /health: жив ли демон и счётчики. Ни путей, ни состояния сессии."""
    return _req("/health")


def состояние() -> dict:
    """Полное состояние — под токеном: сессия, каталоги, последняя ошибка.

    Отдельно от health() намеренно: /health читает любой, кто может сделать
    GET на петлю, и абсолютным путям машины там не место.
    """
    return _req("/state")


def probe() -> dict:
    return _req("/probe", {})


def logs() -> dict:
    return _req("/logs")


def restart() -> dict:
    return _req("/restart", {})


def login() -> dict:
    """Вход в подписку: окно открывает ДЕМОН, на своём же профиле.

    Второго процесса на монопольный профиль здесь нет ни на секунду
    (решение 15, ограничение 2). Прежняя версия печатала «демон будет
    остановлен», слала /restart — а тот перезапускает контекст, не
    процесс, — и запускала отдельную программу входа вторым процессом.

    Ждём дольше, чем демон: его потолок ожидания — общий, из protocol.py.
    Ждать столько же значит оборвать связь ровно тогда, когда демон
    собрался ответить.
    """
    обеспечить_демона()
    return _req("/login", {}, timeout=protocol.ПОТОЛОК_ВХОДА_СЕК + ЗАПАС_КЛИЕНТА_СЕК)


def подтвердить_вход() -> dict:
    """Сказать демону «я вошёл» — из другого процесса, пока окно открыто.

    Признак входа нужен потому, что консоли у демона нет: он работает
    фоном, а под задачей планировщика её нет вовсе, и прежний `input()`
    в окне входа ждал бы нажатия, которого некому сделать.
    """
    return _req("/login", {"готово": True}, timeout=15.0)


def main():
    cmd = sys.argv[1] if len(sys.argv) > 1 else "health"
    try:
        if cmd == "health":
            print(json.dumps(health(), ensure_ascii=False, indent=2))
        elif cmd == "state":
            st = состояние()
            print(json.dumps(st, ensure_ascii=False, indent=2))
            if st.get("сессия") != "жива":
                print("\nСессия не подтверждена. Проверить живым запросом:\n  "
                      + paths.команда("doctor"))
        elif cmd == "port":
            # Без ✗-обёртки и без ненулевого кода: «демон не работает» —
            # это ответ, а не сбой. Пульт разбирает JSON, а не код возврата.
            print(json.dumps(адрес(), ensure_ascii=False))
        elif cmd == "probe":
            print(json.dumps(probe(), ensure_ascii=False, indent=2))
        elif cmd == "logs":
            for line in logs()["лог"]:
                print(line)
        elif cmd == "restart":
            print(json.dumps(restart(), ensure_ascii=False))
        elif cmd == "login":
            print("Демон откроет окно входа на своём профиле. Страница "
                  "грузится около 40 секунд.")
            print("Когда войдёте — либо закройте окно, либо выполните "
                  "в другом окне терминала:\n  "
                  + paths.команда("login", "--готово"))
            print(json.dumps(login(), ensure_ascii=False, indent=2))
        elif cmd in ("вошёл", "готово"):
            print(json.dumps(подтвердить_вход(), ensure_ascii=False))
        elif cmd == "call":
            if len(sys.argv) < 3:
                print("Укажите метод. Пример: call article doc_id=12125178 article=97")
                sys.exit(1)
            method = sys.argv[2]
            params: dict = {}
            for kv in sys.argv[3:]:
                if "=" not in kv:
                    print(f"Аргумент «{kv}» без знака равенства — пропущен")
                    continue
                k, v = kv.split("=", 1)
                if v.isdigit():
                    v = int(v)
                params[k] = v
            print(json.dumps(call(method, **params), ensure_ascii=False, indent=2))
        else:
            print(__doc__)
    except DaemonError as e:
        print("✗", e)
        sys.exit(1)


if __name__ == "__main__":
    main()
