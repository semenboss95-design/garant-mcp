# -*- coding: utf-8 -*-
"""Единственный источник истины о том, где что лежит.

До этого модуля каждый файл считал пути сам, и договорённости расходились:
демон писал токен рядом с кодом, установщик прописывал GARANT_HOME, которую
никто не читал, а PowerShell искал .venv в четырёх разных местах.

Два понятия, и их не надо путать:

  HOME  — каталог кода (пакет garant_mcp). Только чтение: под pip или uvx он
          лежит в site-packages либо в эфемерном кэше uv. Оттуда читается
          endpoints.json.
  STATE — каталог состояния: токен, порт, логи, кэш, профиль браузера,
          отпечаток. Единственное место, куда контур пишет.

Почему STATE отделён от HOME. Установка через pip/uvx кладёт код в каталог,
доступный только на чтение либо стираемый между запусками. Запись рантайма
рядом с кодом там либо запрещена, либо бессмысленна: профиль браузера,
в котором живёт авторизованная сессия подписки, исчезнет вместе с кэшем uv,
и пользователь будет входить заново после каждого обновления.

STATE вычисляется без единой догадки: GARANT_HOME, иначе каталог данных ОС
(решение 14). Прежняя эвристика «рядом с кодом найдены следы установки —
значит, установка портативная» удалена: она угадывала намерение по следам
и угадывала неверно ровно тогда, когда копий кода становилось больше одной.
Перенос профиля из старой установки — явная команда `garant migrate`,
а не догадка на импорте.

НИ ОДНОГО mkdir НА ИМПОРТЕ. Модуль только вычисляет пути. Создаёт каталоги
ensure_state(), и её вызывают явно из main(). Раньше daemon.py создавал logs/
и bridge/ прямо при импорте: на read-only установке это исключение в момент
импорта, а пользователь видел невнятное «сервер не запустился».
"""

from __future__ import annotations

import os
from pathlib import Path

import platformdirs

HOME = Path(__file__).resolve().parent

# Умолчание порта живёт в config.py. Здесь только имена файлов.
ИМЯ_ТОКЕНА = "daemon_token"
ИМЯ_ПОРТА = "daemon_port"
ИМЯ_СОСТОЯНИЯ = "daemon_state.json"
ИМЯ_ПРОФИЛЯ_ПО_УМОЛЧАНИЮ = "chrome_profile"


def _имя_профиля() -> str:
    """Имя каталога профиля браузера из карты эндпоинтов.

    Читается здесь, а не берётся константой: имя каталога переопределимо,
    и константа не нашла бы уже существующий профиль — а цена ошибки здесь
    ровно одна, повторный ручной вход в подписку.

    Читается через config.карта(), то есть с учётом endpoints.local.json:
    иначе пользователь, переопределивший имя профиля у себя, получил бы
    один каталог у paths и другой у всех остальных.

    Чтение файла на импорте — единственное осознанное исключение из правила
    «импорт без побочных эффектов»: это не запись, на read-only установке
    оно проходит. Любая неудача даёт умолчание, а не исключение — сорваться
    на разборе JSON в момент импорта было бы худшим вариантом.
    """
    from . import config

    имя = (config.карта().get("browser_profile") or {}).get("user_data_dir")
    return имя if isinstance(имя, str) and имя else ИМЯ_ПРОФИЛЯ_ПО_УМОЛЧАНИЮ


def _путь(значение: str) -> Path:
    """Строку из окружения — в абсолютный путь.

    Пустая строка и `.` означают «каталог данных ОС», а НЕ текущий каталог:
    MCP-клиент запускает сервер из своего рабочего каталога, и разворачивание
    `.` относительно cwd раскидало бы состояние по случайным папкам — а вместе
    с ним и профиль с живой сессией.

    abspath, а не resolve(): resolve() разворачивает симлинки, и путь,
    который пользователь задал сам, перестал бы совпадать с тем, что он
    видит в переменной.
    """
    значение = значение.strip().strip('"')
    if значение in ("", ".", "./", ".\\"):
        return Path(platformdirs.user_data_dir("garant-mcp"))
    return Path(os.path.abspath(os.path.expanduser(значение)))


def _определить_state() -> tuple[Path, str]:
    """Возвращает каталог состояния и причину выбора — для диагностики."""
    задано = os.environ.get("GARANT_HOME")
    if задано and задано.strip().strip('"'):
        return _путь(задано), "задан GARANT_HOME"
    return Path(platformdirs.user_data_dir("garant-mcp")), "каталог данных ОС"


STATE, ПРИЧИНА_STATE = _определить_state()

token_file = STATE / ИМЯ_ТОКЕНА
port_file = STATE / ИМЯ_ПОРТА
state_file = STATE / ИМЯ_СОСТОЯНИЯ
fingerprint_file = STATE / "fingerprint.json"
# Замок владения профилем. Здесь только путь: занимает и держит его демон
# (daemon.занять_профиль), потому что владелец профиля — он один.
profile_lock_file = STATE / "profile.lock"
local_endpoints_file = STATE / "endpoints.local.json"
log_dir = STATE / "logs"
cache_dir = STATE / "cache"
recordings_dir = STATE / "recordings"
bridge_dir = STATE / "bridge"

def __getattr__(имя: str):
    """`ПРОФИЛЬ` и `profile_dir` — по требованию, а не строкой на импорте.

    Круг `paths` ↔ `config` реален: paths спрашивает у config имя каталога
    профиля, а config читает у paths `HOME` и `local_endpoints_file`. Пока
    `ПРОФИЛЬ` вычислялся присваиванием на уровне модуля, круг был развязан
    ЕДИНСТВЕННО порядком двух строк: `local_endpoints_file` обязан стоять
    выше. Перестановка присваиваний компилируется, не ловится проверкой
    типов и ломает импорт — а какая из трёх точек входа сломается, решает
    вызывающий, а не автор правки.

    Отложенное вычисление (PEP 562) убирает не симптом, а причину: к моменту
    первого обращения к профилю оба модуля исполнены целиком, и порядок
    объявлений значения больше не имеет. Дешевизна обеспечена кэшем карты
    в config.
    """
    if имя == "ПРОФИЛЬ":
        return _имя_профиля()
    if имя == "profile_dir":
        return STATE / _имя_профиля()
    raise AttributeError("модуль {} не имеет атрибута {!r}".format(__name__, имя))


def ensure_state(bridge: bool = False) -> Path:
    """Создаёт каталоги состояния. Вызывается явно из main(), не на импорте.

    Мост по умолчанию не создаётся: каталог bridge/ — костыль под песочницу,
    у которой свой localhost, но общая с Windows файловая система. Обычному
    пользователю он не нужен, а раньше создавался всем и всегда.

    recordings/ тоже не создаётся: запись сырых тел включается флагом
    GARANT_RECORD, и создаёт каталог тот, кто пишет, — пустой каталог
    записей у всех выглядел бы как «записи есть, но пустые».
    """
    STATE.mkdir(parents=True, exist_ok=True)
    log_dir.mkdir(exist_ok=True)
    cache_dir.mkdir(exist_ok=True)
    # profile_dir не создаём: его создаёт сам Playwright при запуске
    # persistent context, и делает это правильнее нас.
    if bridge:
        bridge_dir.mkdir(exist_ok=True)
        (bridge_dir / "requests").mkdir(exist_ok=True)
        (bridge_dir / "responses").mkdir(exist_ok=True)
    return STATE


def описание() -> str:
    """Одна строка о том, где контур держит состояние. Для логов и диагностики."""
    return "состояние: {} ({})".format(STATE, ПРИЧИНА_STATE)


def команда(*подкоманда: str) -> str:
    """Команда контура, готовая к вставке в терминал: `garant <подкоманда>`.

    Существует ради текстов ошибок. Абсолютного пути здесь нет намеренно:
    `garant` кладётся установщиком пакета в PATH, а прежняя форма — путь
    к интерпретатору плюс путь к файлу — была путём конкретной машины,
    который уходил пользователю в текст ошибки и в безтокенный /health.
    Путь к тому же ещё и устаревал при каждом обновлении пакета.
    """
    return " ".join(("garant", *подкоманда))
