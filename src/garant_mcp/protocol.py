# -*- coding: utf-8 -*-
"""Договор между демоном и его клиентами. Не настройка.

Здесь лежит то, о чём демон и клиент обязаны думать одинаково, иначе они
перестают узнавать друг друга. От config.py отличается принципиально:
config — слой НАСТРОЕК, значение там вправе поменять пользователь. Признак
демона менять не вправе никто: он не про предпочтения машины, а про то,
как две половины одной программы опознают друг друга.

Почему отдельный модуль, а не импорт из daemon.py: импорт daemon тянет
garant_client, Playwright и настройку логирования. Клиенту, которому нужна
одна строка, всё это не нужно и на чужой машине может не завестись вовсе.

НИ ОДНОГО mkdir И НИ ОДНОГО СЕТЕВОГО ВЫЗОВА НА ИМПОРТЕ — как в paths.py
и config.py.
"""

from __future__ import annotations

# Ключ, который демон кладёт в тело GET /health, и признак, по которому его
# там ищут второй экземпляр демона и клиент — прежде чем послать токен.
#
# Раньше эта строка была написана трижды: в daemon.py как константа, в теле
# ответа /health — литералом, и в daemon_client.py второй константой. Рядом
# с двумя из них стоял комментарий, что расхождение сломает опознание.
# Расхождение при этом ничему не мешало: три независимых литерала, ни одной
# проверки. Цена расхождения не «странный ответ»: клиент объявляет свой же
# демон посторонним и отказывается работать, а второй экземпляр садится
# рядом с первым — то есть два процесса на монопольный профиль браузера.
ПРИЗНАК_ДЕМОНА = "демон"

# --- ошибки ----------------------------------------------------------------
#
# Ошибка обязана пережить три границы: поток браузера → HTTP демона →
# клиент. Раньше на каждой из них она была строкой, и на каждой решение
# принималось поиском подстрок «401», «403», «Unauthorized», «сесси» без
# приведения регистра. Цена этого не теоретическая: запрос «статья 401.11»
# объявлял сессию подписки мёртвой, а настоящее «Сессия…» с заглавной
# не ловилось вовсе. Тип ставит тот, кто знает причину, — и дальше он
# едет как поле, а не как слово в тексте.
ТИП_СЕССИЯ = "session"          # 401/403, переживший повтор после продления
ТИП_API = "api_changed"         # ответ не тот, что описан картой эндпоинтов
ТИП_НЕ_НАЙДЕНО = "not_found"    # спросили то, чего в базе нет
ТИП_БРАУЗЕР = "browser"         # профиль, контекст, окно — сторона браузера
ТИП_ТАЙМАУТ = "timeout"         # не дождались; о сессии это НИЧЕГО не говорит

ТИПЫ = (ТИП_СЕССИЯ, ТИП_API, ТИП_НЕ_НАЙДЕНО, ТИП_БРАУЗЕР, ТИП_ТАЙМАУТ)

# HTTP-код, которым демон отвечает на ошибку такого типа. Здесь, а не по
# месту ответа: код читает клиент, и разъехавшись, две половины начнут
# по-разному понимать одну и ту же неудачу.
HTTP_ПО_ТИПУ = {
    ТИП_СЕССИЯ: 503,
    ТИП_API: 502,
    ТИП_НЕ_НАЙДЕНО: 404,
    ТИП_БРАУЗЕР: 503,
    ТИП_ТАЙМАУТ: 504,
}

# Тексты самого Playwright, означающие, что контекст под нами закрылся.
# Подстрока здесь допустима и границы не переходит: это фразы чужой
# библиотеки, и решают они ровно одно — перезапускать ли контекст.
# Состояния сессии подписки они не касаются.
ПРИЗНАКИ_ЗАКРЫТОГО_БРАУЗЕРА = ("Target closed", "Browser closed",
                               "has been closed", "Connection closed")


class GarantError(RuntimeError):
    """Ошибка контура с типом. Тип ставит тот, кто знает причину.

    `http` — код, полученный от «Гаранта», если он был. Именно он, а не
    догадка по тексту, отличает 403 подписки от числа 403 внутри запроса.
    """

    def __init__(self, сообщение: str, тип: str = ТИП_API,
                 http: int | None = None):
        super().__init__(сообщение)
        self.тип = тип if тип in ТИПЫ else ТИП_API
        self.сообщение = str(сообщение)
        self.http = http

    def словарь(self) -> dict:
        return {"тип": self.тип, "сообщение": self.сообщение, "http": self.http}


def из_словаря(d) -> GarantError:
    """Обратно в исключение — на другой стороне границы."""
    if not isinstance(d, dict):
        return GarantError(str(d))
    return GarantError(str(d.get("сообщение") or d.get("ошибка") or d),
                       str(d.get("тип") or ТИП_API), d.get("http"))


def _таймаут(exc: BaseException) -> bool:
    """Это «не дождались»? Проверяется и по имени класса, а не только по типу.

    `playwright.sync_api.TimeoutError` от встроенного `TimeoutError`
    НЕ наследуется — он потомок `Error`, то есть обычного `Exception`.
    Поэтому единственная проверка `isinstance(exc, TimeoutError)` уводила
    каждый таймаут Playwright — а это самая частая неудача контура —
    в `api_changed`: код ответа выходил 502 «карта разошлась с ответом»
    вместо 504, и читающий шёл искать сломанный эндпоинт вместо медленного.

    Импортировать playwright сюда нельзя: модуль обязан оставаться лёгким —
    его тянет клиент, у которого playwright может не стоять вовсе. Поэтому
    имя класса ищется по всей цепочке наследования: перекрёстных «чужих»
    TimeoutError, означающих что-то иное, не бывает.
    """
    if isinstance(exc, TimeoutError):
        return True
    return any(к.__name__ == "TimeoutError" for к in type(exc).__mro__)


def классифицировать(exc: BaseException) -> GarantError:
    """Любое исключение — в типизированную ошибку.

    Неопознанное сваливается в api_changed намеренно: это единственный
    поведенчески нейтральный тип. Ошибиться в сторону session значит
    объявить живую сессию подписки мёртвой, а это ровно тот дефект,
    ради которого типы и заведены.
    """
    if isinstance(exc, GarantError):
        return exc
    текст = "{}: {}".format(type(exc).__name__, exc)
    if _таймаут(exc):
        return GarantError(текст, ТИП_ТАЙМАУТ)
    if any(x in текст for x in ПРИЗНАКИ_ЗАКРЫТОГО_БРАУЗЕРА):
        return GarantError(текст, ТИП_БРАУЗЕР)
    return GarantError(текст, ТИП_API)


# Сколько демон держит открытым окно входа. Не настройка: это предел
# терпения, а не предпочтение машины, и знать его обязаны обе стороны —
# демон, чтобы вернуться к своей работе, и клиент, чтобы ждать дольше
# демона.
#
# Пять минут выбраны так. Страница входа «Гаранта» грузится около сорока
# секунд, дальше OAuth: логин, пароль, иногда код из письма — минуты.
# Жёсткий предел сверху нужен ровно за тем, чтобы забытое окно не выключило
# продление сессии навсегда: пока идёт вход, поток-владелец браузера занят
# и таймер keepalive не идёт. Ждать дольше бессмысленно — сессия, ради
# которой всё затевалось, к тому времени всё равно перевходится заново.
ПОТОЛОК_ВХОДА_СЕК = 300

# Сколько пульт ждёт остановки демона после сигнала — и сколько сам демон
# отводит себе на уборку. Два числа об одном факте, поэтому лежат рядом
# и второе выводится из первого: демон обязан закрыть браузер и снять
# daemon_port РАНЬШЕ, чем пульт перестанет ждать. Разъехавшись, они дают
# `garant stop`, объявляющий зависшим демона, который штатно прибирается.
ПОТОЛОК_ОСТАНОВКИ_СЕК = 15
ПОТОЛОК_УБОРКИ_СЕК = ПОТОЛОК_ОСТАНОВКИ_СЕК - 5

# Охрана вычитания. `Thread.join(0)` и `join(-5)` возвращаются мгновенно
# и молча — ни исключения, ни предупреждения. То есть уменьшение потолка
# пульта до пяти секунд и ниже не сокращает ожидание уборки, а отменяет
# его целиком: демон уходит, не дождавшись закрытия браузера, chromium
# переживает хозяина и держит профиль — ровно тот исход, ради которого
# существует ограничение 2, и получается он правкой одного числа в чужом
# файле. Поднять нижнюю границу через `max()` нельзя: тогда потолок уборки
# сравняется с потолком остановки или превысит его, и тихим станет уже
# обещание «демон прибирается раньше, чем пульт перестаёт ждать» — риск
# просто переедет. Проверка зависит только от литерала выше, поэтому
# сработать может лишь у того, кто правит это число, и сработает при
# первом же импорте, а не на чужой машине.
#
# Чего охрана НЕ ловит — «положительно, но мало»: при потолке остановки
# в шесть секунд уборке остаётся одна, и это пройдёт молча. Сторожится
# ровно вырождение в ноль и ниже, то есть отмена ожидания как таковая.
# Достаточен ли сам запас в пять секунд, здесь не известно: он выбран по
# прежним числам, а не измерен, и измеряет его пункт 7б живой приёмки
# (`docs/ACCEPTANCE.md`). Обещать в тексте охраны «шесть уже безопасно»
# значит выдать невыясненное за проверенное.
if ПОТОЛОК_УБОРКИ_СЕК <= 0:
    raise ValueError(
        "ПОТОЛОК_ОСТАНОВКИ_СЕК={} оставляет на уборку {} с: демон не станет "
        "ждать закрытия браузера вовсе, chromium переживёт его и продолжит "
        "держать профиль. Охрана сторожит только это вырождение; сколько "
        "уборке нужно на самом деле, не измерено — замер идёт живой "
        "приёмкой.".format(ПОТОЛОК_ОСТАНОВКИ_СЕК, ПОТОЛОК_УБОРКИ_СЕК))
