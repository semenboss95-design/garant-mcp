# -*- coding: utf-8 -*-
"""Регистрация сервера у MCP-клиентов: слияние, а не перезапись.

Пишется ровно одна запись — `{"command": "garant-mcp"}`, по ИМЕНИ файла
из PATH. Абсолютного пути здесь нет и быть не может: ради этого затевался
этап 02. Прежний генератор писал путь к интерпретатору и путь к server.py,
и любое обновление кода делало регистрацию ложью — клиент продолжал
запускать то, чего уже нет, а человек видел «сервер не отвечает».

Главное свойство модуля — чужое в конфигурации остаётся целым. Файл клиента
принадлежит не нам: рядом с нашей записью живут другие MCP-серверы,
и потерять их значит сломать человеку работу, к «Гаранту» отношения
не имеющую. Поэтому конфигурация читается, дополняется и пишется обратно
целиком, а перед записью копируется в `.bak`.

Четыре состояния файла разведены намеренно, потому что действия у них
разные: файла нет, каталога клиента нет вовсе, файл пуст, файл не
разбирается как JSON. Последний случай — единственный, в котором мы
не пишем ничего: перезапись битого файла уничтожила бы чужие записи,
которые в нём, скорее всего, целы, а сломана одна запятая.

Codex — тот же смысл на другом формате: TOML, раздел `mcp_servers`,
и в записи добавлен `env` (см. `СТРОКИ_CODEX`). Все четыре состояния
и запрет трогать битый файл действуют там так же; отличается способ
записи — текстовое слияние, и почему именно оно, сказано у самих строк.

НИ ОДНОГО mkdir И НИ ОДНОГО СЕТЕВОГО ВЫЗОВА НА ИМПОРТЕ.
"""

from __future__ import annotations

import json
import os
import re
import shutil
import sys
import tomllib
from pathlib import Path

from . import paths

# Имя записи в конфигурации клиента и её содержимое. Одно место: имя
# читают и запись, и снятие, и диагностика, а разойдясь, они начали бы
# писать одну запись и снимать другую.
ИМЯ_ЗАПИСИ = "garant"
ЗАПИСЬ = {"command": "garant-mcp"}
РАЗДЕЛ = "mcpServers"

# Формат файла клиента. Codex держит настройки в TOML и зовёт раздел иначе;
# формат хранится в цели, чтобы `прочитать`, `статус`, `зарегистрировать`
# и `снять` остались ОДНОЙ точкой входа: разойдясь на два набора функций,
# они начали бы отвечать по-разному об одном и том же файле, а вызывающий
# (пульт) обязан был бы помнить, какую из них звать для какого клиента.
JSON = "json"
TOML = "toml"
РАЗДЕЛ_CODEX = "mcp_servers"


class Цель:
    """Куда пишем: имя клиента для человека и путь его конфигурации."""

    def __init__(self, имя: str, путь: Path, требует_каталог: bool = True,
                 формат: str = JSON):
        self.имя = имя
        self.путь = Path(путь)
        # Создавать каталог клиента, которого нет, — значит объявить
        # установленным клиента, которого не ставили. Для проектного
        # .mcp.json наоборот: каталог указал человек, он существует.
        self.требует_каталог = требует_каталог
        self.формат = формат


def цель_desktop() -> Цель:
    """Конфигурация Claude Desktop в каталоге настроек этой ОС."""
    if os.name == "nt":
        база = Path(os.environ.get("APPDATA") or (Path.home() / "AppData/Roaming"))
        путь = база / "Claude" / "claude_desktop_config.json"
    elif sys.platform == "darwin":
        путь = (Path.home() / "Library" / "Application Support" / "Claude"
                / "claude_desktop_config.json")
    else:
        путь = Path.home() / ".config" / "Claude" / "claude_desktop_config.json"
    return Цель("Claude Desktop", путь)


def цель_code() -> Цель:
    """Пользовательская конфигурация Claude Code — одна на все проекты."""
    return Цель("Claude Code", Path.home() / ".claude.json")


def цель_codex() -> Цель:
    """Конфигурация Codex CLI (подписка ChatGPT) — TOML, а не JSON.

    Каталог берётся из `CODEX_HOME`, если он задан: так его переопределяет
    сам Codex, и вычислить `~/.codex` в обход переменной значило бы писать
    не в тот файл, который клиент читает.
    """
    база = Path(os.environ.get("CODEX_HOME") or (Path.home() / ".codex"))
    return Цель("Codex", база / "config.toml", формат=TOML)


def цель_проекта(каталог) -> Цель:
    """`.mcp.json` в конкретном проекте: регистрация, приезжающая с клоном."""
    путь = Path(os.path.abspath(os.path.expanduser(str(каталог)))) / ".mcp.json"
    return Цель("проект " + путь.parent.name, путь, требует_каталог=False)


# --- чтение ----------------------------------------------------------------
НЕТ_КАТАЛОГА = "нет каталога клиента"
НЕТ_ФАЙЛА = "файла нет"
ПУСТОЙ = "файл пуст"
БИТЫЙ = "файл не разбирается как JSON"
# Отдельная строка, а не «как JSON» для всех: человеку показывают её как есть,
# и совет починить JSON в файле TOML отправил бы его искать не то.
БИТЫЙ_TOML = "файл не разбирается как TOML"
ЕСТЬ = "прочитан"


def _раздел(цель: Цель) -> str:
    return РАЗДЕЛ_CODEX if цель.формат == TOML else РАЗДЕЛ


def битый(цель: Цель) -> str:
    """Текст «файл не разбирается» на языке формата этого клиента."""
    return БИТЫЙ_TOML if цель.формат == TOML else БИТЫЙ


def прочитать(цель: Цель) -> tuple[dict, str]:
    """Конфигурация и состояние файла. Исключений не бросает.

    Возвращается пара, а не просто словарь: пустой словарь означает три
    разных вещи — файла нет, файл пуст, файл битый, — и решение у них
    разное. Битый мы не трогаем вовсе.
    """
    if not цель.путь.exists():
        if цель.требует_каталог and not цель.путь.parent.exists():
            return {}, НЕТ_КАТАЛОГА
        return {}, НЕТ_ФАЙЛА
    try:
        текст = цель.путь.read_text(encoding="utf-8")
    except OSError:
        return {}, БИТЫЙ
    if not текст.strip():
        return {}, ПУСТОЙ
    try:
        # tomllib.TOMLDecodeError — тоже ValueError, отдельная ветка не нужна.
        данные = (tomllib.loads(текст) if цель.формат == TOML
                  else json.loads(текст))
    except ValueError:
        return {}, БИТЫЙ
    if not isinstance(данные, dict):
        return {}, БИТЫЙ
    return данные, ЕСТЬ


def зарегистрирован(данные: dict, раздел: str = РАЗДЕЛ) -> bool:
    запись = (данные.get(раздел) or {}).get(ИМЯ_ЗАПИСИ)
    return isinstance(запись, dict) and запись.get("command") == ЗАПИСЬ["command"]


def статус(цель: Цель) -> str:
    """Одна строка о цели — для `garant doctor` и `garant status`."""
    данные, состояние = прочитать(цель)
    if состояние == НЕТ_КАТАЛОГА:
        return "клиент не установлен"
    if состояние == БИТЫЙ:
        return битый(цель)
    if состояние in (НЕТ_ФАЙЛА, ПУСТОЙ):
        return "не зарегистрирован (" + состояние + ")"
    return ("зарегистрирован" if зарегистрирован(данные, _раздел(цель))
            else "не зарегистрирован")


# --- запись ----------------------------------------------------------------
def _записать(цель: Цель, данные: dict) -> None:
    """Копия в .bak, затем атомарная замена.

    Копия обязательна: в файле живут чужие MCP-серверы, и если наша запись
    испортит его, восстановить неоткуда — клиент своих копий не делает.
    Замена через временный файл рядом: читатель, заставший запись
    на середине, получил бы обрезанный JSON и остался бы вовсе без
    MCP-серверов.
    """
    цель.путь.parent.mkdir(parents=True, exist_ok=True)
    if цель.путь.exists():
        shutil.copy2(цель.путь, цель.путь.with_name(цель.путь.name + ".bak"))
    врем = цель.путь.with_name(цель.путь.name + ".tmp")
    врем.write_text(json.dumps(данные, ensure_ascii=False, indent=2) + "\n",
                    encoding="utf-8")
    os.replace(врем, цель.путь)


def зарегистрировать(цель: Цель) -> tuple[bool, str]:
    """Добавить нашу запись. Повторный запуск ничего не меняет."""
    if цель.формат == TOML:
        return _зарегистрировать_toml(цель)
    данные, состояние = прочитать(цель)
    if состояние == НЕТ_КАТАЛОГА:
        return False, ("{}: каталог настроек клиента не найден — похоже, он "
                       "не установлен. Регистрацию не пишу: создать каталог "
                       "значит объявить установленным то, чего нет."
                       .format(цель.имя))
    if состояние == БИТЫЙ:
        return False, ("{}: конфигурация не разбирается как JSON. Ничего "
                       "не записано — в этом файле, скорее всего, целы чужие "
                       "MCP-серверы, а сломана одна запятая. Исправьте файл "
                       "({}) и повторите {}".format(
                           цель.имя, цель.путь, paths.команда("register")))
    if зарегистрирован(данные):
        return True, "{}: уже зарегистрирован, файл не тронут".format(цель.имя)

    раздел = данные.get(РАЗДЕЛ)
    if not isinstance(раздел, dict):
        раздел = {}
    было = ИМЯ_ЗАПИСИ in раздел
    раздел[ИМЯ_ЗАПИСИ] = dict(ЗАПИСЬ)
    данные[РАЗДЕЛ] = раздел
    try:
        _записать(цель, данные)
    except OSError as e:
        return False, "{}: не удалось записать ({}: {})".format(
            цель.имя, type(e).__name__, e)
    хвост = "" if состояние in (НЕТ_ФАЙЛА, ПУСТОЙ) else ", копия рядом в .bak"
    return True, "{}: запись {} {}{}".format(
        цель.имя, ИМЯ_ЗАПИСИ, "обновлена" if было else "добавлена", хвост)


def снять(цель: Цель) -> tuple[bool, str]:
    """Убрать ТОЛЬКО нашу запись. Всё остальное в файле остаётся как было."""
    if цель.формат == TOML:
        return _снять_toml(цель)
    данные, состояние = прочитать(цель)
    if состояние == НЕТ_КАТАЛОГА:
        return True, "{}: клиент не установлен — снимать нечего".format(цель.имя)
    if состояние == БИТЫЙ:
        return False, ("{}: конфигурация не разбирается как JSON — не трогаю: "
                       "{}".format(цель.имя, цель.путь))
    раздел = данные.get(РАЗДЕЛ)
    if not isinstance(раздел, dict) or ИМЯ_ЗАПИСИ not in раздел:
        return True, "{}: записи {} нет — снимать нечего".format(
            цель.имя, ИМЯ_ЗАПИСИ)
    убранное = раздел.pop(ИМЯ_ЗАПИСИ)
    данные[РАЗДЕЛ] = раздел
    try:
        _записать(цель, данные)
    except OSError as e:
        return False, "{}: не удалось записать ({}: {})".format(
            цель.имя, type(e).__name__, e)
    return True, "{}: запись {} убрана ({}), копия рядом в .bak".format(
        цель.имя, ИМЯ_ЗАПИСИ, json.dumps(убранное, ensure_ascii=False))


# --- Codex: тот же смысл, но TOML ------------------------------------------
# Слияние здесь ТЕКСТОВОЕ, а не «разобрать — изменить — записать обратно».
# Причина одна: `tomllib` умеет только читать, писателя TOML в стандартной
# библиотеке нет, а прогон чужого файла через любой сериализатор потерял бы
# комментарии, порядок таблиц и форму записи значений — то есть испортил бы
# человеку файл, к «Гаранту» отношения не имеющий. Зависимость ради этого
# не заводится: наша запись — три строки постоянного вида.
#
# PYTHONIOENCODING не украшение: Codex запускает сервер без консоли, и на
# Windows дочерний процесс берёт кодовую страницу ОС — русский текст в ответе
# инструмента упал бы UnicodeEncodeError на первом же ответе.
СТРОКИ_CODEX = ("[mcp_servers.garant]",
                'command = "garant-mcp"',
                'env = { PYTHONIOENCODING = "utf-8" }')

# TOML разрешает пробелы вокруг точки и кавычки вокруг ключа, поэтому
# сравнение строки буквально не годится: `[mcp_servers."garant"]` — та же
# таблица, и не узнать её значило бы дописать вторую, а файл с двумя
# одинаковыми таблицами не разбирается вовсе.
_ЗАГОЛОВОК_НАШ = re.compile(
    r'^\s*\[\s*mcp_servers\s*\.\s*(?:garant|"garant"|\'garant\')\s*\]\s*$')
_ЗАГОЛОВОК_ЛЮБОЙ = re.compile(r"^\s*\[")


def _найти_заголовок(строки: list[str]) -> int:
    for i, строка in enumerate(строки):
        if _ЗАГОЛОВОК_НАШ.match(строка):
            return i
    return -1


def _конец_блока(строки: list[str], начало: int) -> int:
    """Где кончается наша таблица: следующий заголовок (`[` или `[[`) либо
    конец файла."""
    for i in range(начало + 1, len(строки)):
        if _ЗАГОЛОВОК_ЛЮБОЙ.match(строки[i]):
            return i
    return len(строки)


def _наш_блок(блок: list[str]) -> bool:
    return [с.strip() for с in блок if с.strip()] == list(СТРОКИ_CODEX)


def _чужое(данные: dict) -> dict:
    """Всё в файле, кроме нашей записи, — для сверки «до» и «после».

    Пустой раздел не в счёт: сняв единственную запись, мы оставляем файл
    без раздела вовсе, и без этой оговорки сверка объявила бы потерянным
    чужое, которого не было.
    """
    прочее = {k: v for k, v in данные.items() if k != РАЗДЕЛ_CODEX}
    остальные = {k: v for k, v in (данные.get(РАЗДЕЛ_CODEX) or {}).items()
                 if k != ИМЯ_ЗАПИСИ}
    if остальные:
        прочее[РАЗДЕЛ_CODEX] = остальные
    return прочее


def _текст(цель: Цель) -> str:
    """Файл как он есть. `newline=""` не мелочь: чтение по умолчанию
    превращает CRLF в LF, и файл, живший с CRLF, вернулся бы человеку
    переведённым целиком — правка в три строки показала бы себя правкой
    всего файла в его системе контроля версий.

    Берётся `open`, а не `Path.read_text(newline=…)`: у `read_text` этот
    параметр появился только в 3.13, а пакет объявлен с 3.12 — там вызов
    падал бы TypeError, и вежливый отказ Codex превращался в крах пульта.
    """
    if not цель.путь.exists():
        return ""
    with open(цель.путь, "r", encoding="utf-8", newline="") as ф:
        return ф.read()


def _записать_текст(цель: Цель, текст: str) -> None:
    """Как `_записать`, но текстом: перевод строк выбран вызывающим.

    `newline=""` обязателен — иначе Python на Windows допишет к каждому
    переводу строки возврат каретки, и файл, живший с одним переводом
    строки, вернулся бы человеку с другим: чужие байты обязаны остаться
    теми же байтами.

    Форма записи та же, что у `_текст` (`open`, а не метод `Path`): два
    способа задать `newline` в соседних функциях однажды разойдутся — у
    методов `Path` этот параметр появлялся в разных версиях.
    """
    цель.путь.parent.mkdir(parents=True, exist_ok=True)
    if цель.путь.exists():
        shutil.copy2(цель.путь, цель.путь.with_name(цель.путь.name + ".bak"))
    врем = цель.путь.with_name(цель.путь.name + ".tmp")
    with open(врем, "w", encoding="utf-8", newline="") as ф:
        ф.write(текст)
    os.replace(врем, цель.путь)


def _вернуть_как_было(цель: Цель, исходный: str, состояние: str) -> str:
    """Откат после неудачной сверки; возвращает то, что скажут человеку.

    Текст берётся из памяти, а не из `.bak`: `.bak` мог остаться от прошлого
    запуска, и восстановление из него вернуло бы не то, что было минуту назад.
    """
    try:
        if состояние == НЕТ_ФАЙЛА:
            цель.путь.unlink(missing_ok=True)
        else:
            with open(цель.путь, "w", encoding="utf-8", newline="") as ф:
                ф.write(исходный)
    except OSError as e:
        return "вернуть файл не удалось ({}), исходное содержимое — в .bak".format(
            type(e).__name__)
    return "файл возвращён как был"


def _сверить(цель: Цель, чужое_до: dict, ждём: bool) -> str:
    """Пусто, если после записи всё на месте; иначе — что именно не так.

    Не перестраховка: текстовое слияние не знает грамматики TOML целиком
    (строка чужого многострочного значения тоже может начинаться с «[»),
    и единственный честный способ убедиться, что файл цел, — прочитать его
    заново тем же разборщиком, каким его читает клиент.
    """
    данные, состояние = прочитать(цель)
    if состояние == БИТЫЙ:
        return "после записи файл перестал разбираться как TOML"
    запись = (данные.get(РАЗДЕЛ_CODEX) or {}).get(ИМЯ_ЗАПИСИ)
    if ждём and not зарегистрирован(данные, РАЗДЕЛ_CODEX):
        return "после записи запись {} не читается как наша".format(ИМЯ_ЗАПИСИ)
    if not ждём and запись is not None:
        return "после снятия запись {} осталась в файле".format(ИМЯ_ЗАПИСИ)
    if _чужое(данные) != чужое_до:
        return "после записи изменилось чужое содержимое файла"
    return ""


def _иная_форма(данные: dict) -> bool:
    """Наша запись есть, но не отдельной таблицей: inline-таблицей под
    `[mcp_servers]` или точечными ключами. Вырезать такую форму текстом
    нельзя, не рискуя соседними строками, а переписать файл целиком значит
    потерять чужие комментарии — поэтому отказ, а не попытка."""
    return (данные.get(РАЗДЕЛ_CODEX) or {}).get(ИМЯ_ЗАПИСИ) is not None


def _зарегистрировать_toml(цель: Цель) -> tuple[bool, str]:
    данные, состояние = прочитать(цель)
    if состояние == НЕТ_КАТАЛОГА:
        return False, ("{}: каталог настроек клиента не найден — похоже, он "
                       "не установлен. Регистрацию не пишу: создать каталог "
                       "значит объявить установленным то, чего нет."
                       .format(цель.имя))
    if состояние == БИТЫЙ:
        return False, ("{}: конфигурация не разбирается как TOML. Ничего "
                       "не записано — в этом файле, скорее всего, целы чужие "
                       "MCP-серверы, а сломана одна строка. Исправьте файл "
                       "({}) и повторите {}".format(
                           цель.имя, цель.путь,
                           paths.команда("register", "--codex")))

    исходный = _текст(цель)
    строки = исходный.splitlines()
    i = _найти_заголовок(строки)
    if i < 0 and _иная_форма(данные):
        return False, ("{}: запись {} задана в другой форме, не таблицей "
                       "[{}.{}] — снимите её руками и повторите {}".format(
                           цель.имя, ИМЯ_ЗАПИСИ, РАЗДЕЛ_CODEX, ИМЯ_ЗАПИСИ,
                           paths.команда("register", "--codex")))

    конец_строки = "\r\n" if "\r\n" in исходный else "\n"
    if i >= 0:
        к = _конец_блока(строки, i)
        if _наш_блок(строки[i:к]):
            return True, "{}: уже зарегистрирован, файл не тронут".format(цель.имя)
        # Пустые строки в хвосте блока — разделитель перед чужим заголовком.
        # Он не наш: съев его, мы бы слепили наши строки с чужой таблицей.
        пусто = 0
        while к - пусто > i + 1 and not строки[к - пусто - 1].strip():
            пусто += 1
        новые = строки[:i] + list(СТРОКИ_CODEX) + строки[к - пусто:]
        что = "обновлена"
    else:
        новые = list(строки)
        while новые and not новые[-1].strip():
            новые.pop()
        if новые:
            новые.append("")
        новые = новые + list(СТРОКИ_CODEX)
        что = "добавлена"

    чужое_до = _чужое(данные)
    try:
        _записать_текст(цель, конец_строки.join(новые) + конец_строки)
    except OSError as e:
        return False, "{}: не удалось записать ({}: {})".format(
            цель.имя, type(e).__name__, e)
    беда = _сверить(цель, чужое_до, ждём=True)
    if беда:
        return False, "{}: {}; {}".format(
            цель.имя, беда, _вернуть_как_было(цель, исходный, состояние))
    хвост = "" if состояние in (НЕТ_ФАЙЛА, ПУСТОЙ) else ", копия рядом в .bak"
    return True, "{}: запись {} {}{}".format(цель.имя, ИМЯ_ЗАПИСИ, что, хвост)


def _снять_toml(цель: Цель) -> tuple[bool, str]:
    данные, состояние = прочитать(цель)
    if состояние == НЕТ_КАТАЛОГА:
        return True, "{}: клиент не установлен — снимать нечего".format(цель.имя)
    if состояние == БИТЫЙ:
        return False, ("{}: конфигурация не разбирается как TOML — не трогаю: "
                       "{}".format(цель.имя, цель.путь))

    исходный = _текст(цель)
    строки = исходный.splitlines()
    i = _найти_заголовок(строки)
    if i < 0:
        if _иная_форма(данные):
            return False, ("{}: запись {} задана в другой форме, не таблицей "
                           "[{}.{}] — снимите её руками: {}".format(
                               цель.имя, ИМЯ_ЗАПИСИ, РАЗДЕЛ_CODEX, ИМЯ_ЗАПИСИ,
                               цель.путь))
        return True, "{}: записи {} нет — снимать нечего".format(
            цель.имя, ИМЯ_ЗАПИСИ)

    конец_строки = "\r\n" if "\r\n" in исходный else "\n"
    к = _конец_блока(строки, i)
    начало = i
    if к == len(строки):
        # Блок в конце файла — уносим и пустую строку, которой мы же от
        # чужого текста отделились: иначе файл после снятия отличается от
        # того, что было до регистрации, на лишнюю пустую строку, и каждый
        # цикл «поставил — снял» добавляет ещё одну.
        while начало > 0 and not строки[начало - 1].strip():
            начало -= 1
    новые = строки[:начало] + строки[к:]
    чужое_до = _чужое(данные)
    try:
        _записать_текст(
            цель, (конец_строки.join(новые) + конец_строки) if новые else "")
    except OSError as e:
        return False, "{}: не удалось записать ({}: {})".format(
            цель.имя, type(e).__name__, e)
    беда = _сверить(цель, чужое_до, ждём=False)
    if беда:
        return False, "{}: {}; {}".format(
            цель.имя, беда, _вернуть_как_было(цель, исходный, состояние))
    return True, "{}: запись {} убрана, копия рядом в .bak".format(
        цель.имя, ИМЯ_ЗАПИСИ)
