# -*- coding: utf-8 -*-
"""
garant-mcp — MCP-сервер над подпиской «Гарант».

Восемь инструментов: search · toc · document · article · revisions ·
revision_on_date · kinds · practice.

PROVENANCE ЕСТЬ НЕ У ВСЕХ, и это надо знать до того, как ставить норму
в процессуальный документ.

  · полный (doc_id, редакция, действует_с, изменяющий_акт, источник,
    дата_проверки, hash_текста, правило_отпечатка, при сомнении в редакции —
    оговорки_о_редакции) — только `document` и `article`. Это
    единственные два инструмента, чей ответ содержит текст нормы, а значит
    единственные, где есть что хешировать и к какой редакции привязывать;
  · вырожденный (источник и дата проверки) — `search` и `practice`. Они
    возвращают перечни найденного, а не текст: подтверждать здесь нечего,
    кроме того, откуда и когда взят перечень;
  · нет вовсе — `toc`, `kinds`, `revisions`, `revision_on_date`. Первые два
    возвращают структуру (оглавление акта, дерево видов информации), где
    понятие редакции неприменимо. Вторые два возвращают сведения О редакциях,
    а не норму: реквизиты, периоды действия, изменяющие акты.

Отсюда правило: в документ ставится текст, полученный `document` или
`article`, вместе с его блоком provenance. Ответ без provenance — справка
для выбора, а не цитата.

Запуск: сервер запускает MCP-клиент по записи `{"command": "garant-mcp"}`
в своей конфигурации; руками — командой `garant-mcp`. Прежний совет
«python server.py» неисполним с решения 14: файл лежит внутри пакета,
относительными импортами, и по имени файла не запускается вовсе.

Демона поднимать заранее не нужно: сервер делает это сам при первом
вызове инструмента.
"""
from __future__ import annotations

import asyncio
import functools
import json
import sys
from concurrent.futures import ThreadPoolExecutor

from mcp.server.fastmcp import FastMCP

from . import __version__
from . import daemon_client as dc
from . import paths

try:
    # Ошибка инструмента обязана дойти до клиента КАК ОШИБКА протокола
    # (isError), а не строкой с ключом «ошибка» внутри нормального ответа:
    # такую строку клиент не отличит от данных и вставит в текст как факт.
    from mcp.server.fastmcp.exceptions import ToolError
except Exception:  # состав mcp 1.x менялся; исключение — тоже ошибка MCP
    ToolError = RuntimeError

mcp = FastMCP("garant")
# serverInfo.version клиенту. Без этой строки низкоуровневый сервер отдаёт
# версию пакета «mcp» (там `self.version if self.version else pkg_version("mcp")`),
# и пользователь сообщал бы о «garant 1.29.1» — версии, которой не существует,
# тогда как `garant --version`, `doctor` и /version демона говорят __version__.
# Присваивание, а не аргумент конструктора: параметра version у FastMCP 1.x нет.
#
# Через getattr, потому что `_mcp_server` — приватное поле чужого пакета:
# сборка mcp, где его нет, обязана дать работающий сервер со старой (чужой)
# версией в serverInfo, а не отказ импорта на строке про надпись.
_низкоуровневый = getattr(mcp, "_mcp_server", None)
if _низкоуровневый is not None:
    _низкоуровневый.version = __version__

# Спрашивается РЕЗУЛЬТАТ, а не факт присваивания: сборка, где version
# пересобирается после инициализации, оставит клиенту чужую версию при вполне
# непустом _mcp_server. Само значение — здесь, а голос ему даёт main():
# импорт обязан быть немым в оба потока (на stdio лишний байт в stdout валит
# протокол, а на stderr при импорте стоит тест), тогда как запуск сервера
# пишет в stderr законно — это лог MCP-клиента.
ВЕРСИЯ_В_SERVERINFO = getattr(_низкоуровневый, "version", None)


class _Proxy:
    """Прокси к демону: вызовы уходят по HTTP на 127.0.0.1.

    Сервер намеренно НЕ поднимает собственный браузер. Профилем владеет
    единственный процесс — garant-daemon, который держит сессию живой
    независимо от того, открыт Claude Code или нет. Отсюда же исчезает
    конфликт «профиль занят другим процессом».
    """

    def __getattr__(self, name):
        # ТОЛЬКО именованные аргументы: демон принимает {"метод", "параметры"}
        # и делает getattr(client, метод)(**параметры). Позиционный вызов
        # здесь падает ещё до HTTP — в логах демона такой вызов не виден.
        def fn(**kwargs):
            return dc.call(name, **kwargs)
        return fn


_PROXY = _Proxy()


def client() -> _Proxy:
    return _PROXY


GarantError = dc.DaemonError


def dump(obj) -> str:
    return json.dumps(obj, ensure_ascii=False, indent=2)


# HTTP-запросы к демону блокирующие, а FastMCP исполняет инструменты в цикле
# asyncio — поэтому работа уходит в отдельные потоки. Ограничение в один поток
# больше не нужно: браузером владеет демон, здесь только сетевые вызовы.
_EXEC = ThreadPoolExecutor(max_workers=4, thread_name_prefix="garant")


def guard(fn):
    # functools.wraps обязателен: FastMCP строит схему инструмента по сигнатуре
    # обёртки. Без него все инструменты уходят клиенту с параметрами (*a, **kw),
    # то есть без doc_id, query и прочего — вызвать их корректно невозможно.
    @functools.wraps(fn)
    async def wrapper(*a, **kw):
        def call():
            try:
                # Демон поднимается здесь, а не при импорте сервера: MCP-клиент
                # запускает сервер при своём старте, и поднимать браузер тому,
                # кто, возможно, ни разу не спросит о «Гаранте», незачем.
                # Проверка дешёвая — тот же GET /health, которым клиент и так
                # опознаёт демона перед отправкой токена.
                dc.готов_к_работе()
                return fn(*a, **kw)
            except GarantError as e:
                # Текст без абсолютных путей, команда для человека — всегда
                # `garant <что-то>`: он лежит в PATH, а путь конкретной машины
                # у читающего не существует.
                raise ToolError("{}\n\nНепроверенную норму в документ "
                                "не ставить. Диагностика: {}".format(
                                    e, paths.команда("doctor"))) from e
        return await asyncio.get_running_loop().run_in_executor(_EXEC, call)
    return wrapper


@mcp.tool()
@guard
def garant_search(query: str, page: int = 1, limit: int = 20,
                  use_cache: bool = True) -> str:
    """Поиск документов в базе ГАРАНТ по реквизитам или контексту.

    query — 3–5 КЛЮЧЕВЫХ СЛОВ, а не фраза-тезис. Гарант трактует запрос как
    конъюнкцию всех слов: длинная формулировка даёт одно-два случайных попадания
    или ноль. «продление домашнего ареста мотивированность» — рабочий запрос;
    «суд обязан привести конкретные фактические обстоятельства» — нет.
    Возвращает {total, страница, всего_страниц, items[...], kinds[]},
    где kinds — распределение находок по видам (акты власти, высшие суды, комментарии).
    doc_id использовать дальше в garant_document / garant_article / garant_revisions.

    Перечень находок кэшируется (тексты норм — никогда). Ответ из кэша несёт
    в provenance `из_кэша`, `дата_записи`, `возраст_часов` и
    `срок_годности_часов`: документ,
    появившийся в базе после записи, в таком ответе не появится.
    use_cache=False — потребовать свежего похода в «Гарант»; применять, когда
    важна именно сегодняшняя полнота выдачи.
    """
    return dump(client().search(query=query, page=page, limit=limit,
                                use_cache=use_cache))


