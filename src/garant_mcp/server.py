def main():
    """Точка входа `garant-mcp`: MCP по stdio.

    Отдельная функция, а не только __main__: установленный пакет запускается
    консольным скриптом, а он умеет звать лишь именованную функцию.
    """
    # Исход «версию поставить некуда» обязан быть слышен, и слышен ТОМУ, кому
    # он достаётся: комментарий у присваивания читает правящий файл, а чужую
    # версию называет поставивший пакет — в отчёте об ошибке, где её никто
    # не опознает. Строка уходит в stderr: в stdout сервера нельзя ни байта
    # мимо протокола, MCP-клиент рвёт соединение на постороннем выводе
    # и причины не показывает. Глагола совета нет намеренно: делать
    # пользователю здесь нечего, это сведения для отчёта.
    if ВЕРСИЯ_В_SERVERINFO != __version__:
        print("garant-mcp {}: serverInfo.version остался «{}» — эта сборка "
              "пакета mcp версию не приняла, и MCP-клиент назовёт чужую"
              .format(__version__, ВЕРСИЯ_В_SERVERINFO), file=sys.stderr)
    mcp.run()


if __name__ == "__main__":
    main()
