# -*- coding: utf-8 -*-
"""Общие мелочи для проверок §7 `docs/TEAM.md` («восемь проверок без
исполнителя»): расположение корня репозитория и обёртка над `git`.

Не тест сам по себе — импортируется тестовыми модулями. Имя с подчёркиванием
намеренно: pytest не собирает его как файл с тестами, а `test_paths.py`
(откуда берут `_песочница`/`_окружение`) этот файл не трогает.

Все функции здесь только ЧИТАЮТ репозиторий (`git show`, `git ls-files`,
`git check-ignore`, чтение файлов с диска) — ни одна не пишет в рабочий
индекс и не меняет рабочее дерево. Проверки, которым нужен ЗАПИСЫВАЕМЫЙ
индекс (пробы хука), заводят СОБСТВЕННЫЙ временный репозиторий и никогда
не трогают этот.
"""

from __future__ import annotations

import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def git(*args: str, cwd: Path | None = None, check: bool = False
        ) -> subprocess.CompletedProcess:
    """`git <args>` с текстовым выводом в UTF-8, без падения на не-ASCII путях."""
    return subprocess.run(
        ["git", *args],
        cwd=str(cwd or ROOT),
        capture_output=True, text=True, encoding="utf-8", errors="replace",
        check=check,
    )


def _ls_files_z(*args: str) -> list[str]:
    """`git ls-files <args> -z`, разобранный по NUL, а не по переводу строки.

    Без `-z` git заключает в кавычки и экранирует пути с не-ASCII символами
    (`каталог/Файл.txt` превращается в `"каталог/Ð..."`), и такой путь потом
    не открывается с диска: `open()` получает буквальную escape-строку, а не
    реальное имя файла, чтение падает или возвращает пусто, и файл молча
    выпадает из всех проверок, которые опираются на этот список. Тот же
    приём и то же объяснение — в `hooks/pre-commit`, где однажды это уже
    было учтено; здесь список набирался заново и наступил на те же грабли.
    `subprocess.run(..., text=True)` декодирует поток целиком, включая NUL,
    так что достаточно разбить результат по `"\\0"`.
    """
    r = git("ls-files", "-z", *args)
    return [s for s in r.stdout.split("\x00") if s]


def отслеживаемые() -> list[str]:
    """Файлы, которые уже в индексе (`git ls-files`)."""
    return _ls_files_z()


def публичные_кандидаты() -> list[str]:
    """Файлы, которые СЕЙЧАС могли бы уйти в публичный коммит.

    Это отслеживаемые файлы плюс неотслеживаемые, но не закрытые
    `.gitignore` (`git status` их пометил бы `??`). Второе важно: новый
    публичный файл, который ещё не закоммичен, обязан подчиняться тому же
    правилу висячих ссылок, что и уже закоммиченный, — иначе проверка
    появляется только ПОСЛЕ первого нарушения.
    """
    отслеж = отслеживаемые()
    неотслеж = _ls_files_z("--others", "--exclude-standard")
    return sorted(set(отслеж) | set(неотслеж))


def прочитать_из_рабочего_дерева(путь: str) -> str | None:
    """Содержимое файла с диска (не из индекса — для кандидатов на коммит,
    которых в индексе ещё нет, `git show` не отдаст ничего).

    None — файл не читается как текст (бинарный, отсутствует, битая
    кодировка) и по нему проверка контента не проводится.
    """
    p = ROOT / путь
    try:
        data = p.read_bytes()
    except OSError:
        return None
    if b"\x00" in data[:8000]:
        return None  # бинарный файл — построчные правила по нему не имеют смысла
    try:
        return data.decode("utf-8")
    except UnicodeDecodeError:
        try:
            return data.decode("utf-8-sig")
        except UnicodeDecodeError:
            return None
