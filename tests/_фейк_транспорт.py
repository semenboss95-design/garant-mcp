"""Фейковый Transport — граница подмены решения 17, и не выше неё.

`Transport.fetch(method, url, form) -> (status, text)` — единственная точка
контура, где тесты имеют право заменить настоящую сеть. Ниже этой границы
у фейка нет ничего, кроме списка заготовленных тел; всё, что выше (сборка
URL, кодирование формы, повтор после 401/403, разбор пустого тела, порядок
шагов практики, вырезка статьи, provenance), исполняется настоящим кодом
`garant_mcp.client` — тест ходит в него по-настоящему, а не повторяет его
логику руками.

Признака успеха в контракте нет специально (решение 17): фейк не может
сказать «403, но получилось» — это ровно то, что превратило бы тест
в проверку самого себя.
"""
from __future__ import annotations

from collections.abc import Callable


class ФейкТранспорт:
    """Отдаёт заготовленные ответы по очереди либо считает их функцией.

    `вызовы` — журнал (method, url, form) в порядке фактических обращений:
    по нему тесты практики проверяют ПОСЛЕДОВАТЕЛЬНОСТЬ шагов и то, что
    в форму каждого следующего шага ушёл именно НОВЫЙ doclistId, а не старый.
    """

    def __init__(self, ответы):
        # Список (status, text) — простой сценарий без ветвлений;
        # функция(method, url, form, номер_вызова) -> (status, text) — когда
        # ответ должен зависеть от того, ЧТО именно спросили (например,
        # /document/pages на разные номера страниц).
        self._список = list(ответы) if not callable(ответы) else None
        self._функция: Callable | None = ответы if callable(ответы) else None
        self.вызовы: list[tuple[str, str, str | None]] = []

    def готов(self) -> bool:
        return True

    def fetch(self, method: str, url: str, form: str | None):
        self.вызовы.append((method, url, form))
        if self._функция is not None:
            return self._функция(method, url, form, len(self.вызовы))
        try:
            return self._список[len(self.вызовы) - 1]
        except IndexError:
            raise AssertionError(
                f"ФейкТранспорт: запрошен ответ №{len(self.вызовы)}, а сценарий короче ({len(self._список or [])} шт.) — "
                "клиент сходил в сеть больше раз, чем ожидал тест. "
                f"Последний вызов: {method} {url}")
