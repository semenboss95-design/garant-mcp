"""Единственное место, где тесты клиента подключают пакет к sys.path.

Пакет не устанавливается ни через pip, ни через uv (это отдельная забота —
см. докстринг test_paths.py про механику упаковки). Тесты, которым нужно
поставить в конструктор GarantClient живой объект транспорта (а не строку
кода для subprocess.run), обязаны импортировать пакет в ТОМ ЖЕ процессе —
иначе фейковый транспорт не пересечь границу процесса.

Это не проверка побочных эффектов импорта (для неё в test_paths.py есть
отдельный, изолированный путь через subprocess) — здесь только доступ
к модулю. STATE в этом процессе указывает на настоящий каталог данных ОС
машины, на которой идёт тест; тесты клиента обязаны сами подменять
`client.CACHE_DIR`, если что-то пишут на диск, а не полагаться на то, куда
он указывает по умолчанию.
"""
from __future__ import annotations

import sys
from pathlib import Path

_SRC = Path(__file__).resolve().parent.parent / "src"
if str(_SRC) not in sys.path:
    sys.path.insert(0, str(_SRC))
