# -*- coding: utf-8 -*-
"""`garant login` — код возврата и текст следуют ключу «вошли», а не
самому факту, что демон ответил (спецификация нового поведения, наряд
этапа 03, фаза B, часть 2).

До 07.09.2026 закрытое БЕЗ входа окно печаталось как «вход завершён» и
отдавало код 0 — успех после того, как человек ничего не сделал: демон
ответил (окно закрылось), а «вошли» при этом было `False`. Проверяется
`cli.login()` напрямую, с подменённым `daemon_client.login` (граница
подмены здесь другая, не решение 17 — `cli.py` не HTTP-клиент к «Гаранту»,
а тонкий пульт поверх `daemon_client`; подменяется ровно та функция,
которая в реальности сходила бы к демону по HTTP).
"""
from __future__ import annotations

from garant_mcp import cli
from garant_mcp import daemon_client as dc


def test_окно_закрыто_без_входа_код_не_ноль(monkeypatch, capsys):
    monkeypatch.setattr(dc, "login",
                        lambda: {"вошли": False, "как": "окно закрыто без входа"})

    код = cli.login()

    assert код != 0, (
        "«вошли»: False обязано дать НЕНУЛЕВОЙ код — иначе это успех после "
        "того, как человек ничего не сделал")
    вывод = capsys.readouterr().out
    assert "НЕ подтверждён" in вывод or "не подтверждён" in вывод.lower(), (
        "текст обязан честно сказать, что вход не подтверждён:\n" + вывод)
    assert "вход завершён" not in вывод.lower(), (
        "текст не должен звучать как успех, если «вошли» — False:\n" + вывод)


def test_вошли_true_код_ноль(monkeypatch, capsys):
    monkeypatch.setattr(dc, "login",
                        lambda: {"вошли": True, "как": "подтверждено окном"})

    код = cli.login()

    assert код == 0, "«вошли»: True обязано дать код 0"
    вывод = capsys.readouterr().out
    assert "вход завершён" in вывод.lower(), (
        "текст успеха обязан явно сказать о завершённом входе:\n" + вывод)


def test_вошли_отсутствует_в_ответе_не_считается_успехом(monkeypatch, capsys):
    """Ключа «вошли» может не быть вовсе (неполный/незнакомый ответ демона) —
    это тоже не успех: код читает ИМЕННО значение ключа, а не «что-то
    вернулось»."""
    monkeypatch.setattr(dc, "login", lambda: {"как": "ответ без ключа вошли"})

    код = cli.login()

    assert код != 0, (
        "отсутствие ключа «вошли» не должно молча считаться успехом")
