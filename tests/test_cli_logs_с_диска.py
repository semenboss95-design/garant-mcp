# -*- coding: utf-8 -*-
"""`garant logs`: журнал живого демона идёт по HTTP, журнал молчащего —
с диска (находка (A) наряда python-dev, `cli.py:685-712`).

До правки `logs()` при `DaemonError` от `dc.logs()` (демон не отвечает)
просто отдавал отказ — и человек, который только что позвал `garant stop`
и хочет увидеть, закрылся ли браузер, узнать это не мог: ответ на вопрос
«что делал процесс» лежит в том же файле (`logs/daemon.log`), который
демон при жизни отдавал через `/logs`, только читать его теперь некому.

Три исхода:
  1. демон отвечает — строки из HTTP, диск вообще не трогается;
  2. демон не отвечает (`DaemonError`), файл на диске есть — РОВНО
     последние N строк файла в stdout, пометка «прочитано с диска»
     в stderr (не в stdout — его читают как сам журнал), код 0;
  3. демон не отвечает, файла на диске нет — отказ (код 1) с исполнимым
     советом `garant start`, без пути к файлу в тексте (путь читающему
     неизвестен, и вычислять его он не обязан — `.claude/rules/python.md`).

Стиль подмены — как в `test_stop_потолок_и_честный_текст.py`: `cli.logs()`
зовётся напрямую (у `cli.py` нет побочных эффектов на импорте, наряд
python-dev это прямо утверждает), подменяется коллаборатор границы
демон/пульт (`daemon_client.logs`) — место, которое в реальности сходило
бы к демону по HTTP. Путь к файлу на диске (`paths.log_dir`) — обычный
атрибут модуля `paths`, а не свойство, вычисляемое на импорте от
`GARANT_HOME`: `cli.logs()` читает `paths.log_dir` в момент вызова, а не
на импорте, поэтому подмена работает без подпроцесса и без переменной
окружения — так же, как `daemon_client.адрес` подменяется в тестах stop().
"""
from __future__ import annotations

from garant_mcp import cli
from garant_mcp import daemon_client as dc
from garant_mcp import paths


class _ДискЗапрещён:
    """Стоит на месте `paths.log_dir`. Взрывается при первом же обращении —
    доказывает, что `logs()` не пытается собрать путь к файлу на диске,
    когда демон отвечает по HTTP. Обычный `tmp_path`, даже указывающий на
    пустой каталог, этого бы не отличил: «не читали диск вовсе» и
    «прочитали и не нашли файл» выглядели бы одинаково зелёными.
    """

    def __truediv__(self, other):
        raise AssertionError(
            "logs() обратился к paths.log_dir (запросил {!r}), хотя демон "
            "ответил по HTTP — в этом исходе диск ни при чём".format(other))


def _падает_daemonerror():
    raise dc.DaemonError("демон не отвечает (тест)")


# --------------------------------------------------------------------------
#  1. демон отвечает — строки из HTTP, диск не читается
# --------------------------------------------------------------------------

def test_logs_демон_отвечает_строки_из_http_диск_не_читается(
        monkeypatch, capsys):
    строки_http = ["строка http 1", "строка http 2", "строка http 3"]
    monkeypatch.setattr(dc, "logs", lambda: {"лог": строки_http})
    monkeypatch.setattr(paths, "log_dir", _ДискЗапрещён())

    код = cli.logs()

    assert код == cli.КОД_ОК
    вывод = capsys.readouterr()
    assert вывод.out.splitlines() == строки_http, (
        "logs() обязан напечатать РОВНО строки, вернувшиеся по HTTP, "
        "и ничего больше:\n" + вывод.out)
    assert вывод.err == "", (
        "демон ответил по HTTP — пометки «прочитано с диска» в stderr "
        "здесь быть не должно (диск вообще не открывался):\n" + вывод.err)


# --------------------------------------------------------------------------
#  2. демон не отвечает, файл на диске есть — ровно последние N строк
#      в stdout, пометка о чтении с диска строго в stderr
# --------------------------------------------------------------------------

def test_logs_демон_не_отвечает_файл_есть_последние_n_строк_с_диска(
        monkeypatch, capsys, tmp_path):
    monkeypatch.setattr(dc, "logs", _падает_daemonerror)

    каталог = tmp_path / "logs каталог"
    каталог.mkdir()
    все_строки = ["строка {}".format(i) for i in range(1, 301)]
    (каталог / "daemon.log").write_text(
        "\n".join(все_строки) + "\n", encoding="utf-8")
    monkeypatch.setattr(paths, "log_dir", каталог)

    код = cli.logs(5)

    assert код == cli.КОД_ОК, (
        "журнал прочитан с диска — это честная замена ответа демона, "
        "не отказ")
    вывод = capsys.readouterr()
    assert вывод.out.splitlines() == все_строки[-5:], (
        "stdout обязан содержать РОВНО последние 5 строк файла с диска "
        "(запрошено `logs(5)`), не больше и не меньше:\n" + вывод.out)
    assert "диска" in вывод.err.lower(), (
        "stderr обязан пометить, что журнал прочитан с диска, а не "
        "получен от демона:\n" + вывод.err)
    assert "демон не отвечает" not in вывод.out.lower(), (
        "пометка о чтении с диска подмешалась в stdout — вывод `garant "
        "logs` читают как сам журнал, и подмешивать в него служебную "
        "строку значит подделывать журнал:\n" + вывод.out)


def test_logs_демон_не_отвечает_файл_есть_умолчание_сорок_строк(
        monkeypatch, capsys, tmp_path):
    """Контраст к предыдущему: без явного аргумента действует то же
    умолчание (40 строк), что и на пути через HTTP — обрезка с диска не
    получила отдельного, более узкого умолчания."""
    monkeypatch.setattr(dc, "logs", _падает_daemonerror)

    каталог = tmp_path / "logs"
    каталог.mkdir()
    все_строки = ["запись {}".format(i) for i in range(1, 101)]
    (каталог / "daemon.log").write_text(
        "\n".join(все_строки) + "\n", encoding="utf-8")
    monkeypatch.setattr(paths, "log_dir", каталог)

    код = cli.logs()

    assert код == cli.КОД_ОК
    вывод = capsys.readouterr().out
    assert вывод.splitlines() == все_строки[-40:], (
        "без аргумента `logs()` обязан отдать последние 40 строк с диска, "
        "как и по умолчанию с HTTP:\n" + вывод)


# --------------------------------------------------------------------------
#  3. демон не отвечает, файла на диске нет — отказ с исполнимым советом,
#      без пути к файлу в тексте
# --------------------------------------------------------------------------

def test_logs_демон_не_отвечает_файла_нет_отказ_без_пути(
        monkeypatch, capsys, tmp_path):
    monkeypatch.setattr(dc, "logs", _падает_daemonerror)

    каталог = tmp_path / "пустой каталог логов"
    каталог.mkdir()
    monkeypatch.setattr(paths, "log_dir", каталог)

    код = cli.logs()

    assert код == cli.КОД_НЕ_СДЕЛАНО, (
        "демон не отвечает, и на диске журнала нет — это отказ (код 1), "
        "а не тихий код 0")
    ошибка = capsys.readouterr().err
    assert "garant start" in ошибка, (
        "отказ обязан дать исполнимый совет — чем поднять демона:\n"
        + ошибка)
    assert str(каталог) not in ошибка, (
        "текст отказа не должен называть путь конкретной установки — "
        "каталог состояния читающему неизвестен и вычислять его он не "
        "обязан:\n" + ошибка)
    assert "daemon.log" not in ошибка, (
        "текст отказа не должен называть имя файла журнала:\n" + ошибка)
