# -*- coding: utf-8 -*-
"""POSIX-ветвь опроса `ps`: зомби не значит «жив» — наряд 4-6,
`src/garant_mcp/cli.py` (`_спросить_ps`, `_имя_процесса`, `_командная_строка`),
решение 42 в `docs/DECISIONS.md`, дополнение про зомби.

Причина наряда: в CI на ubuntu (run 34396351534) приманка после SIGTERM
успевала стать зомби до того, как пульт проверял её ещё раз. `ps -o comm=`
печатает имя зомби так же, как имя живого процесса — `garant stop` после
потолка ожидания отвечал, что процесс всё ещё жив. Правка спрашивает
`stat=` тем же вызовом `ps`, что и нужное поле (`_спросить_ps`), и состояние
`Z*` трактует как «процесса, который может что-то держать (ограничение 2),
уже нет» — отдельно в `_имя_процесса` (даёт `None`) и в `_командная_строка`
(даёт `("нет", "")`).

Ветвь POSIX выбирается подменой `cli.os.name`, а не настоящей ОС теста:
файл обязан быть зелёным и на Windows (машина автора), и на Linux в CI, не
трогая ни PATH, ни настоящий `ps`. `cli.subprocess.run` подменён на
подделку, отдающую заранее заготовленный `stdout`/код возврата — вызовов
к операционной системе нет вовсе, только разбор уже полученного текста.

Проверено, что на HEAD-версии `cli.py` (до этого наряда — там `ps` зовётся
с одним полем, `-o comm=` / `-o args=`, и зомби считается живым) те же
проверки красны: копия пакета была собрана во временном каталоге с
`cli.py`, взятым из `git show HEAD:src/garant_mcp/cli.py`, и прогнана
отдельным скриптом (не через этот файл — `tests/conftest.py` вставляет
в `sys.path[0]` НАСТОЯЩИЙ `src/` репозитория и перекрыл бы временную копию
тем же импортом `garant_mcp.cli`). Результат: 5 из 7 проверок падают
(«зомби даёт None», «зомби даёт (нет, '')», «живой даёт имя»/«строку целиком»
— на HEAD ответ подделки читается как один нерасщеплённый ответ ps без
`stat=`, и «один вызов ps со stat= первым полем» — HEAD вызывает `ps` с
`-o comm=`/`-o args=`, без `stat=` вовсе). Две проверки («код 1 → None» /
«код 1 → (нет, '')») зелены и на HEAD — они не про зомби, а про
предсуществовавшую ветку «процесса нет», которую наряд не трогал.
"""
from __future__ import annotations

import types

from garant_mcp import cli


def _подделка_ps(ответ_stdout: str, код: int = 0):
    """Подделка `subprocess.run`: запоминает КАЖДЫЙ вызов целиком (argv),
    отдаёт один и тот же заготовленный ответ независимо от того, что
    спрошено — так же, как заготовлена подделка в пробе python-dev."""
    вызовы: list = []

    def _run(argv, **kw):
        вызовы.append(list(argv))
        return types.SimpleNamespace(returncode=код, stdout=ответ_stdout,
                                      stderr="")

    return _run, вызовы


def _posix(monkeypatch, ответ_stdout: str, код: int = 0) -> list:
    """Ветвь POSIX без единого настоящего обращения к ОС."""
    _run, вызовы = _подделка_ps(ответ_stdout, код)
    monkeypatch.setattr(cli.os, "name", "posix")
    monkeypatch.setattr(cli.subprocess, "run", _run)
    return вызовы


# --------------------------------------------------------------------------
#  _имя_процесса
# --------------------------------------------------------------------------

def test_имя_процесса_зомби_даёт_none_а_не_имя(monkeypatch):
    _posix(monkeypatch, "Z    python\n")
    assert cli._имя_процесса(4242) is None, (
        "зомби ничего не держит (ограничение 2) — своё имя `ps -o comm=` "
        "печатает и после смерти, а `_имя_процесса` обязан вернуть None")


def test_имя_процесса_живой_даёт_имя(monkeypatch):
    _posix(monkeypatch, "S    python\n")
    assert cli._имя_процесса(4242) == "python"


def test_имя_процесса_код_1_пустой_stdout_даёт_none(monkeypatch):
    _posix(monkeypatch, "", код=1)
    assert cli._имя_процесса(4242) is None


# --------------------------------------------------------------------------
#  _командная_строка
# --------------------------------------------------------------------------

def test_командная_строка_зомби_даёт_нет_и_пустую_строку(monkeypatch):
    _posix(monkeypatch, "Z+   [python] <defunct>\n")
    assert cli._командная_строка(4242) == ("нет", ""), (
        "зомби лишён своей командной строки — ps печатает «[имя] "
        "<defunct>», маркера демона там нет и быть не может; молчащий "
        "путь `stop()` обязан читать это как «процесс не наш», а не "
        "как незнание")


def test_командная_строка_живой_демон_даёт_есть_и_строку_целиком(monkeypatch):
    строка = "/usr/bin/python3 -m garant_mcp.daemon --port 57671"
    _posix(monkeypatch, "S+   " + строка + "\n")
    исход = cli._командная_строка(4242)
    assert исход[0] == "есть"
    assert исход[1] == строка, (
        "внутренние пробелы командной строки (между `-m`, модулем, "
        "`--port`, числом) обязаны дойти без изменений, потеряться "
        "может только КРАЙНИЙ пробел разделителя со `stat=` — "
        "получено {!r}".format(исход[1]))


def test_командная_строка_код_1_даёт_нет(monkeypatch):
    _posix(monkeypatch, "", код=1)
    assert cli._командная_строка(4242) == ("нет", "")


# --------------------------------------------------------------------------
#  сторож формы: состояние и поле спрашиваются ОДНИМ вызовом ps, `stat=`
#      обязан идти первым в спецификации `-o`
# --------------------------------------------------------------------------

def test_состояние_и_поле_спрашиваются_одним_вызовом_ps_с_stat_первым(
        monkeypatch):
    """Если следующая правка расщепит опрос на два отдельных вызова ps
    (сначала состояние, потом поле, или наоборот), между ними у процесса
    будет время смениться — комментарий к `_спросить_ps` называет это
    гонкой напрямую. Сторож проверяет ФОРМУ вызова, а не только итоговое
    значение: иначе ошибка «два вызова, но каждый по отдельности верный
    на этом стенде» прошла бы этим файлом незамеченной."""
    вызовы = _posix(monkeypatch, "S    python\n")

    cli._имя_процесса(4242)

    assert len(вызовы) == 1, (
        "опрос процесса обязан быть ОДНИМ вызовом ps, а не несколькими: "
        "{}".format(вызовы))
    argv = вызовы[0]
    assert argv[0] == "ps", argv
    спец = argv[-1]
    assert спец.startswith("stat="), (
        "поле `stat=` обязано идти ПЕРВЫМ в спецификации `-o` — иначе "
        "`_спросить_ps` не сможет отделить состояние от значения простым "
        "partition(' '): {!r}".format(спец))
