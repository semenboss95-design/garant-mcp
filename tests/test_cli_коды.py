# --------------------------------------------------------------------------
#  update/uninstall/migrate — с шага 4 больше не заглушки (наряд python-dev).
#  Код 3 («появится позже») здесь больше не подходит: каждая команда что-то
#  ДЕЛАЕТ и заканчивается по конкретной, разной для каждой причине —
#  ни одна не молчаливый успех (0) и не «нет такой команды» (2).
#
#  Три сценария разные по устройству, поэтому не параметризованы одной
#  функцией с общим кодом — так было бы подгонкой под старое число, а не
#  проверкой того, что каждая команда действительно делает без аргументов
#  в пустой песочнице:
#
#    update    — без метки uv tool/pipx на пути к своему же коду `_чем_
#                поставлено()` честно не понимает, чем поставлен пакет,
#                и отказывает, НЕ пытаясь выполнить неверную команду
#                обновления (код 1, КОД_НЕ_СДЕЛАНО);
#    uninstall — без `--yes` и без интерактивного stdin спросить не у кого
#                («ответа нет»), отказывает ДО того, как тронуть демона,
#                регистрации или профиль (код 1, тот же КОД_НЕ_СДЕЛАНО);
#    migrate   — единственная из трёх требует позиционный аргумент ПУТЬ,
#                и его разбор — на уровне main(), до входа в саму функцию:
#                без пути это КОД_УПОТРЕБЛЕНИЕ (2), а не «не сделано».
# --------------------------------------------------------------------------

def test_update_без_настроенного_установщика_код_1(tmp_path, чужой_каталог):
    пакет = _песочница(tmp_path)
    r = _garant(пакет, чужой_каталог, ["update"])
    assert r.returncode == 1, (
        "update в песочнице (код лежит не в окружении uv tool и не pipx) "
        "обязан честно отказать (1), не пытаясь выполнить угаданную команду "
        "обновления: получено {}\n{}".format(r.returncode, r.stdout + r.stderr))
    assert "не понял, чем поставлен пакет" in r.stderr, (
        "причина отказа обязана быть названа:\n" + r.stderr)


def test_uninstall_без_yes_и_без_терминала_код_1(tmp_path, чужой_каталог):
    пакет = _песочница(tmp_path)
