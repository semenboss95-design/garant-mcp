ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
if str(SRC) not in sys.path:
    sys.path.insert(0, str(SRC))
import garant_mcp as _pkg  # noqa: E402


def _garant(пакет: Path, cwd: Path, аргументы: list[str],
           доп: dict | None = None) -> subprocess.CompletedProcess:
    return subprocess.run(
        [sys.executable, "-m", "garant_mcp.cli", *аргументы],
        cwd=str(cwd),
        env=_окружение({"PYTHONPATH": str(пакет.parent),
                        "GARANT_HOME": str(cwd / "состояние"),
                        **(доп or {})}),
        capture_output=True, text=True, encoding="utf-8", errors="replace",
        timeout=60,
    )


