# --------------------------------------------------------------------------
#  register/unregister: неизвестный ключ и лишний позиционный — код 2,
#  ДО построения целей (Д-5)
#
#  До правки `_цели` смотрела только «есть ли в списке аргументов знакомая
#  строка» (`"--desktop" in аргументы`) и молча пропускала всё непонятное:
#  `garant register --codexx` не находил ни `--desktop`, ни `--code`, ни
#  `--project` и падал в ветку «без ключей» — регистрировал Claude Desktop
#  и Claude Code с кодом 0, ничего не сказав об опечатке и не записав
#  Codex, о котором единственно просили. Опечатка стала правдоподобной
#  именно с появлением `--codex`: `--desktop`/`--code` было спутать не с
#  чем — заглавных букв в них ошибиться сложно, а `--codex`/`--codexx`
#  отличаются одним символом.
#
#  Три сценария ниже безопасны без подмены HOME/APPDATA ТОЛЬКО потому,
#  что на исправленном коде `_цели` возвращает КОД_УПОТРЕБЛЕНИЕ раньше,
#  чем зовёт `register.цель_desktop()`/`цель_code()`/`цель_codex()` —
#  тот же довод, что уже действует для `test_register_project_без_пути_код_2`
#  (см. докстринг файла). Но довод «код так написан» — это чтение исходника,
#  а не измерение: на СЛОМАННОМ `_цели` (до правки Д-5) ветка «без ключей»
#  сработала бы и потянула бы `Path.home()`/`APPDATA` НАСТОЯЩЕЙ машины —
#  поэтому здесь `USERPROFILE`/`HOME`/`APPDATA` всё равно подменены на
#  каталог-двойник (`_чужой_дом`/`_окружение_с_чужим_домом`, как в
#  `test_cli_необратимое.py`), и после прогона проверяется, что в нём
#  не появилось ни одного файла: на исправленном коде это тривиально верно
#  (файлы не тронуты вовсе), а на сломанном — это ровно то, что отличило
#  бы красный прогон от зелёного.
# --------------------------------------------------------------------------

def _файлов_в(корень: Path) -> set[str]:
    if not корень.exists():
        return set()
    return {str(p.relative_to(корень)) for p in корень.rglob("*") if p.is_file()}


def test_register_неизвестный_ключ_код_2(tmp_path, чужой_каталог):
    пакет = _песочница(tmp_path)
    дом = _чужой_дом(tmp_path)
    до = _файлов_в(дом)

    r = _garant(пакет, чужой_каталог, ["register", "--codexx"],
                _окружение_с_чужим_домом({}, дом))

    assert r.returncode == 2, r.stdout + r.stderr
    assert "--codexx" in r.stderr, (
        "отказ обязан назвать конкретный неизвестный ключ:\n" + r.stderr)
    assert "неизвестный ключ" in r.stderr, r.stderr
    for ключ in ("--desktop", "--code", "--codex", "--project"):
        assert ключ in r.stderr, (
            "подсказка обязана перечислить допустимые ключи ({}):\n{}"
            .format(ключ, r.stderr))
    assert _файлов_в(дом) == до, (
        "register с опечаткой в ключе не должен коснуться ни одного файла "
        "в домашнем каталоге — до правки Д-5 он тихо регистрировал Claude "
        "Desktop и Claude Code, приняв опечатку за «ключей нет»")


