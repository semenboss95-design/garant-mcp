# -*- coding: utf-8 -*-
"""Коды возврата пульта `garant` (`cli.py`, этап 02, шаг 3).

Проверяется подмножество из таблицы «команда — ситуация — код» сдачи
исполнителя, достижимое БЕЗ живой подписки и БЕЗ изменения машины: разбор
аргументов командной строки решается раньше, чем код успевает тронуть демона,
зарегистрировать что-то у настоящего MCP-клиента или изменить автозапуск.

НЕ проверяется здесь (и не может быть проверено в этой среде без нарушения
границ наряда):
  · start/stop/restart/status/doctor/login/setup с реально живым или реально
    отсутствующим демоном — это код, трогающий процесс и порт, для него есть
    отдельные файлы (`test_port.py`, `test_doctor_починка.py`);
  · register/unregister БЕЗ `--project` — они пишут в конфигурацию НАСТОЯЩИХ
    Claude Desktop/Code этой машины (`register.цель_desktop()`/`цель_code()`
    берут `Path.home()`), а наряд запрещает трогать эти файлы;
  · autostart on/off — прямо запрещено нарядом (на машине живая задача
    прежнего установщика, `off` её снимет).

Каждый сценарий здесь завершается ДО того, как код коснулся диска клиента,
демона или планировщика: это видно по самому коду — see `cli.py` `main()`
и `_цели()`/`autostart_cmd()`.

Демон при этом не поднимается, `daemon_client` в этих путях не
импортируется вовсе (импорт внутри веток — `from . import daemon_client
as dc` — по коду `cli.py` лежит ЛОКАЛЬНО в функциях, которые сюда не
доходят).
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

import pytest

from test_paths import _песочница, _окружение, чужой_каталог  # noqa: F401

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
if str(SRC) not in sys.path:
    sys.path.insert(0, str(SRC))
import garant_mcp as _pkg  # noqa: E402


def _garant(пакет: Path, cwd: Path, аргументы: list[str],
           доп: dict | None = None) -> subprocess.CompletedProcess:
    return subprocess.run(
        [sys.executable, "-m", "garant_mcp.cli", *аргументы],
        cwd=str(cwd),
        env=_окружение({"PYTHONPATH": str(пакет.parent),
                        "GARANT_HOME": str(cwd / "состояние"),
                        **(доп or {})}),
        capture_output=True, text=True, encoding="utf-8", errors="replace",
        timeout=60,
    )


# --------------------------------------------------------------------------
#  без аргументов — код 2, справка на stdout
# --------------------------------------------------------------------------

def test_без_аргументов_код_2_и_справка(tmp_path, чужой_каталог):
    пакет = _песочница(tmp_path)
    r = _garant(пакет, чужой_каталог, [])
    assert r.returncode == 2, r.stdout + r.stderr
    assert "setup" in r.stdout, (
        "без аргументов пульт обязан печатать справку со списком команд — "
        "получено:\n" + r.stdout)


