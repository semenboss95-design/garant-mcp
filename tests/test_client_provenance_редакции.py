"""Провенанс редакции: три случая и нераспознанный статус — все четыре
помечены (.claude/rules/provenance.md, «Редакция обязана быть ТОЙ»).

`_текущая_редакция` — единственное место, где решается, какую редакцию
показать под видом действующей. Три исхода различаются оговорками:
действующая найдена (оговорок нет), список пуст (цитировать нельзя вовсе),
действующая не найдена — взята первая (оговорка называет это явно), плюс
отдельная оговорка на нераспознанный код статуса.

Синтетика — `tests/fixtures/редакции.json`, собрана по форме endpoints.json
(секция revisions: items, item_map, status_map). Названия актов выдуманы.
"""
from __future__ import annotations

import json
from pathlib import Path

from _фейк_транспорт import ФейкТранспорт

from garant_mcp import client

_ФИКСТУРА = json.loads(
    (Path(__file__).parent / "fixtures" / "редакции.json").read_text(encoding="utf-8"))


def _клиент_с_редакциями(сценарий: str) -> client.GarantClient:
    def маршрут(method, url, form, номер):
        assert "/redactions/list" in url, "в этом тесте ожидается только revisions()"
        return 200, json.dumps(_ФИКСТУРА[сценарий], ensure_ascii=False)
    return client.GarantClient(transport=ФейкТранспорт(маршрут))


def test_действующая_найдена_оговорок_нет():
    к = _клиент_с_редакциями("обычная")
    rev, оговорки = client._текущая_редакция(к.revisions(1))
    assert rev["статус"] == "действующая"
    assert оговорки == []


def test_список_редакций_пуст_цитировать_нельзя():
    к = _клиент_с_редакциями("пустая")
    rev, оговорки = client._текущая_редакция(к.revisions(1))
    assert rev == {}
    assert оговорки, "пустой список обязан дать явную оговорку"
    assert "НЕ УСТАНОВЛЕНА" in оговорки[0]
    assert "цитировать нельзя" in оговорки[0].lower()


def test_действующая_не_найдена_взята_первая_с_оговоркой():
    к = _клиент_с_редакциями("без_действующей")
    revs = к.revisions(1)
    rev, оговорки = client._текущая_редакция(revs)
    # Взята ИМЕННО первая запись списка — не какая попало.
    assert rev == revs[0]
    assert оговорки, "молчаливая подмена действующей первой записью запрещена"
    assert "НЕ НАЙДЕНА" in оговорки[0]
    assert "первая запись" in оговорки[0]


def test_нераспознанный_статус_даёт_отдельную_оговорку():
    к = _клиент_с_редакциями("статус_не_распознан")
    revs = к.revisions(1)
    assert revs[0]["статус_распознан"] is False
    # Нераспознанный код проезжает СЫРЫМ — сравнение со «действующая» не
    # совпадёт ни с чем, поэтому этот сценарий идёт тем же путём, что и
    # «действующая не найдена», плюс СВОЯ, вторая оговорка.
    _rev, оговорки = client._текущая_редакция(revs)
    assert len(оговорки) == 2, (
        "нераспознанный статус обязан дать ВТОРУЮ, отдельную оговорку — "
        "она не заменяет, а дополняет «действующая не найдена»"
    )
    assert "нет в карте эндпоинтов" in оговорки[1]
    assert "rs_Черновик" in оговорки[1]


def test_provenance_document_несёт_оговорки_о_редакции():
    """Оговорки обязаны дойти до `provenance`, а не остаться внутри клиента:
    server.py сериализует ответ целиком, но только если ключ там есть."""
    def маршрут(method, url, form, номер):
        if "/server/keepalive" in url:
            return 200, ""
        if "/document/info" in url:
            return 200, json.dumps({"pageCount": 1})
        if "/document/pages" in url:
            return 200, json.dumps({"items": [{"number": 1, "text": "текст"}]})
        if "/redactions/list" in url:
            return 200, json.dumps(_ФИКСТУРА["без_действующей"], ensure_ascii=False)
        raise AssertionError(url)

    к = client.GarantClient(transport=ФейкТранспорт(маршрут))
    ответ = к.document(doc_id=1)
    assert "оговорки_о_редакции" in ответ["provenance"]
    assert "НЕ НАЙДЕНА" in ответ["provenance"]["оговорки_о_редакции"][0]
