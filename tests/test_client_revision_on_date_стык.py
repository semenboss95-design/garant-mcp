# -*- coding: utf-8 -*-
"""`revision_on_date` на дне стыка двух редакций несёт оговорку о
неоднозначности, а не молча первую (спецификация нового поведения,
наряд этапа 03, фаза B, часть 2).

Синтетика — `fixtures/редакции_стык.json`: две редакции, чьи периоды
действия ОБА покрывают дату 01.01.2024 (конец первого периода и начало
второго — граница читается включительно с обеих сторон, как объявляет
сам client.py). До 07.09.2026 такой день отвечал уверенно и, по всей
видимости, ошибочно — половина случаев стыка.
"""
from __future__ import annotations

import json
from pathlib import Path

from _фейк_транспорт import ФейкТранспорт

from garant_mcp import client

_ФИКСТУРА = json.loads(
    (Path(__file__).parent / "fixtures" / "редакции_стык.json")
    .read_text(encoding="utf-8"))


def _клиент():
    def маршрут(method, url, form, номер):
        assert "/redactions/list" in url
        return 200, json.dumps(_ФИКСТУРА, ensure_ascii=False)
    return client.GarantClient(transport=ФейкТранспорт(маршрут))


def test_день_стыка_несёт_оговорку_о_неоднозначности():
    к = _клиент()
    ответ = к.revision_on_date(doc_id=1, on="01.01.2024")

    assert "_предупреждение" in ответ, (
        "на дату, подходящую под ДВЕ редакции сразу, обязана появиться "
        "оговорка о неоднозначности — иначе выбор выглядит доказанным")
    оговорка = ответ["_предупреждение"].upper()
    assert "НЕ ОДНА" in оговорка or "НЕ ОДНОЗНАЧН" in оговорка, (
        "оговорка не называет саму суть — что под условия подошла не одна "
        "редакция и выбор не доказан:\n" + ответ["_предупреждение"])
    # Оба кандидата обязаны быть НАЗВАНЫ — не только выбранный: читатель
    # должен иметь возможность свериться самостоятельно.
    assert "01.01.2020" in ответ["_предупреждение"], (
        "оговорка не называет первого кандидата:\n" + ответ["_предупреждение"])
    assert "01.01.2024" in ответ["_предупреждение"], (
        "оговорка не называет второго кандидата:\n" + ответ["_предупреждение"])


def test_день_вне_стыка_оговорки_не_несёт():
    """Контрольная проверка: дата ВНУТРИ одного периода не должна ложно
    получать оговорку о неоднозначности — иначе оговорка обесценивается
    (появляется всегда, читатель перестаёт её замечать)."""
    к = _клиент()
    ответ = к.revision_on_date(doc_id=1, on="15.06.2022")

    assert ответ.get("редакция") == "ред. от 01.01.2020"
    оговорка = ответ.get("_предупреждение", "").upper()
    assert "НЕ ОДНА" not in оговорка and "НЕ ОДНОЗНАЧН" not in оговорка, (
        "дата внутри одного периода не должна выглядеть неоднозначной:\n"
        + ответ.get("_предупреждение", ""))
