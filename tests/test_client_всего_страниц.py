# -*- coding: utf-8 -*-
"""Д-15 аудита: `всего_страниц` считается по РАЗНЫМ `doc_id`, а не по сырым
строкам выдачи (client.py:784-789).

Одна строка результата поиска — не всегда один документ: подпункты акта
(разные пункты/статьи одного и того же `documentId`) приходят отдельными
строками той же страницы. Делитель «страниц всего», взятый как число
СЫРЫХ строк, занижает знаменатель, когда `pageSize` сервер не отдал вовсе
(так бывает у `/list/page` — см. комментарий в client.py) — тогда клиент
обязан подставить вместо него число РАЗНЫХ документов на странице, а не
число строк.

Синтетика — `fixtures/поиск_дубликаты.json`: единственный сценарий, где
на одной странице пять строк, но три документа (один документ представлен
тремя подпунктами), а pageSize отсутствует и в poll, и в page — то есть
запасной путь обязан сработать.
"""
from __future__ import annotations

import json
import math
from pathlib import Path

from _фейк_транспорт import ФейкТранспорт

from garant_mcp import client

_ПОИСК = json.loads(
    (Path(__file__).parent / "fixtures" / "поиск_дубликаты.json")
    .read_text(encoding="utf-8"))


def _маршрутизатор():
    def маршрут(method, url, form, номер):
        if "/server/keepalive" in url:
            return 200, ""
        if "/search/base/run" in url:
            return 200, json.dumps(_ПОИСК["run"])
        if "/search/poll" in url:
            return 200, json.dumps(_ПОИСК["poll"])
        if "/list/page" in url:
            return 200, json.dumps(_ПОИСК["page"], ensure_ascii=False)
        raise AssertionError(f"незнакомый URL в тесте поиска: {method} {url}")
    return маршрут


def test_всего_страниц_считается_по_документам_а_не_по_строкам(monkeypatch, tmp_path):
    monkeypatch.setattr(client, "CACHE_DIR", tmp_path / "cache")
    транспорт = ФейкТранспорт(_маршрутизатор())
    к = client.GarantClient(transport=транспорт)

    ответ = к.search("запрос с подпунктами", limit=20, use_cache=False)

    # Пять СЫРЫХ строк, но их держателей — documentId — только три
    # (111 повторяется трижды: сам акт и два его подпункта). Прочитано
    # глазами из fixtures/поиск_дубликаты.json, а не регэкспом реализации.
    РАЗНЫХ_ДОКУМЕНТОВ_НА_СТРАНИЦЕ = 3
    СЫРЫХ_СТРОК_НА_СТРАНИЦЕ = 5
    ВСЕГО_НАЙДЕНО = 30  # kindTree.total в фикстуре

    ожидаемое_число_страниц = math.ceil(
        ВСЕГО_НАЙДЕНО / РАЗНЫХ_ДОКУМЕНТОВ_НА_СТРАНИЦЕ)
    # Если бы клиент делил на число строк (дефект Д-15), получилось бы
    # другое число — проверяем именно расхождение, а не совпадение случайно.
    неверное_по_строкам = math.ceil(
        ВСЕГО_НАЙДЕНО / СЫРЫХ_СТРОК_НА_СТРАНИЦЕ)
    assert ожидаемое_число_страниц != неверное_по_строкам, (
        "числа подобраны так, что дефект и его отсутствие неразличимы — "
        "поправьте фикстуру")

    assert ответ["всего_страниц"] == ожидаемое_число_страниц, (
        "«всего_страниц» посчитано неверно: ожидалось {} (30 документов / "
        "{} различных documentId на странице), получено {}. Похоже на "
        "деление по числу СЫРЫХ строк ({}) вместо числа документов — "
        "именно это и есть Д-15.".format(
            ожидаемое_число_страниц, РАЗНЫХ_ДОКУМЕНТОВ_НА_СТРАНИЦЕ,
            ответ["всего_страниц"], СЫРЫХ_СТРОК_НА_СТРАНИЦЕ))
