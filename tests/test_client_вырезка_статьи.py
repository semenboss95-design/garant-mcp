"""`article()` — вырезка статьи по границе из оглавления (решение 21).

Три требования из наряда: врезка «Гаранта» не становится границей;
статья «5» не ловит «5.1» — ни как узел, ни как границу; статья Конституции
без названия (заголовок без точки) режется одна. Все три — про то, что
дословная цитата не должна обрываться или расширяться молча.
"""
from __future__ import annotations

from _артикль_фикстуры import маршрутизатор_статьи
from _фейк_транспорт import ФейкТранспорт

from garant_mcp import client


def _элемент(текст, id_, тип="article"):
    return {"text": текст, "data": {"element": {"id": id_, "type": тип}}}


def test_редакционная_врезка_не_становится_границей():
    """«Статья 97 дополнена частью 1.1 с 29 апреля 2018 г.» — врезка БЕЗ точки
    сразу после номера. Настоящий заголовок следующей статьи — «Статья 98. »
    С точкой. Врезка обязана остаться ВНУТРИ текста статьи 97, а не отрезать
    её раньше срока и не стать самостоятельной границей."""
    транспорт = ФейкТранспорт(маршрутизатор_статьи(
        children=[
            _элемент("Статья 96", "e96"),
            _элемент("Статья 97", "e97"),
            _элемент("Статья 98", "e98"),
        ],
        page_count=1,
        locate_by_id={"e97": 1, "e98": 1},
        pages_text={1: (
            "<p>Статья 96. Текст девяносто шестой статьи.</p>"
            "<p>Статья 97. Текст девяносто седьмой статьи. "
            "Статья 97 дополнена частью 1.1 с 29 апреля 2018 г.</p>"
            "<p>Статья 98. Текст девяносто восьмой статьи.</p>"
        )},
    ))
    к = client.GarantClient(transport=транспорт)

    ответ = к.article(doc_id=1, article="97")

    assert "_предупреждение" not in ответ, (
        "конец подтверждён однозначно — предупреждения быть не должно: " +
        ответ.get("_предупреждение", ""))
    assert "Статья 97 дополнена частью 1.1" in ответ["text"], (
        "врезка ошибочно стала границей и обрезала статью 97")
    assert "Статья 98" not in ответ["text"], (
        "вырезка статьи 97 прихватила чужой текст статьи 98"
    )


def test_статья_5_не_ловит_5_1():
    """Запрос статьи 5 обязан взять её локатором ОТДЕЛЬНО от статьи 5.1
    (иначе к «Гаранту» уходит запрос страницы для чужого элемента) и
    вырезать текст ровно до начала 5.1, не включая её."""
    транспорт = ФейкТранспорт(маршрутизатор_статьи(
        children=[
            _элемент("Статья 5 (Общие положения)", "e5"),
            _элемент("Статья 5.1 (Специальные основания)", "e5_1"),
            _элемент("Статья 6 (Иное)", "e6"),
        ],
        page_count=1,
        locate_by_id={"e5": 1, "e5_1": 1, "e6": 1},
        pages_text={1: (
            "<p>Статья 5. Текст статьи пять.</p>"
            "<p>Статья 5.1. Текст статьи пять один.</p>"
            "<p>Статья 6. Текст статьи шесть.</p>"
        )},
    ))
    к = client.GarantClient(transport=транспорт)

    ответ = к.article(doc_id=1, article="5")

    locate_вызовы = [v for v in транспорт.вызовы if "/document/locate" in v[1]]
    assert "elements=e5&" in locate_вызовы[0][1], (
        "первый locate обязан спрашивать страницу ИМЕННО узла «Статья 5», "
        f"а не «Статья 5.1» — запрос: {locate_вызовы[0][1]}"
    )
    assert ответ["text"] == "Статья 5. Текст статьи пять."


def test_статья_конституции_без_названия_режется_одна():
    """Заголовок БЕЗ точки после номера («Статья 49», а не «Статья 49.») —
    так оформлены статьи Конституции. Резать всё равно нужно ровно по одной
    статье, а не до конца загруженных страниц."""
    транспорт = ФейкТранспорт(маршрутизатор_статьи(
        children=[
            _элемент("Статья 49", "e49"),
            _элемент("Статья 50", "e50"),
        ],
        page_count=1,
        locate_by_id={"e49": 1, "e50": 1},
        pages_text={1: (
            "<p>Статья 49 Каждый обвиняемый в совершении преступления "
            "считается невиновным.</p>"
            "<p>Статья 50 Никто не может быть повторно осуждён.</p>"
        )},
    ))
    к = client.GarantClient(transport=транспорт)

    ответ = к.article(doc_id=1, article="49")

    assert "_предупреждение" not in ответ
    assert ответ["text"] == (
        "Статья 49 Каждый обвиняемый в совершении преступления "
        "считается невиновным."
    )
