"""Решение 21: границу пункта задаёт оглавление, а не первый больший номер.

Худший класс дефекта в контуре по словам самого решения: пункт 2 с
подпунктами «1.; 2.; 3.» обрывался на третьем подпункте, и признак усечения
не выставлялся — цитата выглядела целой. Тест воспроизводит РОВНО эту форму
текста (нумерованное перечисление внутри пункта, доходящее до номера,
большего собственного) и проверяет, что современный код НЕ обрывает пункт
раньше времени, а различает совпадение внутри тела от настоящего заголовка
следующего пункта — по подтверждению страницы у «Гаранта» (зонд), а не по
фразеологии.
"""
from __future__ import annotations

from _артикль_фикстуры import маршрутизатор_статьи
from _фейк_транспорт import ФейкТранспорт

from garant_mcp import client


def _пункт(текст, id_):
    return {"text": текст, "data": {"element": {"id": id_, "type": "clause"}}}


def test_пункт_с_подпунктами_не_обрывается_на_последнем_подпункте():
    """Внутри пункта 2 — перечисление «1.; 2.; 3.», доходящее до номера,
    большего пункта 2. Старое правило («первый номер больше запрошенного»)
    резало на подпункте «3.» и молчало об этом. Новое обязано:
      · сохранить пункт 2 целиком, включая его собственное «3. …»;
      · не прихватить заголовок пункта 3;
      · назвать риск ИЗБЫТОЧНОСТЬЮ (рез сделан по последнему совпадению),
        а не промолчать.
    """
    транспорт = ФейкТранспорт(маршрутизатор_статьи(
        children=[
            _пункт("Пункт 1", "e1"),
            _пункт("Пункт 2", "e2"),
            _пункт("Пункт 3", "e3"),
        ],
        page_count=1,
        locate_by_id={"e2": 1, "e3": 1},
        pages_text={1: (
            "<p>1. Первый пункт статьи.</p>"
            "<p>2. Второй пункт данной статьи, устанавливающий основания:</p>"
            "<p>1. первое основание;</p>"
            "<p>2. второе основание;</p>"
            "<p>3. третье основание.</p>"
            "<p>3. Третий пункт статьи, о другом.</p>"
        )},
    ))
    к = client.GarantClient(transport=транспорт)

    ответ = к.article(doc_id=1, article="2")

    assert "третье основание" in ответ["text"], (
        "своё содержимое пункта 2 (включая последний подпункт перечисления) "
        "потеряно — это и есть дефект решения 21: молчаливый рез по "
        "внутреннему совпадению номера"
    )
    assert "Третий пункт статьи, о другом" not in ответ["text"], (
        "вырезка пункта 2 прихватила заголовок пункта 3"
    )
    предупреждение = ответ.get("_предупреждение", "")
    assert "ИЗБЫТОЧНОСТЬ" in предупреждение, (
        "совпадений номера «3» в тексте два (подпункт и настоящий заголовок) — "
        "риск обязан быть назван явно, а не проглочен"
    )


def test_зонд_на_незагруженной_странице_не_режет_молча():
    """Оглавление называет следующий узел, текстовое совпадение его номера
    в загруженных страницах есть — но «Гарант» не подтвердил, что СТРАНИЦА
    этого узла среди загруженных (зонд `/document/locate` отвечает пусто).
    Совпадение обязано быть отброшено, а не использовано как граница:
    отдаём весь текст и объявляем риск «оба» — резать нечем."""
    транспорт = ФейкТранспорт(маршрутизатор_статьи(
        children=[
            _пункт("Пункт 5", "e5"),
            _пункт("Пункт 6", "e6"),
        ],
        page_count=1,
        locate_by_id={"e5": 1, "e6": None},   # зонд следующего узла отказал
        pages_text={1: (
            "<p>5. Пятый пункт статьи, короткий.</p>"
            "<p>6. Шестой пункт статьи — но его страница не подтверждена.</p>"
        )},
    ))
    к = client.GarantClient(transport=транспорт)

    ответ = к.article(doc_id=1, article="5")

    assert "Шестой пункт статьи" in ответ["text"], (
        "текстовое совпадение номера «6» отброшено зондом — резать нечем, "
        "весь текст обязан остаться, а не обрубиться по неподтверждённому "
        "совпадению"
    )
    предупреждение = ответ.get("_предупреждение", "")
    assert "НЕ ПОДТВЕРЖДЁН" in предупреждение, (
        "отказ зонда обязан дать явное предупреждение, а не молчаливый рез"
    )
