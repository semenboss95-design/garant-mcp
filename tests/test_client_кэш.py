"""Кэш поиска не выдаёт себя за свежий ответ (.claude/rules/provenance.md,
«Кэш не выдаёт себя за свежий ответ»).

Проверяются четыре подпункта, закрытые 06.09.2026: ключ различает `limit`;
пустая выдача не кэшируется; просроченная запись не отдаётся;
`use_cache=False` идёт в сеть, а не в файл на диске. Плюс общее свойство —
запись из кэша обязана нести отметку и возраст, а не выглядеть свежим походом
в «Гарант».

Транспорт подменён на границе `Transport.fetch` (решение 17); диск подменён
на `tmp_path` через `client.CACHE_DIR`, чтобы тест не касался настоящего
каталога состояния машины.
"""
from __future__ import annotations

import json
from datetime import datetime, timedelta
from pathlib import Path

from _фейк_транспорт import ФейкТранспорт

from garant_mcp import client

_ФИКСТУРА = json.loads(
    (Path(__file__).parent / "fixtures" / "поиск.json").read_text(encoding="utf-8"))


def _маршрутизатор_поиска(page_body=None):
    """/search/base/run → /search/poll → /list/page, стройно по URL, а не
    по позиции вызова: keepalive может встрять между ними, и от теста это
    скрыто намеренно (не его забота)."""
    page_body = page_body if page_body is not None else _ФИКСТУРА["page"]

    def маршрут(method, url, form, номер):
        if "/server/keepalive" in url:
            return 200, ""
        if "/search/base/run" in url:
            return 200, json.dumps(_ФИКСТУРА["run"])
        if "/search/poll" in url:
            return 200, json.dumps(_ФИКСТУРА["poll"])
        if "/list/page" in url:
            return 200, json.dumps(page_body, ensure_ascii=False)
        raise AssertionError(f"незнакомый URL в тесте кэша: {method} {url}")
    return маршрут


def _клиент(monkeypatch, tmp_path, транспорт):
    к = client.GarantClient(transport=транспорт)
    # CACHE_DIR — модульная константа, читаемая по имени внутри search():
    # подмена на tmp_path не даёт тесту касаться настоящего каталога
    # состояния машины, на которой он выполняется.
    monkeypatch.setattr(client, "CACHE_DIR", tmp_path / "cache")
    return к


def _сеть(транспорт) -> int:
    """Сколько раз запрос реально ушёл транспорту на /search/base/run —
    начало цепочки, которое бывает ровно один раз на один живой поиск."""
    return sum(1 for (_, url, _) in транспорт.вызовы if "/search/base/run" in url)


def test_ключ_различает_limit(monkeypatch, tmp_path):
    """Запись, положенная поиском с limit=1, не обязана подойти запросу
    с limit=3: до починки второй запрос получал те же ОДНУ позицию без
    единой отметки, что выдача урезана чужим вызовом."""
    транспорт = ФейкТранспорт(_маршрутизатор_поиска())
    к = _клиент(monkeypatch, tmp_path, транспорт)

    первый = к.search("запрос", limit=1)
    второй = к.search("запрос", limit=3)

    assert len(первый["items"]) == 1
    assert len(второй["items"]) == 3, (
        "поиск с limit=3 получил не три позиции — похоже, ключ кэша не "
        "различает limit, и вернулась запись, положенная запросом с limit=1"
    )
    assert _сеть(транспорт) == 2, (
        "оба запроса обязаны были сходить в сеть — они не могли переиспользовать "
        "чужую запись кэша"
    )


def test_повторный_запрос_с_тем_же_limit_берётся_из_кэша(monkeypatch, tmp_path):
    транспорт = ФейкТранспорт(_маршрутизатор_поиска())
    к = _клиент(monkeypatch, tmp_path, транспорт)

    первый = к.search("запрос", limit=3)
    второй = к.search("запрос", limit=3)

    assert _сеть(транспорт) == 1, "второй одинаковый запрос обязан взяться из кэша"
    assert второй["provenance"]["из_кэша"] is True
    assert "дата_записи" in второй["provenance"]
    assert "возраст_часов" in второй["provenance"]
    assert "срок_годности_часов" in второй["provenance"]
    assert первый["items"] == второй["items"]


def test_пустая_выдача_не_кэшируется(monkeypatch, tmp_path):
    """Один неудачный момент у «Гаранта» не обязан означать «ничего не
    находит» до конца жизни каталога кэша."""
    транспорт = ФейкТранспорт(_маршрутизатор_поиска(page_body={"items": []}))
    к = _клиент(monkeypatch, tmp_path, транспорт)

    первый = к.search("пусто", limit=5)
    assert первый["items"] == []
    assert not client.CACHE_DIR.exists() or not list(client.CACHE_DIR.iterdir()), (
        "пустая выдача не должна была лечь в кэш"
    )

    # Второй запрос — тем же ключом. Если бы пустой ответ закэшировался,
    # второй заход тоже получил бы пустоту БЕЗ похода в сеть.
    к.search("пусто", limit=5)
    assert _сеть(транспорт) == 2, "пустая выдача закэширована — второй запрос не сходил в сеть"


def test_просроченная_запись_не_отдаётся(monkeypatch, tmp_path):
    транспорт = ФейкТранспорт(_маршрутизатор_поиска())
    к = _клиент(monkeypatch, tmp_path, транспорт)
    monkeypatch.setattr(client.config, "CACHE_TTL_HOURS", 1.0)

    к.search("запрос", limit=2)
    assert _сеть(транспорт) == 1

    # «Состарим» единственный файл записи кэша задним числом.
    файлы = list(client.CACHE_DIR.iterdir())
    assert len(файлы) == 1
    старое_время = (datetime.now() - timedelta(hours=2)).timestamp()
    import os
    os.utime(файлы[0], (старое_время, старое_время))

    к.search("запрос", limit=2)
    assert _сеть(транспорт) == 2, (
        "просроченная запись (2 часа при сроке годности 1 час) отдана как "
        "свежая — второй запрос обязан был сходить в сеть заново"
    )


def test_ключ_различает_версию_правила_отпечатка(monkeypatch, tmp_path):
    """`ПРАВИЛО_ОТПЕЧАТКА` — версия нормализации ЗАГОЛОВКОВ, часть ключа
    (комментарий в `search()`: «правило меняет вид заголовков в items...
    без неё записи прежней формы доживали срок годности и отдавались как
    есть — нормализованные одним правилом, а объявленные другим»).

    Одинаковые q/p/limit, разные версии правила между двумя вызовами —
    второй обязан сходить в сеть заново, а не взять запись, положенную
    под старой версией. Если бы ключ версию не различал, оба вызова легли
    бы в один файл и второй получил бы кэш-хит вместо похода в сеть."""
    транспорт = ФейкТранспорт(_маршрутизатор_поиска())
    к = _клиент(monkeypatch, tmp_path, транспорт)

    monkeypatch.setattr(client, "ПРАВИЛО_ОТПЕЧАТКА", "strip_html/1")
    к.search("запрос", limit=2)
    assert _сеть(транспорт) == 1

    monkeypatch.setattr(client, "ПРАВИЛО_ОТПЕЧАТКА", "strip_html/2")
    к.search("запрос", limit=2)
    assert _сеть(транспорт) == 2, (
        "смена ПРАВИЛО_ОТПЕЧАТКА при тех же q/p/limit обязана дать промах "
        "кэша — иначе запись, нормализованная старым правилом, отдаётся "
        "под видом отпечатка новой версии"
    )


def test_use_cache_false_идёт_в_сеть(monkeypatch, tmp_path):
    транспорт = ФейкТранспорт(_маршрутизатор_поиска())
    к = _клиент(monkeypatch, tmp_path, транспорт)

    к.search("запрос", limit=2)
    assert _сеть(транспорт) == 1

    к.search("запрос", limit=2, use_cache=False)
    assert _сеть(транспорт) == 2, (
        "use_cache=False обязан требовать свежий поход в «Гарант», а не "
        "отдавать файл с диска"
    )
