def _клиент_с_испорченной_картой(транспорт) -> "client.GarantClient":
    """Ломаем путь `in_force_from` до одного сегмента — `_периоды_действия`
    отдаёт `None` (карта не описывает список из трёх частей), ровно как
    в `test_client_периоды_действия.py::test_периоды_none_...`. Копия
    карты — своя на клиента, чтобы не испортить глобальный кэш `config.карта()`."""
    к = client.GarantClient(transport=транспорт)
    к.cfg = copy.deepcopy(к.cfg)
    к.cfg["revisions"]["item_map"]["in_force_from"] = "flatFrom"
    return к


def test_revision_on_date_карта_без_периодов_не_дублирует_оговорку():
    """revisions() уже говорит «карта не описывает список периодов» своим
    текстом (`_оговорка_о_периодах` при `периоды is None`); revision_on_date
    добавляет СВОЮ, более полную версию той же мысли (ветвь
    `if карта_без_периодов:`) — но не обе сразу. Раздвоенная почти
    одинаковая пара абзацев читатель просто перестанет читать.

    Рецепт поломки — не «добавить текст», а снять ОДНО условие: в
    `revision_on_date` короткая оговорка записи добавляется под явным
    охранником `if своя and r.get("периоды") is not None:` — при `периоды
    is None` эта строка подавляется нарочно, чтобы не встать рядом со своей
    более полной версией. Убери `r.get("периоды") is not None` из условия —
    метка появится в тексте ДВАЖДЫ, и это тест ловит через `оговорка.
    count(МЕТКА) == 1`, а не через одно лишь присутствие подстроки."""
    редакция = {
        "text": "ред.", "status": "rs_Actual", "documentId": 1,
        "flatFrom": "01.01.2015",
        "activity": [{"from": "01.01.2015", "to": ""}],
    }
    к = _клиент_с_испорченной_картой(
        ФейкТранспорт(_маршрутизатор([редакция])))

    ответ = к.revision_on_date(doc_id=1, on="01.06.2020")
    оговорка = ответ.get("_предупреждение") or ""

    МЕТКА = "не описывает список периодов действия"
    assert МЕТКА in оговорка, "оговорка о карте без периодов обязана появиться"
    assert оговорка.count(МЕТКА) == 1, (
        "оговорка о карте без периодов обязана появиться РОВНО один раз — "
        "собственная оговорка записи (из revisions()) и более полная версия "
        "revision_on_date() не должны стоять рядом:\n" + оговорка)


