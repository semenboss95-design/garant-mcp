# Это не дефект теста и не дефект решения 36 — оба ведут себя ровно так,
# как решение 36 предписывает («доказанно не покрывающая запись кандидатом
# не считается»). Но код на строке ~903 (`_граница_текстом(покрывают[0]
# .get("с")) or "?"`) фактически МЁРТВ для нестрокового входа: `.get("с")`
# там всегда либо отсутствует у пустого списка (сюда мы не дойдём — список
