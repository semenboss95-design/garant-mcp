# --------------------------------------------------------------------------
#  общая инфраструктура — тот же вид синтетики, что в test_client_периоды_
#  действия.py и test_покрытие_периодом.py: своя запись `activity`, свой
#  маршрутизатор HTTP по URL.
# --------------------------------------------------------------------------

def _редакция(*periods: dict) -> dict:
    """Одна запись `/redactions/list` с произвольным числом периодов
    `activity`. Первый период дублируется на верхний уровень (`activity.0`)
    ровно так, как это делает сам «Гарант» — карта эндпоинтов читает
    `in_force_from`/`in_force_to` именно оттуда."""
    return {
        "text": "ред. от {}".format(periods[0].get("from") or "?"),
        "status": "rs_Actual",
        "documentId": 1,
        "activity": list(periods),
    }


def _маршрутизатор(redactions: list[dict]):
    """Один документ, одна страница текста, редакции — по списку теста."""
    тело_редакций = {"redactions": redactions}

    def маршрут(method, url, form, номер):
        if "/server/keepalive" in url:
            return 200, ""
        if "/document/info" in url:
            return 200, json.dumps({"pageCount": 1, "documentTitle": "Д"})
        if "/document/pages" in url:
            return 200, json.dumps({"items": [{"number": 1, "text": "текст"}]})
        if "/redactions/list" in url:
            return 200, json.dumps(тело_редакций, ensure_ascii=False)
        raise AssertionError(f"незнакомый URL в тесте оговорки о дате: {method} {url}")
    return маршрут


def _клиент(*redactions: dict) -> "client.GarantClient":
    return client.GarantClient(transport=ФейкТранспорт(_маршрутизатор(list(redactions))))


def _запись_revisions(редакция: dict) -> dict:
    """Тот же вход через `revisions()` — отдельный транспорт и клиент,
    чтобы `revisions()` и `document()`/`revision_on_date()` не делили
    состояние теста между собой (тот же приём, что в соседних файлах)."""
    [запись] = _клиент(редакция).revisions(doc_id=1)
    return запись


