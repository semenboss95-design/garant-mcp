def test_revisions_число_в_по_не_роняет_и_даёт_нечем_а_не_непрерывность():
    """«По» первого периода — число (не строка). До дифа
    `(значение or "").strip()` упал бы `AttributeError` уже на первом стыке
    `_разрыв_в_действии`, и весь ответ `revisions()` терялся бы вместе
    с ним. Годный ответ — оговорка «стык нечем», а не тихая непрерывность
    и не утверждённый разрыв: посчитать нечем, а не «мы посчитали и там
    пусто»."""
    редакция = _редакция(
        {"from": "01.01.2015", "to": 20191231},   # число вместо строки
        {"from": "01.01.2020", "to": ""},
    )
    запись = _запись_revisions(редакция)   # не должно поднять AttributeError

    оговорка = запись.get("_предупреждение") or ""
    assert оговорка, "нечитаемая нестроковая граница обязана оставить оговорку"
    assert "посчитать их стык нечем" in оговорка, (
        "стык, где «по» — число, обязан давать ветвь «нечем», а не "
        "непрерывность и не разрыв:\n" + оговорка)
    assert "не прекращалось" not in оговорка, (
        "ложная непрерывность — число в «по» не разобралось датой, "
        "утверждать непрерывность здесь нечем:\n" + оговорка)
    assert "разрыв больше суток" not in оговорка, (
        "ложный разрыв — число в «по» не разобралось датой, значит "
        "стык не посчитан, а не посчитан-и-это-разрыв:\n" + оговорка)


def test_revisions_список_в_с_не_роняет_и_даёт_нечем_а_не_непрерывность():
    """То же самое, но с другой стороны стыка и другим типом: «с» второго
    периода — список. Симметричная проверка: обе границы, обе формы шума
    из чужого JSON, обязаны обрабатываться одним и тем же примитивом."""
