# Тест этого места («первого по порядку кандидата» — фраза, привязанная
# к строке ~903 client.py, `покрывают[0].get("с")` в ветви множественности)
# СНЯТ 09.09.2026 (решение 36), а не переписан на новый текст — не потому
# что лень, а потому что сценарий, который он проверял, стал недостижим
# ЧЕРЕЗ ПУБЛИЧНЫЙ API.
#
# `_покрытие_периодом` возвращает «покрывает» (True) ТОЛЬКО если «с» этого
# периода разобралось датой (`f is not None` — обязательное условие первым
# делом в функции). Значит любой элемент, попавший в список `покрывают`,
# по построению несёт строковую, уже разобравшуюся «с» — нестроковое
# значение (список, объект, число) в этом слоте `_граница_текстом` внутри
# ветви множественности просто никогда не увидит. Проверено четырьмя
