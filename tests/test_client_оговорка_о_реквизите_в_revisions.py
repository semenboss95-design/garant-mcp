# -*- coding: utf-8 -*-
"""Наряд 4-3: оговорка о реквизите «Ф3» доходит не только через provenance
`document()`/`article()` (это уже покрывает `test_client_редакция_по_id_и_
реквизит.py`), но и через ДВЕ ДРУГИЕ выдачи, у которых `_предупреждение` —
свой, отдельный ключ: `revisions()` — на самой записи списка, и
`revision_on_date()` — на найденной редакции. Третья выдача (провенанс)
уже проверена соседним файлом; здесь — те два места, что python-dev назвал
в сдаче наряда («третьей в список оговорок... встала
`_оговорка_о_реквизите_акта`», `client.py:2170-2180` и `2320-2325`).

Форма входа — секция `revisions` карты эндпоинтов (`endpoints.json`):
`changingDocuments.0.text`. Это образец «по карте» (правило
`.claude/rules/tests.md`): форму задаёт сама карта, а не реализация,
и придумывать её не значит повторять код.

Транспорт подменён на границе `Transport.fetch` (решение 17): разбор
`/redactions/list` и вся арифметика периодов исполняются настоящим
`garant_mcp.client`, тест только поставляет вход.

Проверено обе стороны условия — с цифрой «Ф3» оговорка появляется,
с буквой «ФЗ» молчит, — как и требует наряд: тест, который зажигается на
любом входе, ничего не различает.
"""
from __future__ import annotations

import json

from _фейк_транспорт import ФейкТранспорт

from garant_mcp import client


def _редакция(documentId: int, status: str, text: str, activity: list[dict],
              изменяющий_акт: str) -> dict:
    """Одна запись `/redactions/list`, форма — как в `endpoints.json`
    (секция `revisions.item_map`): `changingDocuments.0.text` даёт
    `изменяющий_акт`."""
    return {
        "documentId": documentId, "status": status, "text": text,
        "date": "01.01.2000",
        "activity": activity,
        "changingDocuments": [{"text": изменяющий_акт, "documentId": documentId + 1}],
    }


def _маршрутизатор(redactions: list[dict]):
    def маршрут(method, url, form, номер):
        if "/server/keepalive" in url:
            return 200, ""
        if "/redactions/list" in url:
            return 200, json.dumps({"redactions": redactions}, ensure_ascii=False)
        raise AssertionError(
            f"незнакомый URL в тесте оговорки о реквизите: {method} {url}")
    return маршрут


def _клиент(*redactions: dict) -> client.GarantClient:
    return client.GarantClient(transport=ФейкТранспорт(_маршрутизатор(list(redactions))))


# ==========================================================================
#  1. revisions(): оговорка живёт НА ЗАПИСИ, ключ `_предупреждение`
# ==========================================================================

def test_revisions_ф3_с_цифрой_несёт_оговорку_на_записи():
    """Один период, обе границы читаемые строки — единственный источник
    оговорки здесь может быть только реквизит. Если бы `revisions()` не
    спрашивала `_оговорка_о_реквизите_акта` (поведение до наряда 4-3),
    запись осталась бы вовсе без `_предупреждение` — молчание было бы
    неотличимо от «оговаривать нечего»."""
    редакция = _редакция(
        100, "rs_Old", "ред. от 01.01.2020",
        [{"from": "01.01.2020", "to": "01.01.2021"}],
        изменяющий_акт="N 164-Ф3 от 01.01.2020")
    [запись] = _клиент(редакция).revisions(doc_id=100)

    оговорка = запись.get("_предупреждение") or ""
    assert оговорка, (
        "изменяющий_акт содержит «Ф3» (цифра 3) — запись revisions() "
        "обязана нести оговорку о нём, а не молчать")
    assert "Ф3" in оговорка and "цифрой" in оговорка, (
        "оговорка обязана называть именно дословность реквизита «Ф3», "
        "а не что-то другое:\n" + оговорка)


def test_revisions_фз_буквой_молчит_на_той_же_записи():
    """Контрольный случай, зеркальный первому: буква «З» — обычное
    написание, ничего не заслуживает. Если бы условие срабатывало по
    наличию любого «Ф», а не именно цифры «3», оговорка обесценилась бы
    частотой — здесь ровно то входное значение, на котором это стало бы
    видно."""
    редакция = _редакция(
        100, "rs_Old", "ред. от 01.01.2020",
        [{"from": "01.01.2020", "to": "01.01.2021"}],
        изменяющий_акт="N 164-ФЗ от 01.01.2020")
    [запись] = _клиент(редакция).revisions(doc_id=100)

    assert not запись.get("_предупреждение"), (
        "буква «З» в реквизите — обычное написание, оговорки не "
        "заслуживает, а один читаемый период сам по себе оговорки не "
        "рождает:\n" + str(запись.get("_предупреждение")))


# ==========================================================================
#  2. revision_on_date(): та же оговорка, когда НАЙДЕННАЯ запись несёт «Ф3»
# ==========================================================================

def test_revision_on_date_ф3_с_цифрой_несёт_оговорку_в_ответе():
    """Единственная запись, её период доказанно покрывает запрошенную
    дату — никакой другой оговорки (ни о периодах, ни о нескольких
    кандидатах, ни о дате) здесь взяться неоткуда, кроме реквизита."""
    редакция = _редакция(
        100, "rs_Old", "ред. от 01.01.2020",
        [{"from": "01.01.2020", "to": "01.01.2021"}],
        изменяющий_акт="N 164-Ф3 от 01.01.2020")
    ответ = _клиент(редакция).revision_on_date(doc_id=100, on="01.06.2020")

    assert ответ["id_редакции"] == 100
    оговорка = ответ.get("_предупреждение") or ""
    assert оговорка, (
        "найденная редакция несёт «Ф3» в изменяющем акте — "
        "revision_on_date() обязан донести ту же оговорку, что и "
        "revisions(), а не молчать о ней")
    assert "Ф3" in оговорка and "цифрой" in оговорка, (
        "оговорка ответа обязана называть именно дословность реквизита "
        "«Ф3»:\n" + оговорка)


def test_revision_on_date_фз_буквой_молчит_в_ответе():
    """Зеркальный контроль: буквенное написание в найденной записи не
    рождает оговорку в ответе `revision_on_date()`."""
    редакция = _редакция(
        100, "rs_Old", "ред. от 01.01.2020",
        [{"from": "01.01.2020", "to": "01.01.2021"}],
        изменяющий_акт="N 164-ФЗ от 01.01.2020")
    ответ = _клиент(редакция).revision_on_date(doc_id=100, on="01.06.2020")

    assert ответ["id_редакции"] == 100
    assert not ответ.get("_предупреждение"), (
        "буква «З» в реквизите найденной записи — обычное написание, "
        "ответ revision_on_date() оговорки не заслуживает:\n"
        + str(ответ.get("_предупреждение")))
