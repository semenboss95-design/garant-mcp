"""Отпечаток текста сходится с ним же (.claude/rules/provenance.md, «Отпечаток
текста несёт версию правила»).

До 06.09.2026 хеш в `provenance` считался НЕ над тем текстом, который уходит
пользователю, — и это не замечали, потому что никто не пересчитывал sha256
руками. Тест здесь — механическая замена именно этого несделанного пересчёта:
он не знает и не имеет права знать, ЧТО написано в `strip_html`, он проверяет
только то, что `hash_текста` в ответе — это sha256 РОВНО того `text`, который
в этом же ответе лежит, и что рядом стоит версия правила нормализации.

Транспорт подменён на границе `Transport.fetch` (решение 17): всё, что выше
неё — сборка URL, разбор JSON, `_prov`, — исполняется настоящим кодом клиента.
"""
from __future__ import annotations

import hashlib
import json

from _фейк_транспорт import ФейкТранспорт

from garant_mcp import client


def _маршрутизатор(тела: dict[str, object]):
    """Диспетчер по подстроке в URL — устойчив к тому, сколько раз и когда
    клиент решит попутно сходить в keepalive (троттл — деталь реализации,
    не предмет этого теста)."""
    def маршрут(method, url, form, номер):
        if "/server/keepalive" in url:
            return 200, ""
        for кусок, тело in тела.items():
            if кусок in url:
                if isinstance(тело, str):
                    return 200, тело
                return 200, json.dumps(тело, ensure_ascii=False)
        raise AssertionError(f"незнакомый URL в тесте отпечатка: {method} {url}")
    return маршрут


def test_hash_текста_равен_sha256_возвращённого_text():
    """Отпечаток и текст — из одного места. Историческая ошибка (06.09.2026):
    хеш считался над текстом ДО обрезки/нормализации, а пользователю уходил
    текст ПОСЛЕ — sha256 не совпадал ни с чем, и это не читал никто."""
    транспорт = ФейкТранспорт(_маршрутизатор({
        "/document/info": {"pageCount": 1, "documentTitle": "Выдуманный документ"},
        "/document/pages": {"items": [
            {"number": 1, "text": "<p>Текст выдуманного документа для теста.</p>"}]},
        "/redactions/list": {"redactions": [
            {"text": "ред. от 01.01.2024", "status": "rs_Actual",
             "activity": [{"from": "01.01.2024", "to": ""}], "documentId": 1}]},
    }))
    к = client.GarantClient(transport=транспорт)

    ответ = к.document(doc_id=1)

    ожидаемый = "sha256:" + hashlib.sha256(ответ["text"].encode("utf-8")).hexdigest()[:16]
    assert ответ["provenance"]["hash_текста"] == ожидаемый
    assert ответ["provenance"]["правило_отпечатка"] == client.ПРАВИЛО_ОТПЕЧАТКА


def test_версия_правила_отпечатка_поднимется_с_правкой_нормализации():
    """Не проверка значения (оно постоянное), а страховка от расхождения:
    _prov обязан класть КОНСТАНТУ модуля, а не переписанное число рядом."""
    транспорт = ФейкТранспорт(_маршрутизатор({
        "/document/info": {"pageCount": 1, "documentTitle": "Д"},
        "/document/pages": {"items": [{"number": 1, "text": "текст"}]},
        "/redactions/list": {"redactions": []},
    }))
    к = client.GarantClient(transport=транспорт)
    ответ = к.document(doc_id=1)
    # Литерал — ТЕКУЩЕЕ значение client.ПРАВИЛО_ОТПЕЧАТКА, а не произвольное:
    # тест обязан обновляться вместе с каждой легитимной правкой strip_html
    # (07.09.2026 — версия поднята до strip_html/2 добавлением разбора
    # надстрочных индексов и границ ячеек/строк); проверяет он не число,
    # а то, что `_prov` кладёт именно КОНСТАНТУ, а не переписанный рядом
    # литерал, который от неё мог разойтись.
    assert ответ["provenance"]["правило_отпечатка"] == "strip_html/2"
