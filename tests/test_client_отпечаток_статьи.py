# -*- coding: utf-8 -*-
"""Д-1 аудита на `article()` — парный тест к `test_client_отпечаток.py`.

Существующий `test_hash_текста_равен_sha256_возвращённого_text` проверяет
только `document()` (client.py вокруг `_prov`, вызванный из `document`).
Дефект Д-1, который он ловит, жил на строке `client.py:1242` — в `article()`,
на другом вызове `_prov`, а не там, где стоит тест. `_prov` — общая функция,
но это её общность и скрыла асимметрию: правка (или её отсутствие) в одной
точке вызова прошла бы мимо теста, помеченного «отпечаток проверен».

Проверяется то же самое свойство, что и для документа: `hash_текста` в
`provenance` — это sha256 РОВНО того текста, что лежит в `ответ["text"]`,
а не текста до вырезки/нормализации.
"""
from __future__ import annotations

import hashlib

from _артикль_фикстуры import маршрутизатор_статьи
from _фейк_транспорт import ФейкТранспорт

from garant_mcp import client


def _элемент(текст, id_, тип="article"):
    return {"text": текст, "data": {"element": {"id": id_, "type": тип}}}


def test_hash_текста_статьи_равен_sha256_возвращённого_text():
    транспорт = ФейкТранспорт(маршрутизатор_статьи(
        children=[
            _элемент("Статья 5", "e5"),
            _элемент("Статья 6", "e6"),
        ],
        page_count=1,
        locate_by_id={"e5": 1, "e6": 1},
        pages_text={1: (
            "<p>Статья 5. Текст выдуманной пятой статьи для теста.</p>"
            "<p>Статья 6. Текст шестой статьи, сюда попадать не должен.</p>"
        )},
    ))
    к = client.GarantClient(transport=транспорт)

    ответ = к.article(doc_id=1, article="5")

    ожидаемый = "sha256:" + hashlib.sha256(
        ответ["text"].encode("utf-8")).hexdigest()[:16]
    assert ответ["provenance"]["hash_текста"] == ожидаемый, (
        "hash_текста статьи посчитан не над тем text, который вернулся: "
        "провал ровно того рода, что Д-1 нашёл в document() — только на "
        "другом вызове _prov (article(), client.py:1242).")
    assert ответ["provenance"]["правило_отпечатка"] == client.ПРАВИЛО_ОТПЕЧАТКА
