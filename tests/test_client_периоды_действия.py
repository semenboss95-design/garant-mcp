# -*- coding: utf-8 -*-
"""Сторожа на периоды действия редакции (`_периоды_действия`,
`_разрыв_в_действии`, `_начало_действия` в `client.py`) — наряд «этап 03,
фаза B, часть 4», задание 2.

`python-dev` закрыл блокер визы (день стыка двух редакций, часть 2 этого же
этапа) собственными пробами, а не тестами. Здесь — тесты на СОСЕДНЮЮ, но
другую часть той же логики: не «какая редакция действовала на дату»
(`revision_on_date`, уже покрыт `test_client_revision_on_date_стык.py`),
а «какой датой заверять цитату, когда у редакции периодов действия
БОЛЬШЕ ОДНОГО» — то, что реально уходит в `provenance` документа и статьи
через `_prov` → `_начало_действия`.

Транспорт подменён на границе `Transport.fetch` (решение 17): вызывается
настоящий `document()`, разбор `/redactions/list` и вся арифметика дат —
исполняются по-настоящему, тест только поставляет вход.
"""
from __future__ import annotations

import json
import re

from _фейк_транспорт import ФейкТранспорт

from garant_mcp import client


def _маршрутизатор(redactions: list[dict]):
    """Один документ, одна страница текста, редакции — по списку теста."""
    тело_редакций = {"redactions": redactions}

    def маршрут(method, url, form, номер):
        if "/server/keepalive" in url:
            return 200, ""
        if "/document/info" in url:
            return 200, json.dumps({"pageCount": 1, "documentTitle": "Д"})
        if "/document/pages" in url:
            return 200, json.dumps({"items": [{"number": 1, "text": "текст"}]})
        if "/redactions/list" in url:
            return 200, json.dumps(тело_редакций, ensure_ascii=False)
        raise AssertionError(f"незнакомый URL в тесте периодов: {method} {url}")
    return маршрут


def _редакция(*periods: dict) -> dict:
    """Одна запись `/redactions/list` с произвольным числом периодов
    `activity`. Первый период дублируется на верхний уровень (`activity.0`)
    ровно так, как это делает сам «Гарант» — карта эндпоинтов читает
    `in_force_from`/`in_force_to` именно оттуда."""
    return {
        "text": "ред. от {}".format(periods[0].get("from") or "?"),
        "status": "rs_Actual",
        "documentId": 1,
        "activity": list(periods),
    }


def _действует_с_и_оговорки(ответ: dict) -> tuple[str | None, str]:
    prov = ответ["provenance"]
    return prov.get("действует_с"), "\n".join(prov.get("оговорки_о_редакции") or [])


def _запись_revisions(редакция: dict) -> dict:
    """Тот же вход через `revisions()` — второе место, отвечающее на тот же
    вопрос о стыке периодов, но своим путём (`_оговорка_о_периодах`, а не
    `_начало_действия`). Отдельный транспорт и клиент: `revisions()` и
    `document()` не должны делить состояние теста между собой."""
    транспорт = ФейкТранспорт(_маршрутизатор([редакция]))
    к = client.GarantClient(transport=транспорт)
    [запись] = к.revisions(doc_id=1)
    return запись


_ОБЩАЯ_ФРАЗА = re.compile(
    r"границу периода МЫ читаем включительно с обеих сторон.*?"
    r"дыра в действии нормы\.", re.S)


def _атрибуция_границы(текст: str) -> str:
    """Общий кусок текста про НАШЕ (включительное) чтение границы.

    По решению 30 сторожим не текст, а совпадение: `_прov` (провенанс)
    и `_оговорка_о_периодах` (запись `revisions()`) обязаны нести ОДНУ
    и ту же атрибуцию дословно — они отвечают на один и тот же вопрос
    «чем держится непрерывность» по одним и тем же входным данным.
    """
    м = _ОБЩАЯ_ФРАЗА.search(текст or "")
    return м.group(0) if м else ""


# --------------------------------------------------------------------------
#  смежность день-в-день (days == 0) — непрерывность держится на арифметике,
#  а не на нашем чтении границы: оговорки о прерывании НЕТ ни в одном месте.
# --------------------------------------------------------------------------

def test_смежность_день_в_день_оговорки_нет_ни_в_provenance_ни_в_атрибуции_revisions():
    """«…—01.01.2018» и «01.01.2018—…»: конец и начало совпадают день в день.
    Непрерывность верна при ЛЮБОМ чтении границы.

    Provenance `document()` в этом случае молчит вовсе (оговорка о
    прерывании не о чем — считать нечего). У `revisions()` своя, отдельная
    оговорка о самой СТРУКТУРЕ записи (перечень из двух записей приглашает
    прочесть между ними паузу) — она стоит независимо от рода смежности,
    и её присутствие само по себе не проверяется здесь. Проверяется другое:
    ни там, ни там нет атрибуции «наше чтение границы» — она нужна ТОЛЬКО
    там, где непрерывность держится на трактовке, а не на арифметике. Слив
    дня-в-день с «на следующий день» (атрибуция появилась бы и здесь тоже)
    сделал бы этот тест красным."""
    редакция = _редакция(
        {"from": "01.01.2015", "to": "01.01.2018"},
        {"from": "01.01.2018", "to": ""},
    )
    транспорт = ФейкТранспорт(_маршрутизатор([редакция]))
    к = client.GarantClient(transport=транспорт)

    ответ = к.document(doc_id=1)
    действует_с, оговорки_prov = _действует_с_и_оговорки(ответ)
    запись = _запись_revisions(редакция)
    оговорка_revisions = запись.get("_предупреждение") or ""

    assert действует_с == "01.01.2015"
    assert оговорки_prov == "", (
        "день в день непрерывен при любом чтении границы — оговорки в "
        "provenance быть не должно:\n" + оговорки_prov)
    assert not _атрибуция_границы(оговорки_prov), (
        "атрибуция «наше чтение границы» появилась там, где непрерывность "
        "доказана арифметикой, а не трактовкой:\n" + оговорки_prov)
    assert not _атрибуция_границы(оговорка_revisions), (
        "то же самое со стороны revisions(): день-в-день не должен нести "
        "атрибуцию, которая нужна только «на следующий день»:\n"
        + оговорка_revisions)


# --------------------------------------------------------------------------
#  смежность «на следующий день» (days == 1) — непрерывность держится
#  ТОЛЬКО на нашем (включительном) чтении границы: оговорка ОБЯЗАНА быть,
#  и в ключе `_предупреждение` записи revisions(), и в `оговорки_о_редакции`
#  провенанса, и обе — одной и той же атрибуцией.
# --------------------------------------------------------------------------

def test_смежность_на_следующий_день_несёт_оговорку_в_обоих_местах_одинаково():
    """«…—31.12.2020» и «01.01.2021—…»: конец и начало отличаются на сутки.
    При исключающей трактовке границы 31.12.2020 не покрыт НИ ОДНИМ периодом
    — суточная дыра в действии нормы. До 08.09.2026 этот стык давал ту же
    (пустую) оговорку, что и день-в-день, и читатель не мог отличить
    утверждение на арифметике от утверждения на нашей трактовке."""
    редакция = _редакция(
        {"from": "01.01.2015", "to": "31.12.2020"},
        {"from": "01.01.2021", "to": ""},
    )
    транспорт = ФейкТранспорт(_маршрутизатор([редакция]))
    к = client.GarantClient(transport=транспорт)

    ответ = к.document(doc_id=1)
    действует_с, оговорки_prov = _действует_с_и_оговорки(ответ)
    запись = _запись_revisions(редакция)
    оговорка_revisions = запись.get("_предупреждение") or ""

    assert действует_с == "01.01.2015", (
        "заверять обязана дата начала ПЕРВОГО периода — по нашему чтению "
        "действие непрерывно с неё")
    assert оговорки_prov, (
        "смежность «на следующий день» держится ТОЛЬКО на нашем чтении "
        "границы — provenance обязан сказать об этом, а не промолчать")
    assert оговорка_revisions, (
        "то же самое обязана сказать и запись revisions() — молчание здесь "
        "разошлось бы с provenance на вопрос «был ли перерыв»")

    атрибуция_prov = _атрибуция_границы(оговорки_prov)
    атрибуция_rev = _атрибуция_границы(оговорка_revisions)
    assert атрибуция_prov, (
        "оговорка provenance обязана назвать чтение границы НАШИМ и "
        "непроверенным на живой базе:\n" + оговорки_prov)
    assert атрибуция_rev, (
        "то же самое обязана назвать и оговорка revisions():\n"
        + оговорка_revisions)
    assert атрибуция_prov == атрибуция_rev, (
        "решение 30: два места отвечают на один и тот же вопрос об одних "
        "и тех же данных — атрибуция обязана совпасть ДОСЛОВНО, а не "
        "разными словами про одно и то же.\n"
        f"provenance:  {атрибуция_prov!r}\n"
        f"revisions(): {атрибуция_rev!r}")


# --------------------------------------------------------------------------
#  периоды is None (карта эндпоинтов не описывает список путём из трёх
#  частей) — провенанс обязан сказать, что периодов мы НЕ ЧИТАЛИ, а не
#  заверить `действует_с` молча.
# --------------------------------------------------------------------------

def test_периоды_none_provenance_говорит_что_периоды_не_читали():
    """Ломаем карту эндпоинтов ровно так, как это делает пользовательский
    `endpoints.local.json` без пути из трёх частей (докстрока
    `_периоды_действия`): путь `in_force_from` короче трёх сегментов,
    `_периоды_действия` возвращает `None`.

    До этого наряда provenance заверял `действует_с` первым периодом молча
    — читатель не мог отличить «периодов один» от «периоды не читали
    вовсе». Сторожим то же решение 30: и revisions(), и provenance обязаны
    сказать одно и то же — что список периодов картой не описан."""
    # Своя запись, а не `_редакция()`: нужен ОТДЕЛЬНЫЙ плоский путь к дате
    # начала («flatFrom»), не связанный со списком `activity` — иначе замена
    # `in_force_from` сломала бы заодно и обычное чтение «действует_с»
    # записи, и тест бы не отличал «периоды не читаются» от «карта сломана
    # целиком».
    редакция = {
        "text": "ред.", "status": "rs_Actual", "documentId": 1,
        "flatFrom": "01.01.2015",
        "activity": [{"from": "01.01.2015", "to": ""}],
    }

    # `client.config.карта()` кэширует словарь ГЛОБАЛЬНО на модуль (docstring
    # `config.карта`): мутация `к.cfg[...]` на месте испортила бы карту для
    # ВСЕХ следующих тестов в этом же процессе. Ломаем ГЛУБОКУЮ КОПИЮ и кладём
    # её клиенту явно — ровно так, как выглядела бы своя карта в
    # `endpoints.local.json`, без побочных эффектов на общий кэш.
    import copy

    def _клиент_с_испорченной_картой(транспорт):
        к = client.GarantClient(transport=транспорт)
        к.cfg = copy.deepcopy(к.cfg)
        # один сегмент вместо трёх — `_периоды_действия` отдаёт `None`,
        # а «действует_с» продолжает читаться по тому же (единственному) пути
        к.cfg["revisions"]["item_map"]["in_force_from"] = "flatFrom"
        return к

    транспорт = ФейкТранспорт(_маршрутизатор([редакция]))
    к = _клиент_с_испорченной_картой(транспорт)
    ответ = к.document(doc_id=1)
    действует_с, оговорки_prov = _действует_с_и_оговорки(ответ)

    транспорт2 = ФейкТранспорт(_маршрутизатор([редакция]))
    к2 = _клиент_с_испорченной_картой(транспорт2)
    [запись] = к2.revisions(doc_id=1)
    оговорка_revisions = запись.get("_предупреждение") or ""

    assert действует_с == "01.01.2015"
    assert оговорки_prov, (
        "периоды не прочитаны картой — provenance обязан сказать об этом "
        "явно, а не заверить дату молча")
    assert оговорка_revisions, (
        "то же самое обязана сказать и запись revisions()")

    ОБЩЕЕ = "не описывает список периодов действия"
    assert ОБЩЕЕ in оговорки_prov, (
        "provenance обязан назвать причину — карта не описывает список "
        "периодов:\n" + оговорки_prov)
    assert ОБЩЕЕ in оговорка_revisions, (
        "revisions() обязана назвать ту же причину той же фразой:\n"
        + оговорка_revisions)


