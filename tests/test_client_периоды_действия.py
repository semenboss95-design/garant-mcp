def test_нормализация_в_search_та_же_оговорка_что_в_document(monkeypatch, tmp_path):
    """Оговорка о нормализации HTML заголовков обязана стоять в `search()`
    под тем же ключом `_нормализация` — иначе взявший заголовок из поиска
    не узнаёт, что «^»/«_»/« | » там расставлены нами, а не «Гарантом»."""
    # search() пишет непустую выдачу в кэш безусловно (use_cache влияет
    # только на ЧТЕНИЕ) — без подмены каталог реального CACHE_DIR получил
    # бы файл от этого теста.
    monkeypatch.setattr(client, "CACHE_DIR", tmp_path / "cache")

    def маршрут(method, url, form, номер):
        if "/server/keepalive" in url:
            return 200, ""
        if "/search/base/run" in url:
            return 200, json.dumps({"sid": "sid-1"})
        if "/search/poll" in url:
            return 200, json.dumps({
                "kindTree": {"doclistId": "dl-1", "total": 1},
                "filters": [],
            })
        if "/list/page" in url:
            return 200, json.dumps({"items": [
                {"documentId": 1, "html": "Документ 1", "relevance": 1}]})
        raise AssertionError(f"незнакомый URL: {method} {url}")

    транспорт = ФейкТранспорт(маршрут)
    к = client.GarantClient(transport=транспорт)

    ответ = к.search("запрос", use_cache=False)

    assert "_нормализация" in ответ, (
        "search() обязан нести ту же оговорку о нормализации заголовков, "
        "что и document()/article() — без неё правка знаков нормализации "
        "молча не долетает до заголовков поиска")
    assert ответ["_нормализация"] == client._оговорка_о_заголовках()


