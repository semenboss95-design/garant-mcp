def test_настоящий_разрыв_несёт_хедж_а_не_утверждение():
    """Разрыв больше суток между периодами — оговорка ОБЯЗАНА появиться,
    и в ней обязано быть сказано, что прочтение (акт приостанавливали
    и вернули в силу) — НАШЕ и на живой базе НЕ проверено. Утвердительная
    формулировка вида «акт был приостановлен» без этой оговорки была бы
    ложью — client.py сам не знает, чем вызван разрыв (карта эндпоинтов
    этого не объясняет)."""
    редакция = _редакция(
        {"from": "01.01.2015", "to": "01.01.2018"},
        {"from": "01.03.2018", "to": ""},  # разрыв — почти два месяца
    )
    транспорт = ФейкТранспорт(_маршрутизатор([редакция]))
    к = client.GarantClient(transport=транспорт)

    ответ = к.document(doc_id=1)

    действует_с, оговорки = _действует_с_и_оговорки(ответ)
    assert оговорки, "настоящий разрыв обязан оставить оговорку в provenance"
    нижний = оговорки.lower()
    assert "не провер" in нижний, (
        "оговорка обязана назвать прочтение НЕ проверенным на живой базе — "
        "иначе разрыв выглядит доказанным фактом, а не нашей интерпретацией:\n"
        + оговорки)
    assert "наше прочтение" in нижний or "не знаем" in нижний, (
        "оговорка обязана явно назвать интерпретацию НАШЕЙ, а не фактом "
        "«Гаранта»:\n" + оговорки)


