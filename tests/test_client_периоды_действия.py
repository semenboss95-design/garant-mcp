def test_смешанная_форма_несёт_оба_факта_разрыв_и_неизвестность():
    """Три периода: «01.01.2019—31.12.2019», «01.01.2025—бессрочно»,
    «01.06.2025—бессрочно». Стык 1→2 — настоящий разрыв (больше пяти лет).
    Стык 2→3 — посчитать нечем: у второго периода `по` пусто, а он не
    последний в списке (третий период существует), и это ровно форма
    «граница не разобралась» из докстроки `_разрыв_в_действии`.

    До 07.09.2026 `_разрыв_в_действии` выходила из цикла ранним `return True`
    сразу на первом найденном разрыве и до второй пары не доходила вовсе —
    флаг «неизвестно», поднятый парой 2→3, терялся. Оговорка обязана нести
    ОБА факта: она может быть либо ОДНИМ текстом с двумя утверждениями, либо
    просто содержать оба маркера — но не только один из двух."""
    редакция = _редакция(
        {"from": "01.01.2019", "to": "31.12.2019"},
        {"from": "01.01.2025", "to": ""},
        {"from": "01.06.2025", "to": ""},
    )
    транспорт = ФейкТранспорт(_маршрутизатор([редакция]))
    к = client.GarantClient(transport=транспорт)

    ответ = к.document(doc_id=1)

    _, оговорки = _действует_с_и_оговорки(ответ)
    assert оговорки, "смешанная форма обязана оставить оговорку"
    нижний = оговорки.lower()
    assert "разрыв больше суток" in нижний, (
        "первая пара периодов — настоящий разрыв больше пяти лет, факт "
        "разрыва обязан остаться в оговорке даже при наличии второго "
        "неопределённого стыка:\n" + оговорки)
    assert "не все стыки" in нижний, (
        "вторая пара периодов (пустое «по» не у последнего элемента) — "
        "стык, который посчитать нечем; ранний выход из цикла на первом "
        "разрыве терял именно этот факт:\n" + оговорки)


# --------------------------------------------------------------------------
#  несколько периодов покрывают дату проверки — выбор назван выбором
