def test_несколько_периодов_покрывают_дату_выбор_назван_выбором():
    """Три периода: «01.01.2010—01.01.2011» (в прошлом, дату не покрывает),
    «01.01.2020—бессрочно» и «01.06.2020—бессрочно» — оба покрывают
    сегодняшнюю дату и пересекаются между собой. Стык 1→2 — настоящий
    разрыв (девять лет), стык 2→3 — стык посчитать нечем (у второго `по`
    пусто, он не последний). Согласно `python-dev` (комментарий в
    `_начало_действия`), «чистой» формы без второго факта здесь не бывает:
    любая пара периодов, покрывающих одну и ту же дату, либо перекрывается
    датами (тогда стык считается отрицательным и это неизвестность), либо
    один из них бессрочен и стоит не последним (тоже неизвестность) —
    поэтому эта форма проверяет то же утверждение, что и первый тест, но
    с другой стороны: «выбор» обязан быть назван выбором даже когда он
    появляется ВМЕСТЕ с фактом настоящего разрыва, а не только с
    неизвестностью."""
    редакция = _редакция(
        {"from": "01.01.2010", "to": "01.01.2011"},
        {"from": "01.01.2020", "to": ""},
        {"from": "01.06.2020", "to": ""},
    )
    транспорт = ФейкТранспорт(_маршрутизатор([редакция]))
    к = client.GarantClient(transport=транспорт)

