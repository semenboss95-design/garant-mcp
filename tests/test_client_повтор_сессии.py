"""Повтор после 401/403 — ровно то, ради чего граница подмены (решение 17)
проведена по `Transport.fetch`, а не выше: подмена самого `_fetch` увела бы
эту ветку из-под проверки целиком.

Гонка холодного старта: первый запрос иногда уходит раньше, чем «Гарант»
успевает получить свежий `_keepalive_`, и отвечает 403 на живой сессии.
Один принудительный keepalive и повтор отличают эту гонку от истёкшей
подписки. Два 403 подряд, включая повтор, — это уже `GarantError` типа
`session` (`protocol.ТИП_СЕССИЯ`), и другого места в контуре, где этот тип
ставится, нет.
"""
from __future__ import annotations

import json

import pytest
from _фейк_транспорт import ФейкТранспорт

from garant_mcp import client, protocol


def test_403_потом_200_проходит_через_принудительный_keepalive_и_повтор():
    """Сценарий по шагам (см. `_fetch`): keepalive (не форс) → запрос (403) →
    keepalive (форс) → повтор запроса (200)."""
    сценарий = [
        (200, ""),                                   # 1. keepalive, некритично
        (403, "Forbidden"),                           # 2. первый настоящий запрос
        (200, ""),                                   # 3. keepalive форсированный
        (200, json.dumps({"children": [{"id": 1, "text": "Вид", "leaf": True}]})),
    ]
    транспорт = ФейкТранспорт(сценарий)
    к = client.GarantClient(transport=транспорт)

    результат = к.kinds()

    assert результат == [{"id": 1, "вид": "Вид", "конечный": True}]
    assert len(транспорт.вызовы) == 4, (
        "ожидались ровно 4 обращения к транспорту: keepalive, запрос(403), "
        f"форс-keepalive, повтор запроса(200). Получено: {len(транспорт.вызовы)}"
    )


def test_два_403_подряд_дают_ошибку_типа_session():
    сценарий = [
        (200, ""),               # keepalive
        (403, "Forbidden"),       # первый запрос
        (200, ""),               # форс-keepalive
        (403, "Forbidden"),       # повтор — снова 403
    ]
    транспорт = ФейкТранспорт(сценарий)
    к = client.GarantClient(transport=транспорт)

    with pytest.raises(client.GarantError) as excinfo:
        к.kinds()

    ошибка = excinfo.value
    assert ошибка.тип == protocol.ТИП_СЕССИЯ, (
        "два 403 подряд (включая повтор после принудительного продления) — "
        "это единственное место контура, где ставится тип session; "
        f"получен тип {ошибка.тип!r}"
    )
    assert ошибка.http == 403


def test_401_ведёт_себя_так_же_как_403():
    """401 и 403 — оба относятся к одному классу «сессия недействительна»,
    и оба обязаны идти по одной и той же ветке повтора."""
    сценарий = [
        (200, ""),
        (401, "Unauthorized"),
        (200, ""),
        (401, "Unauthorized"),
    ]
    к = client.GarantClient(transport=ФейкТранспорт(сценарий))
    with pytest.raises(client.GarantError) as excinfo:
        к.kinds()
    assert excinfo.value.тип == protocol.ТИП_СЕССИЯ


def test_404_не_считается_сессионной_ошибкой():
    """404 — «того, что спросили, в базе нет», а не признак мёртвой сессии.
    Другой тип, и повтора через keepalive быть не должно вовсе."""
    сценарий = [
        (200, ""),          # keepalive
        (404, "Not Found"),  # единственный запрос — без повтора
    ]
    транспорт = ФейкТранспорт(сценарий)
    к = client.GarantClient(transport=транспорт)
    with pytest.raises(client.GarantError) as excinfo:
        к.kinds()
    assert excinfo.value.тип == protocol.ТИП_НЕ_НАЙДЕНО
    assert len(транспорт.вызовы) == 2, (
        "404 не 401/403 — повтора после форс-keepalive быть не должно"
    )
