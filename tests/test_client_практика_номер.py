# -*- coding: utf-8 -*-
"""Д-2 аудита: `номер_в_заголовке` — что после «№», и никакого «✓».

Прежнее поле было `status` со значением «✓», проставленным на любое
«№ …» в заголовке — то есть на номер постановления Пленума и номер обзора
практики точно так же, как на номер дела, и читалось это как «номер дела
подтверждён», хотя ничего не подтверждалось (client.py:884-891). Сейчас
поле называется по тому, что оно есть на самом деле: число после «№»,
не обязательно номер дела.

Ожидаемые значения ниже — прочитаны ГЛАЗАМИ из текста заголовков в
`fixtures/практика.json`, а не выведены тем же регэкспом, что в
`client.py`: тест, повторяющий регэксп реализации, зелёный при любой её
ошибке и не проверяет ничего.
"""
from __future__ import annotations

import json
from pathlib import Path

from _фейк_транспорт import ФейкТранспорт

from garant_mcp import client

_ПОИСК = json.loads(
    (Path(__file__).parent / "fixtures" / "поиск.json").read_text(encoding="utf-8"))
_ПРАКТИКА = json.loads(
    (Path(__file__).parent / "fixtures" / "практика.json").read_text(encoding="utf-8"))

# Заголовки в fixtures/практика.json (порядок как в "page"."items"):
#   1. "Определение Верховного Суда РФ № 1-КГ22-1-К1 по выдуманному делу"
#   2. "Постановление Пленума ВС РФ № 5 по выдуманному вопросу"
#   3. "Определение Конституционного Суда РФ № 2-О по другому выдуманному делу"
# Число (в широком смысле — с буквами и дефисами) после «№» в каждом
# заголовке, прочитанное человеком, а не программой:
_ОЖИДАЕМЫЕ_НОМЕРА = ["1-КГ22-1-К1", "5", "2-О"]


def _маршрутизатор():
    def маршрут(method, url, form, номер):
        if "/server/keepalive" in url:
            return 200, ""
        if "/search/base/run" in url:
            return 200, json.dumps(_ПОИСК["run"])
        if "/search/poll" in url:
            return 200, json.dumps(_ПОИСК["poll"])
        if "/list/kind" in url:
            return 200, json.dumps(_ПРАКТИКА["kind"], ensure_ascii=False)
        if "/list/filter" in url:
            return 200, json.dumps(_ПРАКТИКА["date"], ensure_ascii=False)
        if "/list/page" in url:
            return 200, json.dumps(_ПРАКТИКА["page"], ensure_ascii=False)
        raise AssertionError(f"незнакомый URL в тесте практики: {method} {url}")
    return маршрут


def test_номер_в_заголовке_это_то_что_после_решётки():
    транспорт = ФейкТранспорт(_маршрутизатор())
    к = client.GarantClient(transport=транспорт)

    ответ = к.practice("запрос", date_from="01.01.2020", date_to="01.01.2021")
    items = ответ["items"]

    assert len(items) == len(_ОЖИДАЕМЫЕ_НОМЕРА), (
        "фикстура и ожидание разошлись по числу позиций — обновите тест "
        "вместе с fixtures/практика.json")

    for it, ожидание in zip(items, _ОЖИДАЕМЫЕ_НОМЕРА):
        assert "номер_в_заголовке" in it, (
            "поля `номер_в_заголовке` нет вовсе в {!r}".format(it))
        assert it["номер_в_заголовке"] == ожидание, (
            "заголовок {!r}: ожидался номер {!r}, получено {!r}".format(
                it.get("title"), ожидание, it["номер_в_заголовке"]))


def test_status_и_галочка_не_возвращаются():
    """Д-2: прежнее поле `status` со значением «✓» подтверждало номер дела,
    хотя клиент ничего не сверял. Ни ключа, ни символа быть не должно —
    ни в каком поле, а не только в бывшем `status`."""
    транспорт = ФейкТранспорт(_маршрутизатор())
    к = client.GarantClient(transport=транспорт)

    ответ = к.practice("запрос", date_from="01.01.2020", date_to="01.01.2021")

    for it in ответ["items"]:
        assert "status" not in it, (
            "поле `status` вернулось — Д-2 подразумевал его удаление "
            "вместе со значением «✓»: {!r}".format(it))
        for значение in it.values():
            assert значение != "✓", (
                "значение «✓» осталось хоть в каком-то поле: {!r}".format(it))
