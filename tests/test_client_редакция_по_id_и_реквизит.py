"""Синтетика для клонировавшего — три находки записей живой приёмки
09.09.2026 (решение 12, `.claude/rules/tests.md`: «второй род образцов»,
форма /redactions/list — как её описывает `endpoints.json`, секция
`revisions`: `documentId`, `status`, `text`, `activity[].from/to`,
`changingDocuments[].text/documentId`). У клонировавшего каталога
`recordings` нет вовсе (см. `tests/test_записи_владельца.py`), и то же
свойство здесь доказывается на выдуманных, но по форме верных телах —
единственный законный вид синтетики там, где карту эндпоинтов клиент
читает как задокументировано (`.claude/rules/tests.md`, правило про
образцы «по карте»).

Три свойства, найденные `tests/test_записи_владельца.py` на записях УПК:

1. `doc_id` бывает `id` РЕДАКЦИИ, а не документа (решение 12): «Гарант»
   отдаёт по нему текст ИМЕННО этой редакции, и провенанс обязан назвать
   ЕЁ, а не действующую, — молчание здесь ошибка, против которой
   инструмент написан.
2. Пустой `activity` — ЗНАНИЕ «периодов нет», а не «периоды не прочитаны»:
   решение 36, дополнение 09.09.2026. До него такая запись читалась как
   карта без периодов и получала фиктивный период без обеих границ —
   кандидатом на ЛЮБУЮ дату.
3. Реквизит изменяющего акта иногда приходит с цифрой «3» вместо буквы
   «З» (визуально неотличимо на глаз) — провенанс обязан отдать его
   ДОСЛОВНО и оговорить это, а не молча «починить».

Граница подмены — решение 17, `Transport.fetch`: разбор исполняется
настоящим `garant_mcp.client`, тестовый транспорт отдаёт заготовленное
тело.
"""
from __future__ import annotations

import json

import pytest

from _фейк_транспорт import ФейкТранспорт

from garant_mcp import client, protocol


def _редакция(documentId: int, status: str, text: str, activity: list[dict],
              changingDocuments: list[dict] | None = None) -> dict:
    """Одна запись `/redactions/list` — форма ровно та, что описывает
    `endpoints.json` (секция `revisions.item_map`)."""
    return {
        "documentId": documentId, "status": status, "text": text,
        "date": "01.01.2000",
        "activity": activity,
        "changingDocuments": changingDocuments or [],
    }


def _маршрут_редакций(redactions: list[dict]):
    """Документ на одну страницу плюс список редакций — минимум, которого
    хватает `document()`: `/document/info`, `/document/pages`,
    `/redactions/list`."""
    def маршрут(method, url, form, номер):
        if "/server/keepalive" in url:
            return 200, ""
        if "/document/info" in url:
            return 200, json.dumps({"pageCount": 1})
        if "/document/pages" in url:
            return 200, json.dumps({"items": [{"number": 1, "text": "текст"}]})
        if "/redactions/list" in url:
            return 200, json.dumps({"redactions": redactions}, ensure_ascii=False)
        raise AssertionError(f"незнакомый URL в синтетике решения 12: {method} {url}")
    return маршрут


def _клиент(*redactions: dict) -> client.GarantClient:
    return client.GarantClient(transport=ФейкТранспорт(_маршрут_редакций(list(redactions))))


