def test_текущая_редакция_doc_id_совпадает_с_id_редакции_не_действующей():
    """`doc_id`, равный `documentId` НЕ действующей записи, обязан быть
    опознан как запрос именно этой редакции — а не молча подменён
    действующей. Опознание слепое (совпадение id), молчаливой починки нет."""
    действующая = _редакция(100, "rs_Actual", "с 01.06.2020",
                             [{"from": "01.06.2020", "to": ""}])
    старая = _редакция(200, "rs_Old", "с 01.01.2015",
                        [{"from": "01.01.2015", "to": "01.06.2020"}],
                        [{"text": "N 1-ФЗ от 01.01.2015", "documentId": 300}])
    к = _клиент(действующая, старая)
    revs = к.revisions(doc_id=200)
    rev, оговорки = client._текущая_редакция(revs, doc_id=200)

    assert rev["id_редакции"] == 200, (
        "опознана обязана быть ЗАПРОШЕННАЯ по id_редакции запись, "
        "а не первая по списку и не действующая")
    assert rev["статус"] == "утратила силу"
    assert оговорки, "запрос НЕ действующей редакции обязан оставить оговорку"
    объединено = " ".join(оговорки)
    assert "утратила силу" in объединено or "НЕ действует" in объединено
    assert "100" in объединено, (
        "оговорка обязана назвать documentId ДЕЙСТВУЮЩЕЙ — где искать "
        "сегодняшний текст, если он нужен:\n" + объединено)


def test_текущая_редакция_doc_id_равен_собственному_id_действующей_молчит():
    """Документ, запрошенный собственным (действующим) id, — контрольный
    случай: опознание совпадает с действующей, и лишней оговорки быть
    не должно (ключ, стоящий всегда, перестаёт читаться)."""
    действующая = _редакция(100, "rs_Actual", "с 01.06.2020",
                             [{"from": "01.06.2020", "to": ""}])
    к = _клиент(действующая)
    revs = к.revisions(doc_id=100)
    rev, оговорки = client._текущая_редакция(revs, doc_id=100)
    assert rev["id_редакции"] == 100
    assert оговорки == []


def test_document_doc_id_редакции_даёт_текст_той_редакции_с_её_реквизитом():
    """Публичный путь: `document(doc_id=<id редакции>)` обязан заверить
    цитату ДАТОЙ И АКТОМ запрошенной редакции, а не действующей — ровно та
    ошибка, против которой решение 12 написано."""
    действующая = _редакция(100, "rs_Actual", "с 01.06.2020",
                             [{"from": "01.06.2020", "to": ""}],
                             [{"text": "N 2-ФЗ от 01.06.2020", "documentId": 301}])
    старая = _редакция(200, "rs_Old", "с 01.01.2015",
                        [{"from": "01.01.2015", "to": "01.06.2020"}],
                        [{"text": "N 1-ФЗ от 01.01.2015", "documentId": 300}])
    к = _клиент(действующая, старая)
    ответ = к.document(doc_id=200)
    prov = ответ["provenance"]

    assert prov["действует_с"] == "01.01.2015", (
        "заверяющая дата обязана быть началом ЗАПРОШЕННОЙ редакции")
    assert prov["изменяющий_акт"] == "N 1-ФЗ от 01.01.2015", (
        "акт обязан быть актом ЗАПРОШЕННОЙ редакции, не действующей")
    оговорки = "\n".join(prov.get("оговорки_о_редакции") or [])
    assert "100" in оговорки, "действующая (documentId 100) названа для сравнения"


