def test_оговорка_о_периодах_пустой_activity_периодов_нет():
    assert client._оговорка_о_периодах({"периоды": []}) == client._ПЕРИОДОВ_НЕТ


def test_revisions_пустой_activity_даёт_периодов_нет_без_бессрочно():
    запись = _редакция(400, "rs_Old", "без периодов", [])
    к = _клиент(запись)
    [rev] = к.revisions(doc_id=400)

    assert rev["периоды"] == []
    assert rev.get("_предупреждение") == client._ПЕРИОДОВ_НЕТ
    assert client._перечень_периодов(rev) == "периодов нет", (
        "рендер перечня периодов не должен подставлять фиктивную "
        "«? — бессрочно» там, где периода нет вовсе")
    assert "бессрочно" not in (rev.get("_предупреждение") or "")


def test_revision_on_date_пустой_activity_не_становится_кандидатом_на_любую_дату():
    """До решения 36 (дополнение 09.09.2026) запись с `activity: []`
    уравнивалась с «периоды не прочитаны» и получала фиктивный период
    `{с: None, по: None}` — кандидатом на ЛЮБУЮ дату (546 дней 2001-2002
    на живой базе, `действует_с` равным `null`). Единственная запись
    списка с пустым `activity`: сопоставить с датой нечем, и «редакция
    на дату не найдена» — честный ответ на произвольную дату, а не
    случайное совпадение по умолчанию."""
    запись = _редакция(400, "rs_Actual", "без периодов", [])
    к = _клиент(запись)
    with pytest.raises(client.GarantError) as excinfo:
        к.revision_on_date(doc_id=400, on="01.01.2001")
    assert excinfo.value.тип == protocol.ТИП_НЕ_НАЙДЕНО
    assert "не найдена" in str(excinfo.value)


