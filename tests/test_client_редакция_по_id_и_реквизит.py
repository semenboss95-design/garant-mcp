def test_оговорка_о_реквизите_акта_ф3_с_цифрой():
    оговорка = client._оговорка_о_реквизите_акта("N 5-Ф3 от 01.01.2020")
    assert оговорка is not None
    assert "цифрой" in оговорка and "Ф3" in оговорка


def test_оговорка_о_реквизите_акта_обычная_фз_молчит():
    """Буква «З» — обычное написание, оговорки не заслуживает: если бы
    условие срабатывало на любом «Ф», оговорка обесценилась бы частотой."""
    assert client._оговорка_о_реквизите_акта("N 5-ФЗ от 01.01.2020") is None


def test_document_реквизит_ф3_доходит_дословно_в_provenance():
    действующая = _редакция(500, "rs_Actual", "с 01.01.2020",
                             [{"from": "01.01.2020", "to": ""}],
                             [{"text": "N 10-Ф3 от 01.01.2020", "documentId": 600}])
    к = _клиент(действующая)
    ответ = к.document(doc_id=500)
    prov = ответ["provenance"]

    assert prov["изменяющий_акт"] == "N 10-Ф3 от 01.01.2020", (
        "значение НЕ чинится — цитата заверяется реквизитом дословно, "
        "с цифрой, как отдала база")
    оговорки = "\n".join(prov.get("оговорки_о_редакции") or [])
    assert "цифрой" in оговорки and "Ф3" in оговорки
