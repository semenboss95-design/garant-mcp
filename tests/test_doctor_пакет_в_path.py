# -*- coding: utf-8 -*-
"""Дефект Д-2: `doctor` различает «пакета нет вовсе» и «пакет стоит, но
каталог его команд не подхвачен PATH» (наряд test-author, вход — сдача
python-dev по Д-2, 07.09.2026 → 08.09.2026).

До правки `_исполняемые()` при любой пустоте `shutil.which()` отвечала
ОДНИМ и тем же текстом и ОДНОЙ и той же починкой — «нет в PATH» и
«uv tool install --force garant-mcp» — даже тогда, когда пакет уже стоит
и работает, а PATH просто не подхватил новый каталог команд (наблюдалось
живьём после установки через `uv tool`, см. сдачу python-dev). Починка
«переустановите» у РАБОТАЮЩЕЙ установки ничего не меняет: `install --force`
кладёт те же файлы в тот же каталог, а каталог по-прежнему не в PATH —
человек крутится по кругу.

Различение держится на `cli._команды_на_диске()`: два честных факта (её
докстрока), и здесь каждый проверен ОТДЕЛЬНО, а не только оптом через
подмену всей функции, — иначе тест доказывал бы контракт `_исполняемые()`,
но не саму функцию, где и жил дефект (до правки её не существовало вовсе).

Всё здесь — прямой вызов функций модуля в этом же процессе, без
`subprocess`: `_исполняемые()` и `_команды_на_диске()` не читают
`paths.STATE` и не пишут на диск нигде, кроме `Path.is_file()` по путям,
которые называет сам тест (`tmp_path`), — песочница `GARANT_HOME` здесь
ни при чём, в отличие от соседних `test_doctor_*`, которые гоняют
`doctor()` целиком подпроцессом ради состояния демона и регистраций.
`shutil.which` подменяется явно, поэтому от реального PATH разработчика
исход не зависит.
"""
from __future__ import annotations

import sys

from garant_mcp import cli

from test_paths import чужой_каталог  # noqa: F401


def _без_which(monkeypatch, найдено=None):
    """`shutil.which` отвечает заготовкой теста, а не реальным PATH машины."""
    найдено = найдено or {}
    monkeypatch.setattr(cli.shutil, "which", lambda имя: найдено.get(имя))


# ---------------------------------------------------------------------------
# контракт `_исполняемые()` при заданном (подменённым целиком) признаке
# ---------------------------------------------------------------------------

def test_ничего_в_path_и_признака_установленности_нет_даёт_install_force(monkeypatch):
    """(б) which пуст всюду, `_команды_на_диске()` лжёт «нет» — прежняя
    починка «поставьте заново», потому что и вправду не стоит."""
    _без_which(monkeypatch)
    monkeypatch.setattr(cli, "_команды_на_диске", lambda: False)

    значок, текст, починка = cli._исполняемые()

    assert значок == cli.ПЛОХО
    assert "нет в PATH" in текст
    assert "uv tool install --force garant-mcp" in починка
    assert "update-shell" not in починка


def test_ничего_в_path_но_признак_установленности_есть_даёт_update_shell(monkeypatch):
    """(а) which пуст всюду, но `_команды_на_диске()` доказывает: пакет уже
    стоит. Красный пункт обязан различать это от «пакета нет» — иная
    починка (обновить оболочку, а не переустановить пакет) и путь
    к каталогу команд в тексте НЕ называется (у читающего он свой и
    меняется с обновлением — комментарий у самой ветки в cli.py)."""
    _без_which(monkeypatch)
    monkeypatch.setattr(cli, "_команды_на_диске", lambda: True)

    значок, текст, починка = cli._исполняемые()

    assert значок == cli.ПЛОХО
    assert "uv tool update-shell" in починка
    assert "uv tool install --force" not in починка
    # Абсолютный путь каталога команд — не в диагнозе и не в починке.
    assert "\\" not in текст and "/" not in текст
    assert "\\" not in починка and "/" not in починка


def test_всё_в_path_зелёный(monkeypatch):
    """(в) которую находят все три файла — обычный зелёный пункт, и признак
    установленности вообще не обязан спрашиваться: ветка выходит раньше."""
    _без_which(monkeypatch, {
        "garant": "куда-то\\garant.exe",
        "garant-mcp": "куда-то\\garant-mcp.exe",
        "garant-daemon": "куда-то\\garant-daemon.exe",
    })

    значок, текст, починка = cli._исполняемые()

    assert значок == cli.ОК
    assert починка == ""
    for имя in ("garant", "garant-mcp", "garant-daemon"):
        assert имя in текст


# ---------------------------------------------------------------------------
# сама `_команды_на_диске()` — два честных факта отдельно
# ---------------------------------------------------------------------------

def test_признак_первый_факт_argv0_называется_garant_без_расширения(
        tmp_path, monkeypatch):
    """windows-лаунчер отдаёт `sys.argv[0]` БЕЗ расширения — на диске лежит
    `garant.exe`, а argv[0] называет файл без «.exe». Признак обязан узнать
    и эту форму, а не только буквальное совпадение имени с файлом на диске
    (замерено python-dev на установке через `uv tool`)."""
    (tmp_path / "garant.exe").write_bytes(b"")
    monkeypatch.setattr(sys, "argv", [str(tmp_path / "garant"), "doctor"])
    # Второй факт — пуст: признак обязан сработать РОВНО от первого.
    пусто = tmp_path / "пусто"
    пусто.mkdir()
    monkeypatch.setattr(cli.sysconfig, "get_path", lambda имя: str(пусто))

    assert cli._команды_на_диске() is True


def test_признак_второй_факт_каталог_скриптов_интерпретатора(
        tmp_path, monkeypatch, чужой_каталог):
    """`garant` лежит в каталоге скриптов ЭТОГО интерпретатора — признак
    обязан сработать независимо от того, чем и как запущен сам doctor
    (первый факт — намеренно про другое имя). Каталог — с пробелом
    и кириллицей: у пользователя машина бывает именно такой."""
    скрипты = чужой_каталог
    (скрипты / "garant").write_bytes(b"")
    monkeypatch.setattr(sys, "argv",
                        [str(tmp_path / "python"), "-m", "garant_mcp.cli", "doctor"])
    monkeypatch.setattr(cli.sysconfig, "get_path", lambda имя: str(скрипты))

    assert cli._команды_на_диске() is True


def test_признак_ни_одного_факта_нет(tmp_path, monkeypatch):
    """Ни argv[0], ни каталог скриптов не называют «garant» — признак
    честно отвечает «нет», и «пакета нет вовсе» — правильный диагноз."""
    monkeypatch.setattr(sys, "argv",
                        [str(tmp_path / "python"), "-m", "garant_mcp.cli", "doctor"])
    пусто = tmp_path / "пусто"
    пусто.mkdir()
    monkeypatch.setattr(cli.sysconfig, "get_path", lambda имя: str(пусто))

    assert cli._команды_на_диске() is False
