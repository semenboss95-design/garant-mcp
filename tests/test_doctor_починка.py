# -*- coding: utf-8 -*-
"""«Красный пункт обязан нести команду починки» (`cli._пункт`, этап 02, шаг 3).

Правило держится на исключении ВНУТРИ `cli.py`: `_пункт()` печатает красный
пункт и, если для него не передана строка починки, поднимает `RuntimeError` —
но это исключение сработает только тогда, когда КТО-ТО в `doctor()`
действительно допустит такой вызов, а это происходит только при живом
исполнении отчёта, а не при чтении кода. Наряд прямо требует поймать
нарушение здесь, а не у пользователя: «соберите отчёт doctor в среде без
демона».

Среда здесь — самая недружелюбная из достижимых без сети и без изменения
машины: `GARANT_HOME` в чистом `tmp_path` (демона в этой жизни не было
вовсе), демон не поднят и не поднимается (`doctor()` НЕ зовёт
`обеспечить_демона()` — только `dc.адрес()`, который лишь спрашивает
`/health` и не запускает процессов), порт — заведомо свободный, пакет —
копия во временной песочнице (`garant`/`garant-mcp`/`garant-daemon` не
в PATH). Это гарантирует по меньшей мере несколько красных пунктов
(демон, пакет в PATH), и именно на них исполняется настоящий код `doctor()`.

`register.цель_desktop()`/`цель_code()` внутри `doctor()` читают НАСТОЯЩИЕ
конфигурации Claude Desktop/Code этой машины — но только НА ЧТЕНИЕ
(`register.статус()` не пишет), поэтому запуск безопасен и не требует
песочницы для них. `autostart.состояние()` тоже только читает (`schtasks
/Query` и аналоги на других ОС) — ничего не создаёт и не удаляет.

Тест не считает, сколько именно пунктов красные, — доктор диагностирует
реальную машину, и её состояние (собственный PATH разработчика, наличие
chromium) тесту не подчиняется. Проверяется инвариант, а не число.
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

from test_paths import _песочница, _окружение, чужой_каталог  # noqa: F401
from test_port import _свободный_порт  # noqa: F401

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src"


def _прогнать_doctor(пакет: Path, cwd: Path, живой_флаг: bool = False):
    порт = _свободный_порт()
    аргументы = ["doctor"] + (["--живой"] if живой_флаг else [])
    return subprocess.run(
        [sys.executable, "-m", "garant_mcp.cli", *аргументы],
        cwd=str(cwd),
        env=_окружение({"PYTHONPATH": str(пакет.parent),
                        "GARANT_HOME": str(cwd / "состояние"),
                        "GARANT_PORT": str(порт)}),
        capture_output=True, text=True, encoding="utf-8", errors="replace",
        timeout=120,
    )


# Значки красного пункта в двух видах: юникодный «✗» и ASCII-запасной
# «[X]» — какой из них напечатается, решает кодировка консоли подпроцесса
# (см. `cli._значки()`). Тест обязан узнавать оба, а не только тот, что
# выведет консоль разработчика.
_КРАСНЫЙ = re.compile(r"^(?:✗|\[X\])\s+(.+?):\s+(.*)$")
_ПОЧИНИТЬ = re.compile(r"^\s{2}(?:почин(?:ить|ка)):\s+(.*)$")


def test_doctor_не_падает_и_каждый_красный_пункт_несёт_починку(tmp_path, чужой_каталог):
    пакет = _песочница(tmp_path)
    r = _прогнать_doctor(пакет, чужой_каталог)

    assert "Traceback" not in r.stderr, (
        "doctor упал с трассировкой вместо диагностики:\n" + r.stderr)
    assert "дефект пульта" not in (r.stdout + r.stderr), (
        "doctor сам поймал собственное нарушение («дефект пульта: красный "
        "пункт … без команды починки») — значит, где-то в коде красный "
        "пункт печатается без строки почин:\n" + r.stdout + r.stderr)
    # Код возврата — 0 или 1 (сделано/не сделано), не 2 (там код добрался
    # бы не до диагностики, а до разбора аргументов) и не что-то ещё.
    assert r.returncode in (0, 1), (
        "doctor вернул неожиданный код {}:\n{}".format(
            r.returncode, r.stdout + r.stderr))

    строки = r.stdout.splitlines()
    красных_найдено = 0
    for i, строка in enumerate(строки):
        # Итоговая строка «красных пунктов: N» — не ПУНКТ диагностики, а
        # сводка после них: у неё та же внешняя форма («✗ …: …»), но она не
        # обязана и не должна нести строку почин: под собой — там просто
        # конец вывода.
        if "красных пунктов" in строка:
            continue
        if _КРАСНЫЙ.match(строка):
            красных_найдено += 1
            следующая = строки[i + 1] if i + 1 < len(строки) else ""
            assert _ПОЧИНИТЬ.match(следующая), (
                "красный пункт без строки починки сразу под ним:\n"
                "  {}\n  (дальше: {!r})\n\nВесь вывод:\n{}".format(
                    строка, следующая, r.stdout))

    # Инвариант без починки достижим только если пунктов не оказалось вовсе —
    # тогда его не проверить, и это стоит явно назвать, а не молчать зелёным.
    assert красных_найдено > 0, (
        "ни одного красного пункта не найдено — в песочнице без демона и "
        "без пакета в PATH ожидался хотя бы один («демон», «пакет в PATH»); "
        "проверка «у каждого красного — починка» на пустом множестве ничего "
        "не доказывает. Вывод:\n" + r.stdout)
