# -*- coding: utf-8 -*-
"""Дефект без теста из `780a303`, ДЕФЕКТ 2 из его сообщения: `doctor` красил
зелёным «демон работает» для ЛЮБОГО демона на порту — включая демона ДРУГОЙ
установки. Признак принадлежности — не `/health` (он одинаков у всех копий),
а `/state` ПОД НАШИМ ТОКЕНОМ: токен демон читает из своего каталога
состояния, и «токен принят» + «названный каталог совпал» вместе означают
«этот демон живёт нашим состоянием».

Стенд — фальшивый демон на `http.server`, без chromium и без сети наружу:
отвечает на `/health` признаком демона и на `/state` — под правильным
токеном — телом с полем `каталоги.состояние`. Поднимается в ЭТОМ процессе
на СВОБОДНОМ порту (не 8787 — на машине уже работает демон владельца,
трогать его нельзя) и гасится в `finally` каждого теста.

Два свойства, каждое отдельным тестом:
  * пункт «демон» ЗЕЛЁНЫЙ, когда стенд называет каталог, совпадающий
    с `paths.STATE` этой копии doctor;
  * пункт «демон» НЕ зелёный (жёлтый), когда стенд называет ЧУЖОЙ каталог —
    и сообщение прямо называет это «ДРУГОЙ установкой».

`PYTHONIOENCODING=utf-8` в `_окружение()` делает значки детерминированными:
`cli._значки()` в подпроцессе видит `sys.stdout.encoding == "utf-8"`
независимо от кодовой страницы консоли и печатает юникодные ✓/⚠, а не
ASCII-запасные `[ok]`/`[!]` — их и ищем.
"""

from __future__ import annotations

import http.server
import json
import re
import threading

import subprocess
import sys

from test_paths import _песочница, _окружение, чужой_каталог  # noqa: F401
from test_port import _свободный_порт  # noqa: F401

from garant_mcp import protocol

# ASCII: попадает в заголовок X-Token, а HTTP-заголовки latin-1-only —
# кириллица здесь роняла бы клиента `UnicodeEncodeError` до всякого стенда.
ТОКЕН = "proba-token-dlya-stenda-doctor-123"

_ПУНКТ_ДЕМОН = re.compile(r"^(?P<значок>\S+)\s+демон:\s+(?P<текст>.*)$")


class _ФейковыйДемон(http.server.BaseHTTPRequestHandler):
    # Выставляется на подклассе для каждого сервера отдельно — так два
    # теста, поднятые последовательно, не делят состояние через класс.
    каталог_состояния: str = ""

    def _json(self, код: int, тело: dict) -> None:
        данные = json.dumps(тело).encode("utf-8")
        self.send_response(код)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(данные)))
        self.end_headers()
        self.wfile.write(данные)

    def do_GET(self):
        if self.path == "/health":
            self._json(200, {protocol.ПРИЗНАК_ДЕМОНА: True, "версия": "0.0.0"})
            return
        if self.path == "/state":
            if self.headers.get("X-Token") != ТОКЕН:
                self._json(403, {"ошибка": "неверный токен", "тип": "auth"})
                return
            self._json(200, {"каталоги": {"состояние": self.каталог_состояния}})
            return
        self._json(404, {"ошибка": "нет такого пути в стенде"})

    def log_message(self, *a, **k):
        pass  # тихий стенд: не засорять вывод pytest посторонним логом


def _поднять_стенд(порт: int, каталог_состояния: str) -> http.server.HTTPServer:
    класс = type("_Стенд", (_ФейковыйДемон,),
                 {"каталог_состояния": каталог_состояния})
    сервер = http.server.HTTPServer(("127.0.0.1", порт), класс)
    поток = threading.Thread(target=сервер.serve_forever, daemon=True)
    поток.start()
    return сервер


def _прогнать_doctor_на_порту(пакет, cwd, порт: int):
    """То же самое, что `test_doctor_починка._прогнать_doctor`, но с портом,
    заданным ВЫЗЫВАЮЩИМ, а не выбранным внутри функции: здесь порт обязан
    совпасть с портом, на котором уже поднят стенд-демон, а вычислять его
    заново значило бы гонять doctor против пустого порта."""
    return subprocess.run(
        [sys.executable, "-m", "garant_mcp.cli", "doctor"],
        cwd=str(cwd),
        env=_окружение({"PYTHONPATH": str(пакет.parent),
                        "GARANT_HOME": str(cwd / "состояние"),
                        "GARANT_PORT": str(порт)}),
        capture_output=True, text=True, encoding="utf-8", errors="replace",
        timeout=120,
    )


def _строка_демон(вывод: str) -> re.Match:
    for строка in вывод.splitlines():
        m = _ПУНКТ_ДЕМОН.match(строка)
        if m:
            return m
    raise AssertionError(
        "в выводе doctor нет пункта «демон»:\n" + вывод)


def test_doctor_красит_зелёным_демона_этой_установки(tmp_path, чужой_каталог):
    пакет = _песочница(tmp_path)
    порт = _свободный_порт()
    каталог_состояния = чужой_каталог / "состояние"
    каталог_состояния.mkdir(parents=True, exist_ok=True)
    (каталог_состояния / "daemon_token").write_text(ТОКЕН, encoding="utf-8")

    # Стенд называет РОВНО тот каталог, на который укажет GARANT_HOME
    # запускаемого doctor (см. `_прогнать_doctor` в test_doctor_починка.py).
    сервер = _поднять_стенд(порт, str(каталог_состояния))
    try:
        r = _прогнать_doctor_на_порту(пакет, чужой_каталог, порт)
    finally:
        сервер.shutdown()
        сервер.server_close()

    m = _строка_демон(r.stdout)
    assert m.group("значок") == "✓", (
        "демон СВОЕЙ установки (токен принят, каталог совпал) обязан "
        "красить пункт «демон» зелёным (✓), а не {!r}:\n{}\n{}".format(
            m.group("значок"), m.group("текст"), r.stdout))


def test_doctor_не_красит_зелёным_демона_чужой_установки(tmp_path, чужой_каталог):
    пакет = _песочница(tmp_path)
    порт = _свободный_порт()
    каталог_состояния = чужой_каталог / "состояние"
    каталог_состояния.mkdir(parents=True, exist_ok=True)
    (каталог_состояния / "daemon_token").write_text(ТОКЕН, encoding="utf-8")

    # Стенд ПРИНИМАЕТ наш токен (иначе это была бы «принадлежность не
    # доказана», а не «другая установка»), но называет ЧУЖОЙ каталог
    # состояния — токен совпадает, а самоотчёт демона про себя другой.
    чужой = чужой_каталог / "не_наше_состояние_другой_установки"
    чужой.mkdir(parents=True, exist_ok=True)
    сервер = _поднять_стенд(порт, str(чужой))
    try:
        r = _прогнать_doctor_на_порту(пакет, чужой_каталог, порт)
    finally:
        сервер.shutdown()
        сервер.server_close()

    m = _строка_демон(r.stdout)
    assert m.group("значок") != "✓", (
        "демон ЧУЖОЙ установки (токен принят, каталог НЕ совпал) не имеет "
        "права красить пункт «демон» зелёным (✓) — иначе ворота снова "
        "примут чужой процесс за свой:\n{}\n{}".format(m.group("текст"), r.stdout))
    assert "ДРУГОЙ установки" in m.group("текст"), (
        "сообщение обязано прямо назвать причину — «ДРУГОЙ установки» — "
        "а не просто быть некрасным:\n{}\n{}".format(m.group("текст"), r.stdout))
