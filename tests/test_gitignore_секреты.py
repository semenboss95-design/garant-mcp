# -*- coding: utf-8 -*-
"""§7 `docs/TEAM.md`, проверка 1 — `.gitignore` закрывает секреты сам по себе.

Раньше это делал `scripts/acceptance.ps1` (одиннадцать офлайн-проверок),
удалённый решением 18; из них заменён `pytest`, эта — нет (осиротевшая
проверка №1 в таблице §7 «Восемь проверок, оставшихся без исполнителя»).

Почему это не покрыто хуком `pre-commit`: хук смотрит содержимое того, что
УЖЕ уходит в индекс. Ослабление самого `.gitignore` (снятая строка, опечатка
в образце, случайно суженный шаблон) пройдёт мимо хука незамеченным — он
ведь смотрит на файлы, а не на список исключений. Единственная защита от
этого — прямая проверка `.gitignore` тем же инструментом, которым его
читает git: `git check-ignore`.

Список имён — из CLAUDE.md, раздел «Что публично, что нет», и из наряда:
`storage_state.json`, `daemon_token`, `daemon_port`, `daemon_state.json`,
`chrome_profile`, `recordings`, `fingerprint.json`, `endpoints.local.json`,
`memory/STATE.md`, `.venv`, `cache`, `logs`.

Каждое имя проверяется ОТДЕЛЬНО и все двенадцать — в одном тесте с полным
списком провалов, а не первым же `assert`: одна строка, случайно снятая
из `.gitignore`, не должна прятаться за тем, что тест остановился на
предыдущей.
"""

from __future__ import annotations

from _repo_git import ROOT, git

ИМЕНА_СЕКРЕТОВ = (
    "storage_state.json",
    "daemon_token",
    "daemon_port",
    "daemon_state.json",
    "chrome_profile",
    "recordings",
    "fingerprint.json",
    "endpoints.local.json",
    "memory/STATE.md",
    ".venv",
    "cache",
    "logs",
)


def test_gitignore_закрывает_каждое_имя_секрета():
    """`git check-ignore -q <имя>` обязан дать попадание (код 0) по каждому.

    Путь заведомо не существует на диске нигде, кроме, может быть, реально
    работающей установки, — и это не важно: `check-ignore` match по
    шаблону не требует существования файла. Если он не отвечает — либо
    отсутствует, либо `.gitignore` его больше не закрывает.
    """
    провалы = []
    for имя in ИМЕНА_СЕКРЕТОВ:
        r = git("check-ignore", "-q", "--", имя)
        if r.returncode != 0:
            провалы.append(имя)
    assert not провалы, (
        "`.gitignore` больше не закрывает: {}. Это ослабление правила "
        "«секрет неиндексируем в принципе» — коммит с любым из этих имён "
        "уйдёт в публичный репозиторий и его нельзя будет отозвать."
        .format(провалы))


def test_каталог_состояния_целиком_а_не_поимённо():
    """`memory/` закрыт КАТАЛОГОМ, а не только `memory/STATE.md`.

    CLAUDE.md прямо называет это регрессией, которая уже случалась
    («Расхождение вскрылось, когда в него лёг второй файл — аудит
    архитектуры»): поимённая строка не защищает следующий новый файл
    в каталоге. Пробуем ИМЯ, которого в `.gitignore` заведомо нет
    буквально, — попадание возможно только через правило на весь каталог.
    """
    выдуманное_имя = "memory/совершенно_новый_файл_которого_нет_в_образцах.md"
    r = git("check-ignore", "-q", "--", выдуманное_имя)
    assert r.returncode == 0, (
        "`{}` не закрыт `.gitignore` — значит, правило по `memory/` "
        "поимённое, а не по каталогу целиком, и следующий новый файл "
        "уйдёт в публичный коммит незамеченным.".format(выдуманное_имя))


def test_gitignore_существует_и_не_пуст():
    """Предохранитель от вырожденного случая: пустой файл 'закрывает' всё
    выше нулём совпадений и оба теста прошли бы по ошибке — если бы
    `check-ignore` не падал на пустом файле сам. Явная проверка честнее."""
    путь = ROOT / ".gitignore"
    assert путь.exists(), "в репозитории нет .gitignore вовсе"
    assert путь.stat().st_size > 100, ".gitignore подозрительно мал"
