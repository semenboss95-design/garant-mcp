# ROOT в новом paths.py удалён (не нужен рантайму); HOME теперь — сам каталог
# пакета garant_mcp, а не прежней плоской папки с кодом. local_endpoints_file,
# fingerprint_file и recordings_dir — новые производные этапа 02.
ПРОИЗВОДНЫЕ = ("HOME", "STATE", "token_file", "port_file", "state_file",
               "fingerprint_file", "local_endpoints_file", "log_dir",
               "cache_dir", "recordings_dir", "profile_dir", "bridge_dir")


def _состояние(пакет, cwd, доп=None):
    """Возвращает HOME и STATE, как их видит paths.py, плюс эталон от ОС.

    Эталон считается тем же вызовом platformdirs в том же процессе: иначе
    тест пришлось бы дублировать раскладку каталогов Windows, macOS и Linux
    и он ломался бы на каждой из них по-своему.
    """
    код = (
        "import sys, json\n"
        "sys.path.insert(0, r'{site}')\n"
        "import garant_mcp.paths as paths\n"
        "import platformdirs\n"
        "print(json.dumps({{'HOME': str(paths.HOME), "
        "'STATE': str(paths.STATE), "
        "'эталон': platformdirs.user_data_dir('garant-mcp')}}))\n"
    ).format(site=пакет.parent)
    r = _запуск(код, cwd, доп, таймаут=60)
    assert r.returncode == 0, (
        "garant_mcp.paths не отдаёт STATE (либо нет platformdirs):\n"
        + r.stderr.strip()
    )
    return json.loads(r.stdout.strip())


def test_paths_есть_и_отдаёт_производные(tmp_path, чужой_каталог):
    пакет = _песочница(tmp_path)
    состояние = tmp_path / "состояние"
    код = (
        "import sys, json\n"
        "sys.path.insert(0, r'{site}')\n"
        "import garant_mcp.paths as paths\n"
        "print(json.dumps({{k: str(getattr(paths, k)) for k in {ключи}}}))\n"
    ).format(site=пакет.parent, ключи=list(ПРОИЗВОДНЫЕ))
    r = _запуск(код, чужой_каталог, {"GARANT_HOME": str(состояние)},
                таймаут=60)
    assert r.returncode == 0, (
        "paths.py не отдаёт именованные производные:\n" + r.stderr.strip()
    )
    данные = json.loads(r.stdout.strip())
    assert данные["HOME"] == str(пакет)
    assert данные["STATE"] == str(состояние), (
        "GARANT_HOME обязана задавать STATE."
    )


# --------------------------------------------------------------------------
#  5. STATE по умолчанию — каталог данных ОС; следы рядом с кодом не влияют
# --------------------------------------------------------------------------
#
#  Решение 14 (05.09.2026) удаляет понятие «портативной установки»: следы
#  рядом с кодом (chrome_profile/, daemon_token) на выбор STATE больше не
#  влияют вовсе. На прежнем `paths.py` (последний коммит до переноса на
#  пакет, файл `paths.py` в прежней плоской раскладке) непустой HOME означал
#  портативную установку и STATE оставался в HOME — три следующих теста
#  красны именно на нём.

@pytest.mark.parametrize("след", ["chrome_profile", "daemon_token"])
def test_следы_рядом_с_кодом_не_влияют_на_state(след, tmp_path, чужой_каталог):
    """Есть след установки рядом с кодом, GARANT_HOME не задана.

    Раньше это означало «установка портативная» и STATE оставался в HOME.
    Решением 14 эвристика удалена: STATE обязан остаться каталогом данных
    ОС независимо от того, что лежит рядом с кодом.
    """
    пакет = _песочница(tmp_path)
    if след == "chrome_profile":
        (пакет / след).mkdir()
    else:
        (пакет / след).write_text("проба", encoding="utf-8")

    данные = _состояние(пакет, чужой_каталог)
    assert данные["STATE"] == данные["эталон"], (
        "рядом с кодом лежит {}, но понятие «портативной установки» "
        "удалено решением 14 — STATE обязан быть каталогом данных ОС, "
        "а не папкой кода.".format(след)
    )
    assert данные["STATE"] != данные["HOME"]


def test_чистая_установка_уходит_в_каталог_данных_ОС(tmp_path, чужой_каталог):
    """HOME пуст, GARANT_HOME не задана -> STATE = user_data_dir."""
    пакет = _песочница(tmp_path)
    данные = _состояние(пакет, чужой_каталог)
    assert данные["STATE"] == данные["эталон"], (
        "на чистой установке STATE обязан быть каталогом данных ОС "
        "(platformdirs.user_data_dir), а не папкой кода: под pip/uvx каталог "
        "кода доступен только на чтение либо стирается между запусками."
    )
    assert данные["STATE"] != данные["HOME"]


def test_GARANT_HOME_сильнее_следов_рядом_с_кодом(tmp_path, чужой_каталог):
    """Явно заданная переменная побеждает и след установки, и умолчание."""
    пакет = _песочница(tmp_path)
    (пакет / "chrome_profile").mkdir()          # след прежней «портативности»
    состояние = tmp_path / "явное состояние"
    данные = _состояние(пакет, чужой_каталог, {"GARANT_HOME": str(состояние)})
    assert данные["STATE"] == str(состояние)


# --------------------------------------------------------------------------
#  6. модули не расходятся в путях к общим файлам
# --------------------------------------------------------------------------
#
#  Отдельный класс поломки, который пункт 4 не ловит: paths.py есть и верен,
#  но модуль к нему не подключён и считает путь сам. Тогда один файл пишет
#  туда, другой читает отсюда, и это молчит ровно до тех пор, пока
#  STATE == HOME. У решения 14 таких совпадений больше нет вовсе — оно
#  расходится у ПЕРВОГО же пользователя.
#
#  Проверка намеренно не перечисляет known-bad пары: она сверяет ВСЕ
#  модульные константы-пути по имени файла. Два модуля, назвавшие путь
#  одинаково («daemon_token», «storage_state.json», «chrome_profile»),
#  обязаны указывать в одно место — иначе один пишет мимо другого.

СВЯЗКА = ["client", "daemon_client", "daemon", "fingerprint"]


def _пути_модулей(пакет, cwd, доп=None):
    """Модульные константы типа Path из каждого модуля связки — одним процессом.

    Один процесс, а не четыре: расхождение видно только при сравнении, а
    сравнивать надо значения, полученные при одинаковом окружении.
    """
    код = (
        "import sys, json, importlib\n"
        "from pathlib import Path\n"
        "sys.path.insert(0, r'{site}')\n"
        "out = {{}}\n"
        "for имя in {модули}:\n"
        "    m = importlib.import_module('garant_mcp.' + имя)\n"
        "    out[имя] = {{k: str(v) for k, v in vars(m).items()\n"
        "                if isinstance(v, Path)}}\n"
        "print(json.dumps(out))\n"
    ).format(site=пакет.parent, модули=СВЯЗКА)
    r = _запуск(код, cwd, доп, таймаут=120)
    assert r.returncode == 0, (
        "связка модулей не импортируется:\n" + r.stderr.strip())
    return json.loads(r.stdout.strip())


def test_модули_не_расходятся_в_общих_путях(tmp_path, чужой_каталог):
    """GARANT_HOME задан НАРОЧНО отличным от каталога кода: пока STATE == HOME,
    расхождение не проявляется вовсе.
    """
    for модуль in СВЯЗКА:
        _пропустить_если_нет_зависимости(модуль)

    пакет = _песочница(tmp_path)
    состояние = tmp_path / "состояние"
    данные = _пути_модулей(пакет, чужой_каталог,
                           {"GARANT_HOME": str(состояние)})

    по_имени: dict[str, dict[str, list[str]]] = {}
    for модуль, константы in данные.items():
        for имя_константы, путь in константы.items():
            имя_файла = Path(путь).name
            по_имени.setdefault(имя_файла, {}).setdefault(путь, []).append(
                "{}.{}".format(модуль, имя_константы))

    расхождения = []
    for имя_файла, варианты in sorted(по_имени.items()):
        if len(варианты) > 1:
            расхождения.append("  «{}»:\n{}".format(
                имя_файла,
                "\n".join("    {} <- {}".format(п, ", ".join(кто))
                          for п, кто in sorted(варианты.items()))))

    assert not расхождения, (
        "модули указывают на разные места для одного и того же файла:\n"
        + "\n".join(расхождения)
        + "\n\nПишущий и читающий обязаны брать путь из paths.py."
    )


def test_модули_не_расходятся_в_порту(tmp_path, чужой_каталог):
    """Порт был константой в двух Python-файлах. Модуль, оставшийся вне слоя
    настроек, ведёт себя ровно как daemon_client с токеном раньше: демон
    садится на GARANT_PORT, клиент продолжает стучаться в 8787.
    """
    пакет = _песочница(tmp_path)
    состояние = tmp_path / "состояние"
    код = (
        "import sys, json\n"
        "sys.path.insert(0, r'{site}')\n"
        "import garant_mcp.config as config\n"
        "import garant_mcp.daemon as daemon\n"
        "import garant_mcp.daemon_client as daemon_client\n"
        "print(json.dumps({{'config': config.PORT,\n"
        "                   'daemon': daemon.DEFAULT_PORT,\n"
        "                   'daemon_client': daemon_client.PORT}}))\n"
    ).format(site=пакет.parent)
    # GARANT_HOME задан нарочно, во временный каталог: импорт daemon.py без
    # него молча падает на каталог данных ОС владельца этой машины — здесь
    # меряется только совпадение портов между модулями, а не куда указывает
    # состояние, но зависимость от машины запускающего в этой проверке
    # не нужна и структурно неверна.
    r = _запуск(код, чужой_каталог,
                {"GARANT_PORT": "8799", "GARANT_HOME": str(состояние)},
                таймаут=120)
    assert r.returncode == 0, r.stderr.strip()
    порты = json.loads(r.stdout.strip())
    assert set(порты.values()) == {8799}, (
        "модули разошлись в порту: {}. Порт обязан приходить из config.py "
        "всем одинаково — иначе демон слушает один порт, а клиент стучится "
        "в другой.".format(порты)
    )
