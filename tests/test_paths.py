@pytest.mark.parametrize("модуль", MODULES)
def test_импорт_из_чужого_каталога(модуль, tmp_path, чужой_каталог):
    _пропустить_если_нет_зависимости(модуль)
    пакет = _песочница(tmp_path)
    r = _импорт(модуль, пакет, чужой_каталог)
    assert r.returncode == 0, (
        "garant_mcp.{} не импортируется из каталога {}:\n{}".format(
            модуль, чужой_каталог, r.stderr.strip())
    )


