# -*- coding: utf-8 -*-
"""Обвязка под развязку путей (этап 01, шаг 0 → перенос на пакет, этап 02).

Полноценные тесты клиента — отдельный этап. Здесь минимум, который делает
безопасным именно рефакторинг путей, и ничего сверх: живой подписки в этой
среде нет, сеть к «Гаранту» не проверяется вообще.

Код теперь — установленный по форме пакет `garant_mcp` в `src/garant_mcp`,
`sys.path` внутри него не трогают, импорты внутри пакета относительные.
Тесты НЕ ставят пакет через pip: каждая проверка копирует `src/garant_mcp`
в свежий каталог и подключает его родителя через `sys.path.insert` в
ПОДПРОЦЕССЕ. Это то же самое, что видит второй экземпляр кода на диске
(что и требуется для проверки побочных эффектов и путей), но не то же
самое, что видит `pip install -e .` — .pth-файл или консольный скрипт этим
не проверяются. Раз проверяемое здесь — расположение и импортируемость
кода, а не механика упаковки, этого достаточно, а точки входа
(`garant`, `garant-mcp`, `garant-daemon`) — вопрос отдельной проверки,
которой в этом наряде нет.

Проверяется ровно то, что ломается именно при развязке путей:

1. Модули импортируются из ЧУЖОГО рабочего каталога. Скрипты писались под
   плоскую папку, где всё лежало рядом; запуск не из своего каталога —
   первое, что отваливается.
2. Импорт не создаёт каталогов на файловой системе. На установке через
   pip/uvx каталог кода доступен только на чтение — там это исключение
   при импорте, а пользователь увидит невнятное «сервер не запустился».
3. Приоритет конфигурации: env перекрывает endpoints.json, endpoints.json
   перекрывает умолчание.
4. paths.py — единственный источник истины о расположении.
5. `STATE` по умолчанию — каталог данных ОС, и следы рядом с кодом на этот
   выбор больше не влияют (решение 14): понятие «портативной установки»
   удалено. `GARANT_HOME` по-прежнему единственный способ переопределить
   `STATE`.

Каждый импорт исполняется в отдельном процессе: импорт кэшируется, и второй
раз побочных эффектов уже не будет — в одном процессе пункт 2 не измерить.
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
PKG_SRC = SRC / "garant_mcp"

# Модули, которые обязаны импортироваться из любого каталога.
# `garant_client` переименован в `client` при переносе на пакет.
# `auth_login` удалён решением 15 (вход выполняет демон, отдельного процесса
# входа больше нет); вместо него — новые модули этапа 02: `fingerprint`
# (отпечаток браузера, решение 16) и `protocol` (договор демон/клиент,
# ошибка с типом). Для `fingerprint` пункт 2 («импорт не создаёт каталогов»)
# особенно важен: модуль умеет запускать браузер (`снять()`), и запуск
# playwright на импорте был бы худшим видом побочного эффекта — там
# специально сказано, что это делает только явный вызов, не импорт.
MODULES = ["client", "daemon_client", "daemon", "server", "fingerprint",
           "protocol"]

# Что модулю нужно снаружи, чтобы вообще импортироваться. Если этого нет,
# тест пропускается с явной причиной, а не падает так, будто сломаны пути.
#
# Проверяется РОВНО та строка импорта, которая стоит в коде, а не имя пакета:
# `import mcp` проходит и на mcp 2.x, где FastMCP переименован в MCPServer, —
# и тогда server.py падает по причине, к путям отношения не имеющей.
# pyproject.toml не зря пишет `mcp>=1.2,<2`.
THIRD_PARTY = {
    "server": "from mcp.server.fastmcp import FastMCP",
}

# Переменные контура снимаются перед каждым запуском: на рабочей машине
# GARANT_HOME прописана установщиком, и тест приоритета читал бы её вместо
# того, что задаёт сам.
#
# Единственный источник: раньше тот же кортеж был скопирован в
# tests/test_bridge.py буквально, и совпадение двух копий ничем не было
# гарантировано (найдено 05.09.2026). test_bridge.py и test_config.py
# импортируют его отсюда.
ENV_КОНТУРА = ("GARANT_HOME", "GARANT_PY", "GARANT_PORT",
               "GARANT_KEEPALIVE_SEC", "GARANT_HEADLESS",
               "GARANT_BRIDGE", "GARANT_CALL_TIMEOUT")


