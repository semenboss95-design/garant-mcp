def _импорт_проходит(строка):
    """Отдельным процессом, потому что find_spec недостаточно.

    find_spec находит файл, не исполняя его. mcp 2.x кладёт на месте
    fastmcp.py заглушку, которая возбуждает ModuleNotFoundError в теле
    модуля, — find_spec это пропустит, а импорт упадёт.
    """
    r = subprocess.run(
        [sys.executable, "-c", строка],
        capture_output=True, text=True, encoding="utf-8",
        errors="replace", timeout=120,
    )
    return r.returncode == 0, r.stderr.strip().splitlines()[-1:] or [""]


def _песочница(куда):
    """Копия `garant_mcp` в чистый каталог, в форме пакета.

    Возвращается путь к КОПИИ ПАКЕТА (каталог `garant_mcp`), а не к его
    родителю: так вызывающему коду не нужно помнить, что копируется пакет,
    а не плоский набор модулей. Родитель для sys.path — `.parent` от
    возвращённого пути.

    Копия, а не оригинал: часть тестов меряет появление каталогов, а
    в оригинале cache/ и logs/ могли остаться от прошлого запуска — тогда
    mkdir сработает вхолостую и тест пройдёт по случайности.
    """
    пакет = куда / "site" / "garant_mcp"
    пакет.mkdir(parents=True)
    for f in PKG_SRC.iterdir():
        if f.is_file() and f.suffix in (".py", ".json", ".txt"):
            shutil.copy2(f, пакет / f.name)
    return пакет


def _каталоги(корень):
    if not корень.exists():
        return set()
    return {
        str(p.relative_to(корень))
        for p in корень.rglob("*")
        if p.is_dir() and "__pycache__" not in p.parts
    }


def _окружение(доп=None):
    e = dict(os.environ)
    for k in ENV_КОНТУРА:
        e.pop(k, None)
    e["PYTHONDONTWRITEBYTECODE"] = "1"
    e["PYTHONIOENCODING"] = "utf-8"
    if доп:
        e.update(доп)
    return e


def _запуск(код, cwd, доп=None, таймаут=120):
    return subprocess.run(
        [sys.executable, "-c", код],
        cwd=str(cwd),
        env=_окружение(доп),
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        timeout=таймаут,
    )


def _импорт(модуль, пакет, cwd, доп=None):
    код = (
        "import sys\n"
        "sys.path.insert(0, r'{site}')\n"
        "import garant_mcp.{модуль} as m\n"
        "print('OK', m.__file__)\n"
    ).format(site=пакет.parent, модуль=модуль)
    return _запуск(код, cwd, доп)


def _пропустить_если_нет_зависимости(модуль):
    строка = THIRD_PARTY.get(модуль)
    if not строка:
        return
    ок, причина = _импорт_проходит(строка)
    if not ок:
        pytest.skip(
            "среда не даёт «{}» — импорт {} не проверить. Причина: {}. "
            "Это не про пути: нужен интерпретатор с зависимостями из "
            "pyproject.toml.".format(строка, модуль, причина[0])
        )


@pytest.fixture
def чужой_каталог(tmp_path):
    """Рабочий каталог с пробелом и кириллицей — как в критерии приёмки."""
    d = tmp_path / "чужой каталог"
    d.mkdir()
    return d


