def _задать_секцию_daemon(пакет, секция):
    f = пакет / "endpoints.json"
    cfg = json.loads(f.read_text(encoding="utf-8"))
    if секция is None:
        cfg.pop("daemon", None)
    else:
        cfg["daemon"] = секция
    f.write_text(json.dumps(cfg, ensure_ascii=False, indent=2),
                 encoding="utf-8")


def _порт(пакет, cwd, доп=None):
    код = (
        "import sys\n"
        "sys.path.insert(0, r'{site}')\n"
        "import garant_mcp.config as config\n"
        "print(config.PORT)\n"
    ).format(site=пакет.parent)
    r = _запуск(код, cwd, доп, таймаут=60)
    assert r.returncode == 0, (
        "garant_mcp.config.PORT не читается:\n" + r.stderr.strip()
    )
    return r.stdout.strip()


def test_приоритет_умолчание(tmp_path, чужой_каталог):
    """Без env и без секции daemon в endpoints.json — умолчание 8787."""
    пакет = _песочница(tmp_path)
    _задать_секцию_daemon(пакет, None)
    assert _порт(пакет, чужой_каталог) == "8787"


def test_приоритет_json_перекрывает_умолчание(tmp_path, чужой_каталог):
    пакет = _песочница(tmp_path)
    _задать_секцию_daemon(пакет, {"port": 8791})
    assert _порт(пакет, чужой_каталог) == "8791"


def test_приоритет_env_перекрывает_json(tmp_path, чужой_каталог):
    """Главный из трёх: настройка машины побеждает файл из репозитория."""
    пакет = _песочница(tmp_path)
    _задать_секцию_daemon(пакет, {"port": 8791})
    assert _порт(пакет, чужой_каталог, {"GARANT_PORT": "8799"}) == "8799"


