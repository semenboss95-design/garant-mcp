#  2. импорт не создаёт каталогов
# --------------------------------------------------------------------------

@pytest.mark.parametrize("модуль", MODULES)
def test_импорт_не_создаёт_каталогов(модуль, tmp_path, чужой_каталог):
    _пропустить_если_нет_зависимости(модуль)

    пакет = _песочница(tmp_path)
    состояние = tmp_path / "состояние"   # намеренно не создаём: ensure_state()
    до = _каталоги(пакет)                # ещё никто не звал

    r = _импорт(модуль, пакет, чужой_каталог, {"GARANT_HOME": str(состояние)})
    assert r.returncode == 0, "garant_mcp.{} не импортировался:\n{}".format(
        модуль, r.stderr.strip())

    появилось = _каталоги(пакет) - до
    assert not появилось, (
        "импорт garant_mcp.{} создал каталоги рядом с кодом: {}. На установке "
        "через pip/uvx каталог кода доступен только на чтение — там это "
        "исключение при импорте. Создание каталогов должно жить в "
        "ensure_state(), вызываемой явно из main().".format(модуль, sorted(появилось))
    )
    assert not состояние.exists(), (
        "импорт garant_mcp.{} создал GARANT_HOME ({}). Импорт обязан проходить "
        "без побочных эффектов на файловой системе.".format(модуль, состояние)
    )


