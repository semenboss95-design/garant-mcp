"""Обвязка под выбор порта (этап 01, шаг 3).

Шаг 3 — единственный на этапе, который делает разрушительную операцию
безопасной, и единственный, который трогает и Python, и PowerShell. Поэтому
тесты здесь поднимают НАСТОЯЩИЙ демон подпроцессом, а не изображают его.

Браузер при этом не запускается, и это не случайность: в песочнице нет
профиля, а `_ensure_client` до импорта Playwright не доходит — падает раньше,
на проверке «профиля браузера нет». Демон при этом продолжает обслуживать
HTTP, то есть ровно то, что здесь и проверяется.

Четыре свойства, и цена у них разная:

1. `daemon_port` содержит фактический порт и PID и появляется целиком.
   Без PID нечего убивать, кроме как «всех на порту N», — а это убийство
   постороннего процесса.
2. Клиент на протухшем `daemon_port` не отправляет `X-Token`. Это утечка
   секрета, а не неудобство: демон умер, порт занял кто угодно локальный,
   и токен от живой подписки уходит ему.
3. Занятый порт — демон садится на соседний, а не падает.
4. Порт занят НАШИМ демоном — второй экземпляр выходит кодом 0, а не
   плодит второго владельца профиля (ограничение 2).

Все четыре ОБЯЗАНЫ падать до шага 3.

Чего эти тесты не проверяют и проверить не могут: настоящую гонку двух
процессов за один порт, поведение при падении демона посреди вызова
и keepalive — для последнего нужна живая подписка, которой в этой среде нет.
"""

