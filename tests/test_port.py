def test_занятый_порт_демон_берёт_соседний(стенд):
    порт = _свободный_порт()
    стенд.занять(порт)                      # немой слушатель, не наш демон

    p = стенд.демон({"GARANT_PORT": str(порт)})
    данные = _дождаться_порта(стенд.состояние, p)

    assert данные["порт"] != порт, (
        "порт {} занят, а демон объявил, что сел на него".format(порт))
    assert порт < данные["порт"] <= порт + 10, (
        "демон обязан перебирать ограниченный диапазон (11 портов от "
        "заданного), получено {}".format(данные["порт"]))


def test_исчерпание_диапазона_даёт_внятную_ошибку(стенд):
    """Все 11 портов заняты — демон обязан сказать, что именно кончилось."""
    порт = _свободный_порт()
    for сдвиг in range(11):
        try:
            стенд.занять(порт + сдвиг)
        except OSError:
            pytest.skip("порт {} занят снаружи — диапазон не выстроить"
                        .format(порт + сдвиг))

    p = стенд.демон({"GARANT_PORT": str(порт)})
    try:
        p.wait(timeout=ЖДАТЬ_СЕК)
    except subprocess.TimeoutExpired:
        p.kill()
        pytest.fail("демон не завершился, хотя весь диапазон занят")
    вывод = p.stdout.read() if p.stdout else ""
    assert p.returncode != 0, (
        "исчерпание диапазона — это отказ, а не успех:\n" + вывод)
    assert str(порт) in вывод and str(порт + 10) in вывод, (
        "в сообщении должен быть перебранный диапазон, чтобы человек понял, "
        "что освобождать:\n" + вывод)


# --------------------------------------------------------------------------
#  4. порт занят НАШИМ демоном — второй экземпляр выходит кодом 0
# --------------------------------------------------------------------------

def test_второй_экземпляр_выходит_кодом_ноль(стенд):
    """Ограничение 2: один профиль = один процесс.

    Код 0, а не ошибка, потому что запуск уже запущенного демона — это
    не сбой: желаемое состояние достигнуто. Планировщик и ярлык, увидев
    ненулевой код, начнут его чинить.
    """
    порт = _свободный_порт()
    первый = стенд.демон({"GARANT_PORT": str(порт)})
    данные = _дождаться_порта(стенд.состояние, первый)

    второй = стенд.демон({"GARANT_PORT": str(данные["порт"])})
    try:
        второй.wait(timeout=ЖДАТЬ_СЕК)
    except subprocess.TimeoutExpired:
        второй.kill()
        pytest.fail("второй экземпляр не вышел — он занял соседний порт "
                    "и стал вторым владельцем профиля")
    вывод = второй.stdout.read() if второй.stdout else ""
    assert второй.returncode == 0, (
        "второй экземпляр обязан выйти кодом 0: демон уже работает, это "
        "не сбой. Получено {}:\n{}".format(второй.returncode, вывод))
    assert str(данные["порт"]) in вывод, (
        "второй экземпляр обязан назвать порт работающего демона:\n" + вывод)

    assert первый.poll() is None, "первый демон не должен был пострадать"
    после = json.loads((стенд.состояние / "daemon_port").read_text(encoding="utf-8"))
    assert после == данные, (
        "второй экземпляр переписал daemon_port работающего демона: было {}, "
        "стало {}. Тогда клиент пойдёт на порт мертвеца.".format(данные, после))


# --------------------------------------------------------------------------
#  5. признак демона — один объект, а не три одинаковых литерала
# --------------------------------------------------------------------------

def test_признак_демона_один_у_демона_и_клиента(стенд):
    """Демон и клиент обязаны искать в /health одно и то же слово.

    Проверяются обе половины, и вторая важнее первой.

    Первая — что константы совпадают. Пока признак берётся из общего
    модуля, она не может не совпасть, и её задача — заметить возвращение
    второго независимого литерала.

    Вторая — что демон и правда кладёт этот признак в живой ответ. Именно
    здесь и жил третий литерал: ключ в теле /health был написан строкой,
    мимо константы. Сравнение двух констант между собой такого не видит —
    обе согласны, а демон себя не опознаёт.
    """
    код = (
        "import sys, json\n"
        "sys.path.insert(0, r'{site}')\n"
        "import garant_mcp.protocol as protocol\n"
        "import garant_mcp.daemon_client as daemon_client\n"
        "print(json.dumps({{'protocol': protocol.ПРИЗНАК_ДЕМОНА,\n"
        "                  'client': daemon_client.ПРИЗНАК_ДЕМОНА}},\n"
        "                 ensure_ascii=False))\n"
    ).format(site=стенд.пакет.parent)
    r = _запуск(код, стенд.состояние.parent,
                {"GARANT_HOME": str(стенд.состояние)}, таймаут=60)
    строка = [s for s in (r.stdout or "").splitlines() if s.startswith("{")]
    assert строка, "не удалось прочитать признаки:\n" + r.stdout + r.stderr
    признаки = json.loads(строка[-1])
    assert признаки["client"] == признаки["protocol"], (
        "клиент ищет в /health {client!r}, а договор — {protocol!r}. "
        "Клиент объявит собственный демон посторонним и откажется "
        "работать.".format(**признаки))

    порт = _свободный_порт()
    p = стенд.демон({"GARANT_PORT": str(порт)})
    данные = _дождаться_порта(стенд.состояние, p)
    with urllib.request.urlopen(
            "http://127.0.0.1:{}/health".format(данные["порт"]), timeout=10) as о:
        тело = json.loads(о.read().decode("utf-8"))
    assert признаки["protocol"] in тело, (
        "живой демон не кладёт признак {!r} в тело /health: {}. Клиент "
        "опознаёт демон именно по этому телу — значит, не опознает."
        .format(признаки["protocol"], sorted(тело)))
