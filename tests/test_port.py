def _свободный_порт() -> int:
    """Порт, который сейчас свободен.

    Гарантии, что он останется свободным, нет и быть не может — ровно
    поэтому демон биндится, а не проверяет заранее. Здесь этого достаточно:
    цена промаха — перезапуск теста, а не потерянная сессия.
    """
    s = socket.socket()
    s.bind(("127.0.0.1", 0))
    порт = s.getsockname()[1]
    s.close()
    return порт


def _порт_слушается(порт: int, таймаут: float = 1.0) -> bool:
    """Отвечает ли что-нибудь на TCP-подключение к порту прямо сейчас."""
    s = socket.socket()
    s.settimeout(таймаут)
    try:
        s.connect(("127.0.0.1", порт))
        return True
    except OSError:
        return False
    finally:
        s.close()


def _убить_по_pid(pid: int) -> None:
    """Жёстко убить процесс с ИМЕННО этим PID, деревом.

    Не `Popen.kill()`: тот бьёт по процессу, который завела `subprocess`
    (`Popen.pid`). В установке через venv-заглушку (например, `uv tool
    install`) `python.exe`, которого запускает `Popen`, — перенаправляющий
    процесс, а настоящий интерпретатор, вызывающий `os.getpid()` внутри
    демона и пишущий его в `daemon_port`, — её РЕБЁНОК с другим PID.
    `Popen.kill()` в этом случае убивает заглушку и оставляет держателя
    порта и замка профиля живым — ровно то, что должен ловить тест, а не
    прятать. Поэтому убиваем PID из `daemon_port` напрямую и деревом
    (`/T /F` на Windows), чтобы вместе с ним умер и потомок, если PID
    сам оказался обёрткой.
    """
    if os.name == "nt":
        subprocess.run(["taskkill", "/PID", str(pid), "/T", "/F"],
                       capture_output=True, text=True, timeout=30)
    else:
        try:
            os.kill(pid, signal.SIGKILL)
        except OSError:
            pass


class _Занятый:
    """Сокет, который слушает порт и на HTTP не отвечает.

    Именно немой слушатель, а не HTTP-сервер: так выглядит чужая программа,
    случайно занявшая порт демона.
    """

    def __init__(self, порт: int):
        self.s = socket.socket()
        self.s.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
        self.s.bind(("127.0.0.1", порт))
        self.s.listen(5)

    def close(self):
        try:
            self.s.close()
        except OSError:
            pass


class _Самозванец:
    """HTTP-слушатель, отвечающий 200 на всё, но НЕ наш демон.

    Записывает заголовки каждого запроса — по ним и проверяется, ушёл ли
    токен. Тело ответа нарочно правдоподобное: проверка «наш ли демон»
    обязана смотреть на признак нашего демона, а не на «ответили ли вообще».
    """

    def __init__(self):
        самозванец = self
        самозванец.запросы: list[dict] = []

        class H(BaseHTTPRequestHandler):
            def log_message(self, *a):
                pass

            def _ответ(self):
                самозванец.запросы.append({
                    "путь": self.path,
                    "заголовки": {k.lower(): v for k, v in self.headers.items()},
                })
                тело = json.dumps({"ok": True, "status": "healthy"}).encode()
                self.send_response(200)
                self.send_header("Content-Type", "application/json")
                self.send_header("Content-Length", str(len(тело)))
                self.end_headers()
                self.wfile.write(тело)

            do_GET = _ответ
            do_POST = _ответ

        self.srv = ThreadingHTTPServer(("127.0.0.1", 0), H)
        self.порт = self.srv.server_address[1]
        threading.Thread(target=self.srv.serve_forever, daemon=True).start()

    def close(self):
        self.srv.shutdown()
        self.srv.server_close()

    @property
    def токены(self) -> list[str]:
        return [з["заголовки"]["x-token"] for з in self.запросы
                if "x-token" in з["заголовки"]]


def _поднять_демон(пакет: Path, состояние: Path, доп=None):
    """`python -m garant_mcp.daemon`, а не путь к файлу: пакет теперь модуль.

    `PYTHONPATH` указывает на родителя копии пакета (site/) — ровно то, что
    в остальных тестах вставляется в sys.path через `-c`; `-m` так делать
    не позволяет, путь ищется через переменную окружения.
    """
    return subprocess.Popen(
        [sys.executable, "-m", "garant_mcp.daemon"],
        cwd=str(состояние.parent),
        env=_окружение({"GARANT_HOME": str(состояние),
                        "PYTHONPATH": str(пакет.parent), **(доп or {})}),
        stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
        text=True, encoding="utf-8", errors="replace",
    )


def _дождаться_порта(состояние: Path, процесс, таймаут=ЖДАТЬ_СЕК) -> dict:
    """Ждёт появления daemon_port и возвращает его разобранное содержимое.

    Разбор при каждой попытке, а не однократно в конце, — это и есть
    проверка целостности: файл, записанный не атомарно, рано или поздно
    попадётся наполовину, и JSON на нём не разберётся.
    """
    f = состояние / "daemon_port"
    край = time.time() + таймаут
    while time.time() < край:
        if процесс.poll() is not None:
            pytest.fail("демон умер, не написав daemon_port:\n"
                        + (процесс.stdout.read() if процесс.stdout else ""))
        if f.exists():
            сырое = f.read_text(encoding="utf-8").strip()
            if сырое:
                try:
                    return json.loads(сырое)
                except ValueError:
                    pytest.fail(
                        "daemon_port прочитан наполовину: {!r}. Файл обязан "
                        "появляться целиком — временный файл рядом, затем "
                        "os.replace.".format(сырое))
        time.sleep(0.15)
    процесс.kill()
    pytest.fail("daemon_port не появился за {:.0f} с".format(таймаут))


@pytest.fixture
def стенд(tmp_path):
    """Песочница с кодом и пустой каталог состояния. Демоны гасятся сами."""
    пакет = _песочница(tmp_path)
    состояние = tmp_path / "состояние"
    состояние.mkdir()
    процессы: list = []
    сокеты: list = []

    class Стенд:
        def __init__(self):
            self.пакет = пакет
            self.состояние = состояние

        def демон(self, доп=None):
            p = _поднять_демон(пакет, состояние, доп)
            процессы.append(p)
            return p

        def занять(self, порт):
            з = _Занятый(порт)
            сокеты.append(з)
            return з

        def самозванец(self):
            с = _Самозванец()
            сокеты.append(с)
            return с

    yield Стенд()

    for p in процессы:
        if p.poll() is None:
            p.terminate()
            try:
                p.wait(timeout=10)
            except subprocess.TimeoutExpired:
                p.kill()
    for с in сокеты:
        с.close()


# --------------------------------------------------------------------------
#  1. daemon_port: фактический порт и PID, файл появляется целиком
# --------------------------------------------------------------------------

def test_daemon_port_содержит_порт_и_pid(стенд):
    порт = _свободный_порт()
    p = стенд.демон({"GARANT_PORT": str(порт)})
    данные = _дождаться_порта(стенд.состояние, p)

    assert данные.get("порт") == порт, (
        "daemon_port обязан содержать ФАКТИЧЕСКИЙ порт: {}".format(данные))

    pid = данные.get("pid")
    assert isinstance(pid, int) and pid > 0, (
        "daemon_port обязан содержать PID демона — иначе убивать нечего, "
        "кроме как «всех на порту N», а это убийство постороннего "
        "процесса. Получено: {}".format(данные))

    # Не сверяем pid с Popen.pid: это НЕ одно и то же по определению
    # лаунчера. В установке через venv-заглушку (`uv tool install` и
    # подобные) `python.exe`, которого завела `subprocess.Popen`, —
    # перенаправляющий процесс; настоящий интерпретатор — её ребёнок с
    # другим PID, и именно он вызывает `os.getpid()` внутри демона
    # (daemon.py) и пишет daemon_port. Совпадение Popen.pid и записанного
    # PID — случайность конкретной машины, а не гарантия лаунчера; тест,
    # требующий этого совпадения, красный на каждой установке через venv
    # и ничего при этом не проверяет про сам продукт.
    #
    # Настоящее свойство — то, что называет наряд: daemon_port описывает
    # процесс, который ДЕЙСТВИТЕЛЬНО держит порт (и тем самым замок
    # профиля). Проверяем это напрямую и разрушительно: убиваем ИМЕННО
    # записанный PID, деревом (иначе на Windows потомок-заглушка переживёт
    # родителя, и порт продолжит слушаться не из-за лжи в daemon_port,
    # а из-за способа убийства), и смотрим, что порт перестаёт отвечать.
    # Если daemon_port когда-нибудь начнёт называть чужой или мёртвый PID
    # (текущий владелец порта останется другим), порт продолжит слушаться,
    # и это и есть красный тест.
    assert _порт_слушается(порт), (
        "порт {} должен быть занят демоном перед проверкой его PID".format(порт))
    _убить_по_pid(pid)
    предел = time.time() + 15
    while time.time() < предел and _порт_слушается(порт, таймаут=0.3):
        time.sleep(0.2)
    assert not _порт_слушается(порт), (
        "PID {} записан в daemon_port как владелец порта {}, но после "
        "жёсткого убийства именно этого PID порт продолжает слушаться — "
        "daemon_port называет не того, кто на самом деле держит порт."
        .format(pid, порт))

    посторонние = [f.name for f in стенд.состояние.iterdir()
                   if f.name.startswith("daemon_port") and f.name != "daemon_port"]
    assert not посторонние, (
        "рядом остался временный файл {}: os.replace должен был его "
        "переименовать, а не оставить.".format(посторонние))


def test_daemon_port_пишется_после_бинда(стенд):
    """Порт из файла обязан реально слушаться — значит, бинд был раньше записи."""
    порт = _свободный_порт()
    p = стенд.демон({"GARANT_PORT": str(порт)})
    данные = _дождаться_порта(стенд.состояние, p)

    s = socket.socket()
    s.settimeout(5)
    try:
        s.connect(("127.0.0.1", данные["порт"]))
    except OSError as e:
        pytest.fail(
            "порт {} записан в daemon_port, но никто его не слушает ({}). "
            "Запись обязана идти ПОСЛЕ успешного бинда, иначе клиент "
            "уходит на порт, которого нет.".format(данные["порт"], e))
    finally:
        s.close()


