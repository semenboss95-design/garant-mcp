def test_клиент_не_шлёт_токен_постороннему(стенд):
    """Утечка секрета, а не неудобство.

    Демон умер, порт занял кто-то другой, `daemon_port` остался прежним.
    Клиент, добавляющий X-Token всякому, кто ответил, отдаёт токен от живой
    подписки случайному локальному слушателю.
    """
    чужой = стенд.самозванец()
    (стенд.состояние / "daemon_port").write_text(
        json.dumps({"порт": чужой.порт, "pid": 999999}), encoding="utf-8")
    # Токен ASCII, как настоящий (secrets.token_urlsafe). Кириллица здесь
    # ломала бы запрос на кодировании заголовка в latin-1 — и тест проходил
    # бы, ничего не проверив: утечки нет, потому что и запроса нет.
    (стенд.состояние / "daemon_token").write_text(
        ТОКЕН_КАНАРЕЙКА, encoding="utf-8")

    код = (
        "import sys\n"
        "sys.path.insert(0, r'{site}')\n"
        "import garant_mcp.daemon_client as daemon_client\n"
        "for вызов in (lambda: daemon_client.health(),\n"
        "              lambda: daemon_client.call('search', query='проба')):\n"
        "    try:\n"
        "        вызов()\n"
        "    except Exception as e:\n"
        "        print(type(e).__name__, e)\n"
    ).format(site=стенд.пакет.parent)
    _запуск(код, стенд.состояние.parent,
            {"GARANT_HOME": str(стенд.состояние)}, таймаут=120)

    # Сначала — что клиент вообще ДОШЁЛ до порта из daemon_port. Без этой
    # проверки тест зелен и на клиенте, который daemon_port не читает вовсе:
    # запроса нет, значит и утечки нет. Это и есть нынешнее состояние.
    assert чужой.запросы, (
        "клиент не обратился к порту из daemon_port ({}) — значит, он этот "
        "файл не читает и ходит на порт из конфигурации. Тогда после "
        "перезапуска демона на соседнем порту клиент не найдёт его вовсе."
        .format(чужой.порт))

    assert not чужой.токены, (
        "клиент отправил X-Token постороннему слушателю: {}. Прежде чем "
        "слать токен, клиент обязан сходить на GET /health (он токена не "
        "требует) и убедиться, что на порту наш демон.".format(чужой.токены)
    )


def test_клиент_видит_что_на_порту_не_наш_демон(стенд):
    """Ошибка обязана быть про подмену, а не про формат ответа."""
    чужой = стенд.самозванец()
    (стенд.состояние / "daemon_port").write_text(
        json.dumps({"порт": чужой.порт, "pid": 999999}), encoding="utf-8")
    (стенд.состояние / "daemon_token").write_text(ТОКЕН_КАНАРЕЙКА, encoding="utf-8")

    код = (
        "import sys\n"
        "sys.path.insert(0, r'{site}')\n"
        "import garant_mcp.daemon_client as daemon_client\n"
        "try:\n"
        "    daemon_client.call('search', query='проба')\n"
        "    print('НЕ УПАЛО')\n"
        "except daemon_client.DaemonError as e:\n"
        "    print('DaemonError:', e)\n"
    ).format(site=стенд.пакет.parent)
    r = _запуск(код, стенд.состояние.parent,
                {"GARANT_HOME": str(стенд.состояние)}, таймаут=120)
    # Сначала — что клиент вообще ДОШЁЛ до порта из daemon_port. Без этой
    # проверки тест зелен и на клиенте, который daemon_port не читает вовсе:
    # запроса нет, значит и утечки нет. Это и есть нынешнее состояние.
    assert чужой.запросы, (
        "клиент не обратился к порту из daemon_port ({}) — значит, он этот "
        "файл не читает и ходит на порт из конфигурации. Тогда после "
        "перезапуска демона на соседнем порту клиент не найдёт его вовсе."
        .format(чужой.порт))

    вывод = (r.stdout + r.stderr)
    assert "НЕ УПАЛО" not in вывод, (
        "клиент принял ответ постороннего слушателя за ответ демона:\n" + вывод)
    assert "DaemonError" in вывод, (
        "ожидалась внятная DaemonError про чужого на порту, получено:\n" + вывод)


