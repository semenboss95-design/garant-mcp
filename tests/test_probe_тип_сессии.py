"""Д-7 аудита: `except` внутри `_probe` (daemon.py:256-264) ставит
«недействительна» ТОЛЬКО при типе ошибки `ТИП_СЕССИЯ` — таймаут и прочие
сетевые сбои состояния сессии трогать не должны.

Существующие тесты демона идут через рабочий цикл целиком (HTTP-обвязка,
подъём браузера в песочнице падает раньше `_probe`) и этот `except` не
задевают вовсе. Здесь — прямой вызов `BrowserWorker._probe()` на
инстансе, у которого `_ensure_client` и `client.kinds` подменены: конструктор
`BrowserWorker` браузер не поднимает (поток не запущен, только словарь
состояния), поэтому подмена безопасна и не изображает окружающий цикл.

Дефект, который ловит этот тест: до Д-7 (или после регрессии) `_probe`
объявлял сессию недействительной по ЛЮБОМУ исключению — ровно та ошибка,
из-за которой временная сетевая заминка выглядела как «выйдите заново».

Д-В1 фазы B (08.09.2026, независимая проверка чистоты машины): прежняя
версия этого файла вызывала `import garant_mcp.daemon as daemon` ПРЯМО
В ПРОЦЕССЕ pytest, без `GARANT_HOME`. `daemon.py:129` привязывает
`RotatingFileHandler(..., delay=True)` к `paths.log_dir`, вычисленному в
момент импорта из окружения ЭТОГО процесса — то есть к настоящему
каталогу состояния ОС разработчика, раз `GARANT_HOME` в среде pytest не
выставлена. `delay=True` прячет открытие файла до первой записи, но
`test_тип_сессия_объявляет_сессию_недействительной` как раз доводит
`_probe()` до `_set_session(False, …)`, а та — до `log.warning("СЕССИЯ:
недействительна…")`: строка дописывалась во владельческий
`logs/daemon.log` на каждый прогон `pytest tests/`. Исправлено переносом
в подпроцесс — по образцу `tests/test_демон_честность_сессии.py`: демон
импортируется там под собственным `GARANT_HOME` во временном каталоге,
и до владельческого состояния не дотягивается вовсе. Три проверяемых
свойства и все тексты ассертов сохранены дословно — изменился только
процесс, в котором они выполняются.
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src"

# Один подпроцесс на все три сценария этого файла: `_probe()` вызывается
# СИНХРОННО на созданном (но не запущенном) `BrowserWorker` — как в
# исходном in-process тесте, поток-владелец браузера здесь не нужен вовсе
# (в отличие от `test_демон_честность_сессии.py`, где сценарии идут через
# очередь `submit()` и требуют живого потока).
_СКРИПТ = r'''
import sys, json
sys.path.insert(0, r"{site}")
import garant_mcp.paths as paths
paths.ensure_state()
import garant_mcp.daemon as daemon
protocol = daemon.protocol


class _КлиентБросающий:
    def __init__(self, exc):
        self._exc = exc

    def kinds(self, node_id):
        raise self._exc


def _воркер(exc):
    w = daemon.BrowserWorker()
    w._ensure_client = lambda: None   # браузер не поднимаем — не наш предмет
    w.client = _КлиентБросающий(exc)
    # Сессия ранее подтверждена живой — ключевое условие: тест ловит именно
    # НЕПРАВОМЕРНУЮ порчу этого состояния чужим типом ошибки.
    w.state["сессия"] = "жива"
    w.state["сессия_жива_с"] = "2026-01-01T00:00:00"
    return w


def _прогнать(exc):
    w = _воркер(exc)
    поймано = None
    try:
        w._probe()
    except protocol.GarantError as e:
        поймано = e.тип
    return {{
        "поймано_тип": поймано,
        "сессия": w.state["сессия"],
        "сессия_жива_с": w.state["сессия_жива_с"],
        "последняя_ошибка": w.state.get("последняя_ошибка"),
    }}


РЕЗУЛЬТАТ = {{
    "таймаут": _прогнать(
        protocol.GarantError("не дождались ответа", protocol.ТИП_ТАЙМАУТ)),
    "api": _прогнать(
        protocol.GarantError("незнакомая форма ответа", protocol.ТИП_API)),
    "session": _прогнать(
        protocol.GarantError("сервер ответил 403 дважды",
                             protocol.ТИП_СЕССИЯ, 403)),
}}

print(json.dumps(РЕЗУЛЬТАТ, ensure_ascii=False))
'''


def _выполнить(состояние: Path) -> dict:
    import os

    r = subprocess.run(
        [sys.executable, "-c", _СКРИПТ.format(site=str(SRC))],
        cwd=str(состояние.parent),
        env={"GARANT_HOME": str(состояние), "PATH": os.environ.get("PATH", ""),
             "PYTHONIOENCODING": "utf-8"},
        capture_output=True, text=True, encoding="utf-8", errors="replace",
        timeout=60,
    )
    assert r.returncode == 0, (
        "сценарий _probe() упал:\n" + r.stdout + r.stderr)
    строки = [s for s in r.stdout.strip().splitlines() if s.startswith("{")]
    assert строки, "не удалось прочитать результат:\n" + r.stdout + r.stderr
    return json.loads(строки[-1])


@pytest.fixture(scope="module")
def р(tmp_path_factory) -> dict:
    состояние = tmp_path_factory.mktemp("состояние")
    return _выполнить(состояние)


def test_таймаут_не_объявляет_сессию_недействительной(р):
    исход = р["таймаут"]

    assert исход["поймано_тип"] == "timeout", (
        "_probe() обязан пробросить ошибку таймаута, а не проглотить её")
    assert исход["сессия"] == "жива", (
        "таймаут — не приговор сессии: `_probe` обязан пробросить ошибку, "
        "не трогая state['сессия']. Получено: {!r}".format(исход["сессия"]))
    assert исход["сессия_жива_с"] == "2026-01-01T00:00:00", (
        "отметка времени живой сессии не должна сбрасываться таймаутом")
    assert исход["последняя_ошибка"], (
        "ошибка обязана попасть в диагностику демона, даже не будучи "
        "приговором сессии")


def test_ошибка_api_не_объявляет_сессию_недействительной(р):
    """`ТИП_API` — тоже не про сессию: карта эндпоинтов разошлась с формой
    ответа, подписка тут ни при чём."""
    исход = р["api"]

    assert исход["поймано_тип"] == "api_changed"
    assert исход["сессия"] == "жива", (
        "ТИП_API не про сессию — состояние портить не должен")


def test_тип_сессия_объявляет_сессию_недействительной(р):
    исход = р["session"]

    assert исход["поймано_тип"] == "session"
    assert исход["сессия"] == "недействительна", (
        "ТИП_СЕССИЯ обязан пометить сессию недействительной — единственный "
        "тип, ради которого этот except вообще существует")
    assert исход["сессия_жива_с"] is None, (
        "отметка «жива с» обязана сброситься при переходе в недействительна")
