# -*- coding: utf-8 -*-
"""Два потолка остановки демона — решение 33 (`docs/DECISIONS.md`, запись 33).

`protocol.ПОТОЛОК_ОСТАНОВКИ_СЕК` — сколько ждёт пульт (`garant stop`) после
сигнала. `protocol.ПОТОЛОК_УБОРКИ_СЕК` — сколько сам демон отводит себе на
закрытие браузера (`WORKER.join(...)` в `daemon.py`). Числа об одном факте
и обязаны жить в согласии: если уборка не строго меньше остановки, либо
демон не ждёт закрытия браузера вовсе (`join(0)` и `join(-N)` возвращаются
мгновенно и молча — chromium переживает демона, ограничение 2), либо пульт
объявляет зависшим демона, который штатно прибирается.

Два свойства проверяются здесь:

1. Само неравенство `0 < ПОТОЛОК_УБОРКИ_СЕК < ПОТОЛОК_ОСТАНОВКИ_СЕК` —
   прямым импортом (`protocol.py` без побочных эффектов на импорте, прямой
   импорт в процессе теста безопасен, как и в `test_протокол_ошибок.py`).
2. Охрана вычитания: при `ПОТОЛОК_ОСТАНОВКИ_СЕК <= 5` модуль не
   импортируется, а падает `ValueError`, называющей оба числа. Проверяется
   НЕ на модуле из дерева (там число зашито намертво и охрана не должна
   сработать), а на КОПИИ исходника с подставленным литералом, исполненной
   отдельным процессом — `protocol.py` не тянет ничего из пакета
   (`from __future__ import annotations` и всё), поэтому копию можно
   запустить как самостоятельный скрипт, не собирая вокруг неё пакет.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

from garant_mcp import protocol

ROOT = Path(__file__).resolve().parent.parent
_ИСХОДНИК = ROOT / "src" / "garant_mcp" / "protocol.py"


# --------------------------------------------------------------------------
#  1. неравенство потолков
# --------------------------------------------------------------------------

def test_потолок_уборки_меньше_потолка_остановки_и_больше_нуля():
    assert protocol.ПОТОЛОК_УБОРКИ_СЕК > 0, (
        "ПОТОЛОК_УБОРКИ_СЕК={} — при нуле или отрицательном числе "
        "`Thread.join()` возвращается мгновенно и молча: демон не ждёт "
        "закрытия браузера вовсе, chromium переживает демона и держит "
        "профиль (ограничение 2).".format(protocol.ПОТОЛОК_УБОРКИ_СЕК)
    )
    assert protocol.ПОТОЛОК_УБОРКИ_СЕК < protocol.ПОТОЛОК_ОСТАНОВКИ_СЕК, (
        "ПОТОЛОК_УБОРКИ_СЕК={} не меньше ПОТОЛОК_ОСТАНОВКИ_СЕК={} — демон "
        "не успевает закрыть браузер и снять daemon_port раньше, чем пульт "
        "перестанет ждать: `garant stop` объявит зависшим демона, который "
        "ещё штатно прибирается.".format(
            protocol.ПОТОЛОК_УБОРКИ_СЕК, protocol.ПОТОЛОК_ОСТАНОВКИ_СЕК)
    )


# --------------------------------------------------------------------------
#  2. охрана вычитания — на КОПИИ исходника, подпроцессом
# --------------------------------------------------------------------------

def _с_подставленным_потолком(потолок_остановки: int) -> str:
    """Текст `protocol.py`, где литерал `ПОТОЛОК_ОСТАНОВКИ_СЕК = 15` заменён.

    Замена по значению литерала, а не по регулярному выражению на строку —
    так подмена ломается заметно (`AssertionError` теста), если кто-то
    поменяет исходное число 15 в дереве, а не тихо промахивается мимо цели.
    """
    исходник = _ИСХОДНИК.read_text(encoding="utf-8")
    цель = "ПОТОЛОК_ОСТАНОВКИ_СЕК = 15"
    assert цель in исходник, (
        "в protocol.py не нашлась строка {!r} — литерал сменился, "
        "подмену надо поправить вручную.".format(цель)
    )
    return исходник.replace(
        цель, "ПОТОЛОК_ОСТАНОВКИ_СЕК = {}".format(потолок_остановки), 1)


def _выполнить_копию(текст: str) -> subprocess.CompletedProcess:
    """Запускает текст `protocol.py` как самостоятельный скрипт.

    Модуль не импортирует ничего из пакета (`from __future__ import
    annotations` и только), поэтому копию можно исполнить голым
    `python -c` — не нужно собирать вокруг неё ни `garant_mcp`, ни
    `sys.path`. Именно это и означает «модуль не импортируется» из наряда:
    top-level код падает при первом же исполнении, будь оно импортом или
    прямым запуском — разницы для проверяемого свойства нет.
    """
    return subprocess.run(
        [sys.executable, "-c", текст],
        capture_output=True, text=True, encoding="utf-8", errors="replace",
        timeout=30,
    )


def _сообщение_valueerror(stderr: str) -> str:
    """Текст СТРОГО самого исключения — последняя строка вида
    `ValueError: ...` в трейсбеке, а не весь `stderr`.

    Прежняя проверка (`"5" in stderr`, `"0" in stderr`) искала цифры по
    всему трейсбеку — а там их полно и без единого слова из сообщения:
    `File "<string>", line 5, in <module>` уже содержит «5», а строка
    с кареткой `^^^` под ней — координаты. То есть прежняя проверка была
    зелёной даже для сообщения, не называющего ни одного числа. Строка
    `ValueError: <текст>` — единственное место, где traceback печатает
    именно `str(exc)`, а не служебные координаты падения.
    """
    строки = [s for s in stderr.splitlines() if s.startswith("ValueError:")]
    assert строки, (
        "в stderr не нашлась строка вида 'ValueError: ...' — падение, "
        "похоже, вообще не ValueError:\n" + stderr
    )
    return строки[-1]


def test_потолок_остановки_5_секунд_даёт_valueerror_с_обоими_числами():
    """Граница: 5 с на уборку не оставляет вовсе (15 - 10 не при чём — здесь
    сам потолок остановки подставлен в 5, что при вычитании пяти даёт 0)."""
    r = _выполнить_копию(_с_подставленным_потолком(5))
    assert r.returncode != 0, (
        "ПОТОЛОК_ОСТАНОВКИ_СЕК=5 обязан ронять модуль при первом же "
        "исполнении (ValueError), а не проходить молча:\n" + r.stdout + r.stderr)
    assert "ValueError" in r.stderr, (
        "падение обязано быть ИМЕННО ValueError, а не случайной другой "
        "ошибкой:\n" + r.stderr)
    сообщение = _сообщение_valueerror(r.stderr)
    assert "5" in сообщение, (
        "СООБЩЕНИЕ исключения (не весь stderr — там номера строк трейсбека, "
        "в которых цифры находятся случайно) обязано называть подставленный "
        "ПОТОЛОК_ОСТАНОВКИ_СЕК (5):\n" + сообщение)
    assert "0" in сообщение, (
        "СООБЩЕНИЕ исключения обязано называть и то, сколько секунд "
        "остаётся на уборку (0 — потолок остановки минус пять):\n"
        + сообщение)


def test_потолок_остановки_отрицательный_тоже_даёт_valueerror():
    """Отрицательное число — не только строгий ноль на границе."""
    r = _выполнить_копию(_с_подставленным_потолком(-3))
    assert r.returncode != 0, (
        "ПОТОЛОК_ОСТАНОВКИ_СЕК=-3 обязан ронять модуль:\n"
        + r.stdout + r.stderr)
    assert "ValueError" in r.stderr, r.stderr
    сообщение = _сообщение_valueerror(r.stderr)
    assert "-3" in сообщение, (
        "СООБЩЕНИЕ исключения (не весь stderr) обязано называть "
        "подставленный потолок остановки (-3):\n" + сообщение)


def test_потолок_остановки_шесть_секунд_не_падает_контроль():
    """Контроль к двум тестам выше: 6 с (на единицу больше границы) обязаны
    пройти БЕЗ ValueError — иначе охрана слишком строгая и не даёт жить
    даже валидным числам."""
    r = _выполнить_копию(_с_подставленным_потолком(6))
    assert r.returncode == 0, (
        "ПОТОЛОК_ОСТАНОВКИ_СЕК=6 (на уборку остаётся 1 с > 0) не должен "
        "ронять модуль:\n" + r.stdout + r.stderr)
