# -*- coding: utf-8 -*-
"""`register.py`: слияние с чужой конфигурацией MCP-клиента (этап 02, шаг 3).

Модуль новый — до этого шага записи `endpoints.json`, порта и абсолютного
пути в конфигурацию клиента писал прежний генератор, привязанный к машине.
Здесь проверяется главное свойство: конфигурация клиента ЧУЖАЯ — рядом
с нашей записью в ней живут посторонние MCP-серверы, и модуль обязан их
не тронуть ни при каких обстоятельствах, включая четвёртое, самое опасное:
файл, который не разбирается как JSON, ПЕРЕЗАПИСЫВАТЬ НЕЛЬЗЯ никогда — там,
скорее всего, целы чужие записи, а сломана одна запятая.

Прямой импорт `garant_mcp.register` безопасен без песочницы: модуль не имеет
побочных эффектов на импорте (ни mkdir, ни сети — см. `.claude/rules/python.md`),
а все файловые операции здесь и далее идут по путям, которые СОЗДАЁТ САМ ТЕСТ
в `tmp_path`, — ни один настоящий Claude Desktop/Code этого пользователя
не затрагивается: `register.цель_desktop()`/`цель_code()` в тестах не
вызываются вовсе, только `register.Цель(...)` с путём внутри `tmp_path`.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
if str(SRC) not in sys.path:
    sys.path.insert(0, str(SRC))

import garant_mcp.register as register  # noqa: E402


def _цель(путь: Path, требует_каталог: bool = True) -> register.Цель:
    return register.Цель("тестовый клиент", путь, требует_каталог=требует_каталог)


# --------------------------------------------------------------------------
#  1. нет каталога клиента — клиент не установлен, ничего не создаём
# --------------------------------------------------------------------------

def test_нет_каталога_клиента_не_устанавливаем_и_не_пишем(tmp_path):
    путь = tmp_path / "нет_такого_клиента" / "config.json"
    цель = _цель(путь)

    данные, состояние = register.прочитать(цель)
    assert состояние == register.НЕТ_КАТАЛОГА

    ок, текст = register.зарегистрировать(цель)
    assert ок is False
    assert not путь.parent.exists(), (
        "каталог клиента, которого нет, создавать нельзя — это объявило бы "
        "установленным клиента, которого не ставили")
    assert not путь.exists()


# --------------------------------------------------------------------------
#  2. каталог есть, файла нет — пишем с нуля, чужого сохранять нечего
# --------------------------------------------------------------------------

def test_нет_файла_создаём_с_нашей_записью(tmp_path):
    путь = tmp_path / "клиент" / "config.json"
    путь.parent.mkdir()
    цель = _цель(путь)

    данные, состояние = register.прочитать(цель)
    assert состояние == register.НЕТ_ФАЙЛА

    ок, текст = register.зарегистрировать(цель)
    assert ок is True
    записанное = json.loads(путь.read_text(encoding="utf-8"))
    assert записанное["mcpServers"]["garant"] == {"command": "garant-mcp"}


# --------------------------------------------------------------------------
#  3. файл пуст — то же самое, без падения на пустой строке
# --------------------------------------------------------------------------

def test_пустой_файл_не_роняет_и_даёт_нашу_запись(tmp_path):
    путь = tmp_path / "клиент" / "config.json"
    путь.parent.mkdir()
    путь.write_text("", encoding="utf-8")
    цель = _цель(путь)

    данные, состояние = register.прочитать(цель)
    assert состояние == register.ПУСТОЙ

    ок, текст = register.зарегистрировать(цель)
    assert ок is True
    записанное = json.loads(путь.read_text(encoding="utf-8"))
    assert записанное["mcpServers"]["garant"] == {"command": "garant-mcp"}


# --------------------------------------------------------------------------
#  4. битый JSON — САМОЕ ВАЖНОЕ: не трогаем НИКОГДА
# --------------------------------------------------------------------------

def test_битый_json_не_переписывается_никогда(tmp_path):
    путь = tmp_path / "клиент" / "config.json"
    путь.parent.mkdir()
    исходный_текст = '{"mcpServers": {"чужой": {"command": "foo"}}, "битое'
    путь.write_text(исходный_текст, encoding="utf-8")
    цель = _цель(путь)

    данные, состояние = register.прочитать(цель)
    assert состояние == register.БИТЫЙ

    ок, текст = register.зарегистрировать(цель)
    assert ок is False, "регистрация на битом файле обязана отказать, а не тихо переписать его"
    assert путь.read_text(encoding="utf-8") == исходный_текст, (
        "битый файл изменился — модуль переписал конфигурацию, в которой, "
        "скорее всего, целы чужие MCP-серверы, а сломана одна запятая")
    assert не_создан_бак(путь), (
        "на битом файле .bak создаваться не должен — резервировать точно "
        "то же самое содержимое, которое и так остаётся нетронутым, незачем")

    # unregister на битом файле — тот же принцип: не трогаем.
    ок2, текст2 = register.снять(цель)
    assert ок2 is False
    assert путь.read_text(encoding="utf-8") == исходный_текст


def не_создан_бак(путь: Path) -> bool:
    return not путь.with_name(путь.name + ".bak").exists()


# --------------------------------------------------------------------------
#  чужие серверы целы, .bak создаётся с исходным содержимым
# --------------------------------------------------------------------------

def test_чужие_серверы_остаются_целы_и_бак_хранит_исходник(tmp_path):
    путь = tmp_path / "клиент" / "config.json"
    путь.parent.mkdir()
    исходное = {"mcpServers": {"чужой-сервер": {"command": "foo", "args": ["x"]}},
                "прочаяНастройка": 42}
    путь.write_text(json.dumps(исходное, ensure_ascii=False), encoding="utf-8")
    цель = _цель(путь)

    ок, текст = register.зарегистрировать(цель)
    assert ок is True

    итог = json.loads(путь.read_text(encoding="utf-8"))
    assert итог["mcpServers"]["чужой-сервер"] == исходное["mcpServers"]["чужой-сервер"], (
        "чужая запись MCP-сервера обязана остаться нетронутой")
    assert итог["прочаяНастройка"] == 42, "посторонний ключ верхнего уровня потерян"
    assert итог["mcpServers"]["garant"] == {"command": "garant-mcp"}

    бак = путь.with_name(путь.name + ".bak")
    assert бак.exists(), "перед первой записью обязана остаться копия .bak"
    assert json.loads(бак.read_text(encoding="utf-8")) == исходное, (
        ".bak обязан содержать ИСХОДНОЕ содержимое, а не то, что записано поверх")


# --------------------------------------------------------------------------
#  повторный запуск не дублирует и не переписывает файл
# --------------------------------------------------------------------------

def test_повторная_регистрация_не_дублирует_и_не_трогает_файл(tmp_path):
    путь = tmp_path / "клиент" / "config.json"
    путь.parent.mkdir()
    цель = _цель(путь)

    ок1, _ = register.зарегистрировать(цель)
    assert ок1 is True
    содержимое_после_первого = путь.read_text(encoding="utf-8")
    время_первого = путь.stat().st_mtime_ns

    ок2, текст2 = register.зарегистрировать(цель)
    assert ок2 is True
    assert "уже зарегистрирован" in текст2
    assert путь.read_text(encoding="utf-8") == содержимое_после_первого, (
        "повторная регистрация не должна переписывать файл вовсе")
    assert путь.stat().st_mtime_ns == время_первого, (
        "повторная регистрация тронула mtime файла — значит, записала его "
        "заново, хотя запись уже была")


# --------------------------------------------------------------------------
#  unregister убирает ТОЛЬКО нашу запись
# --------------------------------------------------------------------------

def test_unregister_убирает_только_нашу_запись(tmp_path):
    путь = tmp_path / "клиент" / "config.json"
    путь.parent.mkdir()
    исходное = {"mcpServers": {"чужой-сервер": {"command": "foo"},
                               "garant": {"command": "garant-mcp"}}}
    путь.write_text(json.dumps(исходное, ensure_ascii=False), encoding="utf-8")
    цель = _цель(путь)

    ок, текст = register.снять(цель)
    assert ок is True
    итог = json.loads(путь.read_text(encoding="utf-8"))
    assert "garant" not in итог["mcpServers"], "наша запись обязана исчезнуть"
    assert итог["mcpServers"]["чужой-сервер"] == {"command": "foo"}, (
        "чужая запись обязана остаться на месте")


def test_unregister_без_записи_ничего_не_пишет(tmp_path):
    """Снимать нечего — файл не трогаем вовсе, даже перезаписью тем же самым."""
    путь = tmp_path / "клиент" / "config.json"
    путь.parent.mkdir()
    исходное = {"mcpServers": {"чужой-сервер": {"command": "foo"}}}
    исходный_текст = json.dumps(исходное, ensure_ascii=False)
    путь.write_text(исходный_текст, encoding="utf-8")
    цель = _цель(путь)

    ок, текст = register.снять(цель)
    assert ок is True
    assert "нечего" in текст
    assert путь.read_text(encoding="utf-8") == исходный_текст
    assert не_создан_бак(путь), "снятие несуществующей записи не должно писать файл вовсе"
