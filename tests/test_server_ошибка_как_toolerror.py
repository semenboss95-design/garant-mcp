# -*- coding: utf-8 -*-
"""Д-19 аудита: ошибка инструмента — `ToolError` протокола MCP, а не строка
данных с ключом «ошибка» (server.py:112-119).

Разница не косметическая. MCP-клиент отличает ошибку протокола (`isError`)
от обычных данных инструмента: первую он показывает как сбой и не вставляет
в текст ответа как факт, вторую — вставляет как есть. Инструмент, вернувший
`'{"ошибка": "..."}'` строкой, для клиента ничем не отличается от
`'{"total": 5, ...}'` — тот способен процитировать текст несуществующей
нормы как настоящий, потому что формально вызов завершился успешно.

Проверяется офлайн той же заглушкой `mcp.server.fastmcp`, что и немота
импорта (`test_импорт_server_тихий.py`): `mcp.tool()` в ней возвращает
функцию как есть, поэтому `garant_search` — это ровно `guard`-обёртка,
вызываемая напрямую, без сети и без демона. Демон подменяется на уровне
`daemon_client.call` — вызов брошен намеренно, как при реальном отказе
демона (сессия истекла, недоступен и т.п.).
"""
from __future__ import annotations

import re

from test_paths import _песочница, _запуск, чужой_каталог  # noqa: F401
from test_импорт_server_тихий import _поставить_заглушку_mcp

# Буква диска и разделитель пути следом — как в test_подсказки.py: так
# выглядит абсолютный путь КОНКРЕТНОЙ машины на Windows. Ошибка, ушедшая
# клиенту, не имеет права называть файловую систему той машины, где стоит
# демон, — читающий её сидит на другой машине или вовсе не имеет туда доступа.
_БУКВА_ДИСКА = re.compile(r"[A-Za-z]:[\\/]")

_КОД = """
import sys, asyncio
sys.path.insert(0, r'{заглушка}')
sys.path.insert(0, r'{site}')
import garant_mcp.server as server
import garant_mcp.daemon_client as daemon_client


def _не_готов_ни_разу():
    # готов_к_работе() успешен — отказ происходит на самом вызове метода,
    # как при живом, но потерявшем сессию демоне.
    return None


def _отказ_демона(name, **kwargs):
    raise daemon_client.DaemonError(
        "Демон недоступен: подписка истекла или сессия сброшена")


daemon_client.готов_к_работе = _не_готов_ни_разу
daemon_client.call = _отказ_демона

try:
    итог = asyncio.run(server.garant_search(query="проба"))
    print("ВЕРНУЛОСЬ_КАК_ДАННЫЕ:" + repr(итог))
except server.ToolError as e:
    print("TOOLERROR:" + str(e))
except Exception as e:
    print("ДРУГОЕ:" + type(e).__name__ + ":" + str(e))
"""


def test_ошибка_демона_доходит_как_toolerror_без_абсолютного_пути(
        tmp_path, чужой_каталог):
    пакет = _песочница(tmp_path)
    заглушка = _поставить_заглушку_mcp(tmp_path / "заглушка")
    состояние = tmp_path / "состояние"

    код = _КОД.format(заглушка=заглушка, site=пакет.parent)
    r = _запуск(код, чужой_каталог, {"GARANT_HOME": str(состояние)}, таймаут=60)

    assert r.returncode == 0, "скрипт диагностики упал:\n" + r.stdout + r.stderr
    вывод = r.stdout.strip()

    assert "ВЕРНУЛОСЬ_КАК_ДАННЫЕ" not in вывод, (
        "инструмент вернул отказ демона как обычные данные — MCP-клиент "
        "не отличит это от настоящего ответа и процитирует как факт:\n"
        + вывод)
    assert вывод.startswith("TOOLERROR:"), (
        "ожидалась ToolError протокола MCP, получено другое:\n" + вывод)

    текст_ошибки = вывод[len("TOOLERROR:"):]
    assert not текст_ошибки.lstrip().startswith("{"), (
        "текст ToolError выглядит как JSON с данными (например, "
        "{{\"ошибка\": ...}}), а не как читаемое сообщение об отказе: "
        + текст_ошибки)
    assert not _БУКВА_ДИСКА.search(текст_ошибки), (
        "текст ошибки называет абсолютный путь конкретной машины:\n"
        + текст_ошибки)
    assert чужой_каталог and str(чужой_каталог) not in текст_ошибки, (
        "текст ошибки содержит путь рабочего каталога машины:\n" + текст_ошибки)
