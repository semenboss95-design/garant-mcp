# -*- coding: utf-8 -*-
"""`garant stop`, когда порт МОЛЧИТ (HTTP не отвечает), а не отвечает нашим
демоном — наряд 4-3, `cli.py:809-849` (решение 42, `docs/DECISIONS.md`).

Место рядом с `tests/test_stop_чужой_pid.py`: тот файл воспроизводит худший
случай ОТВЕЧАЮЩЕГО пути (порт отвечает `/health`, PID из `daemon_port`
достался чужому). Здесь — тот же класс дефекта на ДРУГОМ пути: HTTP молчит
вовсе. До приёмки 7б (09.09.2026) на этом пути `stop()` не спрашивал о
процессе НИЧЕГО — просто отвечал «останавливать нечего», какой бы PID
в `daemon_port` не лежал. Промежуточная правка опиралась на имя образа
(`_наш_на_вид`, «похоже ли на python/garant») и была измерена той же
приёмкой: посторонний `python -c "time.sleep(90)"`, чей PID лежал
в протухшем `daemon_port`, был убит деревом и объявлен остановленным —
имя образа совпадает у ЛЮБОГО процесса Python, включая совершенно
посторонний. Сверка на этом пути теперь идёт КОМАНДНОЙ СТРОКОЙ.

Два теста ниже (негативный и позитивный) — настоящие подпроцессы, без
единой подмены `cli.py`: `garant stop` запускается как отдельный процесс
(тот же приём, что в `test_stop_чужой_pid.py`), `_командная_строка` внутри
него зовёт настоящий `tasklist`/`ps`/`powershell` на настоящем чужом
процессе. Подделывается только КОМАНДНАЯ СТРОКА процесса-приманки —
маркер демона (`garant_mcp.daemon`) передаётся ей лишним аргументом argv:
процесс при этом не исполняет ни строчки демона, а просто спит, но его
НАСТОЯЩАЯ командная строка (то, что `tasklist`/`ps` увидят у ОС) содержит
маркер буквально, как если бы его запустил `start()`.

Третий тест — противоположный класс причины («прочесть не удалось»), и он
не нуждается в подпроцессе-приманке: там нет процесса, о котором можно было
бы солгать, есть только отказ инструмента спросить. Он в стиле
`test_stop_потолок_и_честный_текст.py`: `cli.stop()` зовётся напрямую,
подменяется граница демон/пульт (`daemon_client.адрес`) и сама
`_командная_строка` — то есть ровно то место, которое расспрашивает ОС.

Каталог состояния — только подменённый: `tmp_path`, ничего не пишется
и не читается в настоящем `GARANT_HOME` машины.
"""
from __future__ import annotations

import json
import socket
import subprocess
import sys
import time
from pathlib import Path

from test_paths import _песочница, _окружение, чужой_каталог  # noqa: F401

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
if str(SRC) not in sys.path:
    sys.path.insert(0, str(SRC))
import garant_mcp.cli as cli  # noqa: E402
from garant_mcp import daemon_client as dc  # noqa: E402


