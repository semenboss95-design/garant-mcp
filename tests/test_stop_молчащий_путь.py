def _свободный_порт() -> int:
    """Порт, который сейчас свободен — тот же приём, что в `test_port.py`:
    гарантии, что он останется свободным между строкой ниже и запуском
    `garant stop`, нет и не нужна — цена промаха здесь перезапуск теста,
    а не потерянная сессия."""
    s = socket.socket()
    s.bind(("127.0.0.1", 0))
    порт = s.getsockname()[1]
    s.close()
    return порт


def _garant_stop(пакет: Path, состояние: Path, cwd: Path) -> subprocess.CompletedProcess:
    return subprocess.run(
        [sys.executable, "-m", "garant_mcp.cli", "stop"],
        cwd=str(cwd),
        env=_окружение({"PYTHONPATH": str(пакет.parent),
                        "GARANT_HOME": str(состояние)}),
        capture_output=True, text=True, encoding="utf-8", errors="replace",
        timeout=60,
    )


