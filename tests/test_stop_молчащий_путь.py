#  1. негативный случай (он же «худший» из наряда): чужой процесс без
#     маркера — жив, «послан сигнал» нет в выводе, код успеха, запись
#     daemon_port снята (PID достался чужой программе)
# --------------------------------------------------------------------------

def test_stop_молчащий_путь_чужой_процесс_без_маркера_жив_и_запись_снята(
        tmp_path, чужой_каталог):
    """Худший случай наряда: `python -c "import time; time.sleep(90)"` —
    настоящий, ничем не связанный с демоном процесс, чей PID оказался
    в `daemon_port` рядом с портом, где никто не слушает (типичная причина —
    демон умер, а PID успел достаться следующему процессу ОС по кругу).

    Проверено ЭМПИРИЧЕСКИ на копии `cli.py` до наряда (git HEAD,
    `git show HEAD:src/garant_mcp/cli.py`, запущена изолированно, минуя
    этот файл): на молчащем порту прежний код спрашивал ТОЛЬКО
    `адрес["alive"]` и, не читая ни PID, ни командную строку, отвечал
    «останавливать нечего» — файл `daemon_port` при этом остаётся, а вывод
    не называет ни PID, ни «не наш демон». Обе оставленные ниже проверки
    (снятая запись и текст «не наш демон») на той копии красны; на текущем
    коде обе зелены — это и есть проверяемое различие, а не общий факт
    «процесс не убит», который у молчащего пути был бы зелён и раньше.
    """
    пакет = _песочница(tmp_path)
    состояние = tmp_path / "состояние"
    состояние.mkdir()
    файл_порта = состояние / "daemon_port"

    порт = _свободный_порт()
    посторонний = subprocess.Popen(
        [sys.executable, "-c", "import time; time.sleep(90)"],
        stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    try:
        файл_порта.write_text(
            json.dumps({"порт": порт, "pid": посторонний.pid}),
            encoding="utf-8")

        assert посторонний.poll() is None, (
            "посторонний процесс не пережил даже запуск теста — "
            "проверка ничего не проверяет")

        r = _garant_stop(пакет, состояние, чужой_каталог)
        # Дать ОС время исполнить возможное убийство, прежде чем опрашивать
        # процесс: оно не мгновенно, а `garant stop` на этой ветке не ждёт
        # ничьей смерти сам (он и не должен был никого убивать).
        time.sleep(1.0)

        вывод = r.stdout + r.stderr

        assert посторонний.poll() is None, (
            "«garant stop» на молчащем порту убил посторонний процесс, чья "
            "командная строка демона не называет — приёмка 7б поймала "
            "именно это на промежуточном коде (сверка по имени образа):\n"
            + вывод)
        assert r.returncode == cli.КОД_ОК, (
            "исход «командная строка прочитана, демон не назван» — это ОК "
            "(ничего не убито, но и разбираться дальше не с чем), а не "
            "отказ:\n" + вывод)
        assert "послан сигнал" not in вывод.lower(), (
            "процессу, чья командная строка не называет демон, сигнал "
            "не посылается вовсе:\n" + вывод)
        assert "не наш демон" in вывод, (
            "вывод обязан прямо назвать причину — командная строка "
            "прочитана и наш демон не названа:\n" + вывод)
        assert str(посторонний.pid) in вывод, (
            "вывод обязан называть PID процесса, которому запись "
            "досталась случайно:\n" + вывод)
        assert not файл_порта.exists(), (
            "запись daemon_port описывает процесс, которому PID достался "
            "случайно (демон умер, порт свободен) — оставить её значит "
            "отправить следующего клиента на порт, где демона нет")
    finally:
        if посторонний.poll() is None:
            посторонний.kill()
            посторонний.wait(timeout=10)


# --------------------------------------------------------------------------
#  2. позитивный случай: командная строка НАЗЫВАЕТ демон — процесс получает
#     настоящий сигнал остановки и погибает, как на отвечающем пути
# --------------------------------------------------------------------------

def test_stop_молчащий_путь_маркер_демона_в_командной_строке_получает_сигнал(
        tmp_path, чужой_каталог):
    """Командная строка процесса-приманки несёт маркер демона
    (`garant_mcp.daemon`) — тем же способом, каким `start()` его узнаёт.
    Маркер передан лишним аргументом `argv`, а не исполнением: процесс
    целиком — `import time; time.sleep(90)`, он никогда не был демоном
    и не открывает браузер. `garant stop` при этом видит настоящую
    командную строку ОС (`tasklist`/`ps`/`powershell` смотрят на неё, а не
    на то, что процесс делает внутри) — эмпирически проверено перед
    написанием теста: `cli._командная_строка(pid)` этого процесса даёт
    `("есть", "... -c \"...\" garant_mcp.daemon")`, `cli._демон_в_строке`
    на этой строке — `True`.

    Проверено эмпирически и на прежнем коде (см. соседний тест): там же
    самый процесс-приманка выживает — молчащий путь до наряда его вообще
    не опрашивал. Здесь — противоположное утверждение: с текущим кодом он
    обязан получить сигнал и уйти.
    """
    пакет = _песочница(tmp_path)
    состояние = tmp_path / "состояние"
    состояние.mkdir()
    файл_порта = состояние / "daemon_port"

    порт = _свободный_порт()
    приманка = subprocess.Popen(
        [sys.executable, "-c", "import time; time.sleep(90)",
         "garant_mcp.daemon"],
        stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    try:
        файл_порта.write_text(
            json.dumps({"порт": порт, "pid": приманка.pid}),
            encoding="utf-8")

        assert приманка.poll() is None, (
            "процесс-приманка не пережил даже запуск теста")

        r = _garant_stop(пакет, состояние, чужой_каталог)
        вывод = r.stdout + r.stderr

        assert r.returncode == cli.КОД_ОК, (
            "демон, замолчавший на HTTP, но опознанный по командной "
            "строке и ушедший по сигналу, — это успех:\n" + вывод)
        assert "послан сигнал" in вывод, (
            "процессу, чья командная строка называет демон, обязан быть "
            "послан настоящий сигнал остановки — как на отвечающем пути:\n"
            + вывод)

        # Сигнал реален (`taskkill /T /F` либо `os.kill(SIGTERM)`), и цена
        # промаха здесь — потерянный процесс, а не текст: ждём его смерти
        # по-настоящему, а не верим выводу на слово.
        try:
            приманка.wait(timeout=20)
        except subprocess.TimeoutExpired:
            pass
        assert приманка.poll() is not None, (
            "«garant stop» отчитался о посланном сигнале, а процесс-приманка "
            "жив спустя 20 с после возврата команды:\n" + вывод)
        assert not файл_порта.exists(), (
            "процесс подтверждённо ушёл — запись daemon_port обязана быть "
            "снята вслед за ним")
    finally:
        if приманка.poll() is None:
            приманка.kill()
            приманка.wait(timeout=10)


# --------------------------------------------------------------------------
#  3. командную строку прочитать не удалось — отказ, запись НЕ снимается
# --------------------------------------------------------------------------

def test_stop_молчащий_путь_командную_строку_прочитать_не_удалось_отказ_без_уборки(
        monkeypatch, capsys):
    """Инструмент опроса (`tasklist`/`ps`/`powershell`) молчит или падает —
    это НЕЗНАНИЕ о процессе, а не знание об его отсутствии. `_командная_
    строка` подменена монkeypatch'ем на возврат `("неизвестно", <причина>)`
    именно ЭТИМ способом наряд и просит проверить исход «прочесть не
    удалось» — без единого настоящего обращения к ОС, поскольку здесь
    нечему быть настоящим: тест воспроизводит молчание самого инструмента,
    а не поведение какого-то процесса.

    На прежнем коде (до наряда) эта ветка отсутствовала целиком: молчащий
    путь при `alive=False` не читал ни PID, ни командную строку, и всегда
    отвечал «останавливать нечего» кодом `КОД_ОК` — проверено ЭМПИРИЧЕСКИ,
    изолированным импортом `git show HEAD:src/garant_mcp/cli.py`, тем же
    вызовом `cli.stop()` (там ни `_pid_из_порта`, ни `_командная_строка`
    не существуют вовсе). Здесь код обязан быть `КОД_НЕ_СДЕЛАНО`, а запись
    `daemon_port` — на месте: ни то, ни другое не выполняется прежним кодом,
    и оба различия сделаны проверяемыми ниже, а не только код возврата.
    """
    PID = 991234
    ПОРТ = 55561
    ПРИЧИНА = "tasklist не ответил (тест)"

    monkeypatch.setattr(dc, "адрес",
                        lambda: {"port": ПОРТ, "pid": None, "alive": False})
    monkeypatch.setattr(cli, "_pid_из_порта", lambda: PID)

    вызовы_командной_строки: list = []

    def _командная_строка(pid):
        вызовы_командной_строки.append(pid)
        return "неизвестно", ПРИЧИНА

    monkeypatch.setattr(cli, "_командная_строка", _командная_строка)

    уборка: list = []
    monkeypatch.setattr(cli, "_убрать_протухший_порт",
                        lambda pid: уборка.append(pid))

    код = cli.stop()

    assert код == cli.КОД_НЕ_СДЕЛАНО, (
        "командную строку прочесть не удалось — это отказ (незнание "
        "о процессе), а не тихий успех «останавливать нечего»")
    assert вызовы_командной_строки == [PID], (
        "командная строка обязана быть спрошена ровно с тем PID, что "
        "лежит в daemon_port")
    ошибка = capsys.readouterr().err
    assert str(PID) in ошибка, (
        "отказ обязан называть PID процесса, который не удалось "
        "опознать:\n" + ошибка)
    assert ПРИЧИНА in ошибка, (
        "отказ обязан называть ПРИЧИНУ неудачи опроса, а не только факт "
        "неудачи:\n" + ошибка)
    assert уборка == [], (
        "молчание инструмента опроса — не знание об отсутствии процесса: "
        "снимать daemon_port нельзя, это единственный след того, кто "
        "может занимать профиль")
