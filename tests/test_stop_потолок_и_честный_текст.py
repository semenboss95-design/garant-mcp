# -*- coding: utf-8 -*-
"""`garant stop`: ждёт потолок из `protocol.py`, а не литерал 15, и не
выдаёт неизмеренное за факт (решение 33, `docs/DECISIONS.md`, запись 33).

До правки `stop()` ждал ровно 15 секунд литералом и, увидев, что демон
перестал отвечать, печатал «демон остановлен» — хотя уборка (закрытие
браузера, снятие `daemon_port`) к этому моменту демон только начинает,
причём уже ПОСЛЕ того, как замолчал на HTTP. Разница не декоративная:
«демон остановлен» утверждает то, чего пульт не видел, а сам литерал 15
живёт отдельно от `protocol.ПОТОЛОК_ОСТАНОВКИ_СЕК`, с которым обязан
совпадать (`protocol.ПОТОЛОК_УБОРКИ_СЕК` выводится из него же) — разъехавшись
эти два числа однажды дадут `garant stop`, объявляющий зависшим демона,
который ещё штатно прибирается.

Стиль подмены — как в `test_cli_login_вошли.py`: `cli.stop()` зовётся
напрямую (не подпроцессом, у `cli.py` нет побочных эффектов на импорте),
подменяется коллаборатор границы демон/пульт (`daemon_client.адрес`) —
то есть ровно то место, которое в реальности сходило бы к демону по HTTP,
а не сам код `cli.stop()`. Опознание процесса (`_имя_процесса`,
`_выполнить_tk`) тоже подменено — наряд прямо запрещает посылать в этом
файле настоящие сигналы и звать настоящий `taskkill`: это уже проверяет
`test_stop_чужой_pid.py`, отдельно и настоящим подпроцессом.

Правка после независимой перепроверки (08.09.2026), два пункта:

  БЛОКЕР CI. Прежняя `_подготовить_опознание` патчила только
  `_выполнить_tk` — ветвь Windows (`os.name == "nt"`). На `ubuntu-latest`
  из матрицы CI `stop()` идёт веткой POSIX и шлёт НАСТОЯЩИЙ
  `os.kill(pid, signal.SIGTERM)` — с несуществующим PID 424242 это упало бы
  `OSError` (тест ушёл бы в отказ по другой причине), а случись PID 424242
  занятым чьим-то настоящим процессом — самый настоящий сигнал ему. Теперь
  `_подготовить_опознание` глушит ОБЕ ветви: `_выполнить_tk` и `os.kill`.

  СЛАБЫЙ УСПЕХ. Прежняя `_подготовить_опознание` отдавала `_имя_процесса`
  одно и то же имя на КАЖДЫЙ вызов — то есть в её мире процесс не умирает
  никогда. Тест успеха при этом читал вывод так, будто демон замолчал и
  ушёл, — но по коду `stop()` (находка B, `cli.py:605-652`) молчание HTTP
  без исчезновения процесса даёт ВТОРОЙ исход (отказ, «замолчал, но
  процесс жив»), а не успех. Тест был зелёным на сломанном коде — то есть
  не проверял то, что называл. `_подготовить_опознание` теперь принимает
  `процесс_умирает`: `True` — имя отдаётся только на первый вызов
  (опознание до сигнала), дальше `None` (процесс ушёл); `False` (умолчание,
  как раньше) — имя неизменно, процесс жив всегда. Второй исход получил
  отдельный тест.
"""

from __future__ import annotations

from garant_mcp import cli
from garant_mcp import daemon_client as dc
from garant_mcp import protocol

_PID = 424242
_ПОРТ = 55555


def _подготовить_опознание(monkeypatch, *, процесс_умирает: bool = False):
    """Демон опознан «нашим» без единого настоящего обращения к ОС.

    `_имя_процесса` не зовёт настоящий tasklist/ps. `процесс_умирает=False`
    (умолчание) — имя неизменно на каждый вызов, процесс жив всё время
    (тесты потолка ожидания и исхода «HTTP замолчал, но процесс жив»).
    `процесс_умирает=True` — имя отдаётся только на первый вызов (тройная
    проверка ДО сигнала), дальше `None`: процесс исчез сразу после сигнала
    (исход успеха). Полное убийство/неубийство по имени процесса —
    предмет `test_stop_чужой_pid.py`, здесь это не проверяется и намеренно
    вынесено за скобки.

    `_выполнить_tk` не зовёт настоящий taskkill (ветвь Windows) — сразу
    «успех». `os.kill` подменён отдельно (ветвь POSIX) — БЕЗ этой подмены
    на `ubuntu-latest` из матрицы CI `stop()` шлёт настоящий
    `SIGTERM` процессу с PID 424242: несуществующему — `OSError`, а
    существующему — самый настоящий сигнал. Обе ветви ОС обязаны быть без
    единого настоящего системного вызова, а какая из них исполнится,
    решает `os.name` той машины, где идёт тест — здесь глушатся ОБЕ.
    """
    счётчик = {"n": 0}

    def _имя(pid):
        счётчик["n"] += 1
        if процесс_умирает and счётчик["n"] > 1:
            return None
        return "python.exe"

    monkeypatch.setattr(cli, "_имя_процесса", _имя)
    monkeypatch.setattr(cli, "_выполнить_tk", lambda pid: (0, "ok (тест)"))
    monkeypatch.setattr(cli.os, "kill", lambda *a, **kw: None)


def _без_уборки_порта(monkeypatch) -> list:
    """`_убрать_протухший_порт` подменяется на спай: реальная версия трогает
    диск (`paths.port_file`), а собственный каталог состояния — не предмет
    этого файла. Возвращает список PID, с которыми её позвали."""
    вызовы: list = []
    monkeypatch.setattr(cli, "_убрать_протухший_порт",
                        lambda pid: вызовы.append(pid))
    return вызовы


# --------------------------------------------------------------------------
#  (а) потолок ожидания и текст отказа читаются из protocol.py, а не
#      зашиты литералом 15 / «до пяти минут»
# --------------------------------------------------------------------------

def test_stop_ждёт_и_считает_из_protocol_а_не_литералы_прежнего_кода(
        monkeypatch, capsys):
    _подготовить_опознание(monkeypatch)
    _без_уборки_порта(monkeypatch)

    # Значения нарочно отличны от прежних литералов (15 и 300//60=5),
    # чтобы сообщение однозначно доказывало чтение ИЗ protocol, а не
    # случайное совпадение с ним же.
    monkeypatch.setattr(protocol, "ПОТОЛОК_ОСТАНОВКИ_СЕК", 1)
    monkeypatch.setattr(protocol, "ПОТОЛОК_ВХОДА_СЕК", 180)

    # Демон отвечает «жив» на каждый опрос — стало быть, стоп никогда
    # не увидит его молчания и обязан отказать по истечении потолка.
    monkeypatch.setattr(
        dc, "адрес",
        lambda: {"port": _ПОРТ, "pid": _PID, "alive": True})

    код = cli.stop()

    assert код == cli.КОД_НЕ_СДЕЛАНО, (
        "демон, который никогда не замолкает, обязан дать отказ (код 1), "
        "а не успех")

    ошибка = capsys.readouterr().err
    assert "за 1 с не остановился" in ошибка, (
        "текст отказа обязан называть ИМЕННО protocol.ПОТОЛОК_ОСТАНОВКИ_СЕК "
        "(здесь подставлено 1), а не литерал 15 прежнего кода:\n" + ошибка)
    assert "до 3 мин" in ошибка, (
        "текст отказа обязан считать минуты из protocol.ПОТОЛОК_ВХОДА_СЕК "
        "(180 // 60 = 3), а не из литерала 300 («до пяти минут» прежнего "
        "кода):\n" + ошибка)
    assert "15 с" not in ошибка and "пять минут" not in ошибка, (
        "в тексте остался прежний литерал вместо значения из protocol.py:\n"
        + ошибка)


def test_stop_реально_ждёт_порядка_потолка_а_не_15_секунд(monkeypatch):
    """Контроль ко времени, а не только к тексту: потолок, патченный в малое
    число, обязан реально сократить ожидание — иначе код мог бы читать
    protocol.ПОТОЛОК_ОСТАНОВКИ_СЕК только для текста сообщения, а сам
    таймер по-прежнему считать от литерала 15."""
    import time

    _подготовить_опознание(monkeypatch)
    _без_уборки_порта(monkeypatch)
    monkeypatch.setattr(protocol, "ПОТОЛОК_ОСТАНОВКИ_СЕК", 1)
    monkeypatch.setattr(
        dc, "адрес",
        lambda: {"port": _ПОРТ, "pid": _PID, "alive": True})

    начало = time.monotonic()
    cli.stop()
    заняло = time.monotonic() - начало

    assert заняло < 10, (
        "garant stop ждал {:.1f} с при protocol.ПОТОЛОК_ОСТАНОВКИ_СЕК=1 — "
        "похоже, таймер по-прежнему считает от литерала 15, а не от "
        "значения из protocol.py.".format(заняло)
    )


# --------------------------------------------------------------------------
#  (б)+(в) успех: не «демон остановлен» как факт, а «перестал отвечать» +
#      pid + порт + совет `garant logs`; код КОД_ОК; уборка порта вызвана
# --------------------------------------------------------------------------

def test_stop_успех_не_утверждает_остановлен_а_называет_pid_порт_и_logs(
        monkeypatch, capsys):
    # процесс_умирает=True: имя процесса пропадает СРАЗУ после опознания
    # до сигнала — ровно то, что stop() обязан прочитать как «процесс
    # ушёл» (находка B, исход 1). Прежняя версия держала имя неизменным —
    # в её мире это исход 2 («замолчал, но процесс жив»), а не успех.
    _подготовить_опознание(monkeypatch, процесс_умирает=True)
    вызовы = _без_уборки_порта(monkeypatch)
    monkeypatch.setattr(protocol, "ПОТОЛОК_ОСТАНОВКИ_СЕК", 5)

    номер_вызова = {"n": 0}

    def _адрес():
        номер_вызова["n"] += 1
        # Первый вызов — ДО сигнала (иначе stop() решил бы, что
        # останавливать нечего). Второй — уже внутри цикла ожидания:
        # демон замолчал сразу после сигнала.
        return {"port": _ПОРТ, "pid": _PID, "alive": номер_вызова["n"] == 1}

    monkeypatch.setattr(dc, "адрес", _адрес)

    код = cli.stop()

    assert код == cli.КОД_ОК, "демон замолчал — это успех (код 0)"

    вывод = capsys.readouterr().out
    assert "демон остановлен" not in вывод.lower(), (
        "текст успеха утверждает «демон остановлен» как факт. Пульт видит "
        "ровно одно — демон перестал отвечать на HTTP; закрылся ли браузер, "
        "он не видит, уборка идёт уже после этого молчания:\n" + вывод)
    assert "перестал отвечать" in вывод, (
        "текст успеха обязан честно говорить, что демон перестал "
        "отвечать, а не утверждать факт остановки:\n" + вывод)
    assert str(_PID) in вывод, "текст успеха обязан называть PID:\n" + вывод
    assert "127.0.0.1:{}".format(_ПОРТ) in вывод, (
        "текст успеха обязан называть порт демона:\n" + вывод)
    assert "garant logs" in вывод, (
        "текст успеха обязан указывать, где искать ответ, если профиль "
        "окажется занят (`garant logs`):\n" + вывод)

    assert вызовы == [_PID], (
        "_убрать_протухший_порт обязан быть вызван РОВНО с PID "
        "остановленного демона на успешном пути — получено: {}".format(вызовы))


# --------------------------------------------------------------------------
#  второй исход находки (B): HTTP замолчал, но сам процесс к потолку
#      не исчез — отказ (не тихий успех по одному молчанию HTTP),
#      совет называет И `garant logs`, И `garant stop`, daemon_port
#      не трогается (файл всё ещё описывает живой процесс)
# --------------------------------------------------------------------------

def test_stop_http_замолчал_но_процесс_жив_отказ_с_logs_и_stop_и_без_уборки_порта(
        monkeypatch, capsys):
    """`процесс_умирает=False` (умолчание) — `_имя_процесса` держит имя на
    каждый вызов: демон замолчал на HTTP сразу, но сам процесс за весь
    потолок так и не ушёл. Раньше именно этот случай (молчание HTTP без
    проверки процесса) объявлялся успехом — здесь это отдельный, второй
    исход находки (B), и он обязан быть отказом.
    """
    _подготовить_опознание(monkeypatch, процесс_умирает=False)
    вызовы = _без_уборки_порта(monkeypatch)
    monkeypatch.setattr(protocol, "ПОТОЛОК_ОСТАНОВКИ_СЕК", 1)

    номер_вызова = {"n": 0}

    def _адрес():
        номер_вызова["n"] += 1
        # Первый вызов — ДО сигнала (демон ещё отвечает). Все следующие —
        # HTTP уже молчит, а вот процесс (см. _подготовить_опознание выше)
        # ни разу не подтверждает, что ушёл.
        return {"port": _ПОРТ, "pid": _PID, "alive": номер_вызова["n"] == 1}

    monkeypatch.setattr(dc, "адрес", _адрес)

    код = cli.stop()

    assert код == cli.КОД_НЕ_СДЕЛАНО, (
        "HTTP замолчал, но процесс спустя весь потолок не ушёл — это "
        "обязан быть отказ (код 1), а не тихий успех по одному молчанию "
        "HTTP")

    ошибка = capsys.readouterr().err
    assert str(_PID) in ошибка, (
        "отказ обязан называть PID процесса, который не ушёл:\n" + ошибка)
    assert "garant logs" in ошибка, (
        "отказ обязан указать, где искать след того, что делал процесс, "
        "пока не уходил (`garant logs`):\n" + ошибка)
    assert "garant stop" in ошибка, (
        "отказ обязан предложить повторить остановку (`garant stop`), "
        "если процесс так и не уйдёт:\n" + ошибка)
    assert вызовы == [], (
        "daemon_port всё ещё описывает ЖИВОЙ процесс — снять файл значило "
        "бы спрятать от следующей команды единственный след того, кто "
        "держит профиль, а _убрать_протухший_порт был вызван: {}"
        .format(вызовы))
