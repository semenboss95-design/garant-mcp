"""`strip_html` как чистая функция — без привязки к `document()`/`article()`.

Наряд (этап 03, фаза B, часть 3): до этого файла новое поведение
`strip_html` (07.09.2026 — `<br>`, ячейки, надстрочный и подстрочный индекс,
`&nbsp;`) не было покрыто НИ ОДНИМ тестом напрямую — только косвенно, через
фикстуры вырезки статьи/пункта, где случайное совпадение с ожидаемым текстом
неотличимо от настоящей проверки. Здесь — сама функция, без транспорта,
без клиента: `strip_html` не ходит в сеть и границы `Transport.fetch`
(решение 17) не касается вовсе.

Каждый тест проверяет ОДНО свойство разметки, а не повторяет регулярки
`client.py` — свойство сформулировано по тексту наряда, а не подсмотрено
в коде.
"""
from __future__ import annotations

from garant_mcp import client


def test_br_варианты_разделяют_строки():
    """<br>, <br/>, <br />, <BR> — разделитель строк, а не пустышка."""
    for разделитель in ("<br>", "<br/>", "<br />", "<BR>"):
        итог = client.strip_html(f"Первая{разделитель}Вторая")
        assert итог.split("\n") == ["Первая", "Вторая"], разделитель


def test_блочные_теги_разделяют_строки():
    """</p>, </div>, </tr> — разделитель, а не склейка соседних блоков."""
    for тег in ("p", "div", "tr"):
        итог = client.strip_html(f"<{тег}>Первая</{тег}><{тег}>Вторая</{тег}>")
        строки = [c for c in итог.split("\n") if c]
        assert строки == ["Первая", "Вторая"], тег


def test_ячейки_таблицы_разделяются_видимым_знаком():
    """</td> и </th> не склеивают соседние ячейки в одно слово."""
    итог = client.strip_html("<tr><td>А</td><td>Б</td></tr>")
    assert итог == "А | Б"
    assert "АБ" not in итог

    итог_th = client.strip_html("<tr><th>А</th><th>Б</th></tr>")
    assert итог_th == "А | Б"


def test_таблица_из_двух_строк_даёт_две_строки():
    """Строка таблицы — строка текста, а не одна большая склейка."""
    таблица = "<tr><td>А</td><td>Б</td></tr><tr><td>В</td><td>Г</td></tr>"
    итог = client.strip_html(таблица)
    assert итог.split("\n") == ["А | Б", "В | Г"]


def test_nbsp_становится_обычным_пробелом():
    """&nbsp; — обычный пробел в выдаче, \\xa0 наружу не уходит."""
    итог = client.strip_html("Слово&nbsp;слово")
    assert итог == "Слово слово"
    assert "\xa0" not in итог


def test_надстрочный_индекс_не_сливается_с_основанием():
    """«ст. 5<sup>1</sup>» — это «ст. 5^1», а не другая норма «ст. 51»."""
    итог = client.strip_html("ст. 5<sup>1</sup>")
    assert итог == "ст. 5^1"
    assert итог != "ст. 51"


def test_надстрочный_индекс_с_атрибутами_тега():
    """Атрибут у <sup> не мешает распознать сам тег как надстрочный."""
    итог = client.strip_html('ст. 5<sup class="idx" data-x="1">1</sup>')
    assert итог == "ст. 5^1"


def test_два_надстрочных_индекса_подряд():
    """Два <sup> подряд — два отдельных индекса, не один слипшийся."""
    итог = client.strip_html("ст. 5<sup>1</sup><sup>2</sup>")
    assert итог == "ст. 5^1^2"


def test_пустой_sup_не_создаёт_каретку_из_ниоткуда():
    """<sup></sup> без содержимого не добавляет «^», которого не было."""
    итог = client.strip_html("ст. 5<sup></sup> текст")
    assert "^" not in итог
    assert итог == "ст. 5 текст"


def test_подстрочный_индекс_не_сливается_с_основанием():
    """«К<sub>д</sub>» — «К_д», а не «Кд»: в формуле это разные переменные.

    Дефект найден вводом визы 07.09.2026; чинится параллельно `python-dev`.
    Форма разделителя («_») — из его правки (`_TAG_SUB` в client.py),
    сюда взята как факт, а не выдумана заново.
    """
    итог = client.strip_html("К<sub>д</sub>")
    assert итог == "К_д"
    assert итог != "Кд"


def test_подстрочный_индекс_с_атрибутами_и_пустой():
    """Атрибут у <sub> не мешает разбору; пустой <sub></sub> каретки не даёт."""
    итог = client.strip_html('К<sub class="idx">д</sub>')
    assert итог == "К_д"
    итог_пустой = client.strip_html("К<sub></sub> текст")
    assert "_" not in итог_пустой
    assert итог_пустой == "К текст"


def test_хвостовые_разделители_снимаются_все_подряд_идущие():
    """Несколько пустых ячеек в хвосте строки — не «А |», а просто «А».

    Один проход снимает только последний разделитель и оставляет след,
    которого в документе не было; здесь — три пустые ячейки подряд.
    """
    итог = client.strip_html("<tr><td>А</td><td></td><td></td></tr>")
    assert итог == "А"
    assert "|" not in итог


def test_правило_отпечатка_это_константа_модуля_а_не_литерал():
    """`ПРАВИЛО_ОТПЕЧАТКА` — единственная константа: сравнение с самим собой
    тавтологично только на бумаге, а на деле ловит опечатку вида
    константа-в-одном-месте vs литерал-в-другом, если кто-то однажды
    заведёт второе имя для той же строки. Это не проверка значения,
    это проверка, что источник истины один."""
    assert client.ПРАВИЛО_ОТПЕЧАТКА.startswith("strip_html/")
    # Ссылка на тот же объект по значению — намеренно тавтологичная форма:
    # реальную защиту от расхождения даёт test_client_отпечаток.py, где
    # константа сверяется с тем, что реально доехало в provenance через
    # подменённый транспорт. Здесь — что константа вообще определена и
    # имеет ожидаемую форму «имя_правила/номер».
    имя, _, номер = client.ПРАВИЛО_ОТПЕЧАТКА.partition("/")
    assert имя == "strip_html"
    assert номер.isdigit()


# Решение tech-lead (наряд «этап 03, фаза B, часть 4», 07.09.2026):
# `ПРАВИЛО_ОТПЕЧАТКА` НЕ поднимается до `strip_html/3` — версия правила
# метит КОНТРАКТ («одинаково ли посчитан текст у меня и у того, кто уже
# держит цитату под этой меткой»), а не считает правки. `strip_html/2` не
# выпущено ни разу (репозиторий не опубликован, тега нет, правка лежит
# в некоммиченном дереве) — поднимать номер внутри одного невыпущенного
# шага значило бы придать номеру значения, которых ни у кого не было.
#
# Правило, которое сторожат тесты ниже — буквально по решению: поведение
# нормализации не имеет права отличаться от последней ВЫПУЩЕННОЙ версии
# правила при том же значении `ПРАВИЛО_ОТПЕЧАТКА`. Выпущенная на сегодня
# версия ровно одна — `strip_html/1`: это то, что лежит в HEAD репозитория
# (последнем коммите) — до некоммиченной правки, поднявшей константу
# в РАБОЧЕМ ДЕРЕВЕ до `strip_html/2`, но не выпустившей её ни одним
# релизом или тегом.
#
# Эталон ниже — не выдумка и не повтор регулярок `client.py`: это буквальный
# вывод `strip_html()` версии HEAD, снятый однократно командой
# `git archive HEAD -- src/garant_mcp`, прогнанный в изолированном
# подпроцессе (без пакета garant_mcp, установленного в текущем venv) и
# записанный здесь ЛИТЕРАЛОМ, а не читаемый из git на каждом прогоне —
# потому что как только правку когда-нибудь закоммитят, `git show HEAD:...`
# перестанет отдавать /1, и тест начнёт молча сверяться не с тем, с чем
# должен. Зафиксированный текстом эталон переживает будущие коммиты именно
# потому, что не ссылается на HEAD во время прогона.
_ЭТАЛОН_STRIP_HTML_1 = [
    ("Первая<br>Вторая", "ПерваяВторая"),        # <br> склеивался, не разделял
    ("<tr><td>А</td><td>Б</td></tr>", "АБ"),       # ячейки склеивались в слово
    ("ст. 5<sup>1</sup>", "ст. 51"),               # надстрочный индекс сливался
    ("Слово&nbsp;слово", "Слово\xa0слово"),        # &nbsp; доживал как \xa0
]


def test_поведение_под_strip_html_1_заморожено_если_версия_на_ней():
    """При `ПРАВИЛО_ОТПЕЧАТКА == "strip_html/1"` вывод обязан побайтово
    совпасть с эталоном ВЫПУЩЕННОЙ версии — в этом и есть контракт версии:
    одна и та же метка обязана значить один и тот же способ счёта хеша
    у всех, кто её когда-либо видел. Расхождение здесь — это правка
    strip_html, протащенная под старой меткой, то есть ситуация из
    задания наряда «изменение поведения при strip_html/1» — обязана
    краснеть безусловно.

    Сегодня `ПРАВИЛО_ОТПЕЧАТКА` — `strip_html/2`, условие не наступает,
    и тест пропускается: сравнивать с эталоном /1 нечего, потому что
    код сейчас работает под ДРУГОЙ, более новой (хоть и невыпущенной)
    меткой — это и есть вторая половина решения, проверяемая тестом ниже.
    """
    if client.ПРАВИЛО_ОТПЕЧАТКА != "strip_html/1":
        import pytest
        pytest.skip(
            "ПРАВИЛО_ОТПЕЧАТКА сейчас {!r}, не strip_html/1 — условие "
            "заморозки не наступает".format(client.ПРАВИЛО_ОТПЕЧАТКА))
    for вход, ожидаемый in _ЭТАЛОН_STRIP_HTML_1:
        assert client.strip_html(вход) == ожидаемый, (
            "strip_html({!r}) разошёлся с эталоном ВЫПУЩЕННОЙ strip_html/1 "
            "({!r}) при том же значении ПРАВИЛО_ОТПЕЧАТКА — версия правила "
            "лжёт о том, что посчитано одинаково".format(вход, ожидаемый))


def test_версия_иначе_strip_html_1_обязана_отличаться_поведением():
    """Обратная половина того же правила: если `ПРАВИЛО_ОТПЕЧАТКА` — НЕ
    `strip_html/1` (то есть версию подняли), результат обязан отличаться
    от эталона /1 хотя бы в тех точках, ради которых версию поднимали.

    Совпадение с эталоном /1 при ДРУГОЙ метке — это и есть сценарий
    «откатили правку (например, вернули склейку `<br>` или ячеек), но
    забыли понизить версию обратно»: снаружи метка утверждает «поведение
    новое», а на деле оно byte-in-byte старое — метка перестаёт что-либо
    различать, и это ровно то, что решение tech-lead требует ловить.

    Сегодня `ПРАВИЛО_ОТПЕЧАТКА == "strip_html/2"`, реализация уже несёт
    все четыре правки — тест зелёный. Он же красный на копии, где ЛЮБАЯ
    одна из этих правок отменена без понижения версии (см. отчёт наряда:
    проверено на `<br>`).
    """
    if client.ПРАВИЛО_ОТПЕЧАТКА == "strip_html/1":
        import pytest
        pytest.skip("версия — strip_html/1, это условие для остальных версий")
    for вход, эталон_v1 in _ЭТАЛОН_STRIP_HTML_1:
        текущий = client.strip_html(вход)
        assert текущий != эталон_v1, (
            "strip_html({!r}) вернул то же самое, что версия strip_html/1 "
            "({!r}), хотя ПРАВИЛО_ОТПЕЧАТКА сейчас {!r} — версию подняли, "
            "а поведение для этого входа осталось прежним: похоже, правку "
            "откатили и забыли понизить версию обратно.".format(
                вход, эталон_v1, client.ПРАВИЛО_ОТПЕЧАТКА))
