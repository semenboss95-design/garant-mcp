"""`/health` не течёт, `/version` минимален (этап 02, шаг 2).

`/health` отвечает БЕЗ токена — его читает любой, кто может сделать GET на
петлю (заголовок Host демон не проверяет). До правки в это тело попадало
`WORKER.state` целиком: в том числе `последняя_ошибка`, у которой в тексте
бывают абсолютные пути машины (`GarantError` часто цитирует путь профиля
или каталога состояния). Состояние сессии и пути переехали под токен,
в `/state`; безтокенный `/health` обязан остаться СЛУЖЕБНЫМ — признак демона
и счётчики, ничего похожего на диагностику.

Признак демона (`protocol.ПРИЗНАК_ДЕМОНА`) в `/health` при этом обязан
остаться: решение 9 требует опознавать демон именно этим безтокенным
запросом, до отправки токена. Тест на утечку не должен случайно разрешить
его тоже убрать — поэтому здесь ровно два свойства и оба обязательны.

`/version` — тот же по духу случай токена: сверка версий (`сверить_версию`)
идёт ДО того, как у клиента может быть токен рабочего процесса, поэтому
`/version` тоже безтокенный, и по той же причине обязан быть минимальным.

Реальный демон, реальный HTTP — как в `test_port.py`, откуда и позаимствованы
стенд и вспомогательные функции: второй их экземпляр здесь разошёлся бы
с первым ровно так же, как расходились пути.
"""

from __future__ import annotations

import json
import re
import sys
import urllib.request
from pathlib import Path

from test_port import стенд, _свободный_порт, _дождаться_порта  # noqa: F401

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
if str(SRC) not in sys.path:
    sys.path.insert(0, str(SRC))

import garant_mcp.protocol as protocol  # noqa: E402

# Признак абсолютного пути машины: буква диска Windows (см. test_подсказки.py)
# либо ведущий разделитель POSIX. Ищем по всем строковым значениям тела —
# рекурсивно, потому что утечка бывает и во вложенном словаре.
_БУКВА_ДИСКА = re.compile(r"[A-Za-z]:[\\/]")
_POSIX_АБСОЛЮТНЫЙ = re.compile(r"(^|[\s\"])/[A-Za-z0-9_.\-]+/")


def _строки(значение):
    """Все строковые листья JSON-структуры, плоским списком."""
    if isinstance(значение, str):
        yield значение
    elif isinstance(значение, dict):
        for v in значение.values():
            yield from _строки(v)
    elif isinstance(значение, list):
        for v in значение:
            yield from _строки(v)


def _get(порт: int, путь: str) -> dict:
    with urllib.request.urlopen(
            "http://127.0.0.1:{}{}".format(порт, путь), timeout=10) as r:
        return json.loads(r.read().decode("utf-8"))


# --------------------------------------------------------------------------
#  /health — признак остаётся, утечки нет
# --------------------------------------------------------------------------

def test_health_несёт_признак_демона_без_токена(стенд):
    порт = _свободный_порт()
    p = стенд.демон({"GARANT_PORT": str(порт)})
    данные = _дождаться_порта(стенд.состояние, p)

    тело = _get(данные["порт"], "/health")
    assert protocol.ПРИЗНАК_ДЕМОНА in тело, (
        "признак демона обязан остаться в безтокенном /health — на нём "
        "держится опознание до отправки токена (решение 9)."
    )


def test_health_не_содержит_последней_ошибки(стенд):
    порт = _свободный_порт()
    p = стенд.демон({"GARANT_PORT": str(порт)})
    данные = _дождаться_порта(стенд.состояние, p)

    тело = _get(данные["порт"], "/health")
    assert "последняя_ошибка" not in тело, (
        "«последняя_ошибка» — под токеном, в /state. В безтокенном /health "
        "ей не место: этот ответ читает любой, кто может сделать GET на "
        "петлю, а в тексте ошибки бывает абсолютный путь машины."
    )
    assert "каталоги" not in тело and "отпечаток" not in тело, (
        "пути (каталоги состояния, профиля, логов) и описание отпечатка — "
        "тоже под токеном, в /state."
    )


def test_health_не_содержит_путей_машины(стенд):
    """Признак демона и служебные счётчики — не абсолютные пути, поэтому
    сканируем ВСЕ строковые значения тела, а не выборочные ключи: утечка
    возвращается копипастой в новое поле, а не обязательно в старое.
    """
    порт = _свободный_порт()
    p = стенд.демон({"GARANT_PORT": str(порт)})
    данные = _дождаться_порта(стенд.состояние, p)

    тело = _get(данные["порт"], "/health")
    подозрительные = [
        s for s in _строки(тело)
        if _БУКВА_ДИСКА.search(s) or _POSIX_АБСОЛЮТНЫЙ.search(s)
        or str(стенд.состояние) in s
    ]
    assert not подозрительные, (
        "безтокенный /health содержит значения, похожие на абсолютный путь "
        "машины: {}".format(подозрительные)
    )


# --------------------------------------------------------------------------
#  /version — минимален, без токена
# --------------------------------------------------------------------------

def test_version_без_токена_минимален(стенд):
    """Версия и признак демона — и только. /version читает клиент ДО того,
    как у него может быть токен рабочего процесса (сверка версий идёт
    раньше опознания под токеном), поэтому лишнее поле здесь — та же утечка,
    что и в /health.
    """
    порт = _свободный_порт()
    p = стенд.демон({"GARANT_PORT": str(порт)})
    данные = _дождаться_порта(стенд.состояние, p)

    тело = _get(данные["порт"], "/version")
    assert set(тело.keys()) == {protocol.ПРИЗНАК_ДЕМОНА, "версия"}, (
        "/version обязан нести ровно два поля — признак демона и версию, "
        "получено: {}".format(sorted(тело.keys()))
    )
