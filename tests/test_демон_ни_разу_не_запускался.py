# -*- coding: utf-8 -*-
"""Дефект без теста из `780a303`: `daemon_client._token()` собирал оба текста
смесью `+` и `.format()` — конкатенация выполняется раньше вызова `.format`,
которому достаётся только последний кусок, а плейсхолдеры соседних кусков
уезжают пользователю сырыми `{}`. Ветка `демон_отвечает=True` теряла порт
и весь блок «Искал здесь / Каталог состояния выбран так» — ровно то
сообщение, что разводит «демон ни разу не запускался» и «демон работает,
но из другой установки». Правка (`780a303`) переписала обе ветки f-строками;
теста на это не было — «дефект без теста живёт до следующей правки рядом».

Свойство: в ОБЕИХ ветках (`демон_отвечает=True` и `False`) сообщение
1) не содержит сырых фигурных скобок `{}` (след потерянной подстановки);
2) несёт блок «Искал здесь» и «Каталог состояния выбран так» — то, что
   `780a303` восстановило конкретно;
3) в ветке True — называет порт числом, который ей передали.

Среда: `GARANT_HOME` указывает на чистую песочницу без `daemon_token`
(файла нет никогда — `_token()` не пишет и не читает сеть, только диск),
поэтому оба вызова гарантированно попадают в ветку исключения. Отдельный
процесс (`subprocess`) — тут не ради побочных эффектов импорта, а чтобы
`GARANT_HOME` подействовал ДО того, как `paths.token_file` вычислится на
уровне модуля (`daemon_client.TOKEN_FILE = paths.token_file` — модульная
константа, второй импорт в этом же процессе её не пересчитает).
"""

from __future__ import annotations

from test_paths import _песочница, _окружение, _запуск, чужой_каталог  # noqa: F401
from test_port import _свободный_порт  # noqa: F401

_КОД = """
import sys
sys.path.insert(0, r'{site}')
from garant_mcp import daemon_client as dc

try:
    dc._token(демон_отвечает={демон_отвечает}, порт={порт})
    print("НЕ_ВОЗБУЖДЕНО")
except dc.DaemonError as e:
    print("ТЕКСТ_НАЧАЛО")
    print(str(e))
    print("ТЕКСТ_КОНЕЦ")
"""


def _сообщение(пакет, cwd, демон_отвечает: bool, порт: int) -> str:
    код = _КОД.format(site=пакет.parent, демон_отвечает=демон_отвечает, порт=порт)
    r = _запуск(код, cwd, {"GARANT_HOME": str(cwd / "состояние")})
    вывод = r.stdout
    assert "ТЕКСТ_НАЧАЛО" in вывод, (
        "_token() не возбудил DaemonError там, где токена нет никогда:\n"
        + r.stdout + r.stderr)
    начало = вывод.index("ТЕКСТ_НАЧАЛО") + len("ТЕКСТ_НАЧАЛО\n")
    конец = вывод.index("ТЕКСТ_КОНЕЦ")
    return вывод[начало:конец]


def test_демон_отвечает_сообщение_несёт_порт_и_где_искали(tmp_path, чужой_каталог):
    пакет = _песочница(tmp_path)
    порт = _свободный_порт()
    текст = _сообщение(пакет, чужой_каталог, демон_отвечает=True, порт=порт)

    assert "{}" not in текст, (
        "в сообщении осталась сырая фигурная скобка — потерянная "
        "подстановка (Д, закрытый 780a303 без теста):\n" + текст)
    assert str(порт) in текст, (
        "сообщение о демоне, который отвечает, но опознан как чужая "
        "установка, не называет порт — читатель не понимает, о каком "
        "демоне речь:\n" + текст)
    assert "Искал здесь" in текст, (
        "пропал блок «Искал здесь» — тот самый, ради которого делался "
        "прошлый коммит:\n" + текст)
    assert "Каталог состояния выбран так" in текст, (
        "пропал блок «Каталог состояния выбран так»:\n" + текст)


def test_демон_не_запускался_сообщение_несёт_где_искали(tmp_path, чужой_каталог):
    пакет = _песочница(tmp_path)
    порт = _свободный_порт()
    текст = _сообщение(пакет, чужой_каталог, демон_отвечает=False, порт=порт)

    assert "{}" not in текст, (
        "в сообщении «демон ни разу не запускался» осталась сырая "
        "фигурная скобка — потерянная подстановка:\n" + текст)
    assert "Искал здесь" in текст, (
        "пропал блок «Искал здесь» в сообщении «демон ни разу не "
        "запускался»:\n" + текст)
    assert "Каталог состояния выбран так" in текст, (
        "пропал блок «Каталог состояния выбран так» в сообщении «демон "
        "ни разу не запускался»:\n" + текст)
