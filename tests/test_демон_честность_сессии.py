# -*- coding: utf-8 -*-
"""Честность состояния сессии в `BrowserWorker` (этап 02, шаг 2).

До правки любое исключение из вызова к «Гаранту» судило сессию подписки по
подстроке в тексте: «401», «403», «сесси» без приведения регистра. Запрос
про «статью 401.11» объявлял живую подписку мёртвой, таймаут ожидания
демона — тоже, а ответ из кэша или пустой список видов информации сходили
за подтверждение того, что подписка вообще жива. Теперь решает ТИП ошибки
(`protocol.py`), поставленный тем, кто знает причину, а не текст.

Проверяется здесь `garant_mcp.daemon.BrowserWorker` — реальный код очереди
задач и потока-владельца (`submit()` → очередь → `run()` → классификация →
`_set_session()`), а не его пересказ. Браузер при этом не запускается:
вместо `GarantClient` подставляется фиктивный объект с нужными методами —
это ПОДМЕНА КОЛЛАБОРАТОРА демона (`self.client`), а не подмена того, что
разбирает ответ «Гаранта» (это `client.py`, граница подмены там —
`Transport.fetch`, решение 17, и её эта проверка не касается: она про
демон, а не про клиента).

Сеть не нужна вовсе — фиктивный клиент решает исход синтетически. Процесс
свой на каждый прогон: `daemon.py` при импорте открывает лог-хендлер
(`delay=True`) в каталог состояния, и он обязан существовать
(`paths.ensure_state()`), поэтому демон импортируется в подпроцессе
с отдельным `GARANT_HOME`, а не в процессе pytest, где это загрязнило бы
настоящий каталог состояния разработчика.
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src"

# Скрипт-подпроцесс: поднимает несколько независимых BrowserWorker с
# фиктивным клиентом, прогоняет сценарии и печатает JSON с результатом
# каждого — один прогон демона на все сценарии, чтобы не тратить время
# на повторный импорт daemon.py (он не бесплатный: тянет client.py).
_СКРИПТ = r'''
import sys, json
sys.path.insert(0, r"{site}")
import garant_mcp.paths as paths
paths.ensure_state()
import garant_mcp.daemon as daemon
protocol = daemon.protocol

РЕЗУЛЬТАТ = {{}}


class Фиктивный:
    """Стоит на месте GarantClient. Ничего не открывает и никуда не ходит."""

    def __init__(self):
        self._kinds = []
        self._keepalive_outcome = "HTTP 200"
        self._keepalive_raises = None

    def ok(self, **kw):
        return {{"данные": "живой ответ"}}

    def ok_из_кэша(self, **kw):
        return {{"данные": "из кэша", "provenance": {{"из_кэша": True}}}}

    def падает_session(self, **kw):
        raise protocol.GarantError("сессия недействительна", protocol.ТИП_СЕССИЯ, 403)

    def падает_timeout(self, **kw):
        raise protocol.GarantError("не дождались", protocol.ТИП_ТАЙМАУТ)

    def падает_api(self, **kw):
        raise protocol.GarantError("ответ не по карте", protocol.ТИП_API)

    def падает_not_found(self, **kw):
        raise protocol.GarantError("не найдено", protocol.ТИП_НЕ_НАЙДЕНО)

    def падает_обычным_401_в_тексте(self, **kw):
        # РЕГРЕССИЯ: сообщение с «401» и словом «сессия», но НЕ GarantError —
        # раньше подстрока в тексте любого исключения решала за тип.
        raise ValueError("не найдена статья 401.11 УПК — Сессия поиска пуста")

    def kinds(self, node_id):
        return self._kinds

    def _keepalive(self, force=True):
        if self._keepalive_raises:
            raise self._keepalive_raises
        return self._keepalive_outcome


ВСЕ_ПОТОКИ = []


def новый(сессия_изначально="не проверена"):
    """Свежий BrowserWorker с фиктивным клиентом, поток запущен.

    Каждый созданный поток регистрируется в ВСЕ_ПОТОКИ и останавливается
    перед выходом интерпретатора (см. конец скрипта) — иначе поток-демон
    (`daemon=True`) гонится с финализацией CPython на выходе, и Windows
    изредка ловит это как `Fatal Python error` при завершении процесса.
    """
    w = daemon.BrowserWorker(keepalive_sec=10**9)
    w.state["сессия"] = сессия_изначально
    w.client = Фиктивный()
    w.start()
    ВСЕ_ПОТОКИ.append(w)
    return w


def вызвать(w, метод, **kw):
    """submit(), но не роняет процесс на ошибке — она ожидаема."""
    try:
        return {{"ok": True, "результат": w.submit(метод, kw, timeout=10)}}
    except Exception as e:
        тип = getattr(e, "тип", None)
        return {{"ok": False, "тип": тип, "текст": str(e)}}


# 1. ошибка типа session переводит сессию в "недействительна"
w = новый("жива")
вызвать(w, "падает_session")
РЕЗУЛЬТАТ["session_ставит_недействительна"] = w.state["сессия"]

# 2. ошибка типа timeout состояние не трогает
w = новый("жива")
вызвать(w, "падает_timeout")
РЕЗУЛЬТАТ["timeout_не_трогает"] = w.state["сессия"]

# 3. api_changed и not_found состояние не трогают
w = новый("жива")
вызвать(w, "падает_api")
РЕЗУЛЬТАТ["api_changed_не_трогает"] = w.state["сессия"]

w = новый("жива")
вызвать(w, "падает_not_found")
РЕЗУЛЬТАТ["not_found_не_трогает"] = w.state["сессия"]

# 4. регрессия: «401» и «сессия» в тексте ОБЫЧНОГО исключения — не session
w = новый("жива")
вызвать(w, "падает_обычным_401_в_тексте")
РЕЗУЛЬТАТ["текст_401_не_трогает"] = w.state["сессия"]

# 5. keepalive: любой исход пишет "исход", не трогает "сессия"
w = новый("не проверена")
w._keepalive()
РЕЗУЛЬТАТ["keepalive_успех_исход"] = w.state["последний_keepalive_исход"]
РЕЗУЛЬТАТ["keepalive_успех_сессия"] = w.state["сессия"]
РЕЗУЛЬТАТ["keepalive_успех_время_записано"] = w.state["последний_keepalive"] is not None

w2 = новый("жива")
w2.client._keepalive_raises = RuntimeError("нет соединения")
w2._keepalive()
РЕЗУЛЬТАТ["keepalive_ошибка_исход"] = w2.state["последний_keepalive_исход"]
РЕЗУЛЬТАТ["keepalive_ошибка_сессия"] = w2.state["сессия"]

# 6. ответ из кэша не подтверждает сессию; обычный ответ — подтверждает
w = новый("не проверена")
вызвать(w, "ok_из_кэша")
РЕЗУЛЬТАТ["из_кэша_не_подтверждает"] = w.state["сессия"]
вызвать(w, "ok")
РЕЗУЛЬТАТ["живой_ответ_подтверждает"] = w.state["сессия"]

# 7. kinds(0) == [] не подтверждает подписку; непустой список — подтверждает
w = новый("не проверена")
w.client._kinds = []
пусто = вызвать(w, "_probe")
РЕЗУЛЬТАТ["kinds_пусто_подписка_ответила"] = пусто["результат"]["подписка_ответила"]
РЕЗУЛЬТАТ["kinds_пусто_сессия"] = w.state["сессия"]

w = новый("не проверена")
w.client._kinds = [{{"id": 1}}]
непусто = вызвать(w, "_probe")
РЕЗУЛЬТАТ["kinds_непусто_подписка_ответила"] = непусто["результат"]["подписка_ответила"]
РЕЗУЛЬТАТ["kinds_непусто_сессия"] = w.state["сессия"]

# У BrowserWorker нет публичного stop() — только внутренний threading.Event
# self._остановлен, который run() проверяет раз в такт (не чаще, чем раз
# в 1 с, см. q.get(timeout=1.0)). Не публичный интерфейс, а прямой доступ
# к тому, что есть: даже это делается здесь, в скрипте-подпроцессе, не
# в src/. Имя НЕ `_stop` (решение 32): так называется приватный МЕТОД
# threading.Thread, и присвоение ему threading.Event ловится молча на
# python 3.12 — Thread.join() зовёт его как метод и падает TypeError.
for _w in ВСЕ_ПОТОКИ:
    _w._остановлен.set()
for _w in ВСЕ_ПОТОКИ:
    _w.join(timeout=5)
    if _w.is_alive():
        # Не падаем здесь молча: если поток не остановился за 5 с, это
        # само по себе диагностический факт для сдачи, а не повод скрыть
        # его под общим returncode 0.
        РЕЗУЛЬТАТ.setdefault("потоки_не_остановились", []).append(_w.name)

print(json.dumps(РЕЗУЛЬТАТ, ensure_ascii=False))
'''


def _выполнить(состояние: Path) -> dict:
    import os

    r = subprocess.run(
        [sys.executable, "-c", _СКРИПТ.format(site=str(SRC))],
        cwd=str(состояние.parent),
        env={"GARANT_HOME": str(состояние), "PATH": os.environ.get("PATH", ""),
             "PYTHONIOENCODING": "utf-8"},
        capture_output=True, text=True, encoding="utf-8", errors="replace",
        timeout=60,
    )
    assert r.returncode == 0, (
        "сценарий BrowserWorker упал:\n" + r.stdout + r.stderr)
    строки = [s for s in r.stdout.strip().splitlines() if s.startswith("{")]
    assert строки, "не удалось прочитать результат:\n" + r.stdout + r.stderr
    return json.loads(строки[-1])


@pytest.fixture(scope="module")
def р(tmp_path_factory) -> dict:
    """Один подпроцесс на все сценарии этого файла — они независимы друг от
    друга (каждый сценарий создаёт СВОЙ BrowserWorker), и гонять chromium-less
    импорт daemon.py заново на каждый assert незачем.
    """
    состояние = tmp_path_factory.mktemp("состояние")
    return _выполнить(состояние)


# --------------------------------------------------------------------------
#  1. session — единственный тип, который трогает состояние
