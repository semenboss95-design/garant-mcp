def test_ошибка_session_ставит_сессию_недействительна(р):
    assert р["session_ставит_недействительна"] == "недействительна"


def test_ошибка_timeout_не_трогает_сессию(р):
    assert р["timeout_не_трогает"] == "жива", (
        "таймаут ожидания демона не говорит НИЧЕГО о состоянии подписки — "
        "раньше именно так живая сессия объявлялась мёртвой."
    )


def test_ошибка_api_changed_не_трогает_сессию(р):
    assert р["api_changed_не_трогает"] == "жива"


def test_ошибка_not_found_не_трогает_сессию(р):
    assert р["not_found_не_трогает"] == "жива"


def test_регрессия_401_в_тексте_постороннего_исключения_не_трогает_сессию(р):
    """Тот самый дефект: «статья 401.11», «Сессия…» в тексте ОБЫЧНОГО
    исключения (не GarantError) — решает тип классификации (api_changed
    для неопознанного), а не подстрока.
    """
    assert р["текст_401_не_трогает"] == "жива"


# --------------------------------------------------------------------------
#  2. keepalive: исход всегда, сессия — никогда
# --------------------------------------------------------------------------

def test_keepalive_успех_пишет_исход_и_время_но_не_сессию(р):
    assert р["keepalive_успех_исход"] == "HTTP 200"
    assert р["keepalive_успех_время_записано"] is True
    assert р["keepalive_успех_сессия"] == "не проверена", (
        "keepalive не ходит через типизированную классификацию сессии — "
        "успешное продление НЕ обязано означать, что рабочий контекст "
        "подтверждён живым ответом «Гаранта» на прикладной запрос."
    )


def test_keepalive_ошибка_пишет_исход_но_не_сессию(р):
    assert р["keepalive_ошибка_исход"].startswith("исключение:")
    assert р["keepalive_ошибка_сессия"] == "жива", (
        "keepalive никогда не объявляет сессию подписки мёртвой — иначе "
        "холодный старт (гонка с 403 на живой сессии) выглядел бы как "
        "разрыв подписки."
    )


# --------------------------------------------------------------------------
#  3. кэш и пустая подписка не подтверждают сессию
# --------------------------------------------------------------------------

def test_ответ_из_кэша_не_подтверждает_сессию(р):
    assert р["из_кэша_не_подтверждает"] == "не проверена", (
        "ответ из кэша не был походом в «Гарант» и не доказывает, что "
        "рабочий контекст авторизован."
    )


def test_живой_ответ_подтверждает_сессию(р):
    """Контраст к предыдущему: обычный (не кэшированный) успешный ответ
    сессию подтверждает — иначе кэш оказался бы неотличим от рабочего пути.
    """
    assert р["живой_ответ_подтверждает"] == "жива"


def test_kinds_пустой_список_не_подтверждает_подписку(р):
    assert р["kinds_пусто_подписка_ответила"] is False
    assert р["kinds_пусто_сессия"] == "не проверена", (
        "«Гарант» ответил, но пустым деревом видов — это не подтверждение "
        "подписки, и сессия не обязана становиться «жива»."
    )


def test_kinds_непустой_список_подтверждает_подписку(р):
    assert р["kinds_непусто_подписка_ответила"] is True
    assert р["kinds_непусто_сессия"] == "жива"


# --------------------------------------------------------------------------
#  4. потоки-демоны останавливаются сами, а не полагаются на финализацию
# --------------------------------------------------------------------------

def test_все_поднятые_browserworker_остановлены(р):
    """Регрессия на плавающую ошибку: сценарий поднимает несколько
    `BrowserWorker` (`threading.Thread(daemon=True)`) и обязан остановить
    КАЖДЫЙ явным `join()` перед выходом интерпретатора. Раньше не
    останавливал ни один — и раз из четырёх это ловилось Windows как
    `Fatal Python error: _enter_buffered_busy … at interpreter shutdown»`
    (returncode `0xC0000409`), потому что поток-демон гонится с
    финализацией CPython. Если этот тест зелёный, а в среде разработки
    ошибка вернулась — дефект не здесь, а в `BrowserWorker`: значит,
    `_остановлен.set()` перестал приводить поток к выходу из `run()` за
    отведённые 5 секунд.
    """
    assert "потоки_не_остановились" not in р, (
        "не все BrowserWorker остановились за 5 секунд после "
        "_остановлен.set(): " + str(р.get("потоки_не_остановились"))
    )
