# -*- coding: utf-8 -*-
"""Тест на сам детектор перечисления файлов репозитория (Д-7).

`_repo_git.py` звал `git ls-files` БЕЗ `-z`. Git по умолчанию заключает
в кавычки и экранирует пути с не-ASCII символами (`"каталог/Ð..."`
вместо `каталог/Файл.md`), и такой путь потом не открывается с диска:
`(ROOT / путь).read_bytes()` получает буквальную escape-строку, а не
реальное имя файла на диске, падает `OSError`, и файл молча выпадает
из ЛЮБОЙ проверки, построенной на `публичные_кандидаты()` —
в том числе из `test_ссылки_на_приватное.py` и
`test_следы_прежней_раскладки.py`. Тот же приём (`-z`) и то же
объяснение уже были в `hooks/pre-commit` (см. комментарий там); список
файлов для тестов набирался заново и наступил на те же грабли.

Свойство, которое здесь проверяется: файл с не-ASCII именем в индексе
ОБЯЗАН попасть в список кандидатов и его содержимое ОБЯЗАНО прочитаться
— иначе он для всех проверок этого модуля не существует.

БЕЗОПАСНОСТЬ РАБОЧЕГО ИНДЕКСА: проба ставится в ИЗОЛИРОВАННОМ временном
git-репозитории (тот же приём, что в `test_хук_пробы.py`), а не в этом
дереве. `_repo_git.ROOT` подменяется на каталог пробы ТОЛЬКО на время
теста (`monkeypatch.setattr`), настоящий `ROOT` восстанавливается
автоматически по выходе из теста.
"""

from __future__ import annotations

import subprocess
from pathlib import Path

import _repo_git

ИМЯ_НОНASCII = "заметка с кириллицей.md"


def _репозиторий_с_нонascii_файлом(tmp_path: Path) -> Path:
    """Отдельный git-репозиторий с одним закоммиченным в индекс файлом,
    чьё имя — не-ASCII с пробелом: ровно то, что `git ls-files` без `-z`
    заключает в кавычки."""
    repo = tmp_path
    r = subprocess.run(["git", "init", "-q"], cwd=str(repo),
                        capture_output=True, text=True)
    assert r.returncode == 0, "git init не сработал: " + r.stderr
    subprocess.run(["git", "config", "user.email", "проба@localhost"],
                    cwd=str(repo), capture_output=True)
    subprocess.run(["git", "config", "user.name", "проба"],
                    cwd=str(repo), capture_output=True)

    # Склейка, а не литерал: тот же приём, что в `test_хук_пробы.py` — иначе
    # ЭТОТ файл теста сам попал бы под правило «путь внутрь venv» из
    # `test_следы_прежней_раскладки.py`, которое смотрит по всему дереву.
    метка_venv = ".venv" + "/" + "Scripts"
    (repo / ИМЯ_НОНASCII).write_bytes(
        "нарушение для пробы: путь внутрь {}\n".format(метка_venv).encode("utf-8"))
    r = subprocess.run(["git", "add", "--", ИМЯ_НОНASCII], cwd=str(repo),
                        capture_output=True, text=True)
    assert r.returncode == 0, "git add провалился: " + r.stderr
    return repo


def test_отслеживаемые_видят_файл_с_нонascii_именем(tmp_path, monkeypatch):
    repo = _репозиторий_с_нонascii_файлом(tmp_path)
    monkeypatch.setattr(_repo_git, "ROOT", repo)
    список = _repo_git.отслеживаемые()
    assert ИМЯ_НОНASCII in список, (
        "файл с не-ASCII именем не найден `отслеживаемые()` — "
        "перечисление `git ls-files` без -z заключает такой путь в "
        "кавычки и экранирует байты, полученная строка не совпадает "
        "с реальным именем файла, и он выпадает из проверки молча (Д-7); "
        "получено: {}".format(список))


def test_публичные_кандидаты_видят_файл_с_нонascii_именем(tmp_path, monkeypatch):
    repo = _репозиторий_с_нонascii_файлом(tmp_path)
    monkeypatch.setattr(_repo_git, "ROOT", repo)
    кандидаты = _repo_git.публичные_кандидаты()
    assert ИМЯ_НОНASCII in кандидаты, (
        "файл с не-ASCII именем не найден в `публичные_кандидаты()` — "
        "та же болезнь, что и в `отслеживаемые()` (Д-7); "
        "получено: {}".format(кандидаты))


def test_содержимое_нонascii_файла_читается_с_диска(tmp_path, monkeypatch):
    repo = _репозиторий_с_нонascii_файлом(tmp_path)
    monkeypatch.setattr(_repo_git, "ROOT", repo)
    текст = _repo_git.прочитать_из_рабочего_дерева(ИМЯ_НОНASCII)
    assert текст is not None and ".venv" in текст, (
        "содержимое файла с не-ASCII именем не прочиталось с диска — "
        "путь, полученный из `git ls-files` без -z, экранирован и не "
        "совпадает с реальным именем файла, поэтому `read_bytes()` не "
        "находит файл и проверки контента (ссылки на приватное, следы "
        "прежней раскладки) по нему НЕ выполняются (Д-7); прочитано: {!r}"
        .format(текст))
