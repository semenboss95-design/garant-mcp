# -*- coding: utf-8 -*-
"""Замок подъёма демона внутри одного процесса (`daemon_client._ЗАМОК_ПОДЪЁМА`).

Отдельно от `test_замок_профиля.py`: там проверяется гонка МЕЖДУ процессами
(её решает замок владения профилем в самом демоне), здесь — гонка ВНУТРИ
одного процесса сервера, у которого четыре потока в пуле и каждый на
холодном старте зовёт `обеспечить_демона()`. Без замка это четыре `Popen`
подряд — четыре chromium вместо одного, и в логе это выглядит как поломка.

Границы подмены — `subprocess.Popen` (запуск процесса) и
`_убедиться_что_наш` (сетевой поход на `/health`): это ровно два места,
где `daemon_client` касается внешнего мира. Всё остальное — `обеспечить_демона`,
её повторная проверка под замком, сам замок — исполняется по-настоящему,
в потоках этого же процесса pytest.

Модуль `daemon_client.py` не имеет побочных эффектов на импорте (как и
`paths.py`, который он тянет): импорт лишь вычисляет пути через
`platformdirs`, ничего не создавая на диске, поэтому прямой импорт в
процессе теста безопасен и не требует песочницы с копией пакета — здесь не
меряются побочные эффекты импорта, а проверяется логика синхронизации.
"""

from __future__ import annotations

import sys
import threading
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
if str(SRC) not in sys.path:
    sys.path.insert(0, str(SRC))

import garant_mcp.daemon_client as daemon_client  # noqa: E402


@pytest.fixture(autouse=True)
def _без_замка_на_старте():
    """Каждый тест обязан начинать со свободного замка подъёма.

    Замок — модульный объект (`threading.Lock`), общий на все тесты этого
    процесса pytest. Тест, упавший с удержанным замком, не должен подвесить
    следующий: если по какой-то причине замок остался занят, лучше упасть
    здесь явно, чем зависнуть в `with` следующего теста без единого намёка
    на причину.
    """
    if daemon_client._ЗАМОК_ПОДЪЁМА.locked():
        pytest.fail("замок подъёма занят ДО начала теста — предыдущий тест "
                    "не отпустил его.")
    yield


# --------------------------------------------------------------------------
#  2. четыре параллельных вызова — один Popen
# --------------------------------------------------------------------------

def test_четыре_потока_поднимают_демона_один_раз(monkeypatch):
    """Четыре потока одновременно зовут `обеспечить_демона()` на холодном
    старте (демона ещё нет). Обязан быть ровно один `Popen`: остальные три
    потока обязаны дождаться его на замке и увидеть уже поднятого демона,
    а не запустить свой собственный процесс.
    """
    вызовов_popen: list = []
    поднят = threading.Event()

    def фиктивный_popen(*a, **kw):
        вызовов_popen.append((a, kw))
        # Имитация: процесс запущен, и через мгновение он ответит на /health.
        # threading.Timer — не sleep здесь: Popen обязан вернуться сразу,
        # как и настоящий (он не блокирует запускающего).
        threading.Timer(0.3, поднят.set).start()

        class _Фиктивный:
            pass

        return _Фиктивный()

    def фиктивный_убедиться(порт):
        if not поднят.is_set():
            raise daemon_client.DaemonError("демон ещё не поднят")
        return None  # успех — как настоящая _убедиться_что_наш

    monkeypatch.setattr(daemon_client.subprocess, "Popen", фиктивный_popen)
    monkeypatch.setattr(daemon_client, "_убедиться_что_наш", фиктивный_убедиться)

    ошибки: list = []
    результаты: list = []

    def работа():
        try:
            результаты.append(daemon_client.обеспечить_демона(ждать_сек=5))
        except Exception as e:  # DaemonError или что угодно — фиксируем как отказ
            ошибки.append(e)

    потоки = [threading.Thread(target=работа) for _ in range(4)]
    for t in потоки:
        t.start()
    for t in потоки:
        t.join(timeout=15)

    assert not any(t.is_alive() for t in потоки), "поток(и) не завершились"
    assert not ошибки, "обеспечить_демона упала: {}".format(ошибки)
    assert len(результаты) == 4
    assert len(вызовов_popen) == 1, (
        "обеспечить_демона запустила процесс {} раз(а) из четырёх "
        "параллельных вызовов на холодном старте — замок подъёма не "
        "сериализовал запуск, каждый поток поднял бы свой chromium."
        .format(len(вызовов_popen)))


# --------------------------------------------------------------------------
#  3. опознание не кэшируется: смерть демона снова требует Popen
# --------------------------------------------------------------------------

def test_после_смерти_демона_следующий_подъём_снова_проверяет_и_поднимает(
        monkeypatch):
    """Решение 9: опознание не кэшируется. Замок подъёма синхронизирует
    ПОПЫТКИ поднять демона внутри процесса, но не имеет права подменить
    собой сам факт проверки `/health` перед каждым обращением: однажды
    поднятый и потом умерший демон обязан быть поднят заново, а не
    считаться работающим по памяти о прошлом успехе.
    """
    вызовов_health: list = []
    вызовов_popen: list = []
    жив = {"да": False}

    def фиктивный_убедиться(порт):
        вызовов_health.append(порт)
        if not жив["да"]:
            raise daemon_client.DaemonError("демон не отвечает")

    def фиктивный_popen(*a, **kw):
        вызовов_popen.append(1)
        жив["да"] = True

        class _Фиктивный:
            pass

        return _Фиктивный()

    monkeypatch.setattr(daemon_client, "_убедиться_что_наш", фиктивный_убедиться)
    monkeypatch.setattr(daemon_client.subprocess, "Popen", фиктивный_popen)

    итог1 = daemon_client.обеспечить_демона(ждать_сек=5)
    assert итог1 == "демон поднят"
    assert len(вызовов_popen) == 1
    вызовов_health_после_первого = len(вызовов_health)
    assert вызовов_health_после_первого >= 2, (
        "обеспечить_демона обязана спросить /health хотя бы дважды за один "
        "подъём: один раз ДО (чтобы решить, поднимать ли), и хотя бы один "
        "раз ПОСЛЕ Popen (чтобы дождаться ответа) — иначе решение "
        "принимается без проверки вовсе.")

    # Демон «умер» — опознание обязано увидеть это заново, а не отдать
    # закэшированное «уже работал» из первого вызова.
    жив["да"] = False

    итог2 = daemon_client.обеспечить_демона(ждать_сек=5)
    assert итог2 == "демон поднят"
    assert len(вызовов_popen) == 2, (
        "после смерти демона повторный обеспечить_демона обязан поднять "
        "процесс заново ({} Popen после смерти), а не поверить памяти "
        "о прошлом подъёме.".format(len(вызовов_popen) - 1))
    assert len(вызовов_health) > вызовов_health_после_первого, (
        "второй вызов обеспечить_демона не спросил /health заново — "
        "опознание закэшировалось между вызовами (нарушение решения 9).")
