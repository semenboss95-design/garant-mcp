"""Замок владения профилем (этап 02, шаг 3, `daemon.занять_профиль`).

Ограничение 2 — один профиль = один процесс. До этого шага монопольность
держал только бинд порта, и этого не хватало: между биндом порта и первым
ответом на `/health` лежит подъём chromium — секунды, — и в этом окне
`наш_демон_на_порту()` отвечает «нет». Второй экземпляр, запущенный НА
СВОБОДНЫЙ, НИКЕМ НЕ ЗАНЯТЫЙ порт (не тот же самый, не занятый посторонним —
именно свободный), спокойно проходил бы бинд и поднимал бы второй браузерный
контекст на тот же профиль. Порт как признак занятости эту гонку не
закрывает вообще — он про два процесса на ОДНОМ порту, а не про два процесса
на одном профиле.

Проверяется здесь настоящий подпроцесс `python -m garant_mcp.daemon`, не его
пересказ: стенд и вспомогательные функции — те же, что в `test_port.py`
(четвёртое свойство порта уже опирается на тот же замок, но проверяет его
косвенно, через совпадение порта; здесь — прямая проверка на РАЗНЫХ портах,
где совпадения нет и порт сам по себе второму экземпляру не мешает).

Браузер не запускается: в песочнице нет профиля браузера, `_ensure_client`
падает раньше, на проверке профиля, — но HTTP-обвязка демона (в том числе
замок профиля, который проверяется первым, до всякого браузера) отрабатывает
по-настоящему.
"""

from __future__ import annotations

import json
import subprocess
import time
from pathlib import Path

import pytest

from test_paths import _песочница, _окружение, чужой_каталог  # noqa: F401
from test_port import (  # noqa: F401
    ЖДАТЬ_СЕК,
    _поднять_демон,
    _дождаться_порта,
    _свободный_порт,
    _порт_слушается,
    _убить_по_pid,
)


@pytest.fixture
def стенд(tmp_path):
    """Тот же стенд, что в test_port.py, минимальный: только демоны.

    Не переиспользуем фикстуру `стенд` оттуда напрямую — она заводит ещё
    и немых/самозванцев-слушателей, которые здесь не нужны, а копия из трёх
    строк дешевле межмодульной фикстуры на разделяемом состоянии.
    """
    пакет = _песочница(tmp_path)
    состояние = tmp_path / "состояние"
    состояние.mkdir()
    процессы: list = []

    class Стенд:
        def __init__(self):
            self.пакет = пакет
            self.состояние = состояние

        def демон(self, доп=None):
            p = _поднять_демон(пакет, состояние, доп)
            процессы.append(p)
            return p

    yield Стенд()

    for p in процессы:
        if p.poll() is None:
            p.terminate()
            try:
                p.wait(timeout=10)
            except subprocess.TimeoutExpired:
                p.kill()


# --------------------------------------------------------------------------
#  1. второй демон не поднимается, даже если его порт СВОБОДЕН
# --------------------------------------------------------------------------

def test_второй_демон_не_поднимается_на_свободном_порту(стенд):
    """Ключевое свойство: без замка профиля второй экземпляр садится на
    соседний свободный порт и остаётся жить — два процесса на один профиль.
    С замком он обязан уйти кодом 0, ДО того как тронет порт вообще.
    """
    порт1 = _свободный_порт()
    первый = стенд.демон({"GARANT_PORT": str(порт1)})
    данные1 = _дождаться_порта(стенд.состояние, первый)

    # Порт второго — заведомо другой и заведомо свободный: не диапазон
    # первого (порт1..порт1+10), чтобы никакая логика «перебора соседних»
    # port1 не могла случайно свести оба демона на один и тот же порт и
    # тем самым проверить совсем другое свойство (то, что уже проверяет
    # test_port.py).
    порт2 = _свободный_порт()
    while порт1 <= порт2 <= порт1 + 10:
        порт2 = _свободный_порт()

    второй = стенд.демон({"GARANT_PORT": str(порт2)})
    try:
        второй.wait(timeout=ЖДАТЬ_СЕК)
    except subprocess.TimeoutExpired:
        второй.kill()
        pytest.fail(
            "второй демон не завершился за {:.0f} с — похоже, он поднял "
            "собственный HTTP на свободном порту {} и стал вторым "
            "владельцем профиля (ограничение 2 нарушено, замок профиля "
            "не сработал).".format(ЖДАТЬ_СЕК, порт2))

    вывод = второй.stdout.read() if второй.stdout else ""
    assert второй.returncode == 0, (
        "второй экземпляр на свободном порту обязан выйти кодом 0 — профиль "
        "занят первым. Получено {}:\n{}".format(второй.returncode, вывод))
    assert "профил" in вывод.lower(), (
        "сообщение второго экземпляра обязано говорить про ПРОФИЛЬ, а не "
        "только про порт — иначе непонятно, что перебор соседних портов "
        "здесь ни при чём:\n" + вывод)

    assert not _порт_слушается(порт2), (
        "порт {} был свободен и остался свободен: второй демон обязан был "
        "уйти ДО бинда, не тронув порт вовсе.".format(порт2))

    assert первый.poll() is None, "первый демон не должен был пострадать"
    после = json.loads(
        (стенд.состояние / "daemon_port").read_text(encoding="utf-8"))
    assert после == данные1, (
        "daemon_port обязан по-прежнему описывать первого демона: было {}, "
        "стало {}.".format(данные1, после))


# --------------------------------------------------------------------------
#  2. замок снимается при смерти процесса — в том числе жёстким убийством
# --------------------------------------------------------------------------

def _дождаться_нового_владельца(состояние: Path, процесс, старый_pid: int,
                                 ожидаемый_порт: int, таймаут=ЖДАТЬ_СЕК) -> dict:
    """Ждёт, пока daemon_port начнёт описывать НОВОГО владельца профиля.

    Просто ждать «файл существует» мало: после жёсткого убийства первого
    демона файл на диске может остаться прежним (finally демона не
    исполняется), и наивное ожидание «появления» ничего бы не заметило.

    Сверяем НЕ с `процесс.pid` (`Popen.pid`) — под интерпретатором из
    `uv venv`/`uv tool install` `python.exe`, которого завела `subprocess`,
    перенаправляющая заглушка: настоящий интерпретатор, вызывающий
    `os.getpid()` внутри daemon.py, — её РЕБЁНОК с другим PID. Условие
    «`данные["pid"] == процесс.pid`» на такой установке недостижимо — тест
    падает по таймауту с диагнозом «замок не снялся посмертно», которого
    нет: второй демон полностью занял профиль, просто под другим PID, чем
    у Popen. Это то же третье место того же класса, что уже переписан
    в `test_port.py::test_daemon_port_содержит_порт_и_pid` — там источник
    истины тоже не `Popen.pid`, а сам `daemon_port`.

    Источник истины здесь — ПОРТ: он задан ДО запуска второго демона через
    `GARANT_PORT` (в отличие от PID, который назначает ОС и знать заранее
    нельзя), и он не может совпасть с портом первого демона (вызывающий
    выбирает заведомо другой свободный порт). Совпадение записанного порта
    с ожидаемым однозначно доказывает, что запись в `daemon_port` сделал
    именно второй процесс, а не переживший себя первый. Отличие PID от
    `старый_pid` — вторая, более слабая подпорка на случай гонки записи.
    """
    f = состояние / "daemon_port"
    край = time.time() + таймаут
    while time.time() < край:
        if процесс.poll() is not None:
            pytest.fail(
                "новый демон умер, не заняв профиль:\n"
                + (процесс.stdout.read() if процесс.stdout else ""))
        if f.exists():
            try:
                данные = json.loads(f.read_text(encoding="utf-8"))
            except ValueError:
                данные = None
            if (данные and данные.get("порт") == ожидаемый_порт
                    and данные.get("pid") != старый_pid):
                return данные
        time.sleep(0.15)
    процесс.kill()
    pytest.fail(
        "новый демон за {:.0f} с не стал владельцем профиля (daemon_port "
        "так и не начал описывать порт {}, отличный от прежнего PID {}) — "
        "похоже, замок прежнего процесса не снялся посмертно."
        .format(таймаут, ожидаемый_порт, старый_pid))


def test_замок_снимается_жёстким_убийством_процесса(стенд):
    """`_убить_по_pid` по PID из daemon_port, а не `первый.kill()`.

    `Popen.kill()` бьёт по PID, который `subprocess` завела сама
    (`Popen.pid`). В установке через venv-заглушку (например, `uv tool
    install`) `python.exe` — перенаправляющий процесс, а настоящий
    интерпретатор, держащий порт и замок профиля, — её РЕБЁНОК с другим
    PID: именно он вызывает `os.getpid()` в daemon.py и пишет его в
    daemon_port. `первый.kill()` в этом случае убивает заглушку и оставляет
    настоящего держателя замка живым — тест решил бы, что замок снялся
    жёстким убийством, хотя первый демон продолжает работать и держать
    профиль (ограничение 2 нарушено бы молча). Поэтому убиваем PID,
    которым демон сам себя назвал в daemon_port, и деревом (`/T /F` на
    Windows) — чтобы не пережила и обратная ситуация, когда PID из файла
    сам оказался бы обёрткой с ребёнком.
    """
    порт1 = _свободный_порт()
    первый = стенд.демон({"GARANT_PORT": str(порт1)})
    данные1 = _дождаться_порта(стенд.состояние, первый)
    pid_первого = данные1["pid"]

    _убить_по_pid(pid_первого)
    предел = time.time() + 15
    while time.time() < предел and _порт_слушается(порт1, таймаут=0.3):
        time.sleep(0.2)
    assert not _порт_слушается(порт1), (
        "процесс {} из daemon_port не остановился после жёсткого убийства "
        "именно этого PID — либо daemon_port назвал не настоящего "
        "держателя порта, либо у него остался живой потомок."
        .format(pid_первого))

    порт2 = _свободный_порт()
    второй = стенд.демон({"GARANT_PORT": str(порт2)})
    данные = _дождаться_нового_владельца(стенд.состояние, второй, pid_первого, порт2)

    assert данные["порт"] == порт2
    assert второй.poll() is None, "второй демон обязан продолжать работать"
