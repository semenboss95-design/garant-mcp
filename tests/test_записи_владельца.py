# Путь эндпоинта — как он появляется в РЕАЛЬНОМ URL, который строит client.py
# (`self.cfg["base_url"] + url`), а не как он записан в имени файла (там
# слэши уже заменены на `_`). Только то, что использует хотя бы один тест
# этого файла — не весь список эндпоинтов из record_api.py.
_ЭНДПОИНТ_ПУТЬ = {
    "redactions_list": "/redactions/list",
    "document_info": "/document/info",
    "document_pages": "/document/pages",
    "search_base_run": "/search/base/run",
    "search_poll": "/search/poll",
    "list_page": "/list/page",
    "list_kind": "/list/kind",
}


def _тела(записи: list[dict], имя: str) -> list[tuple[int, str]]:
    """Тела одного эндпоинта в порядке фактического снятия трафика."""
    return [(r["status"], r["text"]) for r in записи if r["путь"].endswith(имя)]


def _маршрут_по_записям(записи: list[dict], *имена: str):
    """Маршрутизатор для `ФейкТранспорт` на РЕАЛЬНЫХ телах.

    Раздаёт тела нужных эндпоинтов по очереди, в том порядке, в каком их
    записал живой трафик — так же, как `_маршрутизатор` в
    `test_client_периоды_действия.py` работает на синтетике. keepalive —
    единственное синтетическое звено (200, "" вместо тела): клиенту важен
    код ответа, а троттл в фейковом транспорте всё равно ничего не меряет.
    """
    очереди = {имя: _тела(записи, имя) for имя in имена}
    for имя, оч in очереди.items():
        if not оч:
            raise AssertionError(
                f"в записях владельца нет тела для {имя!r} — это дефект "
                "самого теста (маршрутизатор собран не по тем именам), "
                "а не пустая среда: она уже отсеяна фикстурой `записи`")

    def маршрут(method, url, form, номер):
        if "/server/keepalive" in url:
            return 200, ""
        for имя in имена:
            if _ЭНДПОИНТ_ПУТЬ[имя] in url:
                оч = очереди[имя]
                if not оч:
                    raise AssertionError(
                        f"записи владельца для {имя!r} кончились раньше, чем "
                        f"клиент перестал их запрашивать: {method} {url}")
                return оч.pop(0)
        raise AssertionError(
            f"незнакомый URL в тесте на записях владельца: {method} {url}")
    return маршрут


