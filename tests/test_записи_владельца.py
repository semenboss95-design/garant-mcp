def test_search_на_записях_total_и_всего_страниц_числа(записи, monkeypatch, tmp_path):
    """`total` и `всего_страниц` — реальные числа, разобранные из
    `/search/poll` и `/list/page`, а не заглушки.

    Числа НЕ совпадают с «862 / 44» из более раннего устного разбора этого
    же наряда: в этом наборе записан ОДИН поиск («мера пресечения истечение
    срока», `kindTree.total = 2534`, 20 уникальных документов на странице
    выдачи, `documentCount` в том же теле — то же число). Тест сверяется
    с тем, что реально лежит в файле записи, а не с числом из другого
    разбора, — расхождение названо в сдаче наряда.
    """
    # search() безусловно пишет непустую выдачу в кэш (use_cache влияет
    # только на ЧТЕНИЕ) — без подмены каталог реального CACHE_DIR получил
    # бы файл от этого теста.
    monkeypatch.setattr(client, "CACHE_DIR", tmp_path / "cache")
    транспорт = ФейкТранспорт(_маршрут_по_записям(
        записи, "search_base_run", "search_poll", "list_page"))
    к = client.GarantClient(transport=транспорт)

    ответ = к.search("мера пресечения истечение срока", use_cache=False)

    poll_тело = json.loads(_тела(записи, "search_poll")[0][1])
    ожидаемый_total = poll_тело["kindTree"]["total"]
    assert isinstance(ответ["total"], int)
    assert ответ["total"] == ожидаемый_total

    страница_тело = json.loads(_тела(записи, "list_page")[0][1])
    уникальных = len({it.get("documentId") for it in страница_тело["items"]} - {None})
    assert isinstance(ответ["всего_страниц"], int)
    assert ответ["всего_страниц"] == -(-ожидаемый_total // уникальных), (
        "то же деление с округлением вверх, что делает сам client.search() "
        "— per берётся из числа УНИКАЛЬНЫХ документов на реальной странице, "
        "потому что /list/page в этой записи вообще не отдаёт pageSize")


