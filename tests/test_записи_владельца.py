def test_document_на_упк_provenance_хеш_правило_действует_с(записи):
    """`document(doc_id=12125178)` на реальных `/document/info` +
    `/document/pages` + `/redactions/list`: провенанс несёт `hash_текста`
    формы `sha256:<16 hex>`, СВОЙ (текущий) `правило_отпечатка` — не
    застывшую строку в тесте, а `client.ПРАВИЛО_ОТПЕЧАТКА` — и
    `действует_с`, равный началу единственного периода действующей
    редакции («06.08.2026»)."""
    транспорт = ФейкТранспорт(_маршрут_по_записям(
        записи, "document_info", "document_pages", "redactions_list"))
    к = client.GarantClient(transport=транспорт)

    ответ = к.document(doc_id=12125178, max_pages=1)
    prov = ответ["provenance"]

    assert re.fullmatch(r"sha256:[0-9a-f]{16}", prov["hash_текста"]), prov["hash_текста"]
    assert prov["hash_текста"] == (
        "sha256:" + hashlib.sha256(ответ["text"].encode("utf-8")).hexdigest()[:16]
    ), "отпечаток обязан считаться РОВНО от текста, ушедшего в ответе, не от чего-то ещё"
    assert prov["правило_отпечатка"] == client.ПРАВИЛО_ОТПЕЧАТКА
    assert prov["действует_с"] == "06.08.2026"
    # До 09.09.2026 здесь стояло `"оговорки_о_редакции" not in prov` — верно
    # для периодов (один читаемый, интерпретации взяться неоткуда), но
    # ложно для самого РЕКВИЗИТА: `изменяющий_акт` пришёл «N 251-Ф3 от
    # 26.07.2026» — с цифрой «3» вместо буквы «З», и это молчаливо уезжало
    # читателю без единого слова. Значение не чинится, а оговаривается.
    assert prov["изменяющий_акт"] == "N 251-Ф3 от 26.07.2026", (
        "реквизит обязан дойти ДОСЛОВНО — с цифрой, как отдала база")
    оговорки = prov.get("оговорки_о_редакции") or []
    assert оговорки, (
        "реквизит с цифрой «3» вместо буквы «З» обязан оставить оговорку, "
        "а не молчать")
    assert any("цифрой" in s and "Ф3" in s for s in оговорки), (
        "оговорка обязана назвать ИМЕННО эту подмену буквы цифрой:\n"
        + "\n".join(оговорки))


# Второй `server/keepalive` в наборе отделяет САМОСТОЯТЕЛЬНУЮ сессию живой
# приёмки: до этой отметки записан документ 12125178, после — редакция
# 483426287. Общий маршрутизатор (`_маршрут_по_записям`) раздаёт тела ЛЮБОГО
# запрошенного эндпоинта в порядке их появления во всём наборе — без
# отсечения по времени тест ниже получил бы document_info/document_pages
# ПЕРВОГО документа сессии (12125178), а не 483426287.
_TS_СЕССИИ_РЕДАКЦИИ_483426287 = 1788959397901


def _после(записи: list[dict], ts: int) -> list[dict]:
    return [r for r in записи if r["ts"] >= ts]


def test_document_на_редакции_483426287_provenance_называет_запрошенную_редакцию(записи):
    """`document(doc_id=483426287)`: 483426287 — не отдельный документ,
    а `documentId` РЕДАКЦИИ УПК, утратившей силу 05.08.2026 (решение 12,
    закрыто записями этого же дня). «Гарант» принимает id РЕДАКЦИИ как
    doc_id и отдаёт текст ИМЕННО её — провенанс обязан назвать эту
    редакцию, её дату начала, её акт и то, что сегодня она НЕ действует,
    а не молча подставить действующую (12125178)."""
    сессия = _после(записи, _TS_СЕССИИ_РЕДАКЦИИ_483426287)
    assert сессия, (
        "в этом наборе записей нет сессии после отметки "
        f"{_TS_СЕССИИ_РЕДАКЦИИ_483426287} — датасет отличается от того, "
        "на котором писан этот тест (09.09.2026, второй компьютер)")
    транспорт = ФейкТранспорт(_маршрут_по_записям(
        сессия, "document_info", "document_pages", "redactions_list"))
    к = client.GarantClient(transport=транспорт)

    ответ = к.document(doc_id=483426287, max_pages=1)
    prov = ответ["provenance"]

    assert prov["действует_с"] == "21.06.2026", (
        "заверяющая дата обязана быть началом ЗАПРОШЕННОЙ (483426287), "
        "не действующей редакции")
    assert prov["изменяющий_акт"] == "N 164-Ф3 от 10.06.2026"
    оговорки = "\n".join(prov.get("оговорки_о_редакции") or [])
    assert оговорки, "запрос НЕ действующей редакции обязан оставить оговорку"
    assert "утратила силу" in оговорки or "НЕ действует" in оговорки, (
        "оговорка обязана сказать прямо, что эта редакция сегодня "
        "не действует:\n" + оговорки)
    assert "12125178" in оговорки, (
        "оговорка обязана назвать documentId ДЕЙСТВУЮЩЕЙ редакции — где "
        "искать сегодняшний текст:\n" + оговорки)


