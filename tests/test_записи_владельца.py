_ИМЯ_ЗАПИСИ = re.compile(r"^(\d+)_([A-Z]+)_(.+)_(\d+)\.txt$")


def _прочитать_все(каталог: Path) -> list[dict]:
    """Все распознанные файлы каталога, отсортированные по времени снятия."""
    записи = []
    for f in sorted(каталог.iterdir()):
        if not f.is_file():
            continue
        m = _ИМЯ_ЗАПИСИ.match(f.name)
        if not m:
            continue
        ts, method, путь, status = m.groups()
        записи.append({
            "ts": int(ts), "method": method, "путь": путь,
            "status": int(status), "text": f.read_text(encoding="utf-8"),
        })
    записи.sort(key=lambda r: r["ts"])
    return записи


_ПРИЧИНА_ПРОПУСКА = (
    "записей владельца нет: каталог recordings в состоянии пуст — они "
    "делаются владельцем с подпиской, GARANT_RECORD=1")


