def test_revisions_на_упк_285_записей_ровно_одна_действующая(записи):
    """`/redactions/list` документа 12125178 (УПК): 285 записей.

    Ровно одна rs_Actual → «действующая»; у неё «to» в activity нет вовсе
    (`{"from": "06.08.2026"}` без ключа `to`) — решение 36 читает
    отсутствие/пустое «по» как бессрочность, а не как повод для оговорки.
    284 rs_Old → «утратила силу», из них у 283 обе границы периода читаемые
    строки, а у одной — `activity: []` («не действовала (первоначальная)»):
    это не период, а его отсутствие, и он не должен рождать ложную оговорку
    о стыке (`_оговорка_о_периодах` требует минимум ДВА значащих периода,
    а тут их ноль).
    """
    транспорт = ФейкТранспорт(_маршрут_по_записям(записи, "redactions_list"))
    к = client.GarantClient(transport=транспорт)

    revs = к.revisions(doc_id=12125178)
    assert len(revs) == 285

    действующие = [r for r in revs if r["статус"] == "действующая"]
    assert len(действующие) == 1, (
        "в записи ровно одна rs_Actual — распознаться она обязана в ровно "
        "одну «действующая», не в ноль и не в несколько")
    действующая = действующие[0]
    assert not действующая["действует_по"], (
        "у действующей редакции ключа «to» в activity нет вовсе — решение "
        "36: отсутствие границы читается как бессрочность")
    assert действующая["действует_с"] == "06.08.2026"
    assert действующая["изменяющий_акт"] == "N 251-Ф3 от 26.07.2026", (
        "провенанс не «чинит» данные: «Гарант» в этом поле прислал цифру "
        "«3» внутри «Ф3» (не букву «З»), и она обязана дойти дословно")
    # Наряд 4-3: реквизит с «Ф3» несёт оговорку и НА ЗАПИСИ revisions() —
    # не только в provenance document()/article(). Один читаемый период
    # сам по себе оговорки не рождает (это и утверждала прежняя версия
    # проверки), но «Ф3» в самом реквизите — рождает, и она обязана
    # остаться единственной причиной: период не даёт второй.
    оговорка = действующая.get("_предупреждение") or ""
    assert оговорка, (
        "изменяющий_акт действующей записи содержит «Ф3» — revisions() "
        "обязан нести об этом оговорку, а не молчать")
    assert "Ф3" in оговорка and "цифрой" in оговорка, (
        "оговорка обязана называть именно дословность реквизита «Ф3»:\n"
        + оговорка)

    утратили_силу = [r for r in revs if r["статус"] == "утратила силу"]
    assert len(утратили_силу) == 284

    с_обеими_границами = [
        r for r in утратили_силу
        if r["периоды"] and r["периоды"][0].get("с") and r["периоды"][0].get("по")]
    assert len(с_обеими_границами) == 283, (
        "из 284 «утратила силу» ровно у 283 период с обеими читаемыми "
        "границами — четвёртый минус один уходит записи с пустым activity")

    без_периодов = [r for r in утратили_силу if r["периоды"] == []]
    assert len(без_периодов) == 1
    r0 = без_периодов[0]
    assert r0["редакция"].strip() == "не действовала (первоначальная)"
    # До 09.09.2026 (решение 36, дополнение того же дня) пустой `activity`
    # молчал вовсе — здесь стояло `assert not r0.get("_предупреждение")`,
    # закрепляя ложное молчание: пустой список — ЗНАНИЕ «периодов нет»,
    # а не «периоды не прочитаны», и об этом обязана говорить оговорка,
    # а не тишина. Это не оговорка о РАЗРЫВЕ (`_оговорка_о_периодах` и
    # правда молчит про стык — значащих периодов меньше двух), а отдельная,
    # о самом ОТСУТСТВИИ периодов.
    assert r0.get("_предупреждение") == client._ПЕРИОДОВ_НЕТ, (
        "запись с пустым activity обязана нести оговорку «периодов нет», "
        "а не молчать:\n" + str(r0.get("_предупреждение")))
    assert client._перечень_периодов(r0) == "периодов нет", (
        "рендер перечня периодов не должен подставлять фиктивную "
        "«? — бессрочно» там, где периода нет вовсе")
    assert "бессрочно" not in r0["_предупреждение"], (
        "запись без периодов не бессрочна — она ПУСТА, и путать эти два "
        "слова здесь нельзя:\n" + r0["_предупреждение"])


def test_revisions_упк_284_из_285_записей_несут_оговорку_о_ф3(записи):
    """Замер по всем 285 записям, а не по одной действующей: реквизит с
    цифрой «Ф3» — не редкость этого набора, а его подавляющее большинство.
    284 из 285 записей `изменяющий_акт` содержат «Ф3»; ровно одна не несёт
    оговорку — но НЕ потому, что там буква «З» (такого написания в наборе
    нет вовсе), а потому, что у этой записи `changingDocuments` пуст и
    `изменяющий_акт` — `None`: оговариваться там нечему.
    """
    транспорт = ФейкТранспорт(_маршрут_по_записям(записи, "redactions_list"))
    к = client.GarantClient(transport=транспорт)
    revs = к.revisions(doc_id=12125178)
    assert len(revs) == 285

    с_оговоркой_о_ф3 = [
        r for r in revs
        if r.get("_предупреждение") and "Ф3" in r["_предупреждение"]]
    assert len(с_оговоркой_о_ф3) == 284, (
        "по замеру provenance-guard 284 из 285 записей несут «Ф3» в "
        "изменяющем акте — revisions() обязан дать оговорку РОВНО этому "
        "числу записей, не больше и не меньше:\n"
        "нашлось: {}".format(len(с_оговоркой_о_ф3)))

    без_оговорки_о_ф3 = [
        r for r in revs
        if not (r.get("_предупреждение") and "Ф3" in r["_предупреждение"])]
    assert len(без_оговорки_о_ф3) == 1
    единственная = без_оговорки_о_ф3[0]
    assert not единственная.get("изменяющий_акт"), (
        "единственная запись без оговорки о «Ф3» обязана быть именно той, "
        "у которой изменяющего акта нет вовсе (а не той, где акт написан "
        "буквой «З» — такой записи в этом наборе не существует):\n"
        + str(единственная.get("изменяющий_акт")))


def test_смежность_редакций_упк_05_08_к_06_08_2026_на_реальных_датах(записи):
    """Стык двух РАЗНЫХ редакций (483426287 → действующая 12125178):
    «по» старой — 05.08.2026, «с» новой — 06.08.2026, день в день по
    календарю плюс сутки.

    Это НЕ то, что проверяет сама `_оговорка_о_периодах` в `revisions()` —
    её стык внутри ОДНОЙ записи, между периодами её же `activity`, а не
    между соседними редакциями списка. Но арифметику стыка считает одна
    и та же функция везде в контуре (`client._разрыв_в_действии`), и эти
    реальные граничные значения проверяются ЕЮ ЖЕ напрямую: смежность
    здесь держится на нашем (включительном) чтении границы, а не на
    доказанном самим «Гарантом» факте — то же прочтение, что и во всех
    остальных местах контура.
    """
    транспорт = ФейкТранспорт(_маршрут_по_записям(записи, "redactions_list"))
    к = client.GarantClient(transport=транспорт)
    revs = к.revisions(doc_id=12125178)

    старая = next(r for r in revs if r["id_редакции"] == 483426287)
    действующая = next(r for r in revs if r["статус"] == "действующая")
    assert старая["действует_по"] == "05.08.2026"
    assert действующая["действует_с"] == "06.08.2026"

    разрыв, неизвестно, нашим_чтением = client._разрыв_в_действии([
        {"с": старая["действует_с"], "по": старая["действует_по"]},
        {"с": действующая["действует_с"], "по": действующая["действует_по"]},
    ])
    assert not разрыв, "конец и начало отличаются на сутки — не разрыв больше суток"
    assert not неизвестно, "обе даты реальные и разобрались — считать здесь есть что"
    assert нашим_чтением, (
        "05.08.2026 → 06.08.2026 — смежность «на следующий день», она "
        "держится ИМЕННО на нашем включительном чтении границы")


