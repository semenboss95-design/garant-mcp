# -*- coding: utf-8 -*-
"""Импорт `server.py` обязан быть немым (наряд этапа 03, фаза B, часть 2).

MCP-сервер говорит с клиентом по stdio: JSON-RPC на stdin/stdout. Всё,
что импорт модуля напишет в stdout ДО того, как протокол начал говорить,
клиент прочитает как первый пакет протокола — и уронит сервер молча,
без единой строки в логах пользователя, потому что сервер к этому моменту
уже не отвечает штатно на ошибки. То же с обработчиками логирования:
если импорт вешает свой на `logging.root`, второй импорт (или библиотека
выше по стеку, тоже настраивающая логирование) получает дублирующийся
или неожиданно перенаправленный вывод — и это тоже стало бы видно только
на живой подписке, не здесь.

Проверяется офлайн: `mcp.server.fastmcp` подменяется рабочей заглушкой
собственного изготовления. Обычные два пропуска (`server` на `mcp` 2.x)
здесь ни при чём — с заглушкой версия настоящего пакета `mcp` не участвует
вовсе, и тест обязан идти во ЛЮБОЙ среде, включая ту, где сам `mcp` не
поставлен.

Импорт — в отдельном подпроцессе: кэш модулей `sys.modules` в этом же
процессе исказил бы список хендлеров `logging.root`, накопленный другими
тестами, и завёл бы этот тест в зависимость от порядка запуска.
"""
from __future__ import annotations

import json
import os

from test_paths import _песочница, _запуск, чужой_каталог  # noqa: F401

_ЗАГЛУШКА_MCP = {
    "mcp/__init__.py": "",
    "mcp/server/__init__.py": "",
    "mcp/server/fastmcp/__init__.py": (
        "class FastMCP:\n"
        "    def __init__(self, name):\n"
        "        self.name = name\n"
        "\n"
        "    def tool(self, *a, **k):\n"
        "        def _decorator(f):\n"
        "            return f\n"
        "        return _decorator\n"
        "\n"
        "    def run(self):\n"
        "        pass\n"
    ),
    "mcp/server/fastmcp/exceptions.py": (
        "class ToolError(Exception):\n"
        "    pass\n"
    ),
}


def _поставить_заглушку_mcp(куда):
    """Минимальный `mcp.server.fastmcp`, достаточный для импорта server.py.

    Не настоящий пакет ни одной строкой: цель — исключить сам `mcp` из
    проверки, а не воспроизвести его поведение.
    """
    for относительный, текст in _ЗАГЛУШКА_MCP.items():
        путь = куда / относительный
        путь.parent.mkdir(parents=True, exist_ok=True)
        путь.write_text(текст, encoding="utf-8")
    return куда


def test_импорт_server_не_пишет_в_stdout_и_не_вешает_хендлеры(tmp_path, чужой_каталог):
    пакет = _песочница(tmp_path)
    заглушка = _поставить_заглушку_mcp(tmp_path / "заглушка")
    состояние = tmp_path / "состояние"

    код = (
        "import sys, json, logging\n"
        "до = list(logging.root.handlers)\n"
        "import garant_mcp.server as server\n"
        "после = list(logging.root.handlers)\n"
        "print(json.dumps({'новых_хендлеров': len(после) - len(до)}))\n"
    )
    r = _запуск(
        код, чужой_каталог,
        {
            "GARANT_HOME": str(состояние),
            # Заглушка ПЕРЕД настоящим пакетом: если бы `mcp` был поставлен
            # в среде разработки, реальный fastmcp не должен участвовать —
            # тест обязан идти одинаково что с ним, что без него.
            "PYTHONPATH": str(заглушка) + os.pathsep + str(пакет.parent),
        },
        таймаут=60,
    )
    assert r.returncode == 0, (
        "импорт server.py с заглушкой mcp упал:\n" + r.stdout + r.stderr)

    строки_stdout = [s for s in r.stdout.splitlines() if s.strip()]
    assert len(строки_stdout) == 1, (
        "импорт server.py вывел в stdout что-то, кроме итоговой диагностики "
        "теста. На stdio-протоколе MCP это лишний пакет ПЕРЕД первым "
        "настоящим, и клиент падает молча, без записи в лог. Получено:\n"
        + r.stdout)

    итог = json.loads(строки_stdout[0])
    assert итог["новых_хендлеров"] == 0, (
        "импорт server.py добавил {} обработчик(ов) в logging.root. Модуль "
        "не должен настраивать логирование сам на импорте — иначе второй "
        "импорт или чужой код выше по стеку получит чужой вывод."
        .format(итог["новых_хендлеров"]))

    assert not r.stderr.strip(), (
        "импорт server.py написал в stderr:\n" + r.stderr)
