# -*- coding: utf-8 -*-
"""`uninstall` печатает «ОСТАЛОСЬ НА МАШИНЕ» (`cli._что_осталось`, дефект №2
фазы E2 release-gate, 09.09.2026): пункт про кэш браузеров playwright писал
одну и ту же фразу — «не трогаю: он общий для всех окружений этой машины,
и его используют другие программы на playwright» — независимо от того,
существует ли этот каталог на диске вообще. Для каталога, которого нет
(playwright ни разу не ставил chromium), это не осторожность, а неправда:
там нечему быть «общим» и нечего «использовать другим программам».

Проверяется наблюдаемый КОНТРАКТ (что напечатано человеку), а не то, как
`_что_осталось` внутри устроена: три состояния каталога — отсутствует,
существует и пуст, существует и не пуст — обязаны давать РАЗНЫЙ текст,
и только последнее вправе нести старую фразу «не трогаю».

Подмена и её граница
---------------------
`_что_осталось` спрашивает путь у `_место_браузеров()`, а та шлёт
НАСТОЯЩИЙ подпроцесс `python -m playwright install --dry-run chromium`
(докстринг `cli._место_браузеров`). Это внешняя зависимость, а не логика
под проверкой — ровно так же, как `autostart.py` в `test_cli_необратимое.py`
подменяется целиком заглушкой, потому что настоящий модуль трогает
планировщик задач этой машины. Здесь подмена — не файл, а один атрибут
модуля после импорта, в ПОДПРОЦЕССЕ (`python -c` со своим `sys.path`, как
в `test_paths.py`): `cli._место_браузеров = lambda: (каталог, '')`. Ниже
этой границы ничего не тронуто — ветвление `_что_осталось` по значению
`каталог` исполняется настоящим кодом `cli.py`, не пересказано в тесте.

`GARANT_HOME` изолирован во временный каталог (`_окружение` из
`test_paths.py`, песочница `_песочница`) — печатаемый путь состояния не
имеет права указывать на машину, где гоняется тест.
"""
from __future__ import annotations

import subprocess
import sys
from pathlib import Path

from test_paths import _песочница, _окружение, чужой_каталог  # noqa: F401

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src"


def _вывод_что_осталось(пакет: Path, cwd: Path, tmp_path: Path,
                        чем: str | None, каталог: str | None) -> str:
    """Печать `_что_осталось(чем)` при подменённом `_место_браузеров`."""
    состояние = tmp_path / "состояние"
    код = (
        "import sys\n"
        "sys.path.insert(0, r'{site}')\n"
        "import garant_mcp.cli as cli\n"
        "cli._место_браузеров = lambda: ({каталог}, '')\n"
        "cli._что_осталось({чем})\n"
    ).format(site=пакет.parent, каталог=repr(каталог), чем=repr(чем))
    r = subprocess.run(
        [sys.executable, "-c", код], cwd=str(cwd),
        env=_окружение({"GARANT_HOME": str(состояние)}),
        capture_output=True, text=True, encoding="utf-8", errors="replace",
        timeout=30)
    assert r.returncode == 0, (
        "_что_осталось упал(а) вместо того, чтобы напечатать сводку:\n"
        + r.stdout + r.stderr)
    return r.stdout


def test_что_осталось_каталога_кэша_нет_говорит_прямо(tmp_path, чужой_каталог):
    """Playwright ни разу не ставил chromium: путь из "Install location"
    не существует на диске ни разу. Утверждать «не трогаю: используют
    другие программы» здесь — обещание про то, чего нет.
    """
    пакет = _песочница(tmp_path)
    несуществующий = str(tmp_path / "playwright-cache-которого-нет")

    вывод = _вывод_что_осталось(пакет, чужой_каталог, tmp_path, "uv",
                                несуществующий)

    assert "не трогаю" not in вывод, (
        "при отсутствующем каталоге кэша нельзя утверждать «не трогаю: его "
        "используют другие программы» — там нечего использовать:\n" + вывод)
    assert "каталога нет" in вывод, (
        "отсутствие каталога обязано быть названо прямо, а не спрятано за "
        "старой фразой про общий кэш:\n" + вывод)


def test_что_осталось_каталог_пуст_говорит_прямо(tmp_path, чужой_каталог):
    """Каталог есть, но внутри ничего — например, playwright создал папку
    и не докачал ни одного браузера. «Не трогаю» здесь так же неправда,
    как и при полном отсутствии каталога: удалять всё равно нечего.
    """
    пакет = _песочница(tmp_path)
    пустой = tmp_path / "playwright-cache-пустой"
    пустой.mkdir()

    вывод = _вывод_что_осталось(пакет, чужой_каталог, tmp_path, "uv",
                                str(пустой))

    assert "не трогаю" not in вывод, (
        "пустой каталог — то же самое «нечего не трогать», что и "
        "отсутствующий:\n" + вывод)
    assert "каталог пуст" in вывод, (
        "пустой каталог обязан быть назван прямо:\n" + вывод)


def test_что_осталось_каталог_существует_и_непуст_прежняя_фраза(tmp_path, чужой_каталог):
    """Chromium реально стоит: каталог существует и не пуст. Здесь фраза
    «не трогаю» правдива — и её нельзя было потерять при починке дефекта.
    """
    пакет = _песочница(tmp_path)
    существующий = tmp_path / "playwright-cache-с-chromium"
    (существующий / "chromium-1234").mkdir(parents=True)

    вывод = _вывод_что_осталось(пакет, чужой_каталог, tmp_path, "uv",
                                str(существующий))

    assert "не трогаю" in вывод, (
        "для реально существующего непустого каталога прежняя фраза «не "
        "трогаю: он общий для всех окружений… используют другие программы» "
        "обязана остаться на месте:\n" + вывод)
