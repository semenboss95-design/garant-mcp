# -*- coding: utf-8 -*-
"""Отпечаток браузера — снят один раз, дальше не меняется (решение 16).

Ограничение 3 требует, чтобы отпечаток окна входа и рабочего контекста
СОВПАДАЛ: «Гарант» привязывает сессию к отпечатку, и cookie, выданные окну
с одним UA, в контексте с другим отвергаются как `Unauthorized`. Решение 16
добивается этого не совпадением реализаций, а ОДНИМ источником: пока файл
`fingerprint.json` существует, `отпечаток()` возвращает его содержимое и НЕ
трогает ни ОС, ни браузер — а `client.context_options()`, которым пользуются
и окно входа (`окно_входа`), и рабочий клиент (`GarantClient._ensure`),
буквально вызывает `fingerprint.параметры_контекста()`.

Настоящий chromium здесь не запускается и не должен: `снять()` поднимает
временный браузер, чтобы спросить у него UA, а свойство, которое нужно
проверить, — это НЕ значения, которые вернёт браузер, а то, что после
записи файла к нему больше не обращаются. Это проверяется прямее любого
запуска chromium: `снять()` подменяется на функцию, которая роняет тест,
если её вообще позвали, — и вызывается весь код по обоим путям (вход
и рабочий контекст) с уже существующим файлом.

Импорт `fingerprint` — в подпроцессе с отдельным `GARANT_HOME`: модуль
работает с файлом в `STATE`, и в процессе pytest это писало бы в каталог
состояния разработчика.
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src"

_СКРИПТ = r'''
import sys, json
sys.path.insert(0, r"{site}")
import garant_mcp.paths as paths
import garant_mcp.fingerprint as fp
import garant_mcp.client as client

РЕЗУЛЬТАТ = {{}}

# --- 1. прочитать() на отсутствующем и битом файле — None, не исключение ---
РЕЗУЛЬТАТ["нет_файла_дает_none"] = fp.прочитать() is None

paths.fingerprint_file.parent.mkdir(parents=True, exist_ok=True)
paths.fingerprint_file.write_text("не json вовсе {{", encoding="utf-8")
РЕЗУЛЬТАТ["битый_файл_дает_none"] = fp.прочитать() is None
paths.fingerprint_file.unlink()

# --- 2. записать()/прочитать() — атомарно и без мусора рядом ---
ЗАПИСАННОЕ = {{
    "user_agent": "Mozilla/5.0 (проба) Chrome/151.0.0.0",
    "locale": "ru-RU",
    "timezone_id": "Pacific/Auckland",
    "viewport": {{"width": 1440, "height": 900}},
    "снят": "2026-01-01T00:00:00",
}}
fp.записать(ЗАПИСАННОЕ)
РЕЗУЛЬТАТ["прочитанное_равно_записанному"] = fp.прочитать() == ЗАПИСАННОЕ
РЕЗУЛЬТАТ["временного_файла_не_осталось"] = not paths.fingerprint_file.with_name(
    paths.fingerprint_file.name + ".tmp").exists()

# --- 3. пока файл есть, снять() НЕ вызывается ни для входа, ни для работы ---
def _паника(*a, **kw):
    raise AssertionError("снять() позвана, хотя файл отпечатка уже существует")

fp.снять = _паника  # подмена самой функции модуля, а не мокирование границы

# отпечаток() — то, чем пользуются обе стороны
РЕЗУЛЬТАТ["отпечаток_не_дергает_снять"] = fp.отпечаток() == ЗАПИСАННОЕ

# --- 4. окно входа и рабочий контекст — ОДНА функция, а не два источника ---
# client.context_options() — то, что вызывают И окно_входа(), И
# GarantClient._ensure() (см. client.py: обе точки зовут context_options()).
# Если бы у них были разные реализации, здесь бы это проявилось расхождением.
ИЗ_ОТПЕЧАТКА = fp.параметры_контекста()
ИЗ_КЛИЕНТА = client.context_options()
РЕЗУЛЬТАТ["контекст_клиента_равен_отпечатку"] = ИЗ_КЛИЕНТА == ИЗ_ОТПЕЧАТКА
РЕЗУЛЬТАТ["параметры_контекста"] = ИЗ_ОТПЕЧАТКА

# Вызов повторно — тот же результат, снять() по-прежнему не звана (иначе
# _паника уже уронила бы процесс до этой строки).
РЕЗУЛЬТАТ["повторный_вызов_тот_же"] = client.context_options() == ИЗ_ОТПЕЧАТКА

print(json.dumps(РЕЗУЛЬТАТ, ensure_ascii=False))
'''


def _результаты(tmp_path) -> dict:
    состояние = tmp_path / "состояние"
    r = subprocess.run(
        [sys.executable, "-c", _СКРИПТ.format(site=str(SRC))],
        cwd=str(tmp_path),
        env={"GARANT_HOME": str(состояние), "PYTHONIOENCODING": "utf-8",
             "PATH": __import__("os").environ.get("PATH", "")},
        capture_output=True, text=True, encoding="utf-8", errors="replace",
        timeout=60,
    )
    assert r.returncode == 0, (
        "сценарий fingerprint упал:\n" + r.stdout + r.stderr)
    строки = [s for s in r.stdout.strip().splitlines() if s.startswith("{")]
    assert строки, "не удалось прочитать результат:\n" + r.stdout + r.stderr
    return json.loads(строки[-1])


def test_отсутствующий_и_битый_файл_дают_none_а_не_исключение(tmp_path):
    р = _результаты(tmp_path)
    assert р["нет_файла_дает_none"] is True
    assert р["битый_файл_дает_none"] is True


def test_запись_атомарна_без_мусора_рядом(tmp_path):
    р = _результаты(tmp_path)
    assert р["прочитанное_равно_записанному"] is True
    assert р["временного_файла_не_осталось"] is True


def test_отпечаток_пока_файл_есть_не_обращается_к_снять(tmp_path):
    """Ядро решения 16: снять() (временный chromium, чтение ОС) не вызывается
    вовсе, пока файл существует, — поэтому значения не «дрейфуют» вслед за
    сменой часового пояса или локали машины между входом и работой.
    """
    р = _результаты(tmp_path)
    assert р["отпечаток_не_дергает_снять"] is True


def test_окно_входа_и_рабочий_контекст_берут_один_и_тот_же_источник(tmp_path):
    """`client.context_options()` — общая точка, которой пользуются и
    `окно_входа()`, и `GarantClient._ensure()` (см. `client.py`). Проверить
    буквальное совпадение параметров у настоящего окна входа и настоящего
    рабочего контекста без запуска chromium НЕЛЬЗЯ — это и есть то, что
    остаётся непроверенным в этой среде. Проверяемо здесь ровно то, что
    обе точки дёргают ОДНУ функцию, а не считают параметры по отдельности:
    `context_options()` возвращает буквально то же, что и
    `fingerprint.параметры_контекста()`, вызванная напрямую.
    """
    р = _результаты(tmp_path)
    assert р["контекст_клиента_равен_отпечатку"] is True
    assert р["повторный_вызов_тот_же"] is True
    assert set(р["параметры_контекста"].keys()) <= {
        "user_agent", "locale", "timezone_id", "viewport"}
