# -*- coding: utf-8 -*-
"""Совет из текста ошибки можно скопировать в терминал (этап 01, шаг 5).

Тексты ошибок советовали запустить `auth_login.py` по пути с каталогом из
давно исчезнувшей раскладки. Каталога с таким именем нет ни у одного
пользователя, включая нас; такой совет хуже отсутствия совета — человек идёт
искать несуществующую папку. Сам литерал здесь не пишется: тест ищет его
и поймал бы собственную докстроку.

Решением 14 (этап 02) `paths.команда()` перестала быть абсолютной: теперь
она отдаёт `garant <подкоманда>` — команду, которую кладёт в PATH
установленный пакет, а не путь конкретной машины с конкретным
интерпретатором. Абсолютный путь и имя интерпретатора уходили пользователю
в текст ошибки и в безтокенный `/health` — то есть на любую машину,
включая чужую.

Проверяется два свойства и оба нужны по отдельности:

1. `paths.команда` даёт строку вида «garant …» — без абсолютного пути,
   без имени интерпретатора этой машины и без буквы диска.
2. Ни в одном модуле не осталось совета с путём прежней раскладки.
   Это регрессионная проверка: литерал возвращается копипастой из старых
   файлов, а замечают его через полгода и по жалобе.
"""

from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
PKG_SRC = SRC / "garant_mcp"

КОД = """
import sys
sys.path.insert(0, r'{src}')
import garant_mcp.paths as paths
print(paths.команда('login'))
print(paths.команда('daemon', 'health'))
"""

# Буква латиницы, двоеточие и разделитель пути следом — так выглядит корень
# абсолютного пути на Windows. На Linux/macOS абсолютный путь начинается
# с разделителя без буквы и двоеточия перед ним, такого совпадения не
# даёт — проверка бьёт именно по тому, что раньше уходило пользователю:
# путь КОНКРЕТНОЙ машины.
_БУКВА_ДИСКА = re.compile(r"[A-Za-z]:[\\/]")


def test_команда_без_абсолютного_пути_интерпретатора_и_диска():
    r = subprocess.run([sys.executable, "-c", КОД.format(src=SRC)],
                       capture_output=True, text=True, encoding="utf-8",
                       errors="replace", timeout=60)
    assert r.returncode == 0, r.stderr
    вход, health = r.stdout.strip().splitlines()[-2:]

    assert вход.startswith("garant "), (
        "команда обязана быть вызовом пульта `garant`, а не путём "
        "к скрипту: " + вход)
    assert sys.executable not in вход, (
        "команда содержит путь к интерпретатору ЭТОЙ машины — такой текст, "
        "уйдя в /health без токена, раскрывает раскладку диска: " + вход)
    assert not _БУКВА_ДИСКА.search(вход), (
        "в команде осталась буква диска — абсолютный путь конкретной "
        "машины: " + вход)
    assert str(PKG_SRC) not in вход, (
        "команда содержит путь к каталогу кода: " + вход)
    assert health == "garant daemon health", (
        "подкоманды не сложились в ожидаемую строку: " + health)


def test_совета_с_прежней_раскладкой_не_осталось():
    """Ищется по частям, чтобы тест не ловил сам себя."""
    следы = re.compile("|".join((
        "08" + "_Tools",
        r"python\s+\w+[/\\]garant-mcp",
    )))
    виновные = []
    for f in sorted(PKG_SRC.glob("*.py")):
        for n, строка in enumerate(
                f.read_text(encoding="utf-8").splitlines(), 1):
            if следы.search(строка):
                виновные.append("{}:{}: {}".format(f.name, n, строка.strip()))
    assert not виновные, (
        "в текстах остался путь прежней раскладки:\n" + "\n".join(виновные))
