# -*- coding: utf-8 -*-
"""Сторожа на `_покрытие_периодом` и решение 30: три места («покрыт ли
период датой?») обязаны отвечать одинаково — `_начало_действия`,
`_оговорка_о_периодах` (через `revisions()`) и `revision_on_date`.

Наряд «этап 03, ворота фазы B, предмет 2»: `python-dev` завёл единственную
считающую функцию `_покрытие_периодом(п, дата) -> (покрывает, нечем)`
и закрыл дефект — до 08.09.2026 условие `t is None or дата <= t` делало
кривую (не разобравшуюся датой) строку в поле «по» неотличимой от
бессрочности: истёкший период с неразобранным концом молча становился
действующим поныне. Здесь — сторож на сам дефект и на то, что три
потребителя функции берут решение из одного и того же места, а не
пересчитывают его на свой лад.

Транспорт подменён на границе `Transport.fetch` (решение 17): вызывается
настоящий `revisions()` / `document()` / `revision_on_date()`, разбор
`/redactions/list` и вся арифметика дат исполняются по-настоящему.
"""
from __future__ import annotations

import json
from datetime import date, timedelta

import pytest

from _фейк_транспорт import ФейкТранспорт

from garant_mcp import client


# --------------------------------------------------------------------------
#  прямые проверки примитива — единственного места, считающего покрытие
# --------------------------------------------------------------------------

def test_бессрочный_период_покрывает_без_недоказанности():
    """Пустое «по» — бессрочность по самой природе записи «Гаранта»:
    период покрывает любую дату не раньше начала, и это ДОКАЗАНО, а не
    предположено — регресс не должен появиться попутно с починкой дефекта."""
    п = {"с": "01.01.2015", "по": ""}
    покрывает, нечем = client._покрытие_периодом(п, date(2025, 1, 1))
    assert (покрывает, нечем) == (True, False)


def test_обычный_период_покрывает_дату_внутри_границ():
    п = {"с": "01.01.2015", "по": "01.01.2020"}
    покрывает, нечем = client._покрытие_периодом(п, date(2017, 6, 1))
    assert (покрывает, нечем) == (True, False)


def test_дата_до_начала_периода_не_покрыта():
    п = {"с": "01.01.2015", "по": ""}
    покрывает, нечем = client._покрытие_периодом(п, date(2010, 1, 1))
    assert (покрывает, нечем) == (False, False)


def test_дата_после_разобравшегося_конца_не_покрыта_регресс():
    """Конец периода РАЗОБРАЛСЯ датой и она в прошлом — период истёк
    доказанно, и это не тот случай, который чинил наряд: покрытия нет,
    и незнания тоже нет."""
    п = {"с": "01.01.2015", "по": "01.01.2020"}
    покрывает, нечем = client._покрытие_периодом(п, date(2021, 1, 1))
    assert (покрывает, нечем) == (False, False)


def test_неразобравшийся_конец_даёт_нечем_а_не_покрытие():
    """Сам дефект: строка в «по» есть, но датой не разобралась
    (`parse_ru_date` вернёт `None`). До 08.09.2026 это дало бы `True` —
    неотличимо от бессрочности. Правильный ответ — НЕЗНАНИЕ, а не
    утверждение о покрытии."""
    п = {"с": "01.01.2015", "по": "дата не сохранилась"}
    покрывает, нечем = client._покрытие_периодом(п, date(2030, 1, 1))
    assert (покрывает, нечем) == (False, True), (
        "неразобравшаяся строка в «по» обязана давать НЕЗНАНИЕ (False, True), "
        "а не утверждение о покрытии — иначе истёкший период молча "
        "становится действующим поныне")


def test_неразобравшийся_конец_но_дата_до_начала_не_даёт_нечем():
    """Дата раньше начала периода отсекается ДО разбора «по» — период точно
    не покрывает её, и незнания здесь тоже нет: «по» не при чём вовсе."""
    п = {"с": "01.01.2015", "по": "дата не сохранилась"}
    покрывает, нечем = client._покрытие_периодом(п, date(2010, 1, 1))
    assert (покрывает, нечем) == (False, False)


# --------------------------------------------------------------------------
#  вспомогательное для интеграционных тестов через транспорт
# --------------------------------------------------------------------------

def _редакция(*periods: dict, редакция_имя="ред.") -> dict:
    """Одна запись `/redactions/list` с произвольным числом периодов
    `activity`, ровно как в `test_client_периоды_действия.py`."""
    return {
        "text": редакция_имя,
        "status": "rs_Actual",
        "documentId": 1,
        "activity": list(periods),
    }


def _маршрутизатор_редакций(редакция: dict):
    def маршрут(method, url, form, номер):
        if "/server/keepalive" in url:
            return 200, ""
        if "/document/info" in url:
            return 200, json.dumps({"pageCount": 1, "documentTitle": "Д"})
        if "/document/pages" in url:
            return 200, json.dumps({"items": [{"number": 1, "text": "текст"}]})
        if "/redactions/list" in url:
            return 200, json.dumps({"redactions": [редакция]}, ensure_ascii=False)
        raise AssertionError(f"незнакомый URL: {method} {url}")
    return маршрут


def _клиент(редакция: dict) -> "client.GarantClient":
    return client.GarantClient(transport=ФейкТранспорт(_маршрутизатор_редакций(редакция)))


# --------------------------------------------------------------------------
#  revision_on_date: истёкший (в духе) период с неразобранным «по» не
#  выдаётся за действующий БЕЗ оговорки о недоказанности
# --------------------------------------------------------------------------

def test_revision_on_date_единственный_кандидат_с_неразобранным_концом_несёт_оговорку():
    """Один период на всю редакцию, «по» не разобралась датой. Запрошенная
    дата — далеко в будущем: до починки такой период трактовался как
    бессрочный и матчился безоговорочно, то есть истёкшая (по сути) норма
    выдавалась за действующую. После починки редакция остаётся ЕДИНСТВЕННЫМ
    кандидатом (исключить её так же нечем, как и утвердить), но покрытие
    обязано быть названо недоказанным."""
    редакция = _редакция({"from": "01.01.2015", "to": "давно не актуально"})
    к = _клиент(редакция)

    ответ = к.revision_on_date(doc_id=1, on="01.01.2030")

    assert ответ.get("_период_на_дату", {}).get("с") == "01.01.2015"
    оговорка = ответ.get("_предупреждение") or ""
    assert оговорка, (
        "единственный кандидат с неразобранным концом обязан нести "
        "оговорку о недоказанности покрытия, а не выглядеть уверенным "
        "ответом")
    assert client._КАНДИДАТ_БЕЗ_КОНЦА.strip() in оговорка, (
        "оговорка обязана быть той же самой (решение 30), что несёт общий "
        "текст о недоказанности конца периода:\n" + оговорка)


def test_revision_on_date_реально_истёкший_период_не_подходит_регресс():
    """Контроль: если конец периода РАЗОБРАЛСЯ датой и дата проверки после
    него — период истёк доказанно и вообще не должен быть кандидатом.
    Починка дефекта не должна была задеть этот путь."""
    редакция = _редакция({"from": "01.01.2015", "to": "01.01.2020"})
    к = _клиент(редакция)

    with pytest.raises(client.GarantError):
        к.revision_on_date(doc_id=1, on="01.01.2025")


def test_revision_on_date_бессрочный_единственный_кандидат_без_оговорки_регресс():
    """Контроль на регресс в другую сторону: пустое «по» — доказанная
    бессрочность, и оговорки о недоказанности здесь быть не должно."""
    редакция = _редакция({"from": "01.01.2015", "to": ""})
    к = _клиент(редакция)

    ответ = к.revision_on_date(doc_id=1, on="01.01.2030")

    оговорка = ответ.get("_предупреждение") or ""
    assert client._КАНДИДАТ_БЕЗ_КОНЦА.strip() not in оговорка, (
        "бессрочный период — покрытие ДОКАЗАНО, оговорка о недоказанности "
        "конца появляться не должна:\n" + оговорка)


# --------------------------------------------------------------------------
#  _начало_действия / document(): та же оговорка тем же текстом на том же
#  вопросе — единственный кандидат с неразобранным концом, покрывающий
#  «сегодня»
# --------------------------------------------------------------------------

def test_document_provenance_единственный_кандидат_с_неразобранным_концом():
    """Первый период истёк давно и доказанно (не покрывает «сегодня»),
    второй начался пять лет назад, а «по» не разобралась датой — то есть
    ЕДИНСТВЕННЫЙ, кто может покрывать «сегодня», и то недоказанно.
    Разрыв между периодами настоящий (больше суток) — иначе `_начало_
    действия` до `_покрытие_периодом` вообще не дойдёт (смежные периоды
    считаются непрерывными без обращения к «сегодня»)."""
    сегодня = date.today()
    начало_второго = сегодня - timedelta(days=365 * 5)
    редакция = _редакция(
        {"from": "01.01.2000", "to": "01.01.2001"},
        {"from": начало_второго.strftime("%d.%m.%Y"), "to": "конец не сохранился"},
    )
    к = _клиент(редакция)

    ответ = к.document(doc_id=1)
    prov = ответ["provenance"]
    оговорки = "\n".join(prov.get("оговорки_о_редакции") or [])

    assert prov.get("действует_с") == начало_второго.strftime("%d.%m.%Y"), (
        "единственный (недоказанный) кандидат обязан быть выбран, а не "
        "первый период по списку")
    assert client._КАНДИДАТ_БЕЗ_КОНЦА.strip() in оговорки, (
        "provenance обязан нести ту же оговорку о недоказанности конца, "
        "что и revision_on_date (решение 30):\n" + оговорки)


def test_document_provenance_бессрочный_единственный_кандидат_без_оговорки_о_конце_регресс():
    """Контроль: тот же сценарий, но второй период честно бессрочен
    («по» пусто) — недоказанности здесь нет, оговорка о ней появляться
    не должна (хотя оговорка о самом разрыве между периодами — законно
    остаётся, это другой факт)."""
    сегодня = date.today()
    начало_второго = сегодня - timedelta(days=365 * 5)
    редакция = _редакция(
        {"from": "01.01.2000", "to": "01.01.2001"},
        {"from": начало_второго.strftime("%d.%m.%Y"), "to": ""},
    )
    к = _клиент(редакция)

    ответ = к.document(doc_id=1)
    оговорки = "\n".join(ответ["provenance"].get("оговорки_о_редакции") or [])

    assert client._КАНДИДАТ_БЕЗ_КОНЦА.strip() not in оговорки, (
        "бессрочный единственный кандидат — покрытие ДОКАЗАНО, оговорки "
        "о недоказанности конца быть не должно:\n" + оговорки)


# --------------------------------------------------------------------------
#  решение 30: примитив и потребитель (revision_on_date) сверяются между
#  собой, а не с заранее ожидаемым текстом — на наборе дат и границ
# --------------------------------------------------------------------------

@pytest.mark.parametrize("по, target, ожидание", [
    # (строка «по», дата проверки, "match" | "no_match" | "unproven")
    ("01.01.2020", "01.01.2018", "match"),        # доказанно внутри границ
    ("01.01.2020", "01.01.2021", "no_match"),     # доказанно истёк
    ("", "01.01.2099", "match"),                  # бессрочно — доказанно
    ("не сохранилось", "01.01.2099", "unproven"), # неразобранный конец
    ("не сохранилось", "01.01.2010", "no_match"), # дата раньше начала — «по» ни при чём
])
def test_revision_on_date_согласован_с_примитивом_на_наборе_случаев(по, target, ожидание):
    """Ground truth — сам `_покрытие_периодом`; `revision_on_date` не
    имеет права посчитать иначе на тех же входных данных. Не сверка текста
    с ожиданием, а сверка результата функции с поведением потребителя."""
    п = {"с": "01.01.2015", "по": по}
    покрывает, нечем = client._покрытие_периодом(
        п, client.parse_ru_date(target))
    # Ground truth пересчитан для документирования требования — реальная
    # сверка ниже идёт с ПОВЕДЕНИЕМ revision_on_date, а не с этим значением.
    assert (покрывает, нечем) == {
        "match": (True, False),
        "no_match": (False, False),
        "unproven": (False, True),
    }[ожидание]

    редакция = _редакция({"from": "01.01.2015", "to": по})
    к = _клиент(редакция)

    if ожидание == "no_match":
        with pytest.raises(client.GarantError):
            к.revision_on_date(doc_id=1, on=target)
        return

    ответ = к.revision_on_date(doc_id=1, on=target)
    оговорка = ответ.get("_предупреждение") or ""
    несёт_недоказанность = client._КАНДИДАТ_БЕЗ_КОНЦА.strip() in оговорка
    assert несёт_недоказанность == (ожидание == "unproven"), (
        "revision_on_date обязан нести оговорку о недоказанности РОВНО "
        "тогда, когда `_покрытие_периодом` сказал «нечем» — не чаще "
        "и не реже:\n" + оговорка)
