# -*- coding: utf-8 -*-
"""Сторож на КЛАСС дефекта, а не на конкретное имя (решение 32).

`BrowserWorker._stop` был `threading.Event` под именем приватного МЕТОДА
`threading.Thread._stop`/`Thread._wait_for_tstate_lock` (зависит от версии
интерпретатора, какое имя внутри реализации реально ловит подмену). На
python 3.12 — минимуме пакета и версии CI — `Thread.join()` дёргает это
имя как метод и падает `TypeError: 'Event' object is not callable`.
На python 3.14, где сейчас гоняются тесты в среде разработки, внутренняя
реализация другая, и дефект НЕВИДИМ — «зелёный прогон» здесь ничего не
говорит про CI. Наряд, нашедший `_stop`, потребовал сторожа не на само
имя (завтра совпадёт другое), а на КЛАСС: ни один атрибут, который пишет
себе наследник `threading.Thread` в контуре, не имеет права называться
так же, как приватное имя `Thread`.

Проверка статическая и не требует ни сети, ни живого потока, ни python
3.12: она разбирает AST файлов `src/garant_mcp/*.py`, находит классы,
унаследованные от `threading.Thread`, и сравнивает имена, которым они
присваивают `self.<имя>`, со списком приватных имён `Thread`. Список
собран из двух источников и объединён, потому что ни один по отдельности
не покрывает обе версии, между которыми различался этот самый дефект:

* то, что показывает интроспекция `threading.Thread` НА ЭТОЙ машине
  (`dir()` класса и `__dict__` живого экземпляра) — актуально для той
  версии python, на которой сейчас идёт прогон;
* буквальный список приватных имён `Thread` на python 3.12, где дефект
  проявляется (`_stop`, `_bootstrap`, `_delete`, `_initialized`,
  `_reset_internal_locks`, `_set_ident`, `_set_native_id`,
  `_set_tstate_lock`, `_wait_for_tstate_lock`, `_target`, `_tstate_lock`,
  `_started`) — эта версия здесь не запущена, интроспекцией её не
  получить, и список назван явно, а не изображён проверенным.

Объединение — потому что ни дефект, ни его починка не привязаны к тому,
на какой версии сейчас гоняется тест: цель — не пропустить СЛЕДУЮЩЕЕ
совпадение имени, а не подтвердить прошлое.
"""
from __future__ import annotations

import ast
import threading
from pathlib import Path

SRC = Path(__file__).resolve().parent.parent / "src" / "garant_mcp"

# Источник 1 — интроспекция живого threading.Thread на машине, где сейчас
# идёт pytest (для 3.14 в этой среде — пусто на приватные атрибуты
# уровня класса, экземплярные добавляются ниже).
_ЖИВЫЕ_ПРИВАТНЫЕ = {
    n for n in dir(threading.Thread)
    if n.startswith("_") and not n.startswith("__")
}
_т = threading.Thread()
_ЖИВЫЕ_ПРИВАТНЫЕ |= {
    n for n in vars(_т)
    if n.startswith("_") and not n.startswith("__")
}

# Источник 2 — буквальный список для python 3.12 (минимум пакета,
# версия CI, decision 32): интроспекцией здесь не добыть, интерпретатора
# такой версии в этой среде нет, поэтому назван явно.
_ПРИВАТНЫЕ_3_12 = {
    "_stop", "_bootstrap", "_delete", "_initialized",
    "_reset_internal_locks", "_set_ident", "_set_native_id",
    "_set_tstate_lock", "_wait_for_tstate_lock", "_target",
    "_tstate_lock", "_started",
}

ЗАПРЕЩЁННЫЕ_ИМЕНА = frozenset(_ЖИВЫЕ_ПРИВАТНЫЕ | _ПРИВАТНЫЕ_3_12)


def _наследует_thread(база: ast.expr) -> bool:
    """`class X(threading.Thread)` и `class X(Thread)` — обе формы."""
    if isinstance(база, ast.Attribute):
        return база.attr == "Thread"
    if isinstance(база, ast.Name):
        return база.id == "Thread"
    return False


def _self_атрибуты(класс: ast.ClassDef) -> set[str]:
    """Все имена вида `self.<имя> = ...` внутри тела класса, на любой
    глубине вложенности (не только в `__init__`) — присвоение потоку
    собственного состояния бывает и в `run()`."""
    имена: set[str] = set()
    for узел in ast.walk(класс):
        if isinstance(узел, ast.Assign):
            цели = узел.targets
        elif isinstance(узел, ast.AnnAssign):
            цели = [узел.target]
        else:
            continue
        for цель in цели:
            if (isinstance(цель, ast.Attribute)
                    and isinstance(цель.value, ast.Name)
                    and цель.value.id == "self"):
                имена.add(цель.attr)
    return имена


def _подклассы_thread_в_файле(путь: Path) -> dict[str, set[str]]:
    дерево = ast.parse(путь.read_text(encoding="utf-8"), filename=str(путь))
    результат: dict[str, set[str]] = {}
    for узел in ast.walk(дерево):
        if isinstance(узел, ast.ClassDef) and any(
                _наследует_thread(б) for б in узел.bases):
            результат[узел.name] = _self_атрибуты(узел)
    return результат


def test_ни_один_наследник_thread_не_перекрывает_приватное_имя():
    найдено_хотя_бы_один_класс = False
    for файл in sorted(SRC.glob("*.py")):
        for имя_класса, атрибуты in _подклассы_thread_в_файле(файл).items():
            найдено_хотя_бы_один_класс = True
            пересечение = атрибуты & ЗАПРЕЩЁННЫЕ_ИМЕНА
            assert not пересечение, (
                "класс {}.{} присваивает self.{} — это имя приватно "
                "в threading.Thread (на этой версии python и/или на "
                "3.12, минимуме пакета); совпадение с ним ровно тот "
                "класс дефекта, что был у _stop (решение 32): метод "
                "или атрибут Thread молча перекрывается, и join()/старт "
                "потока падают TypeError на той версии, где имя "
                "оказывается методом, а не полем.".format(
                    файл.name, имя_класса, sorted(пересечение)))

    assert найдено_хотя_бы_один_класс, (
        "в src/garant_mcp/*.py не нашлось ни одного класса, наследующего "
        "threading.Thread, — проверка ничего не проверила. Если "
        "BrowserWorker переехал или переименован, сторож обязан найти "
        "его новое имя, а не молчать.")


def test_запрещённый_список_содержит_stop_регресс():
    """Контроль на сам тест: если список приватных имён когда-нибудь
    соберётся пустым (например, из-за опечатки в способе интроспекции),
    проверка выше молча перестанет что-либо проверять. `_stop` — то самое
    имя из уже случившегося дефекта, оно обязано быть в списке всегда,
    независимо от версии python, на которой сейчас идёт прогон."""
    assert "_stop" in ЗАПРЕЩЁННЫЕ_ИМЕНА
