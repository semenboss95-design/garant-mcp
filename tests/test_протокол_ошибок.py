# -*- coding: utf-8 -*-
"""Договор ошибок между демоном и клиентом (этап 02, шаг 2, `protocol.py`).

Раньше ошибка была строкой, и решение «жива ли сессия подписки» принималось
поиском подстрок «401», «403», «сесси» без приведения регистра — в тексте
ЛЮБОГО исключения. Цена не теоретическая: запрос про «статью 401.11 УПК»
объявлял сессию подписки мёртвой, а настоящее «Сессия недействительна»
с заглавной буквы не ловилось вовсе (регистр не приводился).

`protocol.py` вводит тип, который ставит тот, кто знает причину, и он же
решает — а не текст сообщения. Здесь проверяется сам договор: тип переживает
сериализацию в словарь и обратно (граница потока/HTTP имитируется явно,
без реального демона), и `классифицировать()` не поднимает случайное
исключение до `session` только потому, что в тексте случайно нашлось число
«401» или слово «сессия».

Модуль `protocol.py` не имеет побочных эффектов на импорте (ни mkdir, ни
сети) — прямой импорт в процессе теста безопасен и не требует subprocess:
здесь не измеряются побочные эффекты, а измеряется чистая логика.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
if str(SRC) not in sys.path:
    sys.path.insert(0, str(SRC))

import garant_mcp.protocol as protocol  # noqa: E402


# --------------------------------------------------------------------------
#  словарь() / из_словаря() — ошибка переживает границу
# --------------------------------------------------------------------------

def test_тип_переживает_словарь_и_обратно():
    """Тип, сообщение и http-код обязаны доехать через границу без потерь."""
    исходная = protocol.GarantError("сессия истекла", protocol.ТИП_СЕССИЯ, 403)
    приехавшая = protocol.из_словаря(исходная.словарь())
    assert приехавшая.тип == protocol.ТИП_СЕССИЯ
    assert приехавшая.сообщение == "сессия истекла"
    assert приехавшая.http == 403


def test_из_словаря_на_мусоре_не_роняет_и_не_подставляет_session():
    """Испорченное тело (не dict) — не повод объявить тип session."""
    приехавшая = protocol.из_словаря("просто строка, не словарь")
    assert приехавшая.тип == protocol.ТИП_API, (
        "из_словаря на мусорном входе обязана давать нейтральный тип, "
        "а не session — иначе повреждённая передача сама объявляет сессию "
        "подписки мёртвой."
    )


def test_словарь_без_известного_типа_даёт_api_changed():
    """Незнакомый тип (например, из более новой версии на другой стороне
    границы) обязан свестись к нейтральному, а не быть отвергнут исключением.
    """
    приехавшая = protocol.из_словаря({"тип": "совсем-новый-тип-из-будущего",
                                       "сообщение": "х"})
    assert приехавшая.тип == protocol.ТИП_API


# --------------------------------------------------------------------------
#  классифицировать() — тип ставит код, а не текст сообщения
# --------------------------------------------------------------------------

def test_таймаут_классифицируется_отдельно_от_сессии():
    ошибка = protocol.классифицировать(TimeoutError("не дождались"))
    assert ошибка.тип == protocol.ТИП_ТАЙМАУТ


def test_готовый_garant_error_не_переклассифицируется():
    """GarantError уже несёт тип — классифицировать() обязана его не трогать,
    а не решать заново по тексту сообщения.
    """
    исходная = protocol.GarantError("Сессия недействительна", protocol.ТИП_БРАУЗЕР)
    итог = protocol.классифицировать(исходная)
    assert итог is исходная
    assert итог.тип == protocol.ТИП_БРАУЗЕР, (
        "классифицировать() переопределила уже поставленный тип — значит, "
        "решение снова принимается по тексту, а не по тому, кто знает причину."
    )


def test_регрессия_401_в_тексте_не_даёт_session():
    """Тот самый дефект: запрос про «статью 401.11» не должен объявлять
    сессию подписки мёртвой. Обычное исключение (не GarantError) с «401»
    и словом «сесси» в тексте обязано классифицироваться нейтрально —
    решает тип, поставленный явно, а не подстрока в сообщении.
    """
    ошибка = protocol.классифицировать(
        ValueError("не найдена статья 401.11 УПК — Сессия поиска пуста"))
    assert ошибка.тип != protocol.ТИП_СЕССИЯ, (
        "классифицировать() объявила сессию подписки мёртвой по подстроке "
        "«401»/«сесси» в тексте постороннего исключения — это и есть дефект, "
        "ради которого заведён тип."
    )
    assert ошибка.тип == protocol.ТИП_API


def test_заглавная_сессия_тоже_не_ловится_по_тексту():
    """Симметричный случай прежнего дефекта: настоящее «Сессия…» с заглавной
    буквы не давало session по поиску без приведения регистра. Проверяем,
    что теперь текст вообще не участвует в решении — тип остаётся
    нейтральным, если он не поставлен явно.
    """
    ошибка = protocol.классифицировать(RuntimeError("Сессия истекла"))
    assert ошибка.тип == protocol.ТИП_API


def test_признаки_закрытого_браузера_дают_тип_browser():
    ошибка = protocol.классифицировать(RuntimeError("Target closed"))
    assert ошибка.тип == protocol.ТИП_БРАУЗЕР


def test_playwright_подобный_timeout_не_наследующий_builtin_классифицируется_как_таймаут():
    """Регрессия шага 3: `playwright.sync_api.TimeoutError` НЕ наследуется от
    встроенного `TimeoutError` (он потомок `Error`, то есть `Exception`), но
    называется `TimeoutError` по имени класса. Прежняя проверка
    `isinstance(exc, TimeoutError)` такое исключение не ловила вовсе, и самая
    частая неудача контура — не дождались ответа «Гаранта» — уезжала
    в `api_changed` (502 «карта разошлась с ответом») вместо `timeout` (504).

    Playwright здесь не импортируется и не поднимается: имитация — класс
    с тем же именем и тем же местом в иерархии (потомок собственного,
    не встроенного `Error`), этого достаточно, чтобы отличить проверку
    по MRO-имени от проверки по `isinstance`.
    """
    class Error(Exception):
        """Свой Error, не встроенный — как у Playwright."""

    class TimeoutError(Error):  # намеренно перекрывает имя builtins.TimeoutError
        """Класс с именем TimeoutError, НЕ являющийся builtins.TimeoutError."""

    поддельный = TimeoutError("Timeout 30000ms exceeded.")
    assert not isinstance(поддельный, __builtins__["TimeoutError"]
                          if isinstance(__builtins__, dict)
                          else __builtins__.TimeoutError), (
        "тест недостоверен: поддельный класс оказался потомком встроенного "
        "TimeoutError — тогда даже старая проверка isinstance() его ловит, "
        "и тест ничего не проверяет.")

    ошибка = protocol.классифицировать(поддельный)
    assert ошибка.тип == protocol.ТИП_ТАЙМАУТ, (
        "исключение по имени TimeoutError, не наследующее встроенный класс "
        "(ровно как playwright.sync_api.TimeoutError), обязано "
        "классифицироваться как timeout (504), а не как api_changed (502): "
        "иначе самая частая неудача контура — «не дождались» — читается "
        "как «карта разошлась с ответом».")


def test_неопознанное_исключение_нейтрально_а_не_session():
    """Единственный поведенчески безопасный тип для неопознанного —
    api_changed: ошибиться в сторону session значит объявить живую сессию
    подписки мёртвой.
    """
    ошибка = protocol.классифицировать(KeyError("что-то не так"))
    assert ошибка.тип == protocol.ТИП_API
