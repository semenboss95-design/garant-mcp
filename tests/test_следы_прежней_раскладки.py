def test_нет_имени_этой_машины_по_всему_дереву():
    имена = _имена_машины()
    if not имена:
        import pytest
        pytest.skip("не удалось получить ни одного имени пользователя этой "
                    "машины (USER/USERNAME/getpass/HOME) — по нему проверка "
                    "невыполнима, а не пройдена")
    паттерн = re.compile(
        r"(^|[^A-Za-z0-9])({})([^A-Za-z0-9]|$)".format(
            "|".join(re.escape(и) for и in имена)),
        re.IGNORECASE)
    провалы = []
    for путь in публичные_кандидаты():
        текст = прочитать_из_рабочего_дерева(путь)
        if текст is None:
            continue
        for i, строка in enumerate(текст.splitlines(), 1):
            if паттерн.search(строка):
                провалы.append("{}:{}".format(путь, i))
    assert not провалы, (
        "имя пользователя ЭТОЙ машины найдено в дереве репозитория — "
        "публичный файл, называющий чью-то учётную запись, это утечка, "
        "от которой и защищает весь этот наряд (места: {}). Само имя "
        "не печатается: тест уже утечкой не занимается.".format(провалы))


def test_умолчание_порта_объявлено_в_одном_месте():
    """8787 — литерал умолчания порта демона. Единственное разрешённое
    место — `src/garant_mcp/config.py`; появление того же числа где-то
    ещё в `src/` — это второй источник истины, который может тихо
    разойтись с первым при следующей правке.

    Тесты и документация (`tests/test_paths.py`, `CLAUDE.md`) литерал
    ЧИТАЮТ ради проверки/иллюстрации — это не второе объявление умолчания,
    и в область поиска не входит: ниже проверяется только `src/`.
    """
    единственное_место = "src/garant_mcp/config.py"
    найдено_в = []
    for f in (ROOT / "src" / "garant_mcp").glob("*.py"):
        путь = "src/garant_mcp/{}".format(f.name)
        текст = прочитать_из_рабочего_дерева(путь)
        if текст is None:
            continue
        if "8787" in текст:
            найдено_в.append(путь)
    assert найдено_в == [единственное_место], (
        "литерал умолчания порта (8787) обязан жить РОВНО в одном файле "
        "({}), а найден в: {}. Второе объявление того же умолчания может "
        "разойтись с первым молча.".format(единственное_место, найдено_в))
