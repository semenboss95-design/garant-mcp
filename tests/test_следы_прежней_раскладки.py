# -*- coding: utf-8 -*-
"""§7 `docs/TEAM.md`, проверка 6 — следы прежней машины/раскладки по ВСЕМУ
дереву, а не только по тому, что меняется в текущем коммите.

Чем это отличается от `hooks/pre-commit`: хук читает `git diff --cached`,
то есть только ИЗМЕНЁННЫЕ файлы. Литерал, однажды попавший в НЕТРОНУТЫЙ
файл, хук не увидит никогда — трогать этот файл никто не обязан. Раньше
всё дерево целиком смотрели ворота `scripts/acceptance.ps1`; вместе
с ними (решение 18) эта проверка пропала, и здесь она возвращается —
единственное место, которое действительно проходит по каждому файлу,
а не только по диффу.

Что ищем — по списку из наряда, а не всё то же самое, что уже смотрит
хук (там это оправдано форматом diff, здесь — вопрос стоимости: широкий
скан всего дерева на все семь правил хука дал бы много ложных
срабатываний на служебных строках самого хука/тестов, которые explicitly
обсуждают эти образцы как текст, а не как утечку):

  * имя пользователя ЭТОЙ машины — берётся у окружения (`USER`,
    `USERNAME`, `getpass.getuser()`, имя каталога `HOME`), а не
    литералом: тест, который называет чьё-то имя в открытую, был бы
    той же утечкой, которую ищет;
  * путь вида `.../Users/имя` — общий образец, никого не называет;
  * буква диска в тексте (`C:` и разделитель) — общий образец;
  * путь внутрь `.venv` (`Scripts`/`bin`) — после решения 14 это признак
    регрессии, а не один из вариантов;
  * умолчание порта (8787) — ЕДИНСТВЕННОЕ место в `src/` обязано его
    объявлять (`config.py`); появление того же литерала где-то ещё
    в `src/` — это второй, расходящийся источник истины.

Тест читает РЕАЛЬНОЕ дерево репозитория (не копию): здесь ничего не
пишется и не меняется, только чтение файлов с диска и `git ls-files`.
"""

from __future__ import annotations

import getpass
import os
import re
from pathlib import Path

from _repo_git import ROOT, публичные_кандидаты, прочитать_из_рабочего_дерева

# Этот файл и модуль-помощник — единственные места, которым по праву
# позволено ОБСУЖДАТЬ образцы (в комментариях/строках), не подпадая под
# них: сами регэкспы ниже пишутся так, чтобы не совпадать сами с собой
# (то же правило, что и в hooks/pre-commit — через класс символов,
# а не голый литерал), поэтому исключений по имени файла не заводим.

HOME_ПУТЬ = re.compile(r"[/\\][Uu]sers[/\\][A-Za-z0-9._-]")
VENV_ПУТЬ = re.compile(r"\.venv[/\\](Scripts|bin)")
# Тот же образец, что в hooks/pre-commit (см. его комментарий про 'e:\n'):
# буква диска, а не схема URL, и не экранированный перевод строки.
БУКВА_ДИСКА = re.compile(r"""(^|[^A-Za-z0-9])[A-Za-z]:[\\/]([^/nrt]|[nrt][^"']|$)""")

ОБЩИЕ_ИМЕНА = {
    "root", "user", "users", "admin", "administrator", "home",
}


def _имена_машины() -> list[str]:
    """Кандидаты в «имя этой машины» — те же четыре источника, что и хук,
    отфильтрованные так же: короче трёх букв и родовые имена не годятся.
    """
    сырые = {
        os.environ.get("USER", ""),
        os.environ.get("USERNAME", ""),
    }
    try:
        сырые.add(getpass.getuser())
    except Exception:
        pass
    home = os.environ.get("HOME") or os.environ.get("USERPROFILE")
    if home:
        сырые.add(Path(home).name)

    имена = []
    for имя in сырые:
        имя = (имя or "").strip()
        if len(имя) < 3:
            continue
        if имя.lower() in ОБЩИЕ_ИМЕНА:
            continue
        if not re.fullmatch(r"[A-Za-z0-9._-]+", имя):
            continue
        имена.append(имя)
    return имена


def test_нет_пути_вида_users_имя_по_всему_дереву():
    провалы = []
    for путь in публичные_кандидаты():
        текст = прочитать_из_рабочего_дерева(путь)
        if текст is None:
            continue
        for i, строка in enumerate(текст.splitlines(), 1):
            if HOME_ПУТЬ.search(строка):
                провалы.append("{}:{}: {}".format(путь, i, строка.strip()[:120]))
    assert not провалы, (
        "путь вида .../Users/имя найден в НЕТРОНУТОМ дереве — hooks/pre-commit "
        "такое не увидит, пока файл не попадёт в diff:\n" + "\n".join(провалы))


