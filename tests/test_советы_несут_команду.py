# -*- coding: utf-8 -*-
"""Совет из текста ошибки — исполнимая команда, а не пожелание в воздух
(наряд этапа 03, фаза B, часть 2).

`test_подсказки.py` уже проверяет, что `paths.команда()` не отдаёт путь
конкретной машины. Здесь — обратная сторона того же требования: если текст
ошибки ГОВОРИТ пользователю что-то сделать («выполните», «запустите»,
«повторите», «проверьте»), в нём обязана быть КОНКРЕТНАЯ команда —
`garant <подкоманда>` — а не путь к файлу и не имя файла, по которому
человеку самому предстоит догадаться, что делать. 07.09.2026 чтением нашлось
несколько таких расхождений подряд — значит, условие стоит теста, а не
разового вычитывания.

Статический анализ через AST, а не строковый grep построчно: совет часто
собирается из нескольких строк («…и повторите " + paths.команда(...)» или
f-строкой на несколько физических строк), и построчный grep половину таких
случаев не увидит вовсе или разрежет ровно посередине фразы. AST даёт
границы ОДНОГО выражения-инструкции («statement») — этого достаточно, чтобы
понять, относится ли `paths.команда(...)` или литеральное слово «garant»
к тому же совету, что и триггерное слово.

`garant` в исходнике проверяется двумя способами, и оба законны:
литеральное слово (например, в client.py уже используется имя инструмента
`garant_revisions` — это тоже исполнимая команда, только не для терминала,
а для клиента с инструментами) и вызов `paths.команда(...)`, который
всегда собирает строку `"garant " + подкоманда` — сам текст в исходнике
её не содержит, но обещание в его сигнатуре читается ясно (`paths.py`).

Чего тест не проверяет: уместность конкретной подкоманды для конкретной
ошибки — только её присутствие. Обязательно проверить: пары `errors,
found` печатаются с указанием файла и строки, чтобы найденное расхождение
можно было адресно почитать и решить, чинить рерайтом текста или добавлением
подкоманды.
"""

from __future__ import annotations

import ast
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PKG_SRC = ROOT / "src" / "garant_mcp"

# Императив 2-го лица множественного числа — совет пользователю. Границы
# слова важны: без них «Перезапустите» ловится подстрокой «запустите» и
# считается советом, хотя это просьба перезапустить СТОРОННИЙ MCP-клиент —
# для него команды `garant` не существует в принципе. \b с юникодовым \w
# (Python по умолчанию) не проходит внутрь слитного слова: между «е» и «з»
# в «Перезапустите» нет границы, потому что оба соседних символа — «\w».
ТРИГГЕР = re.compile(r"\b(выполните|запустите|повторите|проверьте)\b",
                     re.IGNORECASE)


def _родители(tree: ast.AST) -> dict:
    родители: dict = {}
    for узел in ast.walk(tree):
        for ребёнок in ast.iter_child_nodes(узел):
            родители[ребёнок] = узел
    return родители


def _statement(node: ast.AST, родители: dict) -> ast.stmt | None:
    """Ближайший объемлющий `statement` — единица, в которой совет
    и команда обязаны стоять рядом, чтобы читались как один текст."""
    n = node
    while n is not None and not isinstance(n, ast.stmt):
        n = родители.get(n)
    return n


def _без_команды(путь: Path) -> list[str]:
    исходник = путь.read_text(encoding="utf-8")
    дерево = ast.parse(исходник, filename=str(путь))
    родители = _родители(дерево)

    найдено: list[str] = []
    рассмотрено: set[int] = set()
    for узел in ast.walk(дерево):
        if not (isinstance(узел, ast.Constant) and isinstance(узел.value, str)):
            continue
        if not ТРИГГЕР.search(узел.value):
            continue
        stmt = _statement(узел, родители)
        if stmt is None or id(stmt) in рассмотрено:
            continue
        рассмотрено.add(id(stmt))

        отрезок = ast.get_source_segment(исходник, stmt) or ""
        несёт_команду = (
            "garant" in отрезок.lower()          # литерал «garant …»
            or "команда(" in отрезок             # вызов paths.команда(...)
        )
        if not несёт_команду:
            # Путь или имя файла в отрезке (частый в register.py случай —
            # человеку подставляют `цель.путь`) НЕ засчитывается: наряд
            # прямо говорит — «garant <подкоманда>, а не путь и не имя
            # файла». Отдельная ветка ему не нужна: путь без команды и так
            # ловится этим условием.
            найдено.append(
                "{}:{}: {}".format(
                    путь.name, stmt.lineno,
                    " ".join(отрезок.split())[:200]))
    return найдено


def test_совет_несёт_исполнимую_команду_а_не_путь():
    нарушения: list[str] = []
    for f in sorted(PKG_SRC.glob("*.py")):
        нарушения.extend(_без_команды(f))

    assert not нарушения, (
        "текст ошибки советует действие («выполните/запустите/повторите/"
        "проверьте»), но не несёт исполнимой команды `garant <подкоманда>` "
        "(или несёт путь к файлу вместо неё):\n" + "\n".join(нарушения))
