# -*- coding: utf-8 -*-
"""Сторож минимума `requires-python = ">=3.12"` (`pyproject.toml`) против
одного конкретного класса регресса: `Path.read_text`/`Path.write_text` (и
любого `X.read_text`/`X.write_text`, не только `Path`, — `Цель.путь` в
`register.py` типизирован как `Path`, но детектор не завязан на имя типа)
с именованным аргументом `newline=`.

У `read_text` этот параметр появился только в 3.13, у `write_text` —
раньше (3.10), но `register.py` держит обе функции в одной форме (`open`,
а не метод `Path`) намеренно — читай докстроки `_текст`/`_записать_текст`/
`_вернуть_как_было` в `src/garant_mcp/register.py`. На интерпретаторе этой
машины (3.14) `read_text(newline=…)` не упал бы — несовместимость проявится
только там, где стоит пин из `pyproject.toml` (3.12, он же в CI), а не
здесь. Поэтому проверка статическая: разбор AST, а не запуск кода, — она
ловит регресс независимо от того, каким интерпретатором прогнан `pytest`.

Почему AST, а не `grep`/текстовый поиск построчно: сам `register.py`
объясняет в докстроках, ПОЧЕМУ `newline=` не передаётся методам `Path`, и в
этих объяснениях слово `newline=` встречается буквально (см. `_текст`:
"Берётся `open`, а не `Path.read_text(newline=…)`"). Текстовый поиск по
подстроке `.read_text(` + `newline` на одной строке нашёл бы и это
предложение, объясняющее ОТСУТСТВИЕ бага, как будто это сам баг. AST видит
разницу между вызовом функции с ключевым аргументом и упоминанием того же
текста в строковом литерале (docstring, комментарий, произвольная строка).
Это доказано ниже (`test_детектор_не_путает_текст_объяснения_с_вызовом`) —
не как побочный факт, а как причина, по которой инструмент выбран.

Тест обязан падать на сломанном коде, а не только на сломанном
интерпретаторе: `test_детектор_ловит_реальный_класс_бага` прогоняет
детектор по СИНТЕТИКЕ, воспроизводящей буквальную форму бага, который был
в `register.py` до правки (`цель.путь.read_text(encoding="utf-8",
newline="")` — правка заменила это на `open(цель.путь, "r", ...,
newline="") as ф: ф.read()`), и требует, чтобы детектор его нашёл. Без
этого теста «нулевая находка» на реальных файлах могла бы значить и
«детектор работает», и «детектор ничего не ловит» — разницы снаружи не
видно.
"""

from __future__ import annotations

import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ПАКЕТ = ROOT / "src" / "garant_mcp"

МЕТОДЫ = ("read_text", "write_text")


def _вызовы_с_newline(исходный: str) -> list[str]:
    """`"имя_метода@строка"` для каждого вызова `X.read_text(...)`/
    `X.write_text(...)`, где среди аргументов есть именованный `newline=`
    (значение не важно — сам факт передачи параметра младше минимума пакета).
    """
    дерево = ast.parse(исходный)
    находки = []
    for узел in ast.walk(дерево):
        if not isinstance(узел, ast.Call):
            continue
        функция = узел.func
        if not isinstance(функция, ast.Attribute) or функция.attr not in МЕТОДЫ:
            continue
        if any(кв.arg == "newline" for кв in узел.keywords):
            находки.append("{}@{}".format(функция.attr, узел.lineno))
    return находки


# ---------------------------------------------------------------------------
#  сам сторож: во всём пакете таких вызовов нет
# ---------------------------------------------------------------------------

def test_read_write_text_без_newline_во_всём_пакете():
    находки_по_файлу = {}
    файлы = sorted(ПАКЕТ.glob("*.py"))
    assert файлы, "пакет не найден по пути {} — сторож проверил бы пустоту".format(ПАКЕТ)
    for файл in файлы:
        находки = _вызовы_с_newline(файл.read_text(encoding="utf-8"))
        if находки:
            находки_по_файлу[файл.name] = находки

    assert not находки_по_файлу, (
        "{}.read_text()/write_text() получил параметр `newline=` — у "
        "read_text он появился в Python 3.13, а pyproject.toml объявляет "
        "requires-python >=3.12 (тот же пин ставит CI): вызов упадёт "
        "TypeError на минимуме, до того как код успеет вежливо отказать.\n"
        "{}".format(
            ", ".join(находки_по_файлу),
            "\n".join("  {}: {}".format(f, n) for f, n in находки_по_файлу.items()),
        )
    )


# ---------------------------------------------------------------------------
#  детектор не бесполезен: находит именно ту форму бага, что была в
#  register.py, и не путает её с текстом, который её ОБЪЯСНЯЕТ
# ---------------------------------------------------------------------------

def test_детектор_ловит_реальный_класс_бага():
    синтетика = (
        'def _текст(цель):\n'
        '    if not цель.путь.exists():\n'
        '        return ""\n'
        '    return цель.путь.read_text(encoding="utf-8", newline="")\n'
    )
    находки = _вызовы_с_newline(синтетика)
    assert находки == ["read_text@4"], (
        "детектор обязан находить read_text(newline=) в буквальной форме "
        "бага, который правка убрала из register.py; иначе проверка выше "
        "зелена и на сломанном, и на исправленном коде и не защищает ничего")


def test_детектор_ловит_write_text_тоже():
    синтетика = (
        'def _записать_текст(цель, текст):\n'
        '    цель.путь.write_text(текст, encoding="utf-8", newline="")\n'
    )
    находки = _вызовы_с_newline(синтетика)
    assert находки == ["write_text@2"]


def test_детектор_не_путает_текст_объяснения_с_вызовом():
    """Ровно та форма, что живёт в `register.py` СЕЙЧАС: докстрока
    упоминает `newline=…` словами, а вызов рядом — обычный `open()`.
    Текстовый поиск по подстроке нашёл бы и это; AST — нет.
    """
    синтетика = (
        'def _текст(цель):\n'
        '    """Берётся `open`, а не `Path.read_text(newline=...)`: у '
        'read_text этот параметр появился только в 3.13."""\n'
        '    with open(цель.путь, "r", encoding="utf-8", newline="") as ф:\n'
        '        return ф.read()\n'
    )
    находки = _вызовы_с_newline(синтетика)
    assert находки == [], (
        "открытие через open(..., newline=...) не метод read_text/"
        "write_text — детектор не имеет права его находить: {}".format(находки))
