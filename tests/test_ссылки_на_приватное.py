# -*- coding: utf-8 -*-
"""§7 `docs/TEAM.md`, проверка 4 — публичный файл не ссылается на приватный.

«Правило висячих ссылок» из `CLAUDE.md`: раз рабочие планы и промты
(`PLAN_*.md`, `PROMPT_*.md`, `REVIEW_*.md`, `RELEASE_NOTES_FOR_AGENT.md`,
весь `memory/`) приватны и в клон не попадают, ни один публичный файл не
имеет права требовать от читателя открыть их — ссылка ведёт в пустоту.
У `hooks/pre-commit` такого правила нет вовсе: он смотрит на секреты
и пути машины, а не на структуру документации.

ГЛАВНАЯ ТОНКОСТЬ (названа в наряде явно): правило запрещает не
УПОМИНАНИЕ, а ЗАВИСИМОСТЬ. `CLAUDE.md` вправе написать «рабочие планы
приватны и в клон не попадают» — это утверждение О файле, не отсылка
К нему, и его не открывают, чтобы понять текст, где оно написано.
Запрещено — синтаксическая ссылка вида `[текст](путь)`, которая
СИНТАКСИЧЕСКИ обещает читателю, что по этому пути есть что открыть.

Как это разведено МЕХАНИЧЕСКИ, а не на глаз: ищутся только markdown-ссылки
формата `](путь)` — то есть места, где автор сам, синтаксисом языка,
объявил путь местом перехода. Голое упоминание имени файла в тексте или
в инлайн-коде (`` `PROMPT_...md` ``) — это не переход, и подпадать под
запрет не должно; проверка сюда не заходит вообще, потому что не ищет
инлайн-код и обычный текст, только конструкцию markdown-ссылки.

Мерилом «приватности» цели служит НЕ жёстко вшитый список имён, а сам
`.gitignore` (`git check-ignore` на итоговый путь): это тот же измеритель,
что и в проверке 1, и он не разъезжается с ней — если `.gitignore`
ослабят, обе проверки увидят это одинаково, а не по двум спискам,
которые могут разойтись.
"""

from __future__ import annotations

import re
from urllib.parse import urlsplit

from _repo_git import ROOT, git, публичные_кандидаты, прочитать_из_рабочего_дерева

# `](путь)` — ссылка markdown. Путь без пробелов и без вложенных скобок
# (markdown-ссылки с пробелом в пути и так нечитаемы без экранирования,
# а этот наряд размечает только то, что БЕЗУСЛОВНО ссылка).
ССЫЛКА = re.compile(r"\]\(([^)\s]+)\)")


def _не_переход(цель: str) -> bool:
    """Внешние ссылки и якоря на этот же файл целью с диска не считаем —
    `git check-ignore` на URL просто ничего не найдёт, но фильтр честнее
    выразить явно, чем полагаться на побочный эффект."""
    if цель.startswith("#"):
        return True
    схема = urlsplit(цель).scheme
    return схема in ("http", "https", "mailto")


def test_нет_markdown_ссылок_на_приватное():
    провалы = []
    for путь in публичные_кандидаты():
        if not путь.endswith(".md"):
            continue  # ссылки markdown бывают только в markdown
        текст = прочитать_из_рабочего_дерева(путь)
        if текст is None:
            continue
        база = (ROOT / путь).parent
        for i, строка in enumerate(текст.splitlines(), 1):
            for m in ССЫЛКА.finditer(строка):
                цель = m.group(1)
                if _не_переход(цель):
                    continue
                цель_без_якоря = цель.split("#", 1)[0]
                if not цель_без_якоря:
                    continue
                разрешённый = (база / цель_без_якоря).resolve()
                try:
                    относительный = разрешённый.relative_to(ROOT)
                except ValueError:
                    continue  # ссылка ушла за пределы репозитория — не наш случай
                r = git("check-ignore", "-q", "--", str(относительный).replace("\\", "/"))
                if r.returncode == 0:
                    провалы.append(
                        "{}:{}: ссылка на «{}» ведёт на путь, закрытый "
                        ".gitignore — у клонировавшего этого файла нет"
                        .format(путь, i, цель))
    assert not провалы, (
        "публичный файл ссылается (markdown-ссылкой) на приватное:\n"
        + "\n".join(провалы))
