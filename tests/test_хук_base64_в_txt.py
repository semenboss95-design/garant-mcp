# -*- coding: utf-8 -*-
"""`.txt` больше не «код» для хука — длинная base64url-строка в нём
обязана отклоняться (наряд этапа 03, фаза B, часть 2).

До 07.09.2026 `.txt` входил в список расширений `is_code()` в
`hooks/pre-commit`, и правило про длинную base64url-строку (ОТКАЗ 3)
применяется только к файлам, которые НЕ код, — то есть подложенный
в `.txt` секрет (перенаправленный вывод команды, «сохранил на минуту»)
хук пропускал молча. Решение убрать `.txt` из `is_code()` уже стоит
в самом хуке; здесь — тест, который это доказывает и который обязан
покраснеть, если `.txt` когда-нибудь вернётся в список кода тем же
способом, каким это уже случалось однажды.

Использует ту же инфраструктуру проб, что и `test_хук_пробы.py`
(`_новый_репозиторий`, `_добавить_и_запустить`, изолированный временный
git-репозиторий) — не копию логики, а тот же код, тот же реальный файл
`hooks/pre-commit`, вызванный подпроцессом.
"""
from __future__ import annotations

from test_хук_пробы import _новый_репозиторий, _добавить_и_запустить


def test_base64url_в_txt_отвергается(tmp_path):
    repo = _новый_репозиторий(tmp_path)
    # Тот же состав, что и в пробе на файл без расширения: оба регистра
    # и цифры — то, что отличает настоящий токен от разделителя вида
    # `------` или идентификатора в snake_case.
    токен = "".join(["aB3dEfGh12", "KLmnoPQr7st", "UV9wxYZ01cd"])
    содержимое = "вывод команды, сохранённый на минуту:\n{}\n".format(токен)
    r = _добавить_и_запустить(repo, "заметка.txt", содержимое.encode("utf-8"))
    assert r.returncode != 0, (
        "длинная base64url-строка в .txt обязана отклоняться — .txt "
        "не входит в is_code(), и правило про НЕ-код обязано его "
        "накрывать:\n" + r.stdout + r.stderr)
    assert "base64url" in (r.stdout + r.stderr), (
        "отказ обязан назвать правило (base64url-строка):\n"
        + r.stdout + r.stderr)


def test_обычный_txt_без_секрета_проходит(tmp_path):
    """Хук не отвергает .txt целиком — только состав, похожий на секрет."""
    repo = _новый_репозиторий(tmp_path)
    r = _добавить_и_запустить(
        repo, "заметка.txt",
        "обычная заметка без секретов и длинных идентификаторов\n"
        .encode("utf-8"))
    assert r.returncode == 0, (
        "обычный .txt без секрета отвергнут — хук слишком широк:\n"
        + r.stdout + r.stderr)
