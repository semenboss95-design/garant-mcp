def test_ps1_в_индексе_с_bom():
    """PowerShell 5.1 без BOM читает файл как ANSI и ломается на первой же
    кириллице — а её в `install.ps1` много (текст для человека, кириллица
    и в самом коде). Смотрим БЛОБ ИЗ ИНДЕКСА, а не файл с диска — по той же
    причине, что и в `test_хук_lf_и_без_bom`: рабочая копия законно
    отличается от того, что реально уйдёт клонировавшему.
    """
    import subprocess

    # `-z`: без него git заключает в кавычки пути с не-ASCII символами,
    # квалификация ".endswith(...)" на такой кавычке молча ломается, а файл
    # пропадает из проверки без единого слова (см. `_repo_git._ls_files_z`).
    r = git("ls-files", "-z")
    ps1_файлы = [s for s in r.stdout.split("\x00")
                if s.endswith(".ps1") or s.endswith(".psm1")]
    assert ps1_файлы, (
        "в индексе нет ни одного *.ps1/*.psm1 — если появился install.ps1, "
        "он обязан быть найден здесь; пустой список делает проверку ниже "
        "бессмысленной")
    провалы = []
    for путь in ps1_файлы:
        блоб = subprocess.run(["git", "cat-file", "blob", ":{}".format(путь)],
                              cwd=str(ROOT), capture_output=True,
                              check=True).stdout
        if not блоб.startswith(b"\xef\xbb\xbf"):
            провалы.append(путь)
    assert not провалы, (
        "в индексе нет BOM у: {} — PowerShell 5.1 прочитает файл как ANSI "
        "и сломается на кириллице".format(", ".join(провалы)))


def test_install_sh_lf_без_bom_и_исполняем():
    """`install.sh` — единственный оставшийся POSIX-установщик (решение 18).

    Три условия разом, и все три про одно и то же: то, что реально уходит
    клонировавшему в индексе, а не то, что лежит на диске этой машины.
      · LF — уже покрыто общей проверкой eol выше (`*.sh text eol=lf`),
        но здесь фиксируется явно для одного конкретного файла: `sh`
        не «bad interpreter» на CRLF так же жёстко, как хук, но кириллица
        в сообщениях следом за CRLF на POSIX превращается в мусор с `\\r`
        в каждой строке вывода.
      · без BOM — тем же способом, что и `hooks/pre-commit`: `#!` перед
        BOM не находит интерпретатор шебанг ОС.
      · режим 100755 В ИНДЕКСЕ — на Windows `core.filemode=false`, права
        на диске фикция; клонировавший на Linux/macOS получает РОВНО то,
        что в индексе.
    """
    import subprocess

    r = git("ls-files", "-s", "--", "install.sh")
    assert r.stdout.strip(), (
        "install.sh не найден в индексе — если файла ещё нет, эта проверка "
        "не относится к текущему состоянию")
    режим = r.stdout.split()[0]
    assert режим == "100755", (
        "install.sh лежит в индексе с режимом {} (ожидался 100755) — "
        "клонировавший на Linux/macOS получит неисполняемый установщик"
        .format(режим))

    блоб = subprocess.run(["git", "cat-file", "blob", ":install.sh"],
                          cwd=str(ROOT), capture_output=True,
                          check=True).stdout
    assert b"\r\n" not in блоб, (
        "install.sh в индексе содержит CRLF")
    assert not блоб.startswith(b"\xef\xbb\xbf"), (
        "install.sh в индексе начинается с BOM — шебанг `#!` не сработает")
