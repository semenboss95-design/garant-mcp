"""§7 `docs/TEAM.md`, проверка 2 — `hooks/pre-commit` приезжает с клоном
ИСПОЛНИМЫМ, и проверка 5 — концы строк рабочего дерева совпадают с тем,
что предписывает `.gitattributes`.

Обе проверки читают только ИНДЕКС и `.gitattributes` — ничего не пишут
и не пересобирают.

Почему режим смотрим в ИНДЕКСЕ, а не на диске: на Windows
`core.filemode=false`, и права файла на диске — фикция; git при клоне
воспроизводит РОВНО то, что записано в индексе (`git ls-files -s`).
Если там `100644`, то клонировавший на Linux/macOS, включив
`core.hooksPath` (см. `CLAUDE.md`), получит МОЛЧА невыполняемый хук:
защита выглядит включённой и не работает — ровно тот случай, который
и породил правило «защита обязана приезжать с клоном».

Намеренно НЕ проверяется здесь: `git config core.hooksPath` равен
`hooks`. У клонировавшего это законно НЕ настроено, пока он не выполнил
ручной шаг из README/CLAUDE.md, и красный тест на свежем клоне — худшее
первое впечатление, а не защита (задание прямо просит этого не делать).
"""

from __future__ import annotations

import re

from _repo_git import ROOT, git


# --------------------------------------------------------------------------
#  2. режим хука в ИНДЕКСЕ — 100755
# --------------------------------------------------------------------------

def test_хук_лежит_в_индексе_исполняемым():
    r = git("ls-files", "-s", "--", "hooks/pre-commit")
    assert r.stdout.strip(), (
        "hooks/pre-commit не найден в индексе вовсе — если это так, "
        "клон не принесёт хук, и последующая проверка режима бессмысленна")
    режим = r.stdout.split()[0]
    assert режим == "100755", (
        "hooks/pre-commit лежит в индексе с режимом {} (ожидался 100755). "
        "На Windows core.filemode=false, права на диске фикция — git при "
        "клоне воспроизведёт РОВНО этот режим, и клонировавший на "
        "Linux/macOS получит молча невыполняемый хук.".format(режим))


def test_хук_lf_и_без_bom():
    """CRLF в шебанге даёт «bad interpreter»; BOM ломает `#!` точно так же —
    интерпретатор ищет `#!/bin/sh`, а видит `﻿#!/bin/sh`.

    Байты — НАСТОЯЩИЕ (`subprocess` без `text=True`), а не прогнанные через
    `errors="replace"`: замена невалидного байта на U+FFFD и обратная
    кодировка в UTF-8 меняла бы как раз те байты, которые здесь и ищем.
    """
    import subprocess
    r = subprocess.run(["git", "cat-file", "blob", ":hooks/pre-commit"],
                       cwd=str(ROOT), capture_output=True, check=True)
    содержимое_байт = r.stdout
    assert b"\r\n" not in содержимое_байт, (
        "hooks/pre-commit в индексе содержит CRLF — на POSIX это "
        "«bad interpreter: /bin/sh^M», хук не запустится вовсе")
    assert not содержимое_байт.startswith(b"\xef\xbb\xbf"), (
        "hooks/pre-commit в индексе начинается с BOM — интерпретатор "
        "ищет #!/bin/sh, а видит BOM перед ним, и шебанг не срабатывает")


# --------------------------------------------------------------------------
#  5. концы строк: то, что реально уходит в коммит, совпадает с тем, что
#     предписывает .gitattributes ("дерево совпадает с индексом" в
#     терминах наряда — здесь это ИНДЕКС, а не грязная рабочая копия)
# --------------------------------------------------------------------------
#
# Смотрим ИНДЕКС (`git show :путь`), а не байты файла на диске, и вот
# почему: рабочее дерево в разгар правки закономерно грязное — редактор
# может сохранить файл с CRLF, а git переписывает его по правилам
# .gitattributes только в момент `git add`/checkout, не на каждое
# сохранение. Проверка по диску была бы проверкой того, у кого какой
# редактор открыт последним, а не свойством репозитория. Индекс — это
# ровно то, что получит клонировавший: если он расходится с
# .gitattributes, значит, атрибут завели ПОСЛЕ того, как файл уже был
# закоммичен с другими концами строк, и `git add --renormalize .` для
# него так и не выполнили — ровно тот сценарий, из-за которого этот
# пункт вообще стоит в таблице §7.


def test_gitattributes_на_месте():
    assert (ROOT / ".gitattributes").exists(), (
        "в репозитории нет .gitattributes — концы строк определяются "
        "настройкой core.autocrlf каждой машины, а не репозиторием")


def test_индекс_совпадает_с_gitattributes_по_концам_строк():
    """Для каждого отслеживаемого файла с ЯВНЫМ eol-атрибутом (`lf` ИЛИ
    `crlf`) БЛОБ В ИНДЕКСЕ обязан быть нормализован к LF.

    ИСПРАВЛЕНО 06.09.2026 (диагноз `powershell-dev`, наряд `tech-lead`):
    прежняя версия ждала от файлов с `eol=crlf` буквальный CRLF В ИНДЕКСЕ.
    Такого состояния не бывает вовсе: git при атрибуте `text` всегда хранит
    в блобе LF — `eol=lf`/`eol=crlf` управляют ТОЛЬКО тем, что кладётся
    в рабочее дерево при checkout (`git ls-files --eol` показывает это
    прямо: `i/lf w/crlf attr/text eol=crlf` — «в индексе LF, в рабочем
    дереве CRLF»). Тест был перевёрнут и не мог быть зелёным ни при каком
    файле с `eol=crlf`; молчал только потому, что после удаления `scripts/`
    (решение 18) такого файла в дереве не было — появился `install.ps1`,
    и первый же реальный случай тест не прошёл.

    Настоящая цель проверки — то же самое, что вернулось бы `git status`
    сразу после `git add --renormalize .`, если бы renormalize был нужен:
    расхождение (`i/crlf` или `i/mixed`) означает, что файл закоммитили
    ДО того, как атрибут завели, и renormalize по нему не выполнили.

    `git ls-files --eol` — один вызов на всё дерево, а не по файлу: то же
    свойство, дешевле на порядок отслеживаемых файлов.
    """
    # `-z`: без него не-ASCII имя файла ушло бы в кавычках и с экранированием,
    # `rpartition("\t")` отрезал бы неверный "путь" с хвостовой кавычкой,
    # а сам файл выпал бы из проверки eol молча (см. `_repo_git._ls_files_z`).
    r = git("ls-files", "--eol", "-z")
    провалы = []
    for строка in r.stdout.split("\x00"):
        if not строка.strip():
            continue
        поля, _, путь = строка.rpartition("\t")
        м_индекс = re.match(r"i/(\S+)", поля)
        м_eol = re.search(r"eol=(\S+)", поля)
        if not м_индекс or not м_eol:
            continue
        индекс, ожидание = м_индекс.group(1), м_eol.group(1)
        if ожидание not in ("lf", "crlf"):
            continue
        # "none" — пустой файл либо файл без единого перевода строки:
        # сверять эконцы строк не с чем, и это не нарушение.
        if индекс not in ("lf", "none"):
            провалы.append(
                "{}: в ИНДЕКСЕ '{}' при явном eol={} — блоб должен быть "
                "нормализован к LF независимо от значения eol (оно "
                "управляет только checkout), нужен "
                "`git add --renormalize .`".format(путь, индекс, ожидание))
    assert not провалы, (
        "закоммиченное содержимое разошлось с .gitattributes — правило "
        "объявлено, но уже закоммиченные файлы под него не подведены "
        "(нужен `git add --renormalize .`):\n" + "\n".join(провалы))


