# -*- coding: utf-8 -*-
"""§7 `docs/TEAM.md`, проверка 3 — пробы `hooks/pre-commit` в обе стороны.

Раньше это делалось руками при каждой правке хука (`hooks/README.md`
и комментарии самого хука описывают, что он ловит, но ни один
автоматический прогон этого не подтверждал). Здесь — то же самое, но
воспроизводимо: подложенный литерал отвергается и называет правило;
обычный код с похожими, но законными строками проходит молча.

ГРАНИЦА ПОДМЕНЫ (решение 17 — по аналогии, а не дословно): здесь нечего
подменять вообще. `hooks/pre-commit` — не код репозитория с транспортом,
а автономный `sh`-скрипт; тест зовёт РЕАЛЬНЫЙ файл
(`ROOT/hooks/pre-commit`) как внешнюю программу через `subprocess`,
и ничего в нём не подставляет.

БЕЗОПАСНОСТЬ РАБОЧЕГО ИНДЕКСА: каждая проба живёт в СОБСТВЕННОМ временном
git-репозитории (`git init` в `tmp_path`), а не в этом репозитории. Хук
читает `git diff --cached` и `git show :файл` — оба текут из того `git`,
что видит переданный `cwd`, поэтому подмена репозитория подменяет для
хука весь мир, не трогая ни индекс, ни рабочее дерево ЭТОГО репозитория.
Тест дополнительно СНИМАЕТ и СРАВНИВАЕТ `git status` этого репозитория
до и после — если тест хоть что-то задел, это будет видно, а не
угадано.
"""

from __future__ import annotations

import shutil
import subprocess
from pathlib import Path

import pytest

from _repo_git import ROOT, git

ХУК = ROOT / "hooks" / "pre-commit"

pytestmark = pytest.mark.skipif(
    shutil.which("sh") is None,
    reason="нет /bin/sh в PATH — hooks/pre-commit им и исполняется, "
           "без sh пробу не поставить (это свойство среды, а не кода)")


def _новый_репозиторий(tmp_path: Path) -> Path:
    """Отдельный git-репозиторий для одной пробы — не общий на весь модуль:
    так провал одной пробы не портит индекс другой, и `git add` каждый раз
    стартует с нуля."""
    repo = tmp_path
    r = subprocess.run(["git", "init", "-q"], cwd=str(repo),
                       capture_output=True, text=True)
    assert r.returncode == 0, "git init не сработал: " + r.stderr
    # Локальные user.name/email — иначе на машине без глобального
    # конфига `git commit` внутри пробы (если бы понадобился) упал бы;
    # самому хуку они не нужны, но пусть репозиторий будет пригоден
    # к commit без сюрпризов.
    subprocess.run(["git", "config", "user.email", "проба@localhost"],
                   cwd=str(repo), capture_output=True)
    subprocess.run(["git", "config", "user.name", "проба"],
                   cwd=str(repo), capture_output=True)
    return repo


def _добавить_и_запустить(repo: Path, имя: str, содержимое: bytes):
    путь = repo / имя
    путь.parent.mkdir(parents=True, exist_ok=True)
    путь.write_bytes(содержимое)
    r = subprocess.run(["git", "add", "--", имя], cwd=str(repo),
                       capture_output=True, text=True)
    assert r.returncode == 0, "git add провалился: " + r.stderr
    return subprocess.run(
        ["sh", str(ХУК)], cwd=str(repo),
        capture_output=True, text=True, encoding="utf-8", errors="replace",
        env={"PATH": __import__("os").environ.get("PATH", "")},
        timeout=30,
    )


# --------------------------------------------------------------------------
#  снимок состояния ЭТОГО репозитория — должен остаться нетронутым
# --------------------------------------------------------------------------

@pytest.fixture(autouse=True)
def _рабочий_индекс_нетронут():
    """Проба живёт в СОБСТВЕННОМ временном репозитории (`cwd=repo` у каждого
    `git`/`sh` внутри пробы) — ЭТОТ репозиторий она в принципе не может
    задеть иначе как через путь `ROOT/hooks/pre-commit`, который только
    ЧИТАЕТ (`sh str(ХУК)`).

    До этой правки снимок брался на ВЕСЬ репозиторий (`git status
    --porcelain` без pathspec) — и краснел на правках ПАРАЛЛЕЛЬНОГО агента,
    работающего в это же время над другими файлами дерева (наблюдалось
    07.09.2026 дважды). Свойство «проба не оставляет следов» этим не
    проверялось точнее — оно проверялось ГРУБЕЕ, чем нужно: снимок ловил
    вообще любое изменение дерева, а не только то, что могла бы оставить
    сама проба. Сужено до каталога `hooks/` — единственного, с которым
    проба этого файла вообще соприкасается.
    """
    ПУТЬ = ХУК.relative_to(ROOT).parent.as_posix()  # "hooks"
    до = git("status", "--porcelain", "--", ПУТЬ).stdout
    yield
    после = git("status", "--porcelain", "--", ПУТЬ).stdout
    assert после == до, (
        "проба хука задела каталог `{}` этого репозитория — пробы обязаны "
        "жить в изолированном временном репозитории".format(ПУТЬ))


