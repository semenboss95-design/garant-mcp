def test_обычный_код_с_похожими_строками_проходит(tmp_path):
    """Хук, отвергающий всё подряд, отключат в первый же день (решение 6).

    Здесь нарочно собраны строки, СЛОВЕСНО похожие на образцы выше, но не
    подпадающие под них по СТРУКТУРЕ: слово «cookies» без «origins» рядом,
    слово «users» без слэшей по бокам, «venv» без Scripts/bin,
    правдоподобная переменная без полного набора регистров/цифр.
    """
    код = (
        "# -*- coding: utf-8 -*-\n"
        "\"\"\"Разбор cookies браузера — учебный пример, origins тут нет.\"\"\"\n"
        "\n"
        "def список_users():\n"
        "    \"\"\"Возвращает список пользователей (users), без путей.\"\"\"\n"
        "    return []\n"
        "\n"
        "# venv можно не создавать — пакет ставится и без него\n"
        "ИМЯ_ПЕРЕМЕННОЙ = 'просто_снейк_кейс_без_смешения_регистра'\n"
    ).encode("utf-8")
    repo = _новый_репозиторий(tmp_path)
    r = _добавить_и_запустить(repo, "пример.py", код)
    assert r.returncode == 0, (
        "хук отверг обычный код с похожими, но законными строками — "
        "такой хук отключат в первый же день:\n" + r.stdout + r.stderr)
