# Полезные нагрузки проб собраны СКЛЕЙКОЙ фрагментов, а не единым
# литералом. Это не украшение: тот же принцип, что и в самом хуке
# («образцы пишутся так, чтобы не совпадать сами с собой») — здесь
# наоборот, но тем же способом: цель проб — воспроизвести РОВНО байты,
# которые ловит хук, а если написать их слитно в .py-файле, ЭТОТ файл
# сам перестанет проходить hooks/pre-commit при попытке его закоммитить
# (структура storage_state и Set-Cookie ловятся у ЛЮБОГО файла независимо
# от расширения). Склейка при этом ничего не ослабляет: `_добавить_и_запустить`
# получает точно такую же строку байт, что и слитная запись, — только
# в ИСХОДНОМ файле теста этой подстроки нет целиком.

def test_storage_state_отвергается(tmp_path):
    repo = _новый_репозиторий(tmp_path)
    ключ_1 = '"' + "cook" + "ies" + '"'
    ключ_2 = '"' + "orig" + "ins" + '"'
    тело = '{{{}: [{{"name": "x"}}], {}: [{{"origin": "y"}}]}}'.format(ключ_1, ключ_2)
    r = _добавить_и_запустить(repo, "выгрузка.json", тело.encode("ascii"))
    assert r.returncode != 0, "structura storage_state обязана отклоняться:\n" + r.stdout + r.stderr
    assert "storage_state" in (r.stdout + r.stderr), (
        "отказ обязан НАЗЫВАТЬ правило (structура storage_state):\n"
        + r.stdout + r.stderr)


def test_set_cookie_отвергается(tmp_path):
    repo = _новый_репозиторий(tmp_path)
    заголовок = "Set" + "-Cookie" + ":" + " session=abcdef; Path=/"
    содержимое = "ответ сервера начинался так:\n{}\n".format(заголовок)
    r = _добавить_и_запустить(repo, "заметка.txt", содержимое.encode("utf-8"))
    assert r.returncode != 0, "заголовок Set-Cookie обязан отклоняться:\n" + r.stdout + r.stderr
    assert "Set-Cookie" in (r.stdout + r.stderr), (
        "отказ обязан назвать правило (Set-Cookie):\n" + r.stdout + r.stderr)


def test_base64url_в_файле_без_расширения_отвергается(tmp_path):
    repo = _новый_репозиторий(tmp_path)
    # Ровно как secrets.token_urlsafe(24): смешение регистра и цифр,
    # без пробелов и без расширения у файла — так выглядит daemon_token.
    # Файл-фикстура (.py, "код") под это правило не подпадает вовсе —
    # склейка здесь не обязательна, но выдержана для единообразия проб.
    токен = "".join(["aB3dEfGh12", "KLmnoPQr7st", "UV9wxYZ01cd"])
    r = _добавить_и_запустить(repo, "утёкший_секрет", токен.encode("ascii"))
    assert r.returncode != 0, (
        "длинная base64url-строка в файле без расширения обязана "
        "отклоняться:\n" + r.stdout + r.stderr)
    assert "base64url" in (r.stdout + r.stderr), (
        "отказ обязан назвать правило (base64url-строка):\n"
        + r.stdout + r.stderr)


