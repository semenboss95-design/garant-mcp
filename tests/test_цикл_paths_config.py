# -*- coding: utf-8 -*-
"""Круг `paths` <-> `config` развязан порядком строк, а не структурой.

Найдено `constraint-guard` при приёмке этапа 02, шаг 1.

`paths.py` спрашивает имя каталога профиля у `config.карта()` (функция
`_имя_профиля()`, вызывается на уровне модуля — `ПРОФИЛЬ = _имя_профиля()`),
а `config.карта()` читает `paths.HOME` и `paths.local_endpoints_file`
(функция `_слить`/`карта`, вызывается на уровне модуля — `СЕКЦИЯ =
_секция_daemon()`). Это круг: какой из двух модулей исполнится первым,
решает вызывающий, а не сам круг.

Круг развязан ЕДИНСТВЕННО порядком строк внутри `paths.py`:
`local_endpoints_file` объявлен ВЫШЕ строки `ПРОФИЛЬ = _имя_профиля()`.
Когда до конца исполнения `paths.py` доходит вызов `_имя_профиля()`, он
уходит в `config.карта()`, а та по частично инициализированному
`garant_mcp.paths` читает уже существующие к этому моменту `paths.HOME`
и `paths.local_endpoints_file` — и они обязаны быть определены СТРОКОЙ
ВЫШЕ, иначе `AttributeError: partially initialized module 'garant_mcp.paths'
… has no attribute 'local_endpoints_file'`.

Ничто в структуре модулей не запрещает эти две строки переставить: это
чистая перестановка присваиваний, никакая проверка типов её не поймает,
а компилируется код в обоих порядках. Ломается только исполнение — и то
не при каждом импорте, а в зависимости от того, кто первым дотянется до
модуля `garant_mcp.paths` или `garant_mcp.config` в процессе: MCP-клиент,
демон и CLI импортируют пакет в разном порядке, и какая половина ломается —
решает не разработчик, а вызывающий.

Тест не чинит порядок строк (наряд не трогает `paths.py`) — он закрепляет
СВОЙСТВО: пакет обязан импортироваться, с какого бы модуля из круга ни
начали, и переопределение профиля через `endpoints.local.json` обязано
через этот круг доехать, а не потеряться на молча проглоченном исключении.

Каждая проверка — отдельным процессом: круг заводится один раз на процесс,
импорт кэшируется, и в одном процессе оба входа в круг не различить.
"""

from __future__ import annotations

import json

import pytest

from test_paths import _песочница, _запуск

# Три независимые точки входа в один и тот же круг: `client` дополнительно
# ценен тем, что сам исполняет `from . import config` раньше `from . import
# paths` — третий порядок относительно прямых `import garant_mcp.paths`
# и `import garant_mcp.config`, а не просто третье имя модуля.
ВХОДЫ = ["paths", "config", "client"]


def _написать_локальный(состояние, профиль):
    состояние.mkdir(parents=True, exist_ok=True)
    (состояние / "endpoints.local.json").write_text(
        json.dumps({"browser_profile": {"user_data_dir": профиль}},
                   ensure_ascii=False),
        encoding="utf-8")


@pytest.mark.parametrize("вход", ВХОДЫ)
def test_импорт_не_зависит_от_точки_входа_в_круг(вход, tmp_path):
    """`import garant_mcp.<вход>` первым и в одиночку — код 0.

    Без переопределения профиля: эта проверка не должна зависеть от
    endpoints.local.json вовсе, чтобы не смешивать «круг развязан» с
    «локальный слой работает» — второе проверяется отдельно, ниже.
    """
    пакет = _песочница(tmp_path)
    код = (
        "import sys\n"
        "sys.path.insert(0, r'{site}')\n"
        "import garant_mcp.{вход} as m\n"
        "print('OK')\n"
    ).format(site=пакет.parent, вход=вход)
    r = _запуск(код, tmp_path, таймаут=60)
    assert r.returncode == 0, (
        "garant_mcp.{} не импортируется первым в процессе — круг "
        "paths<->config развязан порядком строк, а не структурой:\n{}"
        .format(вход, r.stderr.strip())
    )


@pytest.mark.parametrize("вход", ВХОДЫ)
def test_переопределение_профиля_доезжает_через_круг(вход, tmp_path):
    """Тот самый путь, что ходит через круг: `_имя_профиля()` читает
    `config.карта()`, а она сливает `endpoints.local.json` из
    `paths.local_endpoints_file`.

    Мало проверить код 0 — важно, что нужное значение ДОЕХАЛО. Тест,
    ограничившийся кодом возврата, был бы зелёным и при разорванном круге,
    если бы кто-то на скорую руку обернул `_имя_профиля()` в `try/except
    AttributeError: return умолчание` — импорт тогда не падает, но
    переопределение из endpoints.local.json просто не работает, и это
    молчит так же, как и сам круг молчал до находки constraint-guard.
    """
    пакет = _песочница(tmp_path)
    состояние = tmp_path / "состояние"
    ожидаемый = "профиль_через_круг"
    _написать_локальный(состояние, ожидаемый)

    код = (
        "import sys, json\n"
        "sys.path.insert(0, r'{site}')\n"
        "import garant_mcp.{вход} as m\n"
        "import garant_mcp.paths as paths\n"
        "print(json.dumps({{'профиль': paths.ПРОФИЛЬ}}))\n"
    ).format(site=пакет.parent, вход=вход)
    r = _запуск(код, tmp_path, {"GARANT_HOME": str(состояние)}, таймаут=60)
    assert r.returncode == 0, (
        "garant_mcp.{} первым в процессе плюс переопределённый профиль "
        "уронили импорт:\n{}".format(вход, r.stderr.strip())
    )
    строка = [s for s in r.stdout.strip().splitlines() if s.startswith("{")]
    assert строка, "не удалось прочитать имя профиля:\n" + r.stdout + r.stderr
    данные = json.loads(строка[-1])
    assert данные["профиль"] == ожидаемый, (
        "имя профиля из endpoints.local.json не доехало через круг "
        "paths<->config при первом импорте garant_mcp.{}: получено {!r}, "
        "ожидалось {!r}. Ветка с локальным файлом не исполнилась либо "
        "исключение внутри неё проглочено молча.".format(
            вход, данные["профиль"], ожидаемый)
    )
